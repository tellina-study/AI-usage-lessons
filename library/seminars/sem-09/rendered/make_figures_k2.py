#!/usr/bin/env python3
"""Схема Кейса 2 — `k2-shema-promt-i-kesh.png`.

База знаний лежит в промте ЦЕЛИКОМ, и у этого есть не только содержание, но и
физика: кэш читается лишь тогда, когда начало промта совпало с прошлым
вызовом знак в знак — до контрольной точки. Отсюда ловушка, ради которой
схема и нарисована: новый пункт дописывают в КОНЕЦ списка, и это кажется
безобидным — но конец списка всё равно стоит ДО контрольной точки, значит
меняется всё начало промта, и сбрасывается весь накопленный кэш, а не одна
изменённая строка.

Поэтому два столбца нарисованы одинаковыми и стоят рядом: различие между ними
ровно одно — лишняя строка в базе, — и именно его должно быть видно без
чтения подписей. Дописанный пункт выделен золотом; контрольная точка —
золотой пунктир поперёк обоих столбцов на одной высоте.

Числа — внешние, из `CHISLA-SVERENO.md` строка 46 (документация провайдера,
прочитана дословно): запись в кэш 1,25× обычной цены токена при коротком
сроке жизни, чтение 0,1×. Срок жизни записан словами, не цифрой с «мин», —
на кадре «5 мин» неотличимо от хронометража занятия, которого в кадре быть
не должно.

Собственного замера у этого кейса нет (единственный такой на занятии), и
схема поэтому не показывает ни одного «нашего» числа — только устройство и
цену из документации.

Запуск: `python3 make_figures_k2.py` (из `rendered/`).
"""
from make_figures_common import *

H = 770

# Высоты пересчитаны после первого прогона: одиннадцатая строка базы вылезала
# ЗА нижнюю грань своего же блока, пунктир контрольной точки ложился на неё
# сверху, а боковые метки «запоминается»/«меняется каждый раз» наезжали на
# столбцы. Метки сняты — то же самое теперь сказано одной подписью под самим
# пунктиром, где оно и читается.
PUNKTY = ("пункт 1 · оплата", "пункт 2 · перенос",
          "пункт 3 · документы", "пункт 10 · связь с преподавателем")


def dashline(d, x1, x2, y, col, *, seg=22, gap=14, wd=5):
    """Пунктир поперёк столбца. Прежде рисовался `dashbox` высотой в четыре
    пикселя — приём не для этого, и концы линии выходили скруглёнными."""
    x = x1
    while x < x2:
        d.line([x, y, min(x + seg, x2), y], fill=col, width=wd)
        x += seg + gap


def stolb(d, x, w, zagolovok, verdikt, *, dopisan):
    """Один столбец — промт сверху вниз: указание, база, контрольная точка,
    вопрос клиента. `dopisan` добавляет в базу одиннадцатую строку."""
    ctxt(d, x + w / 2, 112, zagolovok, 28, DEEP, b=True, limit=w,
         where=f"столбец · {zagolovok[:18]}")

    card(d, x, 156, w, 58)
    ctxt(d, x + w / 2, 170, "указание процессу", 26, LIGHT, limit=w - 40,
         where="сегмент · указание")

    y2, h2 = 226, 252
    card(d, x, y2, w, h2)
    ctxt(d, x + w / 2, y2 + 12, "база знаний в промте", 27, DEEP, b=True,
         limit=w - 40, where="сегмент · база")
    ry = y2 + 54
    for i, p in enumerate(PUNKTY):
        card(d, x + 20, ry, w - 40, 32, fill=W, stroke=LIGHT, sw=2, r=8)
        ctxt(d, x + w / 2, ry + 3, p, 25, MID, limit=w - 70,
             where=f"пункт базы {i}")
        ry += 38
    if dopisan:
        card(d, x + 20, ry, w - 40, 32, fill=W, stroke=GOLD, sw=3, r=8)
        ctxt(d, x + w / 2, ry + 3, "пункт 11 · дописан в конец", 25, GOLD, b=True,
             limit=w - 70, where="дописанный пункт")

    card(d, x, 544, w, 58, fill=W)
    ctxt(d, x + w / 2, 558, "вопрос клиента", 26, DEEP, limit=w - 40,
         where="сегмент · вопрос")

    card(d, x, 618, w, 126, fill=W, stroke=GOLD if dopisan else TEAL, sw=5)
    wrapped(d, x + 22, 636, verdikt, 26, DEEP, w - 44, center=x + w / 2,
            where=f"вывод столбца · {zagolovok[:18]}")


def kesh():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "База знаний целиком в промте: что кэш запоминает и что его сбрасывает",
        34, MID, b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "кэш читается только тогда, когда начало промта совпало с прошлым "
        "вызовом знак в знак", 26, LIGHT, limit=CW - 120, where="подзаголовок")

    stolb(d, 90, 560, "Новый вопрос, база не тронута",
          "начало промта совпало знак в знак — ответ читается из кэша",
          dopisan=False)
    stolb(d, 700, 560, "В базу дописан один пункт",
          "начало промта изменилось — сброшен весь накопленный кэш, не одна строка",
          dopisan=True)

    # Контрольная точка — поперёк обоих столбцов на одной высоте: она делит
    # промт на запоминаемое начало и меняющийся хвост, и делит одинаково.
    yk = 498
    for x0, x1 in ((90, 650), (700, 1260)):
        dashline(d, x0, x1, yk, GOLD)
    ctxt(d, 675, yk + 10, "контрольная точка: выше — запоминается, ниже — "
         "меняется каждый раз", 26, GOLD, b=True, limit=1170,
         where="подпись контрольной точки")

    # Правая колонка: условие кэша прямой формой и цена из документации.
    px, pw = 1360, 960
    card(d, px, 112, pw, 360, fill=SURF, stroke=LIGHT)
    txt(d, px + 36, 134, "Условие кэша", 32, DEEP, b=True, limit=pw - 72,
        where="правая колонка · название")
    uslovia = (
        "начало промта до контрольной точки совпадает знак в знак",
        "любая правка базы стоит до этой точки — значит сбрасывает весь кэш",
        "кэш живёт минуты (у части провайдеров — час) и истекает сам",
    )
    y = 190
    for i, u in enumerate(uslovia):
        d.ellipse([px + 40, y + 9, px + 54, y + 23], fill=GOLD)
        y += wrapped(d, px + 74, y, u, 27, DEEP, pw - 120,
                     where=f"условие {i}") + 22

    plashka_para(d, px, 504, pw, 240,
                 ("1,25×", "записать базу в кэш"),
                 ("0,1×", "прочитать её из кэша"),
                 "к обычной цене токена, по документации провайдера",
                 nsz=56, gold_idx=1, where="плашка цены кэша")
    save(im, "k2-shema-promt-i-kesh.png")


if __name__ == "__main__":
    kesh()
    pt_report("схема Кейса 2")
    audit_sources()

def process_file(path):
    text = path.read_text(encoding='utf-8')
    new_text = text
    changes = 0
    for old, new in REPLACEMENTS:
        if old in new_text:
            cnt = new_text.count(old)
            new_text = new_text.replace(old, new)
            changes += cnt
    if new_text != text:
        path.write_text(new_text, encoding='utf-8')
        return changes
    return 0


def main():
    total = 0
    for f in sorted(SLIDES.glob("*.md")):
        c = process_file(f)
        if c:
            print(f"{f.name}: {c} replacements")
            total += c
    c = process_file(BUILD)
    if c:
        print(f"build_lec08.py: {c} replacements")
        total += c
    print(f"Total replacements: {total}")


if __name__ == "__main__":
    main()

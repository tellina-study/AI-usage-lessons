import sys, statistics
from collections import Counter
from pptx import Presentation
MX = 39.6
LO, HI = 1.0, 20.0
for path in sys.argv[1:]:
    prs = Presentation(path); W = prs.slide_width/12700.0
    melkie = Counter(); vsego = 0; figur_plohih = 0; po_kadram = []
    for s in prs.slides:
        nk = set()
        for sh in s.shapes:
            if None in (sh.left, sh.width): continue
            l = sh.left/12700.0; w = sh.width/12700.0
            if w < 6 or w >= W - 1: continue
            vsego += 1
            # ОБА края, не только левый: блок, стоящий ровно по левому полю и
            # выступающий вправо, по одному левому краю неотличим от ровного
            # (находка владельца 02.11 на кадре 2: блок 29,5-930,5 против
            # 39,6-920,4 у соседей — вылезал на 10,1 пт в КАЖДУЮ сторону).
            #
            # Доля считается ПО ФИГУРАМ: фигура с двумя промахнувшимися
            # кромками — одна неряшливая фигура, а не две. Первая редакция
            # делила ЧИСЛО КРОМОК на ЧИСЛО ФИГУР и печатала величину, которая
            # не является долей ничего и способна превысить 100%. Поймано
            # сводом наработок 03.11; исправлено здесь, а не замолчано.
            plohaya = False
            for d in (l - MX, (W - MX) - (l + w)):
                if LO <= abs(d) <= HI:
                    melkie[round(d)] += 1; nk.add(round(d)); plohaya = True
            if plohaya: figur_plohih += 1
        po_kadram.append(len(nk))
    n = figur_plohih
    print(f"{path.split('/')[-1]:26s} фигур с промахом поля: {n:4d}/{vsego} = {n/max(vsego,1)*100:5.1f}% · "
          f"разных значений {len(melkie):2d} · на кадре медиана {statistics.median(po_kadram):.1f}")
    print(f"{'':26s}   значения: {', '.join(f'{k:+d}пт×{v}' for k,v in melkie.most_common(8))}"
          f"  (кромок с промахом {sum(melkie.values())} из {vsego*2})")

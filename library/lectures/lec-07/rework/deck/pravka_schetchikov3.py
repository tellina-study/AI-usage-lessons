#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Ссылки «Раздел N» после перенумерации (#229) -- третий проход.

Сводов в деке восемь, и каждый называет НОМЕР своего раздела прозой: «свод
раздела 6», «шов в раздел 7». Перенумерация 4-10 -> 3-9 их не касается ни
одним генератором.

ОДНА ПРАВКА ЗДЕСЬ -- НЕ СЧЁТЧИК, А ПРОТИВОРЕЧИЕ, КОТОРОЕ СОЗДАЛО САМО
СЛИЯНИЕ, и сказать об этом надо прямо. `s102` утверждал на видимом слое:
«Разделы 2 и 9 не платят ничем из четырёх». После слияния раздел 2 несёт
разборы постановки диагноза -- в том числе замер взгляда, то есть ПЛАТЁЖ
ВНИМАНИЕМ, который стоит в той же таблице этого же кадра. Утверждение стало
ложным не из-за номера, а из-за состава раздела.

Вторая беда того же места: «9» в прежней записи не разрешается однозначно --
в нумерации разделов деки 9 была «Сборка», которая платить не может по
устройству, а по смыслу подходит «разработка лекарства» (её заметки на `s87`
прямо говорят «не занят ни один из четырёх»). Поэтому номера с видимого слоя
СНЯТЫ и заменены именем: имя не едет при перенумерации и не допускает двух
чтений. Полный пересчёт, какие разделы платят, оставлен сессии содержания
маркером -- он требует разбора по каждому разделу, а не правки числа.
"""
import io

P = [
 ('slides/s73-vyvod-chem-uderzhivayut.md', 'свод раздела 6:', 'свод раздела 5:', 1),
 ('slides/s73-vyvod-chem-uderzhivayut.md', 'сам шов в раздел 7', 'сам шов в раздел 6', 1),
 ('slides/s73i-vyvod-navyk.md', 'свод раздела 7:', 'свод раздела 6:', 1),
 ('slides/s87-vyvod-lekarstvo.md', 'свод раздела 8:', 'свод раздела 7:', 1),
 ('slides/s77-voronka-otrasli.md', 'раздел 8 стоял без единого снимка',
  'раздел разработки лекарства (тогда 8-й, после слияния 7-й) стоял без единого снимка', 1),
 ('slides/s102-chto-menyaetsya-v-cheloveke-i-v-podpisi.md',
  '**Разделы 2 и 9 не платят ничем из четырёх:** рядом с моделью там никто не работает.',
  '**Разработка лекарства не платит ничем из четырёх:** рядом с моделью там никто не работает.\n\n'
  '<!-- СОДЕРЖАНИЕ (#229, сессии содержания): прежняя строка говорила «Разделы 2 и 9». '
  'Снята по двум причинам. (1) Слияние 2+3 сделало её ЛОЖНОЙ: слитый раздел 2 несёт '
  'замер взгляда, то есть платёж ВНИМАНИЕМ из первой строки этой же таблицы. '
  '(2) «9» не разрешалась однозначно: в нумерации разделов 9 — «Сборка», платить ей '
  'нечем по устройству. Оставлена одна проверяемая половина — разработка лекарства '
  '(подтверждено заметками s87: «врача в контуре нет, ни один из четырёх не занят»). '
  'ПЕРЕСЧИТАТЬ по каждому из семи стадийных разделов, какие не платят ни одним из '
  'четырёх адресов, и назвать их ИМЕНАМИ, а не номерами. -->', 1),
 ('slides/s102-chto-menyaetsya-v-cheloveke-i-v-podpisi.md',
  'прочерк по разделам 2 и 9', 'прочерк по разработке лекарства', 1),
]


def main():
    itogo = 0
    for p, staro, novo, zhdem in P:
        t = io.open(p, encoding='utf-8').read()
        n = t.count(staro)
        assert n == zhdem, 'в %s ждали %d, нашли %d: %r' % (p, zhdem, n, staro[:60])
        io.open(p, 'w', encoding='utf-8').write(t.replace(staro, novo))
        itogo += n
        print('  %-7s %r' % (p.split('/')[-1].split('-')[0], staro[:70]))
    print('исправлено вхождений: %d' % itogo)


if __name__ == '__main__':
    main()

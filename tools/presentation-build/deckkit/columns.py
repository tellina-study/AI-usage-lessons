# -*- coding: utf-8 -*-
"""ДВА ИЛИ ТРИ СТОЛБЦА `columns:` — ТОЛЬКО под противопоставление либо разбор.

Из lec-07. Отличается от `flow.two_columns` не видом, а назначением, и
смешивать их нельзя:

* `flow.two_columns` РАЗРЕЗАЕТ одно тело на две колонки, потому что в одну
  оно не влезает. Это решение о месте.
* `columns` объявляет столбцы как СОДЕРЖАНИЕ: «что получается / что не
  получается» (два, тип `comparison`) либо «механизм / объяснение /
  последствия» (три, тип `analitika`). Это утверждение кадра, и оно
  заявлено во фронтматтере.

Поэтому поле `columns` на кадре типа не `comparison`/`analitika` даёт
предупреждение: перечень кейсов в столбцах — это не содержательное
утверждение, а экономия места, и ей место в `flow.two_columns`.

Контракт фронтматтера, два столбца (`comparison`):

    columns:
      left:  {head: "Что получается", items: ["…", "…"]}
      right: {head: "Что не получается", items: ["…", "…"]}

Контракт фронтматтера, три столбца (`analitika`, §9 требований к форме,
владелец 2026-10-17: «надо чтобы была структура в таблице или строчных
блоках — механизм, объяснение, последствия»): средний столбец `mid`
встаёт МЕЖДУ `left` и `right`, остальное не меняется —

    columns:
      left:  {head: "Механизм",    items: ["…", "…"]}
      mid:   {head: "Объяснение",  items: ["…", "…"]}
      right: {head: "Последствия", items: ["…", "…"]}

Без `mid` поведение байт-в-байт то же, что раньше (два столбца, см. §9
«кадр-заземление остаётся схемой по §8» — то есть этот модуль обслуживает
оба случая одним кодом, а не веткой «если три, то другая функция»).

ДОЛЯ ШИРИНЫ столбцов на ТРЁХ не объявляется кадром числом, как на двух
(`dolya_levogo_stolbtsa` — поле под пару, не под троицу, и вызывающий код
(`build_lec07.analitika`) не тронут этой правкой намеренно: его в это же
время правит другая сессия под другую дыру типа `analitika`, межслотовую
для изображений, — трогать его здесь значило бы получить два места,
решающих один вопрос). Доля меряется здесь же, автоматически, по
медианной длине содержимого столбца (`_avto_doli`): кадру с `mid` ничего
объявлять не нужно.
"""
from . import floor, metrics, prims, report
from .theme import DEEP, LIGHT, MID, SURFACE, TEAL, WHITE

GAP = 0.34
PAD = 0.18
TOP_PAD = 0.17
HEAD_PT = 14.0
HEAD_LS = 1.12
# Пол видимого слоя (`floor.py`). Подбор берёт НАИБОЛЬШИЙ кегль, который
# влезает, — то есть ниже 12 пт он опускается только там, где 12 не влезает
# вовсе, и тогда об этом говорит `[пол]` (ниже по тексту). Пол поставлен
# МЯГКИМ нарочно: жёсткий оставил бы перечень торчать из своей коробки —
# замерено на `s55a`, 1,30" текста в коробке 1,11". Между «мелко, и об этом
# сказано» и «вылезло за грань молча» выбрано первое; прежде здесь не было
# ни того, ни другого — столбец уходил под пол без единого слова.
ITEM_HI, ITEM_LO, ITEM_FLOOR = 14.5, 9.0, 9.0
ITEM_LS = 1.26
MIN_H, MAX_H = 1.55, 3.40


def _strok(tekst, kegl, iw):
    """Сколько строк займёт пункт перечня. Высота делится на межстрочный
    шаг того же кегля — та же мера, которой считает раскладка."""
    shag = kegl * ITEM_LS / 72.0
    return max(1, round(metrics.est_h("• " + tekst, kegl, iw, ITEM_LS) / shag))


def proverit_pary(sid, cols, shiriny, kegli):
    """[пары] — строка в одном столбце не стоит напротив своей строки в
    другом. Работает на ЛЮБОМ числе столбцов (два — `comparison`, три —
    `analitika` с механизмом-объяснением-последствиями, §9): пара — это
    строка с тем же индексом во ВСЕХ столбцах разом, не только в двух.

    ЗАЧЕМ ЭТО ЗДЕСЬ. Столбцы рисуются как НЕЗАВИСИМЫЕ перечни, и для сборки
    это N валидных списков: ни одна проверка пакета не знает, что строка с
    одним индексом в разных столбцах — ОДНА пара. Пункт в одну строку
    против пункта в две в соседнем столбце сдвигает всё, что ниже. Молча.

    Найдено не прогоном, а просмотром снимка — сессией кадров о влиянии ИИ
    на человека (#244), и найдено ДВАЖДЫ В ОБЕ СТОРОНЫ на двух столбцах:
    при равных столбцах разъезжался правый, при доле 0,40 — левый.
    Обходилось подгонкой длин, то есть держалось на дисциплине автора, а не
    на мере. Теперь на мере.

    Проверка включается только там, где пара ЕСТЬ по содержанию: у
    противопоставления «получается / не получается» и у разбора «механизм /
    объяснение / последствия» пункты парные; у перечня кейсов в столбцах
    ради экономии места — нет, и равнять их число нечем и незачем.
    """
    counts = [len(c["items"]) for c in cols]
    if len(set(counts)) > 1:
        report.warn(
            f"[пары] {sid}: число строк по столбцам не совпадает — "
            + " · ".join(f"столбец {i + 1}: {n}"
                        for i, n in enumerate(counts))
            + " — столбцы объявлены парами, и при разном числе пунктов "
              "пара читается напротив чужой строки")
        return
    n = counts[0]
    rashod = []
    for i in range(n):
        stroki = [_strok(cols[j]["items"][i], kegli[j],
                         shiriny[j] - 2 * PAD) for j in range(len(cols))]
        if len(set(stroki)) > 1:
            rashod.append(f"пара {i + 1}: " + " против ".join(
                str(s) for s in stroki))
    if rashod:
        report.warn(
            f"[пары] {sid}: строки пар не совпадают по высоте — "
            + " · ".join(rashod[:4])
            + ("…" if len(rashod) > 4 else "")
            + "; всё, что ниже первой такой пары, читается со сдвигом")


def columns_of(sl, *, require_type="comparison"):
    """Поле `columns` → список из двух либо трёх столбцов, или None.

    Средний столбец `mid` опционален и встаёт между `left` и `right` —
    контракт «механизм / объяснение / последствия» (§9). Без `mid`
    возвращаются ровно те же два столбца, что и раньше."""
    raw = sl.meta.get("columns")
    if raw in (None, "", [], {}):
        return None
    if not isinstance(raw, dict) or "left" not in raw or "right" not in raw:
        report.warn(f"[столбцы] {sl.sid}: поле `columns` должно иметь "
                    "`left` и `right`")
        return None
    sides = ["left"] + (["mid"] if "mid" in raw else []) + ["right"]
    cols = []
    for side in sides:
        c = raw[side]
        if not isinstance(c, dict):
            report.warn(f"[столбцы] {sl.sid}: `{side}` не словарь")
            return None
        cols.append({"head": str(c.get("head") or "").strip(),
                     "items": [str(i).strip() for i in (c.get("items") or [])
                               if str(i).strip()]})
    if require_type and sl.meta.get("type") != require_type:
        n = "два столбца" if len(cols) == 2 else "столбцы"
        report.warn(
            f"[столбцы] {sl.sid}: {n} объявлены на кадре типа "
            f"«{sl.meta.get('type')}» — они идут ТОЛЬКО под "
            "противопоставление «что получается / что не получается» либо "
            "разбор «механизм / объяснение / последствия», тип кадра "
            f"`{require_type}`")
    return cols


def _avto_doli(cols):
    """Доли по КОРНЮ ИЗ МЕДИАННОЙ ДЛИНЕ содержимого столбца — заголовок
    считается тоже (он даёт вклад в ширину, когда он длиннее пунктов).

    Нужна там, где столбцов больше двух: соотношение весов троих не
    выводится из пары, как у двоих (там доля объявлена явно кадром —
    0,40, замерено на отношении медиан около 1 : 2), а звать автора кадра
    объявлять долю трёх столбцов числом — значит переносить измерение на
    него при каждой правке текста. Здесь оно переизмеряется само.

    КОРЕНЬ, А НЕ ПРЯМАЯ ДОЛЯ ДЛИНЫ — измерено на кадрах «влияние на
    врача/пациента» (§9, сессия #244): столбец с короткими пунктами
    («механизм» — одно слово) и столбец с длинными (числа с базой) не
    делят ширину пропорционально длине без остатка. Прямая доля даёт
    столбцу механизма ~0,10 от ширины — слово `Разбор несогласий` там не
    влезает, сторож `[ширина]` ловит; столбец длинных последствий получает
    ~0,53 — больше, чем ему требуется, и это ничего не даёт, потому что у
    него и так много точек разрыва строки. У короткого столбца точек
    разрыва почти нет — единственное слово либо входит в свою ширину, либо
    нет, — поэтому ему нужен запас НЕ пропорциональный длине, а
    опережающий её. Корень квадратный даёт эту опережающую прибавку
    короткому столбцу за счёт длинного без явного порога: при длинах
    9/32/44 (медианы кадра о враче) прямая доля даёт 0,106/0,376/0,517, а
    корень — 0,193/0,374/0,432 — и именно второе проходит сторож `[пары]`
    на обоих кадрах без единого предупреждения на диапазоне высоты
    2,8–3,4" (весь диапазон, который даёт `analitika()` этому полю)."""
    import statistics as st
    dliny = []
    for c in cols:
        kandidaty = [len(it) for it in c["items"]] or [1]
        if c["head"]:
            kandidaty.append(len(c["head"]))
        dliny.append(st.median(kandidaty))
    korni = [d ** 0.5 for d in dliny]
    itog = sum(korni) or 1.0
    return [max(0.08, k / itog) for k in korni]


def _doli(dolya_levogo, n, cols):
    """Доля скаляра (поведение, какое было всегда у двух столбцов) либо
    явный список долей, либо — для n > 2 без явного списка — доли по
    длине содержимого (`_avto_doli`)."""
    if isinstance(dolya_levogo, (list, tuple)):
        doli = [max(0.05, float(d)) for d in dolya_levogo]
        if len(doli) != n:
            raise ValueError(
                f"columns.draw_columns: список долей длиной {len(doli)} "
                f"не совпадает с числом столбцов {n}")
        itog = sum(doli)
        return [d / itog for d in doli]
    if n == 2:
        d0 = min(0.75, max(0.25, float(dolya_levogo)))
        return [d0, 1.0 - d0]
    # n > 2 и скаляр не объявлен явно списком: вызывающий код (в этой деке —
    # `analitika()`) всегда передаёт скаляр, читая поле `dolya_levogo_stolbtsa`
    # — поле ИМЕНИ ровно под два столбца, и требовать от него расширения
    # под третий значило бы править ДВЕ реализации одного смысла. Доля
    # меряется здесь же, по содержимому.
    doli = _avto_doli(cols)
    itog = sum(doli)
    return [d / itog for d in doli]


def draw_columns(s, sid, cols, x, y, w, h, dolya_levogo=0.5, pary=False):
    """Два ИЛИ три столбца в коробках мотива. Первый на поверхности,
    остальные белые с бирюзовой обводкой — различие сторон держится цветом
    рамки, а не подписью «против».

    `dolya_levogo` — доля ширины первого столбца на ДВУХ столбцах (как
    раньше, скаляр, объявленный кадром явно — неравное деление нужно там,
    где стороны неравны по весу: пара «как проявляется / последствия»
    даёт отношение медиан около 1 : 2, замер сессии кадров о влиянии ИИ на
    человека #244). На ТРЁХ столбцах («механизм / объяснение /
    последствия», §9) доли этим же параметром не задаются — вызывающий
    код передаёт его как скаляр под старый контракт двух столбцов, и
    требовать от него списка значило бы править код, которым не владеет
    эта сессия; доли меряются здесь же по длине содержимого столбца
    (`_avto_doli`). Список долей, если он всё же передан явно, уважается
    на любом числе столбцов — путь открыт для вызывающего кода, который
    измерит сам."""
    n = len(cols)
    doli = _doli(dolya_levogo, n, cols)
    shiriny = [(w - GAP * (n - 1)) * d for d in doli]
    kegli = [ITEM_HI] * n
    xx = x
    for i, c in enumerate(cols):
        cw = shiriny[i]
        prims.ocean_box(s, xx, y, cw, h, fill=SURFACE if i == 0 else WHITE,
                        stroke=LIGHT if i == 0 else TEAL)
        iw = cw - 2 * PAD
        yy = y + TOP_PAD
        if c["head"]:
            hh = metrics.est_h(c["head"], HEAD_PT, iw, HEAD_LS)
            floor.pt(HEAD_PT, f"{sid}/столбец-{i + 1}", "шапка столбца")
            prims.text_box(s, xx + PAD, yy, iw, hh, c["head"], size=HEAD_PT,
                           bold=True, color=MID if i == 0 else TEAL,
                           ls=HEAD_LS, tag=f"{sid}/столбец-шапка")
            yy += hh + 0.12
        body = "\n".join("• " + it for it in c["items"])
        if body:
            avail = y + h - TOP_PAD - yy
            sz = metrics.fit_size(body, iw, avail, hi=ITEM_HI, lo=ITEM_LO,
                                  floor=ITEM_FLOOR, ls=ITEM_LS,
                                  tag=f"{sid}/столбец-{i + 1}")
            floor.pt(sz, f"{sid}/столбец-{i + 1}", "перечень столбца")
            kegli[i] = sz
            prims.text_box(s, xx + PAD, yy, iw, avail, body, size=sz,
                           color=DEEP, ls=ITEM_LS,
                           tag=f"{sid}/столбец-{i + 1}")
        xx += cw + GAP
    if pary and len(cols) >= 2:
        proverit_pary(sid, cols, shiriny, kegli)
    report.PRIM["столбцы"] += 1

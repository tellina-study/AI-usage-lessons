"""ЗАГОЛОВОК КАДРА: лестница кеглей и ЧИСЛО ВМЕСТО ФРАЗЫ.

ДВЕ ПРАВКИ ОДНОГО КРУГА (#229), и обе куплены замером собранной деки против
доставленной деки Лекции 6, которую читали залу.

── 1. ЛЕСТНИЦА, А НЕ ПОДГОНКА ПО ВЫСОТЕ ──

Было: кегль заголовка подбирался `metrics.fit_size` под ВЫСОТУ рамки (0,92"),
шагом 0,5 пт. Рамка держит две строки при 24,5 пт — значит подбор спокойно
отдавал двухстрочный заголовок, и это засчитывалось как «влез». Замер: 35
заголовков Лекции 7 из 122 набраны в две строки; у Лекции 6 — ОДИН из 100,
при том что заголовки там той же длины (медиана 51 знак против наших 49).

Цена двухстрочного заголовка здесь не «некрасиво». Золотая черта кадра
садится под НАСТОЯЩУЮ высоту заголовка и упирается в потолок тела: на
однострочном она ложится под всю строку и читается как подчёркивание
заголовка, а на двухстрочном — под ПЕРВОЕ СЛОВО второй строки, и читается
как подчёркивание этого слова. «держит», «модели», «арбитражем», «фазе» —
четыре кадра, где зал видит выделенным служебное слово.

Стало: кегль берётся с ЛЕСТНИЦЫ, и правило отбора другое — не «влезает по
высоте», а «СТАВИТСЯ В ОДНУ СТРОКУ». Лестница нужна ровно затем же, зачем
`metrics.GRID_PT` телу: шаг 0,5 пт даёт соседним кадрам 24,5 и 24,0 — разницу,
которой глаз не видит как иерархию, зато видит как дрожь. У Лекции 6 на сто
кадров пять различных кеглей заголовка (21,5 · 23,5 · 24 · 26 · 28), и это
не случайность набора, а то, что держит деку на одном ритме.

Заголовок, который не ставится в одну строку НИ НА ОДНОЙ ступени, — это
длинный заголовок, а не задача раскладки. Он получает ступень, на которой
влезает по высоте, и `[заголовок]` с числом знаков: сократить его может
только тот, кто его написал.

── 2. ЧИСЛО ВМЕСТО ФРАЗЫ: `headline_number` ──

Замер того же круга: у Лекции 6 ~39 кадров из 100, где ЗАГОЛОВОК — само
измеренное число, набранное 28 пт («82,9 % → 81,5 %», «8,9 с → 13,9 с»,
«5 500 см³/с», «2508 → 182»). У Лекции 7 таких НОЛЬ: заголовок всегда фраза
(«Пример 2, цена: …»), а число лежит в плашке под шапкой в 10 пт. Иерархия
кадра перевёрнута — самый крупный текст служебный, измеренное самое мелкое.

Поле `headline_number` эту перестановку делает возможной, и только её:

    headline_number: "82,9 % → 81,5 %"
    title: "Пример 2, цена: чувствительность просела"

Число встаёт на место заголовка и набирается своей лестницей (до 34 пт),
фраза уходит под него подзаголовком. КАДР ПРИ ЭТОМ НЕ ПЕРЕПИСЫВАЕТСЯ: это
перестановка того, что на нём уже есть, и переносить число в поле — работа
того, кто правит кадры, а не сборщика. Сборщик даёт механизм и молчит о том,
на каких кадрах его применить.

Пустое `headline_number` — то же, что его отсутствие: кадр набирается как
прежде. Заголовок при этом обязателен по-прежнему: число без фразы не
говорит, откуда оно, а это ровно то, за что всю деку и критикуют.
"""
from . import floor, metrics, report

# Лестница заголовка-фразы. Ступени редкие нарочно: между соседними глаз
# должен видеть РАЗНИЦУ, иначе лестница не лестница.
LADDER = (27.0, 25.0, 23.0, 21.0, 19.0, 17.5, 16.0)

# Лестница числа-заголовка. Верх выше, чем у фразы: число короче, и ради
# него вся перестановка и делается.
NUM_LADDER = (34.0, 31.0, 28.0, 26.0, 24.0, 22.0, 20.0)

SUB_PT = 15.0          # подзаголовок под числом: фраза, бывшая заголовком


def fit_title(text, w, h, *, ladder=LADDER, ls=1.08, tag="", what="заголовок"):
    """Ступень лестницы для заголовка. Возвращает `(кегль, строк)`.

    Правило отбора: САМАЯ КРУПНАЯ ступень, на которой заголовок ставится в
    ОДНУ строку. Такой нет ни одной — самая крупная, на которой он влезает
    в рамку по высоте, и `[заголовок]` о том, что он длинный.

    Высота проверяется и у однострочного: рамка бывает ниже строки своего
    кегля, и «одна строка» само по себе ещё не «влезло»."""
    if not text:
        return ladder[-1], 0
    one = [f for f in ladder
           if metrics.n_lines(text, f, w, True) == 1
           and metrics.est_h(text, f, w, ls, True) <= h + 1e-9]
    if one:
        return one[0], 1
    fits = [f for f in ladder
            if metrics.est_h(text, f, w, ls, True) <= h + 1e-9]
    f = fits[0] if fits else ladder[-1]
    n = metrics.n_lines(text, f, w, True)
    report.warn(
        f"[заголовок] {tag}: {what} не ставится в одну строку ни на одной "
        f"ступени лестницы — {len(text)} знаков, на {f:.1f} пт выходит "
        f"{n} строк{'и' if 1 < n < 5 else ''}. Золотая черта кадра сядет "
        "под вторую строку и подчеркнёт одно слово; лечится это укорочением "
        "заголовка, а не кеглем")
    return f, n


def headline_of(sl):
    """Поле `headline_number` → строка числа или None.

    Число без заголовка-фразы ОТВЕРГАЕТСЯ, а не принимается молча: кадр, на
    котором стоит «−28%» и больше ничего, не говорит, от чего эти проценты,
    и перестановка иерархии превратилась бы в потерю половины смысла."""
    raw = sl.meta.get("headline_number")
    if raw in (None, "", [], {}):
        return None
    num = str(raw).strip()
    if not num:
        return None
    if not sl.title:
        report.warn(
            f"[заголовок] {sl.sid}: `headline_number` стоит, а `title` пуст "
            "— число встанет на кадр без фразы, которая говорит, откуда оно")
        return None
    if "\n" in num:
        report.warn(f"[заголовок] {sl.sid}: `headline_number` в несколько "
                    "строк — это уже не число, а фраза")
    return num


def fit_headline(num, sub, w, h_num, h_sub, *, tag=""):
    """Кегли пары «число · подзаголовок». Возвращает `(кегль числа, строк
    числа, кегль подзаголовка, строк подзаголовка)`.

    Подзаголовок идёт через пол видимого слоя: он мельче заголовка по
    замыслу, и ровно поэтому его легче всего уронить под порог."""
    nf, nl = fit_title(num, w, h_num, ladder=NUM_LADDER, ls=1.06, tag=tag,
                       what="число-заголовок")
    sf = SUB_PT
    sl_ = metrics.n_lines(sub, sf, w, False)
    floor.pt(sf, tag, "подзаголовок под числом")
    if metrics.est_h(sub, sf, w, 1.14) > h_sub + 1e-9:
        report.warn(
            f"[заголовок] {tag}: подзаголовок под числом не влезает в свою "
            f"полосу — {len(sub)} знаков на {sf:.1f} пт дают {sl_} строк"
            f"{'и' if 1 < sl_ < 5 else ''}")
    return nf, nl, sf, sl_

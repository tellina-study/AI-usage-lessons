# -*- coding: utf-8 -*-
"""МЕРА ТЕКСТА — настоящими метриками шрифта, без единого коэффициента.

Это главный модуль пакета, и единственный, который нельзя упрощать. Он
перенесён из `library/lectures/lec-07/rework/deck/build_lec07.py` целиком и
по поведению, а не по смыслу: там каждая его часть куплена видимым дефектом,
и каждая доказана пробой на нарочно сломанном входе (`selftest.py`).

ЧЕМ МЕРИТСЯ. Ширина строки и число строк — настоящими метриками СВОЕГО
начертания: четыре файла Liberation Sans на четыре сочетания «полужирный ×
курсив». Начертания, файла которого на машине нет, мера НЕ подменяет молча —
выходит блокирующее `[шрифт]`.

ЧТО ЗДЕСЬ БЫЛО СЛОМАНО И ЧЕМ ЭТО КОНЧИЛОСЬ (три разных дефекта, все три
молчаливые — сборка рапортовала «предупреждений нет»):

1. КОЭФФИЦИЕНТ НА КУРСИВ. Стоял `ITAL_W = 1.031` к мере по прямому. Курсив
   Liberation Sans — настоящий курсив, а не наклон: внутри одной строки
   отношение курсива к прямому идёт от 0,990 («дублированная») до 1,064
   («рецензентов»). Один коэффициент на такой размах верным не бывает, и
   промах не в величине: жадный перенос ломается не на средней ширине, а на
   конкретном слове. Цена — слово «госпитализациях» печаталось ПОВЕРХ нижней
   грани плашки `s63`.
2. УСРЕДНЁННОЕ НАЧЕРТАНИЕ АБЗАЦА. Абзац мерился одной строкой: «кегль —
   максимум по абзацу, полужирный — если хоть один кусок полужирный, курсив —
   никак». Курсивные куски тела не мерились курсивом ни разу, при том что их
   в деке 35 на 17 кадрах. Отсюда `_pieces_w` и `wrap_pieces`, которые
   меряют КУСКАМИ.
3. ОТБИВКА АБЗАЦЕВ ВНЕ МЕРЫ. `space_before` не входил в высоту, а поправки
   стояли ПО МЕСТУ — у двух ветвей раскладки из многих. Кадр `s44` печатал
   последний абзац и подпись поверх строки источника: шесть абзацев — это
   0,58" неучтённого, больше двух строк. Отсюда `runs_h` как ЕДИНСТВЕННОЕ
   место, где отбивка входит в меру.

СОВМЕСТИМОСТЬ С МЕРОЙ lec-06. Проверено численно (`selftest.py`, проба
`[мера-06]`): на ОДНОРОДНОМ тексте — одно начертание, один кегль — `est_h`
и `n_lines` этого модуля дают РОВНО те же числа, что `_est_height` и
`n_lines` в `build_lec06_p1.py`. Мера lec-07 — строгое надмножество меры
lec-06, а не другая мера, и поэтому общее ядро не сдвигает геометрию
доставленной деки Лекции 6.

ЧТО ЗДЕСЬ ВСЁ ЕЩЁ ПРИБЛИЖЕНИЕ — перечень в `README.md`, раздел «Что всё ещё
приближение». Он не декоративный: `LH`, `SAFE`, `W_SAFE` и линейность по
кеглю — выверенные по рендеру числа, а не метрики шрифта, и подменять
выверенное «настоящим» нельзя.
"""
import re
from pathlib import Path

from PIL import ImageFont

from . import report

_TTF_DIR = Path("/home/harness/.local/libreoffice-portable/share/fonts/truetype")
_TTF = {
    (False, False): _TTF_DIR / "LiberationSans-Regular.ttf",
    (True, False): _TTF_DIR / "LiberationSans-Bold.ttf",
    (False, True): _TTF_DIR / "LiberationSans-Italic.ttf",
    (True, True): _TTF_DIR / "LiberationSans-BoldItalic.ttf",
}
_PPEM = 200        # кегль чтения файла; ширина линейна по кеглю, см. `_unit_w`
_FCACHE = {}
_UNIT = {}         # (полужирный, курсив, строка) → ширина на ОДИН пункт кегля
_FONT_GAP = {}     # начертание → чем подменено, когда своего файла нет

LH = 1.19          # высота строки LibreOffice, в кеглях. НЕ метрика шрифта:
                   # сам файл заявляет 1,1499 (hhea: 1854+434+67 на 2048), а
                   # 1,19 выверено по рендеру. Подменять выверенное
                   # «настоящим» нельзя — строки раскладывает LibreOffice
                   # своим правилом, а не таблицей шрифта.
SAFE = 1.04        # запас по высоте на расхождение разметки с измерением
W_SAFE = 0.97      # запас по ширине: на пограничной строке метрика и
                   # LibreOffice расходятся ровно на строку


def _font(bold, italic):
    """Файл начертания. Отсутствующий файл НЕ подменяется молча ни соседним
    начертанием, ни коэффициентом: подмена записывается в `_FONT_GAP` и
    выходит из сборки блокирующим `[шрифт]`. Задокументированный пробел
    лучше молчаливой оценки."""
    key = (bold, italic)
    if key not in _FCACHE:
        p = _TTF[key]
        if not p.exists():
            alt = _TTF[(bold, False)]
            if not alt.exists():
                alt = _TTF[(False, False)]
            _FONT_GAP[key] = (p.name, alt.name)
            p = alt
        _FCACHE[key] = ImageFont.truetype(str(p), _PPEM)
    return _FCACHE[key]


def font_gaps():
    """[шрифт] — мера шла по подменённому начертанию. Зовётся из сборки, то
    есть попадает в отчёт КАЖДОГО прогона, а не остаётся внутренним флагом."""
    for (bold, italic), (want, got) in sorted(_FONT_GAP.items()):
        report.warn(
            f"[шрифт] начертания «{want}» на машине нет — мера шла по "
            f"«{got}». Ширина курсива и полужирного отличается от прямого по "
            "словам до 6%, то есть ВСЯ мера высоты и ширины этого начертания "
            "недоказана: это пробел, а не оценка")


def _unit_w(text, bold, italic):
    """Ширина строки в пунктах НА ОДИН ПУНКТ КЕГЛЯ.

    Кеш не зависит от кегля, и это не мелочь: `fit_size` перебирает до
    восемнадцати кеглей, `fit_runs` — до двадцати двух масштабов, и каждый
    перебор меряет ТЕ ЖЕ строки. Ключ без кегля превращает перебор в
    арифметику по готовому числу."""
    key = (bold, italic, text)
    v = _UNIT.get(key)
    if v is None:
        v = _UNIT[key] = _font(bold, italic).getlength(text) / _PPEM
    return v


def text_w(text, size, bold=False, italic=False):
    """Ширина строки в пунктах по НАСТОЯЩИМ метрикам своего начертания."""
    return _unit_w(text, bold, italic) * size


# ── смешанный набор: мера по кускам, а не по абзацу целиком ──────────
# Кусок — `(текст, кегль, полужирный, курсив)`.


def _tokens(pieces):
    """Абзац → слова, каждое со своими начертаниями.

    Слово — СПИСОК кусков, а не строка: граница начертания проходит и посреди
    слова (`*курсив*ное`), а перенос по такой границе не идёт."""
    out, cur = [], []
    for text, size, bd, it in pieces:
        for part in re.split(r"(\s+)", text):
            if not part:
                continue
            if part.isspace():
                if cur:
                    out.append(cur)
                    cur = []
            else:
                cur.append((part, size, bd, it))
    if cur:
        out.append(cur)
    return out


def _pieces_w(pieces):
    """Ширина строки из кусков. Соседние куски ОДНОГО начертания сначала
    склеиваются и меряются одной строкой — иначе однородный абзац мерился бы
    по словам и расходился с мерой строки целиком на пробелах и кернинге.
    Склейка держит это свойство: на однородном абзаце мера даёт ровно то же
    число, что мера по плоской строке, и вся разница приходится на
    смешанные."""
    out = []
    for t, z, b, i in pieces:
        if out and out[-1][1:] == (z, b, i):
            out[-1] = (out[-1][0] + t, z, b, i)
        else:
            out.append((t, z, b, i))
    return sum(text_w(t, z, b, i) for t, z, b, i in out)


def wrap_pieces(pieces, w_in):
    """Жадный перенос по пробелам настоящими метриками КАЖДОГО начертания.
    Возвращает строки — списки кусков. Одно место на всю деку, где решается
    «сколько строк займёт», и потому одно, которое надо держать верным."""
    maxw = w_in * 72.0
    words = _tokens(pieces)
    if not words:
        return []
    lines, cur = [], list(words[0])
    for wd in words[1:]:
        space = (" ",) + cur[-1][1:]       # пробел набран начертанием слева
        cand = cur + [space] + list(wd)
        if _pieces_w(cand) <= maxw:
            cur = cand
        else:
            lines.append(cur)
            cur = list(wd)
    lines.append(cur)
    return lines


def segs_h(pieces, w_in, ls=1.18):
    """Высота ОДНОГО абзаца смешанного набора в дюймах. Высота строки берётся
    по крупнейшему кеглю на ЭТОЙ строке, а не по крупнейшему в абзаце."""
    if w_in <= 0:
        return 0.0
    lines = wrap_pieces(pieces, w_in)
    if not lines:                           # пустой абзац занимает свою строку
        return max([p[1] for p in pieces], default=16.0) * ls * LH / 72.0 * SAFE
    return (sum(max(p[1] for p in ln) for ln in lines)
            * ls * LH / 72.0 * SAFE)


def _longest_word_w(pieces):
    """Ширина самого длинного неразрывного слова абзаца — со своими
    начертаниями, включая слово, пересекающее границу начертания."""
    return max((_pieces_w(wd) for wd in _tokens(pieces)), default=0.0)


def longest_word_w(text, size, bold=False, italic=False):
    """Ширина самого длинного неразрывного куска: перенос идёт по пробелам,
    и слово шире места LibreOffice рвёт посреди корня."""
    return _longest_word_w([(text, size, bold, italic)])


def n_lines(text, size, w_in, bold=False, italic=False):
    """Сколько строк займёт однородный абзац в рамке шириной `w_in` дюймов.

    Та же подпись и то же число, что у `build_lec06_p1.n_lines` — модуль
    `tables.py`, перенесённый из lec-06, зовёт именно её."""
    return len(wrap_pieces([(text, size, bold, italic)], w_in)) or 1


def est_h(text, size, w_in, ls=1.18, bold=False, italic=False):
    """Высота однородного текстового блока в дюймах. `\\n` — разрыв абзаца.

    То же число, что у `build_lec06_p1._est_height` при тех же аргументах."""
    if w_in <= 0:
        return 0.0
    return sum(segs_h([(p, size, bold, italic)], w_in, ls)
               for p in text.split("\n"))


def check_width_segs(pieces, w_in, tag):
    """[ширина] — слово шире рамки. Проверка отдельная от высоты: высокий
    блок ужимается кеглем, а слово, которое не влезает по ширине, кеглем
    почти не лечится и рвётся на экране посреди корня."""
    words = _tokens(pieces)
    if not words:
        return True
    wd = max(words, key=_pieces_w)
    lw = _pieces_w(wd) / 72.0
    if lw > w_in * W_SAFE:
        flat = "".join(t for t, *_ in pieces)
        report.warn(
            f"[ширина] {tag}: слово шире рамки — {lw:.2f}\" против "
            f"{w_in:.2f}\" при кегле {max(p[1] for p in wd):.1f}  "
            f"«{flat[:40]}…»")
        return False
    return True


def check_width(text, size, w_in, tag, bold=False, italic=False):
    return check_width_segs([(text, size, bold, italic)], w_in, tag)


def fit_size(text, w, h, *, hi=17.0, lo=11.5, floor=8.5, ls=1.18,
             bold=False, italic=False, tag=""):
    """Крупнейший кегль, при котором текст укладывается в рамку w × h.

    Два разных исхода и два разных предупреждения. Не влезло даже на полу —
    `[высота]`: текст физически наедет сам на себя. Влезло, но ниже рабочего
    предела — `[кегль]`: блок набран на дне лестницы, и это предел плотности
    кадра, а не раскладки.

    Расхождение с lec-06 здесь ОДНО и только в тексте предупреждения: тот
    сборщик на обоих исходах писал `[кегль]`, не отличая «набрано мелко» от
    «не влезает вовсе». ВОЗВРАЩАЕМЫЙ КЕГЛЬ при любом входе один и тот же
    (проверено пробой `[кегль-06]`), поэтому геометрия доставленной деки
    Лекции 6 от этой правки не двинулась."""
    f = round(hi * 2) / 2
    while f >= floor:
        if est_h(text, f, w, ls, bold, italic) <= h:
            if f < lo:
                report.warn(
                    f"[кегль] {tag}: тело ужалось до {f:.1f} пт "
                    f"(рабочий предел {lo:.1f}) — предел плотности кадра")
            return f
        f -= 0.5
    report.warn(
        f"[высота] {tag}: не укладывается даже при {floor:.1f} пт — "
        f"{est_h(text, floor, w, ls, bold, italic):.2f}\" против {h:.2f}\"")
    return floor


# ── прогоны: абзацы, отбивка, масштаб ───────────────────────────────


def runs_paras(runs):
    """Прогоны → абзацы `(куски, отбивка сверху в пунктах)` ровно так, как их
    потом сложит `prims.text_runs`. Отдельная функция нужна затем, чтобы
    высоту считала и подбирала кегль одна и та же арифметика.

    Абзац отдаётся СПИСКОМ кусков, а не одной строкой с усреднённым
    начертанием: усреднить начертания значит потерять ровно то, из-за чего
    мера и расходится с рендером.

    Отбивка (`space_before`) идёт вторым полем, потому что её ставит тот же
    словарь прогона, что и кегль, — и считаться она обязана там же, где
    считается кегль, а не поправкой у вызывающего."""
    paras, cur, sb, started = [], [], 0.0, False
    for c in runs:
        if c.get("newpara"):
            if started:
                paras.append((cur, sb))
                cur, sb = [], 0.0
            sb = max(sb, float(c.get("space_before") or 0.0))
        started = True
        # Пустой прогон-разделитель кладётся тоже: текста он не несёт, но
        # несёт кегль своего абзаца — им мерится абзац, оставшийся без слов.
        cur.append((c["text"], float(c.get("size", 16)),
                    bool(c.get("bold")), bool(c.get("italic"))))
    paras.append((cur, sb))
    return paras


def runs_h(runs, w, ls=1.18):
    """Высота прогона в дюймах — ВКЛЮЧАЯ отбивку между абзацами.

    ЕДИНСТВЕННОЕ место, где абзацный отступ входит в меру, и потому
    единственное, которое надо держать верным. `est_h` его не считает и
    считать не может: она меряет плоскую строку и о разрывах абзаца ничего
    не знает, а `space_before` живёт в словаре прогона — то есть ровно здесь.

    Отбивка НЕ масштабируется вместе с кеглем: `text_runs` пишет `Pt(…)`
    литералом. Поэтому кадр, перебравший рамку на одну отбивку, ужиманием
    кегля уже не спасается — и правильно, что не спасается: лечить это надо
    текстом, а не кеглем."""
    return sum(segs_h(pieces, w, ls) + sb / 72.0
               for pieces, sb in runs_paras(runs))


def fit_runs(runs, w, h, *, hi=1.0, lo=0.72, floor=0.58, ls=1.26, tag=""):
    """Крупнейший МАСШТАБ кеглей прогона, при котором он укладывается в
    рамку. Масштаб, а не кегль: внутри прогона кегли разные — заголовок
    блока, тело, подпись, — и сбивать их в один нельзя, иначе иерархия
    кадра исчезает.

    Правит `runs` на месте — это и есть результат: вызывающий потом отдаёт
    те же словари в `text_runs`."""
    k = hi
    base = [r.get("size", 15.0) for r in runs]
    while k >= floor - 1e-9:
        for r, b0 in zip(runs, base):
            r["size"] = max(8.5, round(b0 * k, 1))
        if runs_h(runs, w, ls) <= h:
            # Допуск на ошибку представления: шаг −0,02 в двоичной дроби не
            # точен, и на номинальном пределе k держит 0,7199999999999998.
            # Без допуска прогон, уложившийся РОВНО на заявленном пределе,
            # объявлялся «пределом плотности кадра».
            if k < lo - 1e-9:
                report.warn(
                    f"[кегль] {tag}: прогон ужат до {k:.2f} от рабочего "
                    f"кегля — предел плотности кадра")
            return k
        k -= 0.02
    for r, b0 in zip(runs, base):
        r["size"] = max(8.5, round(b0 * floor, 1))
    report.warn(
        f"[высота] {tag}: не укладывается даже при масштабе {floor:.2f} — "
        f"{runs_h(runs, w, ls):.2f}\" против {h:.2f}\"")
    return floor

#!/usr/bin/env python3
"""Мостик к Семинару 9 — развилка на месте одной дороги (n57, issue #292).

    mostik-s9-razvilka.png   две строки одной ширины: СЕГОДНЯ — любая заявка
                             идёт одним путём; ДАЛЬШЕ — тот же вход попадает
                             на шаг, который смотрит на тему, и расходится
                             тремя путями, третий из которых — по умолчанию.

── Зачем фигура и что она заменила ─────────────────────────────────────────

Волна 2б «конфетки» (план `qa/PLAN-KONFETKA-INSTRUKTSII-2026-10-22.md`
§4.13): на n57 стоял текстовый бокс «Сейчас / Дальше», внутри которого
развилка была НАПИСАНА словами со стрелками-символами — «вход типа А → один
путь · вход типа Б → другой · вход, не подошедший ни под один тип → свой
путь по умолчанию». Три пути в одну строку текста читаются как перечисление,
а не как ветвление: именно та разница, ради которой следующее занятие
существует, на экране не показана вовсе. Плюс бокс был золотым и стоял
рядом со второй золотой планкой («Семинар 9: …») — два акцента на экране
при одном допустимом (§3.8 плана).

Фигура снимает и то и другое: ветвление видно формой, а золото остаётся
одной планке под схемой.

── Почему именно так нарисовано ────────────────────────────────────────────

* ДВЕ строки, а не одна схема с пунктирной накладкой. План §4.13 допускал
  «развилку пунктиром поверх бледной текущей схемы», но наложение одного
  графа на другой читается как один сложный граф: студент не знает, какие
  линии «сегодня», а какие «дальше». Две строки одинаковой ширины с общим
  левым краем сравниваются взглядом сразу (§3.4 плана, одна сетка).
* Верхняя строка ПРИГЛУШЕНА (серые рамки, серый текст, серые стрелки) —
  это снимок пройденного, а не предмет разговора.
* ТЕМА — не новый термин: поле `topic` выделено ещё на Семинаре 7 и названо
  в заметке n57 («тема заявки у нас уже выделена отдельным полем ещё с
  прошлого занятия»). Поэтому узел развилки подписан «смотрит на тему
  заявки», а не «классификатор»: слово из речи, а не из нашего словаря.
* Третья ветка — ПУНКТИР и серый, а не красный: вход, не подошедший ни под
  одну ветку, не ошибка и не провал, это штатный случай, у которого есть
  ответ по умолчанию. Красным он читался бы как сбой.
* Золото на схеме — ОДНО, на узле развилки: это та самая точка, которой
  сегодня нет и ради которой есть следующее занятие.
* Подписи веток названы заявками, которые зал уже видел в Кейсе 2
  («про оплату», «про перенос занятия»), а не абстрактными «тип А / тип Б»:
  заметка n57 приводит ровно эту пару.

Пропорция холста — 1380×560 (2,46). Полоса содержания слайда 12,23″ × 5,90″;
под схемой остаётся одна текстовая планка, то есть схеме достаётся около
4,3″ высоты, и при 2,46 она берёт всю ширину полосы (12,23 ≤ 4,3 × 2,46),
то есть не ловит `СХЕМА ЗАЖАТА` (порог 80% ширины). Первая редакция была
1600×600 — на ней правый край холста оставался пустым на 270 px, потому что
содержание кончалось раньше; размер подогнан по фактическому правому краю
веток, а не задан наперёд.

Запуск: `python3 make_figures_n57.py` (из `rendered/`).
"""
import sys as _sys
from pathlib import Path as _Path
_sys.path.insert(0, str(_Path(__file__).resolve().parents[4] / "tools" / "seminar-build"))

from fig_toolkit import *          # noqa: F401,F403

CW, CH = 1380, 560

PALE_STROKE = (0xB8, 0xC3, 0xD0)   # рамка пройденного: светлее GREY_FILL
PALE_TX = (0x8B, 0x9A, 0xAD)       # = DIMTX, подпись пройденного


def card(d, x, y, w, h, top, bottom, *, stroke, fill, tcol, bcol,
         tsz=23, bsz=16, where="?"):
    """Узел схемы: рамка, крупная строка, подпись под ней."""
    d.rounded_rectangle([x, y, x + w, y + h], radius=14, fill=fill,
                        outline=stroke, width=3)
    ft, fb = f(tsz, True), f(bsz)
    lim = w - 36
    fit(d, top, ft, lim, f"{where} · верх")
    th = tsz + bsz + 9 if bottom else tsz
    ty = y + (h - th) / 2
    d.text((x + (w - d.textlength(top, font=ft)) / 2, ty), top, font=ft, fill=tcol)
    if bottom:
        fit(d, bottom, fb, lim, f"{where} · низ")
        d.text((x + (w - d.textlength(bottom, font=fb)) / 2, ty + tsz + 9),
               bottom, font=fb, fill=bcol)


def razvilka():
    im = Image.new("RGB", (CW, CH), W)
    d = ImageDraw.Draw(im)

    L = 200                     # левый край карточек: слева стоят ярлыки строк
    LBL = 108                   # центр ярлыка строки

    # ── строка 1: сегодня ───────────────────────────────────────────────
    y1, BH1, BW1, GAP1 = 46, 92, 340, 55
    clabel(d, LBL, y1 + BH1 / 2 - 14, "Сегодня", 22, PALE_TX, True,
           where="ярлык строки 1", limit=180)
    xs = [L + i * (BW1 + GAP1) for i in range(3)]
    for x, (t, b, where) in zip(xs, (
            ("Любая заявка", "про что угодно", "сегодня · вход"),
            ("Одна цепочка", "одни и те же шаги", "сегодня · цепочка"),
            ("Один выход", "для всех одинаковый", "сегодня · выход"))):
        card(d, x, y1, BW1, BH1, t, b, stroke=PALE_STROKE, fill=W,
             tcol=PALE_TX, bcol=PALE_TX, where=where)
    for a, b in zip(xs, xs[1:]):
        arrow(d, a + BW1 + 8, y1 + BH1 / 2, b - 10, y1 + BH1 / 2,
              col=PALE_STROKE, wd=4, head=13)

    # разделительная линия между пройденным и следующим занятием
    d.line([40, 182, CW - 40, 182], fill=SOFT_GREY, width=3)

    # ── строка 2: дальше ────────────────────────────────────────────────
    cy = 370                    # общая ось строки
    BWI, BHI = 290, 86          # карточка входа
    BWF, FH = 330, 150          # узел развилки
    BW3, BH3, BR_GAP = 330, 84, 20

    x_in = L
    x_fork = x_in + BWI + 54
    x_br = x_fork + BWF + 126

    clabel(d, LBL, cy - 14, "Дальше", 22, GOLDINK, True,
           where="ярлык строки 2", limit=180)

    card(d, x_in, cy - BHI / 2, BWI, BHI, "Заявка", "тема уже выделена",
         stroke=LIGHT, fill=SURF, tcol=DEEP, bcol=MUTE, where="дальше · вход")
    arrow(d, x_in + BWI + 8, cy, x_fork - 10, cy, col=MID, wd=5)

    # узел развилки — единственное золото на схеме
    d.rounded_rectangle([x_fork, cy - FH / 2, x_fork + BWF, cy + FH / 2],
                        radius=14, fill=WARM, outline=GOLD, width=4)
    clabel(d, x_fork + BWF / 2, cy - 44, "Развилка", 24, GOLDINK, True,
           where="развилка · верх", limit=BWF - 36)
    clabel(d, x_fork + BWF / 2, cy - 12, "смотрит на тему заявки", 17, GOLDINK,
           where="развилка · низ 1", limit=BWF - 36)
    clabel(d, x_fork + BWF / 2, cy + 16, "и выбирает, куда её отправить", 17,
           GOLDINK, where="развилка · низ 2", limit=BWF - 36)

    # Ствол рисуется ОДИН раз и первым. Прежняя редакция вела его заново из
    # каждой ветки, и пунктирная серая третья, рисуясь последней, затирала
    # обе сплошные: на экране ствол выходил бледным. Замерено на снимке,
    # а не рассуждением.
    tops = [cy - 1.5 * BH3 - BR_GAP, cy - BH3 / 2, cy + BH3 / 2 + BR_GAP]
    x0 = x_fork + BWF + 6
    x_t = x0 + 54               # вертикаль ствола
    d.line([x0, cy, x_t, cy], fill=MID, width=5)
    d.line([x_t, tops[0] + BH3 / 2, x_t, tops[1] + BH3 / 2], fill=MID, width=5)
    d.line([x_t, tops[1] + BH3 / 2, x_t, tops[2] + BH3 / 2],
           fill=MUTE, width=4)

    # Третья ветка набрана MUTE, а не PALE_STROKE цвета верхней строки:
    # пунктир уже говорит «это не названная ветка», и добавлять к нему ещё и
    # бледность значило бы спрятать ровно то, ради чего ветка на схеме стоит
    # (заметка n57: «ответ по умолчанию… не всегда тот, что вы ожидаете»).
    # Замерено на снимке первой редакции: PALE_STROKE на белом читался хуже
    # всего остального на экране.
    branches = (
        ("Про оплату", "свой путь", LIGHT, SURF, DEEP, MUTE, False),
        ("Про перенос занятия", "другой путь", LIGHT, SURF, DEEP, MUTE, False),
        ("Ни под одну ветку", "путь по умолчанию", MUTE, W,
         GREY_TX, MUTE, True),
    )
    for top_y, (t, b, stroke, fill, tc, bc, dashed) in zip(tops, branches):
        ycen = top_y + BH3 / 2
        arrow(d, x_t, ycen, x_br - 10, ycen,
              col=MUTE if dashed else MID,
              wd=4 if dashed else 5, head=15, dash=dashed)
        card(d, x_br, top_y, BW3, BH3, t, b, stroke=stroke, fill=fill,
             tcol=tc, bcol=bc, tsz=21, bsz=16, where=f"ветка «{t}»")

    save(im, "mostik-s9-razvilka.png")


def main():
    import sys
    if "--lang" in sys.argv:
        set_lang(sys.argv[sys.argv.index("--lang") + 1])
    razvilka()
    report()


if __name__ == "__main__":
    main()

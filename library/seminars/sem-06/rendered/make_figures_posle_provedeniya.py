#!/usr/bin/env python3
"""Схемы круга правок после проведения занятия — `subagent-n49a-tri-yarusa.png`.

Отдельный файл, а не дописка в `make_figures_subagent.py`, по той же причине,
по которой новым слайдам этого круга дан временный буквенный номер: над декой
одновременно работают три сессии, и правка общего файла рисовалок означала бы
конфликт там, где его можно не создавать. Содержательной границы у файла одна
— схемы, появившиеся после проведения (`qa/RAZBOR-PROVEDENIYA.md` §B).

Холст и калибр — те же, что у остальных схем занятия (`make_figures_subagent.py`
преамбула): 1600 px = 12,23″ рабочей ширины слайда, то есть ≈131 px на дюйм,
«20 px ≈ 11 pt». Высота взята МЕНЬШЕ потолка `deck_kit.FIG_NATURAL_H` (4,3″ ≈
562 px) намеренно: на слайде кроме схемы стоят таблица на три строки и строка
критерия, и схема во всю разрешённую высоту вытеснила бы их за нижнее поле.
300 px ≈ 2,29″ — измерено по остатку: заголовок ≈1,2″, таблица ≈2,2″, строка
критерия ≈0,5″ при рабочем поле 6,58″. Первая версия полотна была на 360 px, и
сборщик ужимал её по высоте до ≈1,7″, то есть вместе с полотном мельчал и весь
текст на нём; 300 px сборщик берёт почти без сжатия, и кегль остаётся тем, что
задан здесь.

Самый мелкий текст на полотне — 19 px → 19 × 72/131 ≈ 10,4 pt, выше порога
деки 7,5 pt (`deck_kit.py`, `M.floor_reached`). Красного нет (CLAUDE.md);
золото держит рамка яруса оркестратора — одного раза на полотне достаточно.

    python3 make_figures_posle_provedeniya.py
"""
from fig_toolkit import *

MW, MH = 1600, 300

im = Image.new("RGB", (MW, MH), W)
d = ImageDraw.Draw(im)

# ── Четыре фигуры в один ряд: ваша сессия → оркестратор → дочерние → субагенты
#
# Ряд, а не стопка: ярусов три, и читаются они как глубина слева направо —
# та же грамматика, что у схемы «где что стоит» этого занятия (n08), где
# машина, сервер и внешняя система тоже стоят в ряд.
ROW_Y, ROW_H = 74, 100
XS = (20, 400, 790, 1210)
WS = (330, 330, 330, 370)

box(d, XS[0], ROW_Y, WS[0], ROW_H, ["Ваша рабочая", "сессия"], SURF, INK, sz=25,
    outline=LIGHT, where="n49a/вы")
box(d, XS[1], ROW_Y, WS[1], ROW_H, ["Сессия-оркестратор"], W, DEEP, sz=25,
    outline=GOLD, where="n49a/оркестратор")

# Дочерние сессии — три карточки веером, чтобы было видно, что их несколько.
for k in range(3):
    off = k * 13
    box(d, XS[2] + off, ROW_Y - 16 + off, WS[2] - 26, ROW_H - 16,
        ["Дочерняя сессия"] if k == 2 else [""], MID if k == 2 else PALE,
        W if k == 2 else PALE, sz=24, outline=LIGHT, where="n49a/дочерняя")

# Субагенты — пунктиром: от них приходит итог, зайти внутрь нельзя.
for k in range(3):
    dashbox(d, XS[3], ROW_Y - 12 + k * 44, WS[3] - 20, 36, GHOST, bg=W)
    clabel(d, XS[3] + (WS[3] - 20) / 2, ROW_Y - 4 + k * 44, "субагент", 20,
           GHOST, where="n49a/субагент", limit=WS[3] - 60)

for a in range(3):
    x1 = XS[a] + WS[a] - (0 if a != 2 else -14)
    arrow(d, x1 + 8, ROW_Y + ROW_H / 2, XS[a + 1] - 10, ROW_Y + ROW_H / 2,
          col=MID if a < 2 else GHOST, dash=(a == 2))

# ── Ярлыки ярусов над рядом ────────────────────────────────────────────────
for x, w_, t_ in ((XS[1], WS[1], "ярус 1"), (XS[2], WS[2], "ярус 2"),
                  (XS[3], WS[3] - 20, "ярус 3")):
    clabel(d, x + w_ / 2, 36, t_, 19, MUTE, b=True, where="n49a/ярус")

# ── Подписи под рядом: чем ярусы различаются ───────────────────────────────
BY = ROW_Y + ROW_H + 34
chipw = 300
d.rounded_rectangle([XS[2], BY, XS[2] + chipw, BY + 38], radius=10,
                    fill=(0xE4, 0xF1, 0xF3), outline=TEAL, width=2)
clabel(d, XS[2] + chipw / 2, BY + 8, "можно зайти руками", 20, TEAL, b=True,
       where="n49a/чип1", limit=chipw - 24)
d.rounded_rectangle([XS[3], BY, XS[3] + chipw, BY + 38], radius=10,
                    fill=SOFT_GREY, outline=GREY_TX, width=2)
clabel(d, XS[3] + chipw / 2, BY + 8, "только итог", 20, GREY_TX, b=True,
       where="n49a/чип2", limit=chipw - 24)

CAP = ("Так работает автор курса. Дочерние сессии — полноценные, со своим "
       "контекстом; каждая дробит свою часть дальше сама.")
fo = f(20)
for i, ln in enumerate(wrap(d, CAP, fo, MW - 80)):
    d.text((40, BY + 52 + i * 27), ln, font=fo, fill=MUTE)

save(im, "subagent-n49a-tri-yarusa.png")
report()

"""РАЗНОСТНЫЕ ПРОБЫ НА РАСКЛАДКУ ТЕЛА: обтекание, лестница кеглей, пол
проекции.

Все пробы здесь — ПАРНЫЕ, и это не стиль, а необходимость. Файловая проба
отвечает на вопрос «предупреждение вышло?»; ни одна из трёх проверок этого
круга таким вопросом не измеряется:

  [ступень]              кегли легли на пол-пунктовую сетку — а без неё
                         ложились мимо, и ровно на столько-то прогонов
  [обтекание]            обтекание КУПИЛО кегль, и вот сколько
  [обтекание-отказ]      обтекание стоило бы кегля — и отвергнуто
  [обтекание-вниз]       вырожденный случай: рядом со снимком не влезает ни
                         один блок — тело уходит ПОД него; взято, когда
                         покупает кегль, отвергнуто, когда стоило бы его
  [обтекание-возврат]    отказ вернул кегли нетронутыми: не вернув их, он
                         ронял тело на дно лестницы молча
  [обтекание-геометрия]  отказ не двигает ни одного EMU (отпечатком, который
                         ловит сдвиг на 1 EMU)
  [проекция-выключено]   пол проекции молчит, пока дека не назвала свой
                         кегль тела, — то есть сработало именно это, а не
                         любое предупреждение с тем же тегом

Запускается из `selftest.py`; отдельного входа у файла нет нарочно —
самопроверка ядра одна.
"""
from . import metrics, probes_layout, regress, report, selftest_floor, wrap


def _sizes(runs):
    return [r.get("size") for r in runs]


def _body_runs(blocks, per=3):
    """Прогон тела ровно той склейки, какой его строят деки: блок, перед ним
    пустой прогон-разделитель с отбивкой. Собирается здесь, а не читается из
    файла, потому что мерить надо САМУ подгонку, без раскладки вокруг."""
    runs, first = [], True
    for _ in range(blocks):
        if not first:
            runs.append({"text": "", "size": 15.0, "newpara": True,
                         "space_before": 7})
        first = False
        runs.append({"text": probes_layout.BRICK * per, "size": 15.0})
    return runs


def probe_grid(ok, bad, say):
    """Ступень лестницы делает именно ступень.

    Тот же прогон подгоняется дважды — со ступенью 0,5 пт и без неё. Со
    ступенью все кегли обязаны лечь на сетку, без неё — обязан найтись хоть
    один мимо: проба, в которой и так все попадают, ничего бы не доказала."""
    off, on = [], []
    for blocks in range(2, 9):
        for dst, grid in ((on, metrics.GRID_PT), (off, 0.0)):
            runs = _body_runs(blocks)
            report.reset()
            metrics.fit_runs(runs, 7.51, 5.36, grid=grid, tag="проба")
            dst.extend(_sizes(runs))
    bad_on = [s for s in on if abs(round(s * 2) / 2 - s) > 1e-9]
    bad_off = [s for s in off if abs(round(s * 2) / 2 - s) > 1e-9]
    if bad_on or not bad_off:
        bad.append(f"[ступень] со ступенью мимо сетки {len(bad_on)}, без неё "
                   f"{len(bad_off)} — проба ловит не ступень")
    else:
        ok.append("[ступень]")
        say(f"{'[ступень]':<24} лестница кеглей: ЛОВИТ  →  со ступенью мимо "
            f"сетки 0 из {len(on)} кеглей, без неё {len(bad_off)} из "
            f"{len(off)}; различных кеглей {len(set(on))} против "
            f"{len(set(off))}")


def _fit(blocks, per, w_top, h_top, w_bot, h_bot, w_pl, h_pl):
    runs = _body_runs(blocks, per)
    report.reset()
    res = wrap.fit_runs_wrap(runs, w_top, h_top, w_bot, h_bot, w_pl, h_pl,
                             tag="проба")
    plain = _body_runs(blocks, per)
    metrics.fit_runs(plain, w_pl, h_pl, tag="проба")
    return res, _sizes(runs), _sizes(plain)


def probe_wrap_gain(ok, bad, say):
    """Обтекание покупает кегль — и проба говорит, сколько.

    Геометрия взята та же, что даёт широкий снимок на содержательном кадре:
    рядом со снимком 7,51×2,97", под ним 12,15×2,29", а без обтекания одна
    узкая рамка 7,51×5,36"."""
    res, got, plain = _fit(5, 3, 7.51, 2.967, 12.15, 2.29, 7.51, 5.36)
    if not res or max(got) <= max(plain):
        bad.append(f"[обтекание] обтекание дало {res and max(got)} против "
                   f"{max(plain)} одной надписью — выигрыша нет")
    else:
        ok.append("[обтекание]")
        say(f"{'[обтекание]':<24} возврат ширины под снимком: ЛОВИТ  →  "
            f"{max(plain):.1f} пт одной узкой надписью против "
            f"{max(got):.1f} пт двумя, разрез по границе блока "
            f"{res[1]}, строк сверху {len(res[2])} и снизу {len(res[3])} "
            "прогонов")


def probe_wrap_refuse(ok, bad, say):
    """Обтекание, которое стоило бы кегля, отвергнуто — И отвергнуто именно
    сравнением с обычной раскладкой.

    Доказывается двумя сборками одного входа: с настоящей узкой рамкой
    (обтекание обязано отказаться) и с заведомо негодной рамкой нулевой
    высоты, в которой обычной раскладки просто нет (обтекание обязано
    согласиться — и дать тот самый кегль, мельче которого оно отказалось).
    Без второй половины «отказ» был бы неотличим от «не сложилось»."""
    res_real, _, plain = _fit(3, 3, 7.51, 2.967, 12.15, 2.29, 7.51, 5.36)
    res_free, got_free, _ = _fit(3, 3, 7.51, 2.967, 12.15, 2.29, 7.51, 0.0)
    if res_real is not None or res_free is None \
            or max(got_free) >= max(plain):
        bad.append(f"[обтекание-отказ] с рамкой {res_real}, без рамки "
                   f"{res_free} — сравнение с обычной раскладкой не работает")
    else:
        ok.append("[обтекание-отказ]")
        say(f"{'[обтекание-отказ]':<24} обтекание не платит кеглем: ЛОВИТ  "
            f"→  одной надписью {max(plain):.1f} пт, обтеканием было бы "
            f"{max(got_free):.1f} — отвергнуто")


def probe_wrap_pushed(ok, bad, say):
    """Тело уходит ПОД снимок — и уходит только за кегль.

    Две половины одного утверждения, на одном и том же теле. Первая: под
    снимком просторно (12,15×2,29" против узких 7,51×2,40") — обмен выигран,
    кегль вырос. Вторая: под снимком тесно (12,15×1,30" против 7,51×2,61") —
    ширина не окупает высоту, и обмен обязан быть отвергнут. Без второй
    половины «взято» было бы неотличимо от «берётся всегда».

    Так же устроен и живой отказ: на `s55` Лекции 7 узкая рамка даёт
    7,51×2,61" и 13,0 пт, а уход под снимок — 12,15×2,29" и 12,5 пт, то
    есть мёртвое белое под снимком там снимается не бесплатно, и сборка это
    ЗАМЕРИЛА, а не прошла мимо."""
    out = {}
    for name, h_push, h_plain in (("выигрыш", 2.29, 2.40),
                                  ("проигрыш", 1.30, 2.61)):
        runs = _body_runs(2)
        report.reset()
        k = wrap.fit_pushed(runs, 12.15, h_push, 7.51, h_plain, tag="проба")
        plain = _body_runs(2)
        metrics.fit_runs(plain, 7.51, h_plain, tag="проба")
        out[name] = (k, max(_sizes(runs)), max(_sizes(plain)))
    report.reset()
    win, loss = out["выигрыш"], out["проигрыш"]
    if not win[0] or win[1] <= win[2] or loss[0] is not None:
        bad.append(f"[обтекание-вниз] выигрыш {win}, проигрыш {loss} — "
                   "обмен берётся не по кеглю")
    else:
        ok.append("[обтекание-вниз]")
        say(f"{'[обтекание-вниз]':<24} тело под снимком: ЛОВИТ  →  в низкой "
            f"узкой рамке {win[2]:.1f} пт против {win[1]:.1f} под снимком — "
            f"взято; в рамке `s55` ({loss[2]:.1f} пт) обмен дал бы меньше — "
            "отвергнут")


def probe_wrap_restore(ok, bad, say):
    """Отказ возвращает кегли нетронутыми.

    Это та самая правка, цена которой уже измерена на живой деке: пока отказ
    оставлял прогон ужатым до пола, следом идущая `metrics.fit_runs` брала
    эти кегли ЗА ИСХОДНЫЕ и укладывала их при масштабе 1,00 — кадр `s55`
    Лекции 7 вышел бы 8,5 пт вместо 15,0, и ни одно предупреждение этого бы
    не назвало. Вход — тело в ОДИН блок: разделителей в прогоне нет, резать
    нечем, отказ гарантирован."""
    runs = _body_runs(1, 4)
    before = _sizes(runs)
    report.reset()
    res = wrap.fit_runs_wrap(runs, 7.51, 2.967, 12.15, 2.29, 7.51, 5.36,
                             tag="проба")
    after = _sizes(runs)
    report.reset()
    metrics.fit_runs(runs, 7.51, 5.36, tag="проба")
    final = _sizes(runs)
    if res is not None or after != before or max(final) < 15.0:
        bad.append(f"[обтекание-возврат] отказ {res}, кегли до {before[:1]} "
                   f"после {after[:1]}, итог {max(final)} — возврата нет")
    else:
        ok.append("[обтекание-возврат]")
        say(f"{'[обтекание-возврат]':<24} отказ не портит прогон: ЛОВИТ  →  "
            f"резать нечем, отказ; кегли вернулись {before[0]:.1f} пт, и "
            f"обычная подгонка дала {max(final):.1f} пт, а не дно лестницы "
            f"({metrics.grid_pt(15.0 * 0.58):.1f})")


def probe_wrap_geometry(ok, bad, say, run, tmp, seq):
    """Отказ не двигает НИ ОДНОГО EMU.

    Проверяется не словом, а отпечатком: тот же вход, собранный с включённым
    и выключенным обтеканием, обязан дать побитово ту же геометрию всех
    фигур. Отпечаток ловит сдвиг на один EMU (проба `[отпечаток]`), поэтому
    «расхождений 0» здесь — утверждение, а не отсутствие проверки. Вход —
    кадр, на котором ОБА обмена отвергнуты по кеглю: он и есть обещание
    «дека, которой обтекание не подошло, осталась ровно той же».
    Вторая половина — вход, на котором обтекание СРАБАТЫВАЕТ: там
    расхождений обязано быть много, иначе первая половина доказывала бы лишь
    то, что выключатель ни на что не влияет."""
    files = [("s95-loss.md", probes_layout.WRAP_LOSS)]
    gain = [("s94-gain.md", probes_layout.WRAP_GAIN)]
    res = {}
    for name, fs in (("loss", files), ("gain", gain)):
        for flag in (True, False):
            wrap.ENABLED = flag
            run(fs, tmp, seq, name=f"{name}-{flag}")
        wrap.ENABLED = True
        res[name] = regress.compare(
            regress.fingerprint(tmp / f"{name}-True.pptx"),
            regress.fingerprint(tmp / f"{name}-False.pptx"))
    if res["loss"] or not res["gain"]:
        bad.append(f"[обтекание-геометрия] на отказе расхождений "
                   f"{len(res['loss'])}, на сработавшем {len(res['gain'])} "
                   "— выключатель измеряет не то")
    else:
        ok.append("[обтекание-геометрия]")
        say(f"{'[обтекание-геометрия]':<24} отказ ничего не двигает: ЛОВИТ  "
            f"→  на кадре, где оба обмена отвергнуты, 0 расхождений "
            f"отпечатка, а на кадре, где обтекание сработало, "
            f"{len(res['gain'])}")


def probe_proj_switch(ok, bad, say):
    """Пол проекции молчит, пока дека не назвала свой кегль тела.

    Половина, без которой файловая проба `[проекция]` доказывала бы лишь то,
    что какое-то предупреждение с этим тегом выходит. Тот же прогон в той же
    рамке: с названным `proj_base` обязан сказать, без него — промолчать."""
    out = {}
    for name, base in (("назван", 15.0), ("не назван", None)):
        runs = _body_runs(6)
        report.reset()
        metrics.fit_runs(runs, 12.15, 5.36, tag="проба", proj_base=base)
        out[name] = [w for w in report.WARNINGS if w.startswith("[проекция]")]
    report.reset()
    if not out["назван"] or out["не назван"]:
        bad.append(f"[проекция-выключено] с названным кеглем "
                   f"{len(out['назван'])}, без него {len(out['не назван'])} "
                   "— проба ловит не пол проекции")
    else:
        ok.append("[проекция-выключено]")
        say(f"{'[проекция-выключено]':<24} проба на сам пол: ЛОВИТ  →  с "
            f"названным кеглем тела {len(out['назван'])} предупреждение, без "
            f"него {len(out['не назван'])}")


def run_all(ok, bad, say, run, tmp, seq):
    # Пробы круга #229 на пол видимого слоя, лестницу заголовка,
    # число-заголовок и две колонки зовутся отсюда, а не из `selftest.py`:
    # тот упёрся в предел 600 строк, а по смыслу это те же пробы на
    # РАСКЛАДКУ, что и здешние.
    selftest_floor.run_all(ok, bad, say, run, tmp, seq)
    probe_grid(ok, bad, say)
    probe_wrap_gain(ok, bad, say)
    probe_wrap_refuse(ok, bad, say)
    probe_wrap_pushed(ok, bad, say)
    probe_wrap_restore(ok, bad, say)
    probe_wrap_geometry(ok, bad, say, run, tmp, seq)
    probe_proj_switch(ok, bad, say)
    report.reset()

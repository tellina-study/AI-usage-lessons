# -*- coding: utf-8 -*-
"""ТЕЛО В ДВЕ КОЛОНКИ — для раскладки-ПРОГОНА (lec-07), по границе блока.

ЧТО ЭТО ЛЕЧИТ. Тело этой деки шло ОДНОЙ колонкой во всю ширину кадра:
12,23 дюйма, и самая длинная строка набиралась в 135 знаков. У Лекции 6,
которую читали залу, тело почти везде в две колонки, и самая длинная строка
— 49 знаков. Две следствия замерены на собранной деке, и оба видны залу:

* ПОЛУПУСТАЯ КОРОБКА. Текст, которому во всю ширину хватает трети высоты,
  оставляет две трети коробки мотива пустыми: 21 кадр Лекции 7 против
  ОДНОГО из ста у Лекции 6; худшие — 62%, 58%, 56%, 53% пустоты.
* ОДИНАКОВОСТЬ. Кадры одного типа, набранные одной сплошной колонкой,
  отличаются друг от друга только словами. Две колонки дают кадру рисунок,
  по которому зал отличает его от предыдущего, не читая.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ДВУХ УЖЕ ИМЕЮЩИХСЯ ДВУХКОЛОНОЧНЫХ ХОДОВ. Их в пакете
теперь три, и смешивать нельзя ни одну пару:

* `columns.py` — два СТОЛБЦА КАК СОДЕРЖАНИЕ («что получается / что не
  получается»), объявленные во фронтматтере. Утверждение кадра.
* `flow.two_columns` — разрез ПОТОКА (единица — блок со своей надписью,
  таблицы и цитаты). Решение о месте, но у другой раскладки тела.
* этот модуль — разрез ПРОГОНА (единица — абзац внутри одной надписи, кегли
  внутри разные и масштабируются вместе). Та же задача, что у `flow`, но у
  той раскладки тела, которой набрана вся дека Лекции 7.

ГДЕ РЕЖЕТСЯ. Там же, где режет обтекание (`wrap.cut_points`): по
прогону-РАЗДЕЛИТЕЛЮ между блоками. Это единственные законные места — разрез
посреди абзаца потерял бы его отбивку либо разорвал предложение между
колонками. Разрез сразу ПОСЛЕ подзаголовка запрещён отдельно: он оставляет
вопрос внизу левой колонки, а ответ — вверху правой (тот же запрет и по той
же причине, что `flow.cuts_of`).

КАКОЙ РАЗРЕЗ ВЫБИРАЕТСЯ. Самый РОВНЫЙ: тот, при котором высоты колонок
ближе всего друг к другу. Сумма высот от места разреза не зависит, поэтому
«колонки ровнее» и «высокая колонка ниже» — одно требование, а не два.

КОГДА ДВЕ КОЛОНКИ БЕРУТСЯ. Только если КЕГЛЬ ОТ НИХ НЕ ПАДАЕТ — ровно то же
условие и та же причина, что у `wrap.fit_runs_wrap`: при равном кегле две
колонки выигрывают (короткая строка и заполненная коробка), при меньшем —
проигрывают, потому что мелкий текст хуже длинной строки. Поиск поэтому
ограничен снизу масштабом обычной раскладки, и ограничен МОЛЧА: отказ не
дефект, кадр просто остаётся одноколоночным.

ЧЕГО ЗДЕСЬ НЕТ. Переноса абзаца через границу колонок (как в вёрстке) — у
надписи PPTX такого нет, и подделывать его разрезом по строкам нельзя:
строки двух надписей разъезжаются по кеглю, а блок читается целиком.
"""
from . import metrics, report
from .wrap import cut_points, split_at

GAP = 0.40           # просвет между колонками; число Лекции 6 (`flow.COL_GAP`)


def _is_head_para(runs, i):
    """Абзац, кончающийся перед разделителем `i`, — целиком полужирный?

    Такой абзац в этой деке — подзаголовок блока (`head`), и разрез сразу
    за ним оставил бы его внизу колонки без того, что он объявляет."""
    j = i - 1
    while j >= 0 and not runs[j].get("newpara"):
        j -= 1
    part = [r for r in runs[max(j, 0):i] if str(r.get("text") or "").strip()]
    return bool(part) and all(r.get("bold") for r in part)


def cuts_of(runs):
    """Законные места разреза на колонки. Запрет «не сразу за подзаголовком»
    снимается, если он не оставил ни одного места: разрез где-то быть
    обязан, и выбор наугад хуже выбора по высотам."""
    all_cuts = [i for i in cut_points(runs) if 0 < i < len(runs) - 1]
    ok = [i for i in all_cuts if not _is_head_para(runs, i)]
    return ok or all_cuts


def best_cut(runs, w, h, ls):
    """Самый ровный разрез, при котором ОБЕ колонки влезают в `w × h`.
    None — ни одного такого нет."""
    best, skew = None, None
    for i in cuts_of(runs):
        top, bot = split_at(runs, i)
        if not top or not bot:
            continue
        ht, hb = metrics.runs_h(top, w, ls), metrics.runs_h(bot, w, ls)
        if max(ht, hb) > h:
            continue
        d = abs(ht - hb)
        if skew is None or d < skew:
            best, skew = i, d
    return best


def fit_two(runs, w_col, h, w_plain, h_plain, *, hi=1.0, lo=0.72, floor=0.58,
            ls=1.26, tag="", grid=metrics.GRID_PT, step=metrics.K_STEP,
            proj_base=None, proj_pt=metrics.PROJ_PT):
    """Крупнейший масштаб, при котором тело ложится в ДВЕ колонки шириной
    `w_col` и высотой `h`.

    `w_plain × h_plain` — рамка обычной, одноколоночной раскладки. Она здесь
    не для справки: ниже её масштаба поиск не идёт (см. шапку модуля).

    Возвращает `(масштаб, разрез, левая, правая)` либо `None`. Правит
    `runs` на месте — но ТОЛЬКО ПРИ УСПЕХЕ: отказ обязан вернуть кегли
    ровно такими, какими их отдал вызывающий, иначе следующая подгонка
    пойдёт от уже ужатой основы (цена этой ошибки замерена в `wrap.py`:
    тело село на 8,5 пт вместо 15,0, и ни одно предупреждение этого не
    назвало)."""
    base = [r.get("size", 15.0) for r in runs]
    if len(cuts_of(runs)) == 0:
        return None
    k_plain = metrics.scan_scale(runs, w_plain, h_plain, hi=hi, floor=floor,
                                 ls=ls, grid=grid, step=step)
    bottom = floor if k_plain is None else max(floor, k_plain)
    k, seen = hi, None
    while k >= bottom - 1e-9:
        sizes = metrics.apply_scale(runs, base, k, grid)
        if sizes != seen:
            seen = sizes
            i = best_cut(runs, w_col, h, ls)
            if i is not None:
                left, right = split_at(runs, i)
                metrics.check_proj(k, tag, proj_base, proj_pt, grid)
                if k < lo - 1e-9:
                    report.warn(
                        f"[кегль] {tag}: прогон ужат до {k:.2f} от рабочего "
                        "кегля — предел плотности кадра")
                for part, side in ((left, "лев"), (right, "прав")):
                    paras = metrics.runs_paras(part)
                    metrics.check_thin_margin(
                        [(pieces, w_col) for pieces, _sb in paras], h,
                        metrics.runs_h(part, w_col, ls),
                        max((pc[1] for pieces, _sb in paras for pc in pieces),
                            default=15.0) * ls * metrics.LH / 72.0
                        * metrics.SAFE, f"{tag}/{side}")
                return k, i, left, right
        k -= step
    for r, b0 in zip(runs, base):
        r["size"] = b0
    return None


def used_h(left, right, w_col, ls=1.26):
    """Высота, которую две колонки на деле заняли, — по более высокой.
    Ею и рисуется коробка мотива: коробка «на весь бюджет» и есть то самое
    полупустое место, ради которого всё это."""
    return max(metrics.runs_h(left, w_col, ls),
               metrics.runs_h(right, w_col, ls))

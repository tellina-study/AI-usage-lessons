def bhead(d, x, y, n, title, sz=18, w=760):
    # Кружок-номер — DEEP с белой цифрой: тот же знак, что у одностраничника
    # хука (`khuki-n12-ustroystvo.png`) и у одностраничника MCP этого занятия.
    # Золото на этом полотне держит рамка блока 6 — одного раза достаточно,
    # а шесть золотых кружков разводили два одностраничника по разным жанрам.
    bd = 25
    d.ellipse([x, y, x + bd, y + bd], fill=DEEP)
    tw = d.textlength(str(n), font=f(14, True))
    d.text((x + (bd - tw) / 2, y + 5), str(n), font=f(14, True), fill=W)
    for k, ln in enumerate(wrap(d, title, f(sz, True), w - bd - 10)):
        mtext(d, x + bd + 10, y + 3 + k * (sz + 2), ln, sz, DEEP, b=True)



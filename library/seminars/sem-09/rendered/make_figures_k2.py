def dashline(d, x1, x2, y, col, *, seg=22, gap=14, wd=5):
    """Пунктир поперёк столбца. Прежде рисовался `dashbox` высотой в четыре
    пикселя — приём не для этого, и концы линии выходили скруглёнными."""
    x = x1
    while x < x2:
        d.line([x, y, min(x + seg, x2), y], fill=col, width=wd)
        x += seg + gap


# Общий «пол» содержательной области, одинаковый у обоих столбцов: короче
# заголовок/раскладка — ниже остаётся воздух, а не сжатие. Так контрольная
# точка у обоих столбцов рисуется на ОДНОЙ высоте (иначе читатель ищет
# смысл в разнице высот, которого там нет — разница только в раскладке
# блоков, не в месте точки относительно вопроса клиента).
CONTENT_TOP = 250
CONTENT_BOTTOM = 540


def stolb(d, x, w, zagolovok, verdikt, *, blocks):
    """Один столбец — промт сверху вниз: указание, база, контрольная точка,
    вопрос клиента. Один и тот же дописанный 11-й пункт в обоих столбцах —
    различие ровно в том, СКОЛЬКО блоков у базы. `blocks=1` — весь
    справочник плюс новый пункт нарисованы одной рамкой (точка «видит»
    это как один объект, и правка внутри меняет весь объект). `blocks=4`
    — старые десять пунктов остаются в своей рамке, новый 11-й пункт
    нарисован ОТДЕЛЬНОЙ рамкой с зазором — так на картинке видно то же,
    что измерено: старое не задето, трогают только новый блок."""
    title_h = wrapped(d, x, 108, zagolovok, 27, DEEP, w, b=True,
                       center=x + w / 2, where=f"столбец · {zagolovok[:18]}")
    top = 108 + title_h + 18

    card(d, x, top, w, 50)
    ctxt(d, x + w / 2, top + 13, "указание процессу", 25, LIGHT, limit=w - 40,
         where="сегмент · указание")
    top += 50 + 14

    if blocks == 1:
        y2, h2 = top, CONTENT_BOTTOM - top
        card(d, x, y2, w, h2, stroke=GOLD, sw=3)
        ctxt(d, x + w / 2, y2 + 10, "один блок: 10 старых + новый", 23,
             DEEP, b=True, limit=w - 30, where="сегмент · база единым блоком")
        ry = y2 + 44
        for i, p in enumerate(PUNKTY + ("пункт 11 · дописан в конец",)):
            col = GOLD if i == 4 else MID
            card(d, x + 18, ry, w - 36, 30, fill=W, stroke=LIGHT, sw=2, r=7)
            ctxt(d, x + w / 2, ry + 2, p, 22, col, b=(i == 4), limit=w - 60,
                 where=f"пункт базы {i}")
            ry += 34
    else:
        old_h = 44 + 4 * 34 + 6
        y2 = top
        card(d, x, y2, w, old_h, stroke=LIGHT, sw=3)
        ctxt(d, x + w / 2, y2 + 10, "блок 1–3: старые 10 (не задеты)", 23,
             DEEP, b=True, limit=w - 30, where="сегмент · старые блоки")
        ry = y2 + 44
        for i, p in enumerate(PUNKTY):
            card(d, x + 18, ry, w - 36, 30, fill=W, stroke=LIGHT, sw=2, r=7)
            ctxt(d, x + w / 2, ry + 2, p, 22, MID, limit=w - 60,
                 where=f"пункт базы {i}")
            ry += 34
        gap_y = y2 + old_h + 16
        new_h = CONTENT_BOTTOM - gap_y
        card(d, x, gap_y, w, new_h, stroke=GOLD, sw=4)
        ctxt(d, x + w / 2, gap_y + 10, "блок 4 (новый): пункт 11 · дописан",
             22, GOLD, b=True, limit=w - 30, where="сегмент · новый блок")
        ctxt(d, x + w / 2, gap_y + 36, "точка переставлена сюда", 22, LIGHT,
             limit=w - 30, where="подпись · точка на новом блоке")

    q_top = CONTENT_BOTTOM + 48
    card(d, x, q_top, w, 54, fill=W)
    ctxt(d, x + w / 2, q_top + 13, "вопрос клиента", 25, DEEP, limit=w - 40,
         where="сегмент · вопрос")

    v_top = q_top + 54 + 20
    card(d, x, v_top, w, 108, fill=W, stroke=GOLD if blocks == 1 else TEAL, sw=5)
    wrapped(d, x + 20, v_top + 16, verdikt, 23, DEEP, w - 40, center=x + w / 2,
            where=f"вывод столбца · {zagolovok[:18]}")



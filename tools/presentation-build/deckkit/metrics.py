"""МЕРА ТЕКСТА — настоящими метриками шрифта, без единого коэффициента.

Это главный модуль пакета, и единственный, который нельзя упрощать. Он
перенесён из `library/lectures/lec-07/rework/deck/build_lec07.py` целиком и
по поведению, а не по смыслу: там каждая его часть куплена видимым дефектом,
и каждая доказана пробой на нарочно сломанном входе (`selftest.py`).

ЧЕМ МЕРИТСЯ. Ширина строки и число строк — настоящими метриками СВОЕГО
начертания: четыре файла Liberation Sans на четыре сочетания «полужирный ×
курсив». Начертания, файла которого на машине нет, мера НЕ подменяет молча —
выходит блокирующее `[шрифт]`.

ЧТО ЗДЕСЬ БЫЛО СЛОМАНО И ЧЕМ ЭТО КОНЧИЛОСЬ (три разных дефекта, все три
молчаливые — сборка рапортовала «предупреждений нет»):

1. КОЭФФИЦИЕНТ НА КУРСИВ. Стоял `ITAL_W = 1.031` к мере по прямому. Курсив
   Liberation Sans — настоящий курсив, а не наклон: внутри одной строки
   отношение курсива к прямому идёт от 0,990 («дублированная») до 1,064
   («рецензентов»). Один коэффициент на такой размах верным не бывает, и
   промах не в величине: жадный перенос ломается не на средней ширине, а на
   конкретном слове. Цена — слово «госпитализациях» печаталось ПОВЕРХ нижней
   грани плашки `s63`.
2. УСРЕДНЁННОЕ НАЧЕРТАНИЕ АБЗАЦА. Абзац мерился одной строкой: «кегль —
   максимум по абзацу, полужирный — если хоть один кусок полужирный, курсив —
   никак». Курсивные куски тела не мерились курсивом ни разу, при том что их
   в деке 35 на 17 кадрах. Отсюда `_pieces_w` и `wrap_pieces`, которые
   меряют КУСКАМИ.
3. ОТБИВКА АБЗАЦЕВ ВНЕ МЕРЫ. `space_before` не входил в высоту, а поправки
   стояли ПО МЕСТУ — у двух ветвей раскладки из многих. Кадр `s44` печатал
   последний абзац и подпись поверх строки источника: шесть абзацев — это
   0,58" неучтённого, больше двух строк. Отсюда `runs_h` как ЕДИНСТВЕННОЕ
   место, где отбивка входит в меру.

СОВМЕСТИМОСТЬ С МЕРОЙ lec-06. Проверено численно (`selftest.py`, проба
`[мера-06]`): на ОДНОРОДНОМ тексте — одно начертание, один кегль — `est_h`
и `n_lines` этого модуля дают РОВНО те же числа, что `_est_height` и
`n_lines` в `build_lec06_p1.py`. Мера lec-07 — строгое надмножество меры
lec-06, а не другая мера, и поэтому общее ядро не сдвигает геометрию
доставленной деки Лекции 6.

ЧТО ЗДЕСЬ ВСЁ ЕЩЁ ПРИБЛИЖЕНИЕ — перечень в `README.md`, раздел «Что всё ещё
приближение». Он не декоративный: `LH`, `SAFE`, `W_SAFE` и линейность по
кеглю — выверенные по рендеру числа, а не метрики шрифта, и подменять
выверенное «настоящим» нельзя.
"""
import math
import re
from pathlib import Path

from PIL import ImageFont

from . import report

_TTF_DIR = Path("/home/harness/.local/libreoffice-portable/share/fonts/truetype")
_TTF = {
    (False, False): _TTF_DIR / "LiberationSans-Regular.ttf",
    (True, False): _TTF_DIR / "LiberationSans-Bold.ttf",
    (False, True): _TTF_DIR / "LiberationSans-Italic.ttf",
    (True, True): _TTF_DIR / "LiberationSans-BoldItalic.ttf",
}
_PPEM = 200        # кегль чтения файла; ширина линейна по кеглю, см. `_unit_w`
_FCACHE = {}
_UNIT = {}         # (полужирный, курсив, строка) → ширина на ОДИН пункт кегля
_FONT_GAP = {}     # начертание → чем подменено, когда своего файла нет

LH = 1.19          # высота строки LibreOffice, в кеглях. НЕ метрика шрифта:
                   # сам файл заявляет 1,1499 (hhea: 1854+434+67 на 2048), а
                   # 1,19 выверено по рендеру. Подменять выверенное
                   # «настоящим» нельзя — строки раскладывает LibreOffice
                   # своим правилом, а не таблицей шрифта.
SAFE = 1.04        # запас по высоте на расхождение разметки с измерением
W_SAFE = 0.97      # запас по ширине: на пограничной строке метрика и
                   # LibreOffice расходятся ровно на строку


def _font(bold, italic):
    """Файл начертания. Отсутствующий файл НЕ подменяется молча ни соседним
    начертанием, ни коэффициентом: подмена записывается в `_FONT_GAP` и
    выходит из сборки блокирующим `[шрифт]`. Задокументированный пробел
    лучше молчаливой оценки."""
    key = (bold, italic)
    if key not in _FCACHE:
        p = _TTF[key]
        if not p.exists():
            alt = _TTF[(bold, False)]
            if not alt.exists():
                alt = _TTF[(False, False)]
            _FONT_GAP[key] = (p.name, alt.name)
            p = alt
        _FCACHE[key] = ImageFont.truetype(str(p), _PPEM)
    return _FCACHE[key]


def font_gaps():
    """[шрифт] — мера шла по подменённому начертанию. Зовётся из сборки, то
    есть попадает в отчёт КАЖДОГО прогона, а не остаётся внутренним флагом."""
    for (bold, italic), (want, got) in sorted(_FONT_GAP.items()):
        report.warn(
            f"[шрифт] начертания «{want}» на машине нет — мера шла по "
            f"«{got}». Ширина курсива и полужирного отличается от прямого по "
            "словам до 6%, то есть ВСЯ мера высоты и ширины этого начертания "
            "недоказана: это пробел, а не оценка")


def _unit_w(text, bold, italic):
    """Ширина строки в пунктах НА ОДИН ПУНКТ КЕГЛЯ.

    Кеш не зависит от кегля, и это не мелочь: `fit_size` перебирает до
    восемнадцати кеглей, `fit_runs` — до двадцати двух масштабов, и каждый
    перебор меряет ТЕ ЖЕ строки. Ключ без кегля превращает перебор в
    арифметику по готовому числу."""
    key = (bold, italic, text)
    v = _UNIT.get(key)
    if v is None:
        v = _UNIT[key] = _font(bold, italic).getlength(text) / _PPEM
    return v


def text_w(text, size, bold=False, italic=False):
    """Ширина строки в пунктах по НАСТОЯЩИМ метрикам своего начертания."""
    return _unit_w(text, bold, italic) * size


# ── смешанный набор: мера по кускам, а не по абзацу целиком ──────────
# Кусок — `(текст, кегль, полужирный, курсив)`.


def _tokens(pieces):
    """Абзац → слова, каждое со своими начертаниями.

    Слово — СПИСОК кусков, а не строка: граница начертания проходит и посреди
    слова (`*курсив*ное`), а перенос по такой границе не идёт."""
    out, cur = [], []
    for text, size, bd, it in pieces:
        for part in re.split(r"(\s+)", text):
            if not part:
                continue
            if part.isspace():
                if cur:
                    out.append(cur)
                    cur = []
            else:
                cur.append((part, size, bd, it))
    if cur:
        out.append(cur)
    return out


def _pieces_w(pieces):
    """Ширина строки из кусков. Соседние куски ОДНОГО начертания сначала
    склеиваются и меряются одной строкой — иначе однородный абзац мерился бы
    по словам и расходился с мерой строки целиком на пробелах и кернинге.
    Склейка держит это свойство: на однородном абзаце мера даёт ровно то же
    число, что мера по плоской строке, и вся разница приходится на
    смешанные."""
    out = []
    for t, z, b, i in pieces:
        if out and out[-1][1:] == (z, b, i):
            out[-1] = (out[-1][0] + t, z, b, i)
        else:
            out.append((t, z, b, i))
    return sum(text_w(t, z, b, i) for t, z, b, i in out)


def wrap_pieces(pieces, w_in):
    """Жадный перенос по пробелам настоящими метриками КАЖДОГО начертания.
    Возвращает строки — списки кусков. Одно место на всю деку, где решается
    «сколько строк займёт», и потому одно, которое надо держать верным."""
    maxw = w_in * 72.0
    words = _tokens(pieces)
    if not words:
        return []
    lines, cur = [], list(words[0])
    for wd in words[1:]:
        space = (" ",) + cur[-1][1:]       # пробел набран начертанием слева
        cand = cur + [space] + list(wd)
        if _pieces_w(cand) <= maxw:
            cur = cand
        else:
            lines.append(cur)
            cur = list(wd)
    lines.append(cur)
    return lines


def segs_h(pieces, w_in, ls=1.18):
    """Высота ОДНОГО абзаца смешанного набора в дюймах. Высота строки берётся
    по крупнейшему кеглю на ЭТОЙ строке, а не по крупнейшему в абзаце."""
    if w_in <= 0:
        return 0.0
    lines = wrap_pieces(pieces, w_in)
    if not lines:                           # пустой абзац занимает свою строку
        return max([p[1] for p in pieces], default=16.0) * ls * LH / 72.0 * SAFE
    return (sum(max(p[1] for p in ln) for ln in lines)
            * ls * LH / 72.0 * SAFE)


def _longest_word_w(pieces):
    """Ширина самого длинного неразрывного слова абзаца — со своими
    начертаниями, включая слово, пересекающее границу начертания."""
    return max((_pieces_w(wd) for wd in _tokens(pieces)), default=0.0)


def longest_word_w(text, size, bold=False, italic=False):
    """Ширина самого длинного неразрывного куска: перенос идёт по пробелам,
    и слово шире места LibreOffice рвёт посреди корня."""
    return _longest_word_w([(text, size, bold, italic)])


def n_lines(text, size, w_in, bold=False, italic=False):
    """Сколько строк займёт однородный абзац в рамке шириной `w_in` дюймов.

    Та же подпись и то же число, что у `build_lec06_p1.n_lines` — модуль
    `tables.py`, перенесённый из lec-06, зовёт именно её."""
    return len(wrap_pieces([(text, size, bold, italic)], w_in)) or 1


def est_h(text, size, w_in, ls=1.18, bold=False, italic=False):
    """Высота однородного текстового блока в дюймах. `\\n` — разрыв абзаца.

    То же число, что у `build_lec06_p1._est_height` при тех же аргументах."""
    if w_in <= 0:
        return 0.0
    return sum(segs_h([(p, size, bold, italic)], w_in, ls)
               for p in text.split("\n"))


def check_width_segs(pieces, w_in, tag):
    """[ширина] — слово шире рамки. Проверка отдельная от высоты: высокий
    блок ужимается кеглем, а слово, которое не влезает по ширине, кеглем
    почти не лечится и рвётся на экране посреди корня."""
    words = _tokens(pieces)
    if not words:
        return True
    wd = max(words, key=_pieces_w)
    lw = _pieces_w(wd) / 72.0
    if lw > w_in * W_SAFE:
        flat = "".join(t for t, *_ in pieces)
        report.warn(
            f"[ширина] {tag}: слово шире рамки — {lw:.2f}\" против "
            f"{w_in:.2f}\" при кегле {max(p[1] for p in wd):.1f}  "
            f"«{flat[:40]}…»")
        return False
    return True


def check_width(text, size, w_in, tag, bold=False, italic=False):
    return check_width_segs([(text, size, bold, italic)], w_in, tag)


def fit_size(text, w, h, *, hi=17.0, lo=11.5, floor=8.5, ls=1.18,
             bold=False, italic=False, tag=""):
    """Крупнейший кегль, при котором текст укладывается в рамку w × h.

    Два разных исхода и два разных предупреждения. Не влезло даже на полу —
    `[высота]`: текст физически наедет сам на себя. Влезло, но ниже рабочего
    предела — `[кегль]`: блок набран на дне лестницы, и это предел плотности
    кадра, а не раскладки.

    Расхождение с lec-06 здесь ОДНО и только в тексте предупреждения: тот
    сборщик на обоих исходах писал `[кегль]`, не отличая «набрано мелко» от
    «не влезает вовсе». ВОЗВРАЩАЕМЫЙ КЕГЛЬ при любом входе один и тот же
    (проверено пробой `[кегль-06]`), поэтому геометрия доставленной деки
    Лекции 6 от этой правки не двинулась."""
    f = round(hi * 2) / 2
    while f >= floor:
        used = est_h(text, f, w, ls, bold, italic)
        if used <= h:
            if f < lo:
                report.warn(
                    f"[кегль] {tag}: тело ужалось до {f:.1f} пт "
                    f"(рабочий предел {lo:.1f}) — предел плотности кадра")
            check_thin_margin([([(p, f, bold, italic)], w)
                               for p in text.split("\n")],
                              h, used, f * ls * LH / 72.0 * SAFE, tag)
            return f
        f -= 0.5
    report.warn(
        f"[высота] {tag}: не укладывается даже при {floor:.1f} пт — "
        f"{est_h(text, floor, w, ls, bold, italic):.2f}\" против {h:.2f}\"")
    return floor


# ── ТОНКИЙ ЗАПАС: «не могу измерить» вместо молчания ────────────────
#
# Четыре молчаливых вылета текста найдены в этих деках ОДНИМ способом —
# рендером и глазами, ни один сборкой: `s44` (отбивка вне меры), `s63`
# (курсив коэффициентом), `s18` Лекции 6 (тот же курсив), `s105` (столбец
# «Что отменить нельзя»: слово «процедуру» вышло за нижнюю грань коробки).
#
# Первые три были ошибками МЕРЫ и исправлены мерой. Четвёртый — не ошибка
# меры: она дала 0,953" в рамке 1,021", то есть 0,068" запаса, и этот запас
# съел сам рендер. Причина названа в `README.md`, пункт 1 перечня «Что всё
# ещё приближение»: ширина переноса у нас НЕ ширина переноса LibreOffice.
# `W_SAFE = 0.97` стоит в проверках ширины и НЕ стоит внутри `wrap_pieces`.
#
# ЧИНИТЬ ЭТО КОЭФФИЦИЕНТОМ НЕЛЬЗЯ. Сплошная усадка на три процента вернула
# бы ровно тот класс числа, который работа по курсиву из меры убрала, и
# сдвинула бы геометрию всего, что сейчас влезает. Поэтому здесь не
# уточнение меры, а ОТКАЗ ОТ ЛОЖНОЙ УВЕРЕННОСТИ: где запас кадра меньше
# того, что мера способна разрешить, сборка называет кадр и говорит «здесь
# я не знаю» — вместо того, чтобы молчать. Диагностика не двигает ни одного
# EMU и ни одного кегля: она только смотрит.
#
# УСЛОВИЙ ДВА, и ни одного из них по отдельности не хватает.
#
#   1. ПО ВЫСОТЕ: запас меньше ОДНОЙ строки своего кегля (`THIN_LINES`).
#      Порог не подобран: один несовпавший перенос стоит ровно строку, и
#      запас ниже строки означает «одного несовпадения хватит, чтобы блок
#      перестал влезать». Выше строки лишний перенос ещё укладывается.
#      Само по себе это условие бесполезно: подбор кегля идёт шагом 0,5 пт
#      и садится к грани вплотную, поэтому запас МЕНЬШЕ строки держат 162
#      подогнанных блока Лекции 7 из 230 и 105 из 108 у Лекции 6.
#
#   2. ПО ШИРИНЕ: самая тесная строка блока занимает свою рамку плотнее,
#      чем на `THIN_EDGE` (`tight > 1 - THIN_EDGE`). Это и есть место, где
#      мера неразрешима: чтобы блок поехал, рендеру достаточно посчитать
#      эту строку шире нашей меры на её остаток.
#
# ОТКУДА 0,002 — И ЧЕГО ЗА ЭТИМ ЧИСЛОМ НЕТ. Замерено два распределения на
# 338 подогнанных блоках двух дек (числа — в `README.md`). Естественного
# излома у распределения остатка НЕТ: оно плотное у нуля и ровное, и
# «правильного» порога в данных не лежит. Привязать его к разрешению самой
# меры тоже не вышло — оно замерено (та же строка на 200 и на 4000 ppem) и
# равно 2·10⁻⁵, то есть в сорок раз мельче: наша арифметика здесь ни при
# чём, расходится МОДЕЛЬ переноса, а её ошибка не измерена. Привязать к
# `1 - W_SAFE = 0.03` — к единственному числу, которое этот пакет о
# расхождении уже заявил, — значит получить 56 блоков Лекции 7 и 37
# Лекции 6: столько никто читать не станет, а предупреждение, которое не
# читают, хуже его отсутствия. Поэтому 0,002 — это БЮДЖЕТ ЧТЕНИЯ, а не
# измерение: порог, при котором сборка печатает список, который человек
# откроет. Единственный известный настоящий случай (`s105/столбец-2`,
# остаток 0,00084) лежит внутри с запасом, и выше него внутри порога лежат
# ещё пять блоков — то есть порог не подогнан под этот один кадр. Что
# именно он не знает: сколько из сработавших поедут на самом деле.

THIN_LINES = 1.0    # запас, в строках своего кегля: ниже строки — лишний
                    # перенос уже не укладывается
THIN_EDGE = 0.002   # остаток ширины у самой тесной строки; бюджет чтения,
                    # не измерение (см. выше и `README.md`)
TRACE = None        # список под замер распределения; None — не замеряем


def wrap_risk(frames, edge=None):
    """Сколько строк блока стоит в ПОЛОСЕ НЕРАЗРЕШИМОСТИ — у самой грани
    своей рамки, где наша мера переноса и мера LibreOffice могут решить
    по-разному.

    `frames` — последовательность `(куски, ширина рамки в дюймах)`: абзац
    со своей рамкой, потому что у буллита и цитаты рамка уже абзаца.

    Возвращает `(строк в полосе, всего строк, наибольшая занятость)`.
    Занятость — доля ширины рамки, которую строка заняла по нашей мере."""
    lim = 1.0 - (THIN_EDGE if edge is None else edge)
    risky = total = 0
    tight = 0.0
    for pieces, w_in in frames:
        if w_in <= 0 or not pieces:
            continue
        maxw = w_in * 72.0
        for ln in wrap_pieces(pieces, w_in):
            rel = _pieces_w(ln) / maxw
            total += 1
            tight = max(tight, rel)
            if rel > lim:
                risky += 1
    return risky, total, tight


def check_thin_margin(frames, avail, used, line_h, tag):
    """[запас] — блок ВЛЕЗАЕТ по мере, но тоньше, чем мера разрешает.

    Это не «кадр сломан» и не «кадр в порядке»: это «здесь сборка не
    знает», и единственный честный ответ — назвать кадр и отправить
    смотреть глазами. Поэтому тег НЕ блокирующий (`report.BLOCKING` его не
    держит): блокировать неразрешимость значило бы требовать правки там,
    где правка может и не быть нужна."""
    if used > avail + 1e-9:
        return False                      # это уже [высота], о нём сказано
    head = avail - used
    risky, total, tight = wrap_risk(frames)
    if TRACE is not None:
        TRACE.append({"tag": tag, "head": head, "line_h": line_h,
                      "avail": avail, "used": used, "risky": risky,
                      "lines": total, "tight": tight})
    if line_h <= 0 or head >= line_h * THIN_LINES or not risky:
        return False
    report.warn(
        f"[запас] {tag}: НЕ МОГУ ИЗМЕРИТЬ — влезает, но тоньше, чем мера "
        f"разрешает. Запас {head:.3f}\" меньше строки ({line_h:.3f}\"), а "
        f"{risky} из {total} строк заняли рамку плотнее "
        f"{100 * (1 - THIN_EDGE):.1f}% (до {100 * tight:.2f}%): рендеру "
        "хватит посчитать такую строку чуть шире нашей меры, и блок выйдет "
        "за рамку. Кадр не объявлен сломанным — он не проверен; посмотрите "
        "его глазами")
    return True


# ── прогоны: абзацы, отбивка, масштаб ───────────────────────────────


def runs_paras(runs):
    """Прогоны → абзацы `(куски, отбивка сверху в пунктах)` ровно так, как их
    потом сложит `prims.text_runs`. Отдельная функция нужна затем, чтобы
    высоту считала и подбирала кегль одна и та же арифметика.

    Абзац отдаётся СПИСКОМ кусков, а не одной строкой с усреднённым
    начертанием: усреднить начертания значит потерять ровно то, из-за чего
    мера и расходится с рендером.

    Отбивка (`space_before`) идёт вторым полем, потому что её ставит тот же
    словарь прогона, что и кегль, — и считаться она обязана там же, где
    считается кегль, а не поправкой у вызывающего."""
    paras, cur, sb, started = [], [], 0.0, False
    for c in runs:
        if c.get("newpara"):
            if started:
                paras.append((cur, sb))
                cur, sb = [], 0.0
            sb = max(sb, float(c.get("space_before") or 0.0))
        started = True
        # Пустой прогон-разделитель кладётся тоже: текста он не несёт, но
        # несёт кегль своего абзаца — им мерится абзац, оставшийся без слов.
        cur.append((c["text"], float(c.get("size", 16)),
                    bool(c.get("bold")), bool(c.get("italic"))))
    paras.append((cur, sb))
    return paras


def runs_h(runs, w, ls=1.18):
    """Высота прогона в дюймах — ВКЛЮЧАЯ отбивку между абзацами.

    ЕДИНСТВЕННОЕ место, где абзацный отступ входит в меру, и потому
    единственное, которое надо держать верным. `est_h` его не считает и
    считать не может: она меряет плоскую строку и о разрывах абзаца ничего
    не знает, а `space_before` живёт в словаре прогона — то есть ровно здесь.

    Отбивка НЕ масштабируется вместе с кеглем: `text_runs` пишет `Pt(…)`
    литералом. Поэтому кадр, перебравший рамку на одну отбивку, ужиманием
    кегля уже не спасается — и правильно, что не спасается: лечить это надо
    текстом, а не кеглем."""
    return sum(segs_h(pieces, w, ls) + sb / 72.0
               for pieces, sb in runs_paras(runs))


# ── ЛЕСТНИЦА КЕГЛЕЙ и ПОЛ ПРОЕКЦИИ ─────────────────────────────────
#
# СТУПЕНЬ. Подбор масштаба идёт шагом 0,02 и кладёт кегль куда попало:
# замерено на деке Лекции 7 — 719 прогонов тела из 1415 не лежали ни на
# какой пол-пунктовой ступени, соседние кадры расходились на 0,3 пт, и
# различных кеглей в теле набиралось 25. Лекция 6, набранная `fit_size`
# (шаг 0,5 пт от начала), даёт 11 кеглей на 100 кадрах, и все на ступени.
# Разница видна залу не как «мельче», а как ДРОЖЬ: иерархия кадров перестаёт
# читаться, потому что её ступени меньше, чем отличает глаз.
#
# Округление идёт ВНИЗ, а не к ближайшему: вверх — это кегль, при котором
# прогон уже мерился и НЕ уложился. Пол 8,5 пт тот же, что стоял здесь
# прежде.
#
# ПОЛ ПРОЕКЦИИ. `[кегль]` ниже говорит о МАСШТАБЕ и срабатывает на 0,72 —
# при рабочем теле 15 пт это 10,8 пт. Порог читаемости с задних рядов у
# курса другой и прямее: 12 пт (anti-pattern #22). Между ними полтора
# пункта, в которых сборка молчала: 14 кадров Лекции 7 набраны ниже 12 пт и
# 32 ниже 13, и ни об одном отчёт не сказал.
#
# ПОЧЕМУ `[проекция]` НЕ БЛОКИРУЮЩАЯ. Блокирующей она сегодня валит сборку
# на 14 кадрах сразу, а починить их сборке нечем: кегль там уже наибольший,
# при котором текст влезает, и дальше выбор не между раскладками, а между
# «срезать текст кадра» и «оставить мелко» — решение владельца, не
# сборщика. Поэтому тег заведён по образцу `[запас]`: называет кадр и
# число, не притворяется, что знает, что с этим делать. Перевести в
# блокирующие можно будет в тот круг, когда счётчик дойдёт до нуля, — и
# тогда это будет охраной достигнутого, а не стоп-краном посреди работы.
GRID_PT = 0.5        # ступень лестницы кеглей
GRID_FLOOR = 8.5     # ниже этого ступень не опускает
PROJ_PT = 12.0       # порог проекции курса: ниже — «с задних рядов не видно»


def grid_pt(size, grid=GRID_PT, floor=GRID_FLOOR):
    """Кегль на ближайшую ступень лестницы ВНИЗ, но не ниже пола."""
    if not grid:
        return max(floor, round(size, 1))
    return max(floor, math.floor(size / grid + 1e-9) * grid)


K_STEP = 0.005       # шаг поиска масштаба; см. `fit_runs`


def apply_scale(runs, base, k, grid):
    """Поставить прогонам кегли масштаба `k`. Возвращает набор кеглей —
    по нему видно, не повторяет ли этот масштаб предыдущий."""
    for r, b0 in zip(runs, base):
        r["size"] = grid_pt(b0 * k, grid)
    return tuple(r["size"] for r in runs)


def scan_scale(runs, w, h, *, hi=1.0, floor=0.58, ls=1.26, grid=GRID_PT,
               step=K_STEP):
    """Крупнейший масштаб, при котором прогон влезает в w × h, — МОЛЧА и БЕЗ
    следов: кегли возвращаются ровно такими, какими были. `None` — не
    влезает нигде.

    Нужна там, где раскладку надо СРАВНИТЬ с другой, прежде чем выбрать
    (`wrap.fit_runs_wrap`). Предупреждения выдаёт та раскладка, которую
    выбрали, и ровно один раз: мерить дважды, а говорить один раз —
    единственный способ не завести второй голос об одном дефекте."""
    base = [r.get("size", 15.0) for r in runs]
    k, seen, out = hi, None, None
    while k >= floor - 1e-9:
        sizes = apply_scale(runs, base, k, grid)
        if sizes != seen:
            seen = sizes
            if runs_h(runs, w, ls) <= h:
                out = k
                break
        k -= step
    for r, b0 in zip(runs, base):
        r["size"] = b0
    return out


def fit_runs(runs, w, h, *, hi=1.0, lo=0.72, floor=0.58, ls=1.26, tag="",
             grid=GRID_PT, step=K_STEP, proj_base=None, proj_pt=PROJ_PT):
    """Крупнейший МАСШТАБ кеглей прогона, при котором он укладывается в
    рамку. Масштаб, а не кегль: внутри прогона кегли разные — заголовок
    блока, тело, подпись, — и сбивать их в один нельзя, иначе иерархия
    кадра исчезает.

    `grid` — ступень лестницы кеглей (0 снимает её; нужно пробе, которая
    доказывает, что ступень делает именно ступень). Кегли кладутся на
    ступень ВНИЗ, см. перечень выше.

    `proj_base` — НОМИНАЛЬНЫЙ кегль тела этой деки (у Лекции 7 это 15 пт).
    Пол проекции мерится по нему, а не по наибольшему кеглю прогона:
    наибольший — это заголовок блока, которым набраны единицы строк, а
    порог читаемости относится к тому кеглю, которым набрано БОЛЬШИНСТВО
    слов кадра. Дека обязана назвать его сама: угадывать «где здесь тело»
    по словарю прогона значит завести ещё одно приближение.

    Правит `runs` на месте — это и есть результат: вызывающий потом отдаёт
    те же словари в `text_runs`."""
    k = hi
    base = [r.get("size", 15.0) for r in runs]
    seen = None
    while k >= floor - 1e-9:
        sizes = apply_scale(runs, base, k, grid)
        if sizes == seen:
            # Шаг мельче ступени: тот же набор кеглей уже мерился. Мерить
            # его заново — это и есть вся цена мелкого шага, и она здесь
            # не платится. Шаг взят мелким нарочно: при 0,02 лестница
            # зависела бы от того, на какой масштаб попала сетка, и кадр
            # терял ступень заголовка блока на ровном месте.
            k -= step
            continue
        seen = sizes
        used = runs_h(runs, w, ls)
        if used <= h:
            check_proj(k, tag, proj_base, proj_pt, grid)
            # Допуск на ошибку представления: шаг −0,02 в двоичной дроби не
            # точен, и на номинальном пределе k держит 0,7199999999999998.
            # Без допуска прогон, уложившийся РОВНО на заявленном пределе,
            # объявлялся «пределом плотности кадра».
            if k < lo - 1e-9:
                report.warn(
                    f"[кегль] {tag}: прогон ужат до {k:.2f} от рабочего "
                    f"кегля — предел плотности кадра")
            paras = runs_paras(runs)
            check_thin_margin(
                [(pieces, w) for pieces, _sb in paras], h, used,
                max((pc[1] for pieces, _sb in paras for pc in pieces),
                    default=15.0) * ls * LH / 72.0 * SAFE, tag)
            return k
        k -= step
    apply_scale(runs, base, floor, grid)
    check_proj(floor, tag, proj_base, proj_pt, grid)
    report.warn(
        f"[высота] {tag}: не укладывается даже при масштабе {floor:.2f} — "
        f"{runs_h(runs, w, ls):.2f}\" против {h:.2f}\"")
    return floor


def check_proj(k, tag, proj_base, proj_pt=PROJ_PT, grid=GRID_PT):
    """Пол проекции: тело, набранное ниже порога, названо вслух.

    Молчит, пока дека не назвала свой номинальный кегль тела (`proj_base`),
    — и это не «по умолчанию выключено ради тишины», а отказ угадывать:
    пол, померенный не по тому кеглю, хуже отсутствия пола."""
    if not proj_base:
        return None
    pt = grid_pt(proj_base * k, grid)
    if pt < proj_pt - 1e-9:
        report.warn(
            f"[проекция] {tag}: тело набрано {pt:.1f} пт — ниже порога "
            f"проекции {proj_pt:.0f} пт, с задних рядов не читается. Кадр не "
            "сломан: это наибольший кегль, при котором текст влезает. "
            "Поднять его можно только срезав текст кадра или сняв с него "
            "примитив — решение владельца, не сборки")
    return pt

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Сплошной проход по СЧЁТЧИКАМ деки: что сломает структурный разрез.

ЗАЧЕМ ОТДЕЛЬНЫЙ ПРОГОН. Ни один генератор прозу не пересобирает. Прошлая
свёртка ОДНОГО кейса оставила 15 расхождений в 11 слайдах, не найденных ни
критикой, ни проведением, ни просмотром глазами (`tools/seminar-production/
README.md` §8.10). Здесь сворачивается раздел целиком и снимается восемь
кадров -- класс тот же, объём больше.

ЧТО ЭТОТ ПРОГОН ЧИТАЕТ: все `slides/*.md` целиком (видимый слой И заметки),
`make_deck_yaml.py`, реестры разборов и счёта минут. ПЕЧАТАЕТ, СКОЛЬКО ФАЙЛОВ
ОТКРЫЛ -- без этой строки «чисто» не отличить от «не читал» (приёмка это
проверяет, см. `priyomka.py` п.1).

ЧЕГО ЭТОТ ПРОГОН НЕ УМЕЕТ, сказано вслух:
  * не решает, расхождение это или законная ссылка на снятый кадр в журнале;
  * числительное прозой («шесть действий») ловит ТОЛЬКО из своего словаря
    ниже -- слово вне словаря он не видит, и полнота держится на чтении глазами;
  * про `timing_min` говорит сумму, но не судит, верна ли она содержанию кадра.

КИРИЛЛИЦА: `grep -P` даёт ЛОЖНЫЙ НОЛЬ на русских шаблонах (`\b`/`\w` в PCRE
считают по байтам) -- поэтому Python `re` и якорь с ДВУХ сторон.

    python3 skan_schetchikov.py --snyato s24 s28 ...
    python3 skan_schetchikov.py --selftest
"""
import argparse
import glob
import os
import re
import sys

# ЧИСЛИТЕЛЬНЫЕ ПЕРЕЧИСЛЕНЫ ФОРМАМИ, А НЕ СТЕБЛЕМ С ХВОСТОМ.
# Первая редакция брала «стебель + до трёх букв» -- и САМОПРОВЕРКА НА НАСТОЯЩИХ
# СТРОКАХ КАДРОВ её завалила двумя разными механизмами сразу:
#   * «шести» (из заголовка s49a «собранное из ста шести опытов») НЕ находилось:
#     мягкий знак «шесть» -> «шести» не хвост, а замена последней буквы;
#   * «семья» ЛОЖНО срабатывало как «семь» + «я».
# То есть хвост одновременно и недобирал, и перебирал. Формы надёжнее догадки.
FORMY = {
    1: 'один одна одно одного одному одним одной одну однa'.split(),
    2: 'два две двух двум двумя'.split(),
    3: 'три трёх трем трём тремя трое'.split(),
    4: 'четыре четырёх четырех четырём четырем четырьмя четверо'.split(),
    5: 'пять пяти пятью пятеро'.split(),
    6: 'шесть шести шестью шестеро'.split(),
    7: 'семь семи семеро'.split(),
    8: 'восемь восьми восьмью восьмером'.split(),
    9: 'девять девяти девятью'.split(),
    10: 'десять десяти десятью'.split(),
    11: 'одиннадцать одиннадцати'.split(),
    12: 'двенадцать двенадцати'.split(),
    18: 'восемнадцать восемнадцати'.split(),
}
PORYAD = {
    1: 'первый первая первое первых первого первом первому первым первой первую'.split(),
    2: 'второй вторая второе вторых второго втором второму вторым второй'.split(),
    3: 'третий третья третье третьих третьего третьем третьему третьим'.split(),
    4: 'четвёртый четвертый четвёртая четвёртое четвёртых четвёртого'.split(),
    5: 'пятый пятая пятое пятых пятого пятом пятому пятым'.split(),
    6: 'шестой шестая шестое шестых шестого шестом'.split(),
    7: 'седьмой седьмая седьмое седьмых седьмого'.split(),
    8: 'восьмой восьмая восьмое восьмых восьмого'.split(),
    9: 'девятый девятая девятое девятых девятого'.split(),
    10: 'десятый десятая десятое десятых десятого'.split(),
}
# Омографы: совпадают с формой числительного, числительными НЕ являются.
# «семью» намеренно НЕ здесь -- это и творительный «семь», и винительный
# «семья»; прогон его печатает, разбирает глазами человек (правило 8 журнала:
# при сомнении шаблон расширяют в сторону зачёта).
OMOGRAFY = {'семья', 'семьи', 'семье', 'семей', 'семьям', 'однако', 'одним'}


def slova_chisla():
    """Шаблон с якорем по КИРИЛЛИЧЕСКОЙ границе с ДВУХ сторон.

    Односторонний якорь в этом производстве дал пять ложных срабатываний
    («роля» внутри «контроля»), поэтому оба края обязательны.
    """
    vse = []
    for d in (FORMY, PORYAD):
        for formy in d.values():
            vse.extend(formy)
    alt = '|'.join(sorted(set(vse), key=len, reverse=True))
    return re.compile(r'(?<![А-Яа-яЁё-])(%s)(?![А-Яа-яЁё-])' % alt, re.I)


def selftest():
    """Входы -- НАСТОЯЩИЕ строки с кадров этой деки, не придуманные образцы.

    Правило 7 журнала (2026-10-15): фикстура из слов, которые в словаре уже
    есть, доказывает только непротиворечивость. Поэтому ниже -- строки,
    скопированные с кадров, включая те, на которых шаблон обязан МОЛЧАТЬ.
    """
    rx = slova_chisla()
    da = [
        ('Шесть действий стадии и что заняла модель', 'шесть'),
        ('Одна система, две группы: 8 против 79', 'две'),
        ('Цикл оказания помощи: девять стадий и решение каждой', 'девять'),
        ('Итог карты: четыре клетки заняты, восемь пусты', 'четыре'),
        ('Правило, собранное из ста шести опытов', 'шести'),
        ('Четыре ступени участия', 'Четыре'),
        ('Пример 2, цена: разрыв лечит состав данных', None),
    ]
    net = ['контроля', 'показал', 'пятно', 'однако', 'двойное', 'третировать',
           'семья', 'стодневный', 'восьмёрка']
    sb = []
    for s, zhdem in da:
        got = [m.group(0) for m in rx.finditer(s)
               if m.group(0).lower() not in OMOGRAFY]
        if zhdem is None:
            if got:
                sb.append('ЛОЖНОЕ СРАБАТЫВАНИЕ на %r: %r' % (s, got))
        elif not any(g.lower().startswith(zhdem.lower()[:4]) for g in got):
            sb.append('НЕ НАШЁЛ %r в %r (нашёл %r)' % (zhdem, s, got))
    for s in net:
        got = [m.group(0) for m in rx.finditer(s)
               if m.group(0).lower() not in OMOGRAFY]
        if got:
            sb.append('ЛОЖНОЕ СРАБАТЫВАНИЕ внутри слова %r: %r' % (s, got))
    if sb:
        print('САМОПРОВЕРКА НЕ ПРОШЛА:')
        for s in sb:
            print('  ' + s)
        return 1
    print('самопроверка: %d строк с кадров + %d слов-ловушек -- шаблон ведёт себя '
          'как заложено' % (len(da), len(net)))
    print('ЧЕГО ОНА НЕ ДОКАЗЫВАЕТ: что словарь числительных полон. Полноту '
          'даёт только чтение глазами.')
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--snyato', nargs='*', default=[])
    ap.add_argument('--selftest', action='store_true')
    a = ap.parse_args()
    if a.selftest:
        sys.exit(selftest())

    puti = sorted(glob.glob('slides/s*.md')) + sorted(glob.glob('slides/_snyato/*.md'))
    dop = ['make_deck_yaml.py', 'SCHET-RAZBOROV.md', 'RAZNARYADKA-FORM.md',
           '../SCHET-MINUT.md', '../REESTR-RAZBOROV.md', '../SLIDE-PLAN.md']
    dop = [p for p in dop if os.path.exists(p)]
    print('ПРОЧИТАНО: %d файлов кадров (из них %d в _snyato) + %d служебных'
          % (len(puti), len(glob.glob('slides/_snyato/*.md')), len(dop)))
    print('снятых к проверке: %d -- %s\n' % (len(a.snyato), ', '.join(a.snyato)))

    # 1. ссылки на снятые кадры
    if a.snyato:
        alt = '|'.join(sorted(a.snyato, key=len, reverse=True))
        rx = re.compile(r'(?<![0-9A-Za-z])(%s)(?![0-9A-Za-z])' % alt)
        print('== 1. ССЫЛКИ НА СНЯТЫЕ КАДРЫ ==')
        nash = 0
        for p in puti + dop:
            t = open(p, encoding='utf-8').read()
            for i, ln in enumerate(t.splitlines(), 1):
                for m in rx.finditer(ln):
                    if os.path.basename(p).startswith(m.group(1) + '-'):
                        continue          # сам файл кадра
                    nash += 1
                    print('  %s:%d  [%s]  %s' % (p, i, m.group(1), ln.strip()[:150]))
        print('  итого ссылок: %d\n' % nash)

    # 2. числительные прозой в видимом слое и заголовках
    rx = slova_chisla()
    print('== 2. ЧИСЛИТЕЛЬНЫЕ ПРОЗОЙ (видимый слой + заголовок) ==')
    k = 0
    for p in sorted(glob.glob('slides/s*.md')):
        t = open(p, encoding='utf-8').read()
        fm = t.split('---')[1]
        vid = t.split('## Видимый текст слайда')
        vid = vid[1].split('## Заметки лектора')[0] if len(vid) > 1 else ''
        zag = (re.search(r'^title:\s*(.*)$', fm, re.M) or [None, ''])[1]
        for gde, txt in (('заголовок', zag), ('тело', vid)):
            for m in rx.finditer(txt):
                if m.group(0).lower() in OMOGRAFY:
                    continue
                k += 1
                s = txt[max(0, m.start() - 55):m.end() + 55].replace('\n', ' ')
                print('  %-50s %-10s %-14s …%s…'
                      % (os.path.basename(p), gde, m.group(0), s.strip()))
    print('  итого: %d\n' % k)


if __name__ == '__main__':
    main()

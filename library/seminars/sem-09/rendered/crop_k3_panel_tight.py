#!/usr/bin/env python3
"""Дообрезка `k3-panel-proveryayushchego.png` вокруг редактора кода (issue
#303, n35 — слайд рисовался на 4% своей площади: исходный кадр панели нёс
вкладки `Parameters/Settings`, поля `Mode`/`Language` и подсказку интерфейса
снизу — вместе они делали кадр почти квадратным/портретным и не давали ему
вписаться в широкую раскладку слайда).

Это НЕ пересъёмка и не стилизация (БРИФ §5: реальные снимки не заменяются
рисованными карточками) — ровно те же пиксели настоящего снимка живого
стенда, обрезанные тесьнее вокруг самого кода. Мода и язык узла по-прежнему
названы — словами на слайде, не на кадре.

Источник — уже лежащий в `figures/` кадр (сам получен `n8n_shots.py` ->
`clip_panel()` на живом стенде); эта обрезка работает над его пикселями,
никакой новый снимок не делается и ничего не дорисовывается.

Запуск: `python3 crop_k3_panel_tight.py` (из `rendered/`).
"""
from pathlib import Path
from PIL import Image

FIGS = Path(__file__).parent / "figures"
SRC = FIGS / "k3-panel-proveryayushchego.png"

# Границы найдены измерением самого кадра (профиль неполностью-белых строк/
# столбцов): верхняя и нижняя рамка блока кода, с небольшим полем.
BOX = (28, 424, 1256, 1240)


def main():
    im = Image.open(SRC)
    before = im.size
    cropped = im.crop(BOX)
    cropped.save(SRC)
    print(f"  {SRC.name}  {before} -> {cropped.size} "
          f"(убраны вкладки/Mode/Language сверху и подсказка снизу)")


if __name__ == "__main__":
    main()

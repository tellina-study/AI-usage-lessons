def reachable(line):
    low = line.lower()
    hits = [c for c, words in COCO_RU.items() if any(w in low for w in words)]
    return hits


def main():
    raz = json.loads((HERE / "razmetka-101.json").read_text(encoding="utf-8"))
    sud = []
    for f in sorted(HERE.glob("sud/sud-*.json")):
        sud += json.loads(f.read_text(encoding="utf-8"))
    sudmap = {r["id"]: r for r in sud}

    tot = ceil = taken = 0
    per_author = {"planner": [0, 0, 0], "dobor": [0, 0, 0]}
    misses = []
    for e in raz["entries"]:
        if not e["in_corpus"]:
            continue
        a = e["razmetka_author"]
        cov = set(sudmap[e["id"]]["yolo"]["cov"])
        for i, line in enumerate(e["what_is_visible"], 1):
            tot += 1; per_author[a][0] += 1
            r = bool(reachable(line))
            if r:
                ceil += 1; per_author[a][1] += 1
            if i in cov:
                taken += 1; per_author[a][2] += 1
                if not r:
                    misses.append((e["id"], line))
    print(f"строк разметки всего:                 {tot}")
    print(f"из них ДОСТИЖИМЫ словарём COCO:       {ceil}  = {ceil/tot*100:.1f}%  (ПОТОЛОК детектора)")
    print(f"из них детектор РЕАЛЬНО назвал:       {taken}  = {taken/tot*100:.1f}%  (ДОСТИЖЕНИЕ)")
    print(f"доля потолка, которую детектор взял:  {taken/ceil*100:.1f}%")
    print()
    for a in ("planner", "dobor"):
        t, c, k = per_author[a]
        print(f"  {a:8s}: всего {t:3d}, потолок {c:3d} ({c/t*100:.1f}%), взято {k:3d} ({k/t*100:.1f}%), "
              f"от своего потолка {k/c*100:.1f}%")
    print()
    print(f"РАСХОЖДЕНИЕ грейдера с судом: строк, засчитанных покрытыми, но НЕ признанных")
    print(f"грейдером достижимыми: {len(misses)} из {taken} ({len(misses)/taken*100:.1f}%).")
    print("Каждое такое — либо пробел списка слов, либо ошибка суда; читаются глазами:")
    for i, (eid, line) in enumerate(misses[:12], 1):
        print(f"  {i}. {eid}: {line[:88]}")
    if len(misses) > 12:
        print(f"  … ещё {len(misses)-12}")


if __name__ == "__main__":
    main()

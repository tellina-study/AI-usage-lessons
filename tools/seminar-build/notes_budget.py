BAND_CLASSES = ("разделитель", "голосование", "содержательный", "опорный",
                "обложка")


def bands():
    """Коридоры этого занятия: класс → (от, до) или `None` (порога нет).

    Класс, не названный в конфиге, получает коридор `содержательный` — не
    «без порога»: молчаливое отсутствие порога это проверка, которая ничего
    не проверяет, и заметить её нельзя."""
    raw = D.table("notes").get("bands") or {}
    base = raw.get("содержательный") or [250, 450]
    out = {}
    for c in BAND_CLASSES:
        if c in raw:
            v = raw[c]
            out[c] = None if v is None else (int(v[0]), int(v[1]))
        else:
            out[c] = (int(base[0]), int(base[1]))
    return out



# n36 — СХЕМА «Агент, роль и контекст каждого» (круг 5, issue 225,
# ZADANIE-KRUG-5.md: «путается терминология агенты и роли, нужна схемка с
# агентами… окно тоже термин такой себе… контекст же. И надо показать что и
# откуда в него приходит при запуске»).
#
# Схема отвечает на три вопроса владельца одним экраном и держит весь кейс:
#   ЯРУС 1 — что приходит в контекст при запуске и ОТКУДА (четыре источника,
#     каждый со своим «откуда»): системная часть харнесса, файлы инструкций
#     проекта, описания подключённых серверов, сам разговор. Это же объясняет,
#     почему контекст кончается раньше, чем кажется: три источника из четырёх
#     приходят ДО первой вашей строки.
#   ЯРУС 2 — кто этот контекст держит: сессия с агентом (с ним разговаривает
#     человек), роль, которую агент позвал (свой контекст, обратно только
#     итог — и возвращается он САМ, в ту же сессию), и вторая сессия
#     (свой контекст, но обратно только человеческими руками, пересказом).
#
# Третий бокс яруса 2 — прямой ответ на вопрос зала «а почему не открыть
# вторую сессию?». Он поставлен на схему РАНЬШЕ, чем вопрос прозвучит: до
# круга 5 ответ лежал только в справке к сцене, и владелец читал кейс как
# необъяснённый. Разница рисуется грамматикой стрелок, не словами: сплошная
# золотая от роли в сессию, пунктирная от второй сессии — через человека.
#
# ДОЛИ НЕ РИСУЮТСЯ НАМЕРЕННО. Четыре источника даны равными полосами списка,
# не сегментами одной шкалы: измеренной доли каждого у занятия нет (постоянная
# плата за подключённые серверы измерена в токенах в блоке MCP этого же
# занятия, n15, и только она). Полоса-шкала с выдуманными пропорциями была бы
# числом без базы — то, что CLAUDE.md запрещает отдельным правилом.
#
# КЕГЛЬ МЕРЕН В ПУНКТАХ, не в пикселях. Полотно 2400 px ложится в рабочую
# ширину слайда 12,23″ → 2400/12,23 ≈ 196,2 px на дюйм, то есть 1 pt ≈ 2,73 px.
# Порог деки — 7,5 pt (`deck_kit.py: M.floor_reached(fs, 7.5, …)`) = 20,4 px.
# Самый мелкий текст этой схемы — 23 px ≈ 8,44 pt, основной корпус 24–25 px
# ≈ 8,8–9,2 pt, заголовки ярусов 36 px ≈ 13,2 pt. Ровно та ошибка, на которой
# дважды попадались одностраничники n08 и n37 («крупный текст» на глаз при
# 7,16 и 5,9 pt по мерке), здесь посчитана до отрисовки.
#
# Высота 1120 px при ширине 2400 даёт соотношение 2,14 — выше 12,23/5,81=2,105,
# то есть схема упирается в ШИРИНУ, а не в высоту, и встаёт во всю рабочую
# ширину без автосжатия (`deck_kit.figure`). У слайда пустое `## Visual`, как у
# n37: потолок `FIG_NATURAL_H` на такой слайд не накладывается, вся высота
# между заголовком и нижним полем отдана схеме.
#
# Палитра: красного нет. Золото — стрелка итога и планка нижней строки, по
# одному разу. «Откуда» каждого источника держится цветом чипа, не заливкой
# полосы.
# ═══════════════════════════════════════════════════════════════════════════

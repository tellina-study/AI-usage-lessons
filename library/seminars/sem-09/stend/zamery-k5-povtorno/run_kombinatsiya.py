def prompt_q2_kombinatsiya():
    return ("Ты — ассистент поддержки учебного центра. Ниже база знаний, которой можно "
            "пользоваться для ответа.\n\n" + Q2_FEWSHOT_PREFIX + KB_TEXT + Q2_DESC_SUFFIX +
            f"\n\nВопрос клиента: {Q2_QUESTION}" + TAIL)


def grade_q2(text):
    """Дословно grade() из run_fewshot_desc_combo.py."""
    if not text:
        return "нет ответа"
    no_retake = bool(re.search(r"не\s+(предоставляется|положена|предусмотрен\w*|возможна)",
                                text, re.I))
    mentions_schedule = bool(re.search(r"суббот|расписан", text, re.I))
    has_disclaimer = bool(re.search(
        r"не относится|не означает|не даёт права|в вашем случае|не для вас|не положена вам|"
        r"эта дата (вам )?не",
        text, re.I))
    if mentions_schedule and not has_disclaimer:
        return "НЕВЕРНО (самопротиворечие — дата названа без оговорки)"
    if mentions_schedule and has_disclaimer:
        return "верно (дата упомянута с явной оговоркой)"
    if no_retake and not mentions_schedule:
        return "верно (без даты — непротиворечиво)"
    return "неясно — проверить вручную"


# ============================================================================
# Проверка на протечку (часть В задания) — вызывается до отправки, не после.
# ============================================================================
def check_no_leak():
    """Мехнический грепп по определению протечки из задания: баг 27.10 был в том, что
    FEW-SHOT-ПРИМЕР ФОРМАТА содержал готовый ПРАВИЛЬНЫЙ ОТВЕТ на САМ измеряемый вопрос
    (не на другое число/случай), и модель его копировала вместо решения задачи.

    Описание (DESC_SUFFIX) не проверяется на этот критерий: оно по определению приёма
    обязано явно называть правило, включая пороговое значение 3000 — это сам приём
    "описание", испытанный уже в одиночном замере (`run_fewshot_desc.py`), а не вставка
    отдельно решённого ответа на тестовый вопрос в формате "вопрос-ответ". Проверяем
    только few-shot-примеры, по которым модель может скопировать форму ответа."""
    issues = []
    # Сценарий 1: few-shot-примеры должны оперировать ДРУГИМИ числами (2999, 3001),
    # не самим измеряемым значением 3000 — проверяем, что сумма "3000" в формате
    # "N рублей" не встречается ни в одном из двух примеров.
    if re.search(r"\b3000\s*рубл", Q1_FEWSHOT_PREFIX):
        issues.append("СЦЕНАРИЙ 1: few-shot-примеры содержат сумму 3000 рублей "
                       "напрямую (ожидались только 2999 и 3001) — протечка")
    note1 = ("Сценарий 1: few-shot-примеры используют числа 2999 и 3001, не 3000 — "
             "проверено regex-поиском \"3000 рубл\" в FEWSHOT_PREFIX: "
             f"{'НАЙДЕНО (протечка)' if re.search(r'3000 ?рубл', Q1_FEWSHOT_PREFIX) else 'не найдено'}. "
             "Описание называет правило с порогом 3000 явно — это сам приём, не "
             "протечка формата (см. docstring check_no_leak).")

    p2_examples = Q2_FEWSHOT_PREFIX
    # Протечка для сценария 2 была бы: один из примеров буквально повторяет измеряемый
    # вопрос клиента ("пропустил занятие без предупреждения... когда пересдача, чтобы
    # попасть") и даёт готовый ответ на НЕГО САМОГО. Проверяем: вопрос в примере не
    # идентичен измеряемому вопросу (у него "два занятия... на прошлой неделе" вместо
    # "занятие" без уточнений).
    if Q2_QUESTION.strip() in p2_examples:
        issues.append("СЦЕНАРИЙ 2: few-shot-примеры содержат вопрос клиента буквально "
                       "— протечка формата")
    note2 = ("Сценарий 2: вопрос клиента (\"Я пропустил занятие без предупреждения. Когда "
             "будет следующая пересдача, чтобы я мог на неё попасть?\") не встречается "
             "буквально ни в одном из двух few-shot-примеров (примеры используют другие "
             "формулировки: \"два занятия... на прошлой неделе\" и \"заранее перенести на "
             "вторую субботу\") — проверено прямым сравнением строк: "
             f"{'СОВПАДЕНИЕ' if Q2_QUESTION.strip() in p2_examples else 'совпадения нет'}.")
    return issues, [note1, note2]


def run_group(label, prompt_fn, grade_fn, n=10):
    results = []
    for i in range(n):
        r = call(prompt_fn())
        verdict = grade_fn(r["text"])
        r["verdict"] = verdict
        results.append(r)
        print(f"  [{label}] {i+1:2d}/{n}  exec={r['exec_id']}  {verdict}")
    return results


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default="raw/zamer_kombinatsiya.json")
    ap.add_argument("--check-only", action="store_true",
                     help="только проверка на протечку, без вызовов")
    args = ap.parse_args()

    issues, notes = check_no_leak()
    for n in notes:
        print(f"[проверка протечки] {n}")
    if issues:
        print("\n[проверка протечки] НАЙДЕНЫ ПРОБЛЕМЫ:")
        for iss in issues:
            print(f"  - {iss}")
        sys.exit(1)
    print("[проверка протечки] проблем не найдено\n")

    if args.check_only:
        sys.exit(0)

    out = {}
    out["q1_boundary_kombinatsiya"] = run_group(
        "q1-граница-комбо", prompt_q1_kombinatsiya, grade_q1)
    out["q2_combo_kombinatsiya"] = run_group(
        "q2-комбо-комбо", prompt_q2_kombinatsiya, grade_q2)
    Path(args.output).parent.mkdir(exist_ok=True)
    Path(args.output).write_text(
        json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    total = sum(len(v) for v in out.values())
    print(f"\n{total} вызовов записано в {args.output}")

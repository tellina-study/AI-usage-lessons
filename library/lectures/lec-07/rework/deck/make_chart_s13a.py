# -*- coding: utf-8 -*-
"""Диаграмма охвата кадра s13a (issue #278, 5-й круг доводки PR #278)
— на шаблоне `tools/presentation-build/analitika.py`.

ЗАЧЕМ ПЕРЕПИСАН СНОВА (круг 5). Круг 4 сгруппировал строки ПО ПОДПИСИ
(страна стоит один раз на первой строке группы, дальше «·» без повтора
имени) — но физически это оставалось десять-тринадцать ПОЛНОРАЗМЕРНЫХ
горизонтальных баров, просто с другой подписью слева. Оркестратор открыл
PNG глазами и отклонил: «та же самая [структура], просто подпись страны у
второй/третьей строки заменена на «·» вместо повтора имени… США всё ещё
даёт 2 отдельных прямоугольника-бара». Нужна БУКВАЛЬНАЯ группировка: один
визуальный блок на страну, не несколько полноразмерных баров подряд.

ДВА ВАРИАНТА БЫЛИ НА ВЫБОР (норматив оркестратора, круг 5):

  (А) счётный бар — длина = число болезней с подтверждённым участием ИИ
      В АРХИТЕКТУРЕ программы или С ОПЛАТОЙ/РЕИМБУРСАЦИЕЙ (не пилот за
      периметром программы, не следующий шаг пути типа ArtInCol). Ровно
      один прямоугольник на страну, целое число 0–N, без смешения
      знаменателей.
  (Б) настоящая Chart.js-группировка — `indexAxis:"y"`, несколько
      datasets (по одному на болезнь), одна Y-категория на страну, суб-бары
      внутри неё короче и теснее высоты слота.

ВЫБРАН (Б), и вот почему НЕ (А). Диаграмма этого кадра — единственное
место, где виден сам разброс охвата (18,7–85%), и тезис кадра («модель
встроена в архитектуру там, где классический охват ниже») — это сравнение
ДВУХ осей на одной картинке: охват (разброс по странам) И участие ИИ
(какие бары каким цветом). Вариант (А) выбросил бы охват из картинки
целиком, оставив только счёт «сколько болезней с ИИ» — а это ровно то, что
уже и так сказано текстом в прежних плашках `blocks:` (Польша/Хорватия,
Япония) почти дословно; новая диаграмма была бы избыточна по отношению к
собственному тексту кадра. Вариант (Б) держит обе оси на одной картинке.

ПОЧЕМУ (Б) НЕ СЛОМАЛСЯ НА ЭТОТ РАЗ. Круг 4 пробовал (Б) при стандартной
высоте полосы 3,00" (POLOSA_H) и ЧЕТЫРЁХ датасетах (включая простату) —
слот на бар выходил <6pt, подписи соседних болезней одной страны
(Великобритания: лёгкое+шейка матки; Нидерланды: шейка
матки+колоректальный) наезжали друг на друга — проверено прогоном, не
рассуждением (`/tmp` круга 4, не в репозитории). Норматив круга 5 снял
ДВА ограничения разом: (1) простата у всех восьми стран без исключения
пуста — реальных датасетов нужно 3, не 4; (2) высота полосы для ЭТОГО
кадра не обязана держаться в 3,00" — заведено поле `media_h_in` в
`build_lec07.analitika()` (per-слайдовый потолок ВЫШЕ `POLOSA_H`, default
не сдвинут ни для одного другого кадра деки — проверено прогоном
`--only s01ac`, 0 расхождений). Прогон (не рассуждение) нашёл порог: при
3 датасетах, `categoryPercentage=0.9`, `barPercentage=0.95`, кегле подписи
8,5pt, легенде ВЫКЛЮЧЕННОЙ (см. ниже) — подписи перестают наезжать уже на
220pt полосы (3,06"), а на 260–330pt (3,61–4,58") читаются с явным
запасом. Взят **280pt = 3,89"** — середина диапазона, запас над найденным
порогом, не впритык к нему.

ЛЕГЕНДА ЦВЕТА — ПО-ПРЕЖНЕМУ НЕ В КАРТИНКЕ. Та же находка, что в круге 4:
у QuickChart/Chart.js v4 с `indexAxis:"y"` ручная легенда (`generateLabels`)
рисует цветные плашки, но не текст (`notes/mcp-limitations.md`
`[#278-render-1]`). Подпись каждого бара и так называет болезнь не
напрямую — цвет кодирует болезнь (`DEEP` лёгкое, `MID` шейка матки, `TEAL`
колоректальный), а какая болезнь к какому цвету — названо в теле кадра и
в заметках лектора, не на картинке.

РОССИЯ — ОДНА Y-КАТЕГОРИЯ, ТРИ НУЛЕВЫХ БАРА СО СЛОВЕСНОЙ ПОДПИСЬЮ. Три
датасета дают Y-категории «Россия» три слота; у всех трёх значение 0
(не рисуется видимый бар — цвет слота `SETKA`, тот же серый сетки, что уже
в палитре модуля, новый цвет не заведён), а подпись несёт словесный честный
пробел («пилот Москвы — без %», «программы нет вовсе», «есть (404н), доля
не раскрыта»), не число и не ноль-как-факт. Прогоном (280pt) подтверждено:
три строки у России читаются раздельно, без наложения на соседние бары
других стран и друг на друга.

ПРОСТАТА НЕ ВОШЛА В ДИАГРАММУ — как и в прошлых двух кругах. У простаты
нет сопоставимого числа охвата НИ У ОДНОЙ из восьми стран (включая Россию:
ПСА-тест по приказу №404н есть, доля не публикуется) — четвёртый датасет
был бы пуст у всех восьми строк разом, то есть легендой без единого бара.

ОТКУДА ЧИСЛА — без изменений от круга 4: сверены построчно с
`research/15-skrining-po-stranam.md` и `chapter-part1b.md`
§ «Скрининговые программы по странам и участие ИИ» (7 стран) и с
нормативом круга 4 (Россия, issue #278).

ЧТО СЧИТАНО ЗДЕСЬ, А НЕ ВЗЯТО ГОТОВЫМ — середина диапазона для четырёх
строк, где источник даёт две цифры ОДНОГО измерения:

    Великобритания, лёгкое      32,4–36%        → 34,2 (длина столбца)
    Корея, лёгкое                51,2–58,6%      → 54,9
    США, колоректальный          63,5–67,4%      → 65,5
    Швеция, шейка матки          83–85%          → 84,0
    Япония, колоректальный       49,1% муж/42,8% жен → 46,0 (среднее, НЕ сумма)

Середина нужна только для длины столбца; подпись у его конца несёт
исходный диапазон/обе цифры дословно.

    python3 make_chart_s13a.py
"""
import json as _json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / "tools" / "presentation-build"))

import analitika as A  # noqa: E402

ASSETS = HERE / "assets"
VREMENNO = Path("/tmp/chart-s13a")

# Y-категории — РОВНО восемь, каждая страна один раз, ни одна не повторена.
COUNTRIES = ["США", "Великобритания", "Япония", "Нидерланды",
             "Корея", "Австралия", "Швеция", "Россия"]

# Значение 0 у России не рисует бар (слот цвета SETKA, не придуманный
# новый цвет) — подпись у этих трёх несёт словесный пробел, см. PODPISI_*.
LEGKOE = [18.7, 34.2, None, None, 54.9, None, None, 0]
SHEYKA = [None, 68.8, None, 54.4, None, 74.2, 84.0, 0]
KOLOREKT = [65.5, None, 46.0, 67.1, None, None, None, 0]

PODPISI_LEGKOE = [
    "18,7% из 12,8 млн (2024)", "32,4–36% приглашено из ≈7,5 млн",
    None, None, "51,2–58,6%, два измерения (2023)", None, None,
    "пилот Москвы (с 2017) — не нацпрограмма, без %",
]
PODPISI_SHEYKA = [
    None, "68,8% из 16,5 млн (2024)", None, "54,4% (2024)", None,
    "74,2%, тренд снижается (2024)", "83–85% (2024)",
    "программы нет вовсе",
]
PODPISI_KOLOREKT = [
    "63,5–67,4% (2023)", None, "49,1% муж / 42,8% жен (2022)",
    "67,1% · 1,5 млн человек (2024)", None, None, None,
    "программа есть (приказ №404н) — доля не раскрыта",
]

KEGL_BAR = 8.5           # подпись у конца каждого суб-бара
KEGL_OS = 11.0           # подпись страны на оси Y
KEGL_OS_X = 10.5         # подпись шкалы % на оси X
VYSOTA_PT = 280          # найдено прогоном: порог читаемости — 220pt,
                         # взято с запасом (середина диапазона 220–330)


def proverka_seredin():
    """Середины диапазонов обязаны совпасть с тем, что видит зал на подписи —
    то есть быть настоящей серединой пары чисел источника, не округлением."""
    para = {
        34.2: (32.4, 36.0),
        54.9: (51.2, 58.6),
        65.5: (63.5, 67.4),
        84.0: (83.0, 85.0),
        46.0: (49.1, 42.8),
    }
    for seredina, (a, b) in para.items():
        sch = round((a + b) / 2, 1)
        assert abs(sch - seredina) <= 0.15, (seredina, sch, a, b)
    print("  проверка середин: все пять совпадают с парой чисел источника")


def proverka_grupp():
    """Восемь Y-категорий, каждая страна один раз — тот самый буквальный
    критерий приёмки круга 5: ровно одна визуальная группа-строка на
    страну, не несколько полноразмерных баров подряд."""
    assert len(COUNTRIES) == len(set(COUNTRIES)) == 8, COUNTRIES
    assert "Россия" in COUNTRIES
    for ryad, imya in ((LEGKOE, "Лёгкое"), (SHEYKA, "Шейка матки"),
                       (KOLOREKT, "Колоректальный")):
        assert len(ryad) == 8, (imya, len(ryad))
    print(f"  проверка групп: {len(COUNTRIES)} Y-категорий, каждая — одна "
          "страна один раз: " + " · ".join(COUNTRIES))


def _dataset(imya, cvet, znach, podpisi):
    gotovye = _json.dumps([p or "" for p in podpisi], ensure_ascii=False)
    # Ноль у России — слот без бара (`v===0` не выводит подпись по
    # формуле числа, выводит СЛОВЕСНЫЙ пробел из podpisi); null/undefined
    # у остальных семи стран — слота с этой болезнью у них нет вовсе,
    # подписи datalabels не рисует (в бар нечего подписывать).
    formatter = A._JS(
        "function(v,c){if(v===null||v===undefined)return '';"
        "return %s[c.dataIndex];}" % gotovye)
    cveta = [A.SETKA if v == 0 else cvet for v in znach]
    return {
        "label": imya, "data": znach, "backgroundColor": cveta,
        "borderWidth": 0, "categoryPercentage": 0.9, "barPercentage": 0.95,
        "datalabels": {"color": A.TEKST, "anchor": "end", "align": "right",
                       "offset": 1, "formatter": formatter,
                       "font": {"size": KEGL_BAR, "weight": "bold"}},
    }


def main():
    proverka_seredin()
    proverka_grupp()
    VREMENNO.mkdir(parents=True, exist_ok=True)

    spec = {
        "type": "bar",
        "data": {
            "labels": COUNTRIES,
            "datasets": [
                _dataset("Лёгкое", A.DEEP, LEGKOE, PODPISI_LEGKOE),
                _dataset("Шейка матки", A.MID, SHEYKA, PODPISI_SHEYKA),
                _dataset("Колоректальный", A.TEAL, KOLOREKT, PODPISI_KOLOREKT),
            ],
        },
        "options": {
            "indexAxis": "y",
            "plugins": {
                # Выключена нарочно — см. докстринг файла и
                # notes/mcp-limitations.md [#278-render-1]: подпись
                # легендного пункта не рисуется в этом сочетании
                # инструмента (QuickChart/Chart.js v4, горизонтальные бары).
                "legend": {"display": False},
                "title": {"display": True,
                          "text": ["Охват скрининговых программ по странам",
                                   "% целевой группы/приглашённых · знаменатель "
                                   "у каждой строки свой"],
                          "color": A.TEKST,
                          "font": {"size": 12, "weight": "bold"}},
                "datalabels": {"display": True},
            },
            "layout": {"padding": {"top": 2, "bottom": 0, "right": 150}},
            "scales": {
                "y": {"ticks": {**A._osnova(KEGL_OS), "maxRotation": 0,
                                 "autoSkip": False},
                      "grid": {"display": False}},
                "x": {"ticks": A._osnova(KEGL_OS_X), "grid": {"color": A.SETKA},
                      "beginAtZero": True, "max": 100},
            },
        },
    }

    # ШИРИНА 880pt (12,23" полосы тела) — без изменений. ВЫСОТА 280pt —
    # НЕ 216pt (3,00"/`POLOSA_H`) из кругов 3–4: настоящая группировка на
    # восемь Y-категорий с тремя датасетами требует больше вертикали на
    # категорию, чем стандартная полоса держит без наложения подписей
    # (порог найден прогоном — 220pt, взято 280pt с запасом). Кадр
    # объявляет `media_h_in: 3.89` во фронтматтере — потолок полосы ВЫШЕ
    # стандартного специально для этого кадра (`build_lec07.analitika()`,
    # поле опциональное, default для всех остальных кадров деки не сдвинут).
    out = A.narisovat(spec, ASSETS / "s13a-ohvat-po-stranam.png",
                       shirina_pt=880, vysota_pt=VYSOTA_PT)

    from PIL import Image
    im = Image.open(out)
    print(f"  {out.name}: {im.width}×{im.height} пикс · "
          f"пропорция {im.width / im.height:.2f} · {out.stat().st_size} Б")
    return 0


if __name__ == "__main__":
    sys.exit(main())

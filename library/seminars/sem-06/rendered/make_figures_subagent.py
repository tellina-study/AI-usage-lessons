# MCP n08). Измерено, не на глаз: полотно 1600 px заполняет рабочую ширину
# слайда 12,23″ целиком (ни одна из шести панелей не упирается в потолок
# `deck_kit.FIG_NATURAL_H` — у одностраничника без текстовых блоков рядом
# потолка нет вовсе, см. комментарий `build_sem06.g_content` про n08/n37),
# то есть 1600/12,23 ≈ 130,8 px на дюйм — тот же «20 px ≈ 11 pt» калибр, что
# в make_figures_mcp.py. Самый мелкий текст прежней версии стоял на

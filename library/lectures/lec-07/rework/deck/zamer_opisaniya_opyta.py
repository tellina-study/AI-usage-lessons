#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ОПИСАНИЕ ОПЫТА на кадре-примере: кто и сколько · что делали · чем мерили.

Повод (владелец, 2026-10-15, глядя на восьмой слайд): «в кейсах не хватает
собственно описания кейса. Сразу про ошибку, а что они делали то? Нету только
голосом. Обязательно слайд должен читаться и без голоса, и ключевая информация
должна быть понятна». Сказано ВТОРОЙ раз: первый круг ответил блоком «Что
делали», который описывал ОБСТАНОВКУ («подсказка приходила в готовом виде»), а
не ОПЫТ («пятьдесят врачей читали по пять описаний случаев и строили
рассуждение; оценивали слепо по шкале»). Разница между обстановкой и опытом —
это и есть то, что зал не может восстановить без голоса.

ЧТО СЧИТАЕТСЯ ОПИСАНИЕМ ОПЫТА — три части, все три на ВИДИМОМ слое:
  1. КТО и СКОЛЬКО — «пятьдесят практикующих врачей», «717 изделий»,
     «10 343 пациента». Не «врачи», не «клиницисты» без числа.
  2. ЧТО ДЕЛАЛИ — действие участника, глаголом: читали · оценивали · вели ·
     распределяли вслепую · каждый дважды. Не «инструмент выдали».
  3. ЧЕМ МЕРИЛИ — названная величина со знаменателем: доля верных заключений ·
     чувствительность · балл по шкале · минуты труда · процедуры из ста.

ЧЕГО ЭТОТ ПРОГОН НЕ УМЕЕТ — читать прежде, чем поверить его числу:
  * Он ищет ПРИЗНАКИ по шаблонам, а не понимает текст. «Сорок клиницистов
    читали снимки, каждый дважды» он засчитает; «группа специалистов провела
    серию чтений» — нет, и будет прав по делу, но не по формальному признаку.
    Поэтому выход читают, а не считают: он называет, ЧЕГО не нашёл.
  * Три части он проверяет по отдельности и НЕ проверяет, что они про один и
    тот же опыт. Кадр, где «717 изделий» из одного замера, а «доля верных
    заключений» из другого, он пропустит. Это ловится только чтением.
  * Он молчит про кадры, где описание опыта не нужно вовсе (заземление, свод,
    дивайдер) — смотрит только `type: case`.

Шаблоны — Python `re`, не `grep -P`: на кириллице `-P` даёт ложный ноль.

    python3 zamer_opisaniya_opyta.py --selftest
    python3 zamer_opisaniya_opyta.py            # прогон по slides/s*.md
    python3 zamer_opisaniya_opyta.py s05 s45    # по отдельным кадрам
"""
import glob
import re
import sys

import yaml

sys.path.insert(0, '.')
from vidimyy_sloy_polnyy import polnyy

CHISLO = r'(\d[\d \s]{0,7}|сорок|пятьдесят|тридцать|двадцать|сто|двести|' \
         r'триста|тысяч[аи]?|десять|одиннадцать|двенадцать|пятнадцать|шестнадцать|' \
         r'семнадцать|восемнадцать|девятнадцать)'
LYUDI = r'(врач|клиницист|радиолог|патолог|участник|человек|пациент|специалист|' \
        r'хирург|ординатор|эндоскопист|испытуем|издели|случа|процедур|снимк|' \
        r'маммограмм|программ|больниц|центр|смен)'

# Между числом и существительным помещается определение: «пятьдесят
# ПРАКТИКУЮЩИХ врачей», «717 радиологических изделий». Самопроверка поймала
# это на первом же прогоне: шаблон без зазора объявил ложную тревогу на
# образцовом описании опыта. Зазор — до двух слов, дальше начинается другая мысль.
KTO = re.compile(CHISLO + r'\s+(?:[а-яёa-z]+\s+){0,2}' + LYUDI + r'\w*', re.I)
CHTO = re.compile(
    r'(читал\w+|оценивал\w+|разбирал\w+|строил\w+|назначал\w+|выполнял\w+|'
    r'проводил\w+|сравнивал\w+|распредел\w+|вели\b|каждый\s+дважды|вслепую|'
    r'слепо|рандомизир\w+|случайным\s+распределением|контрольн\w+\s+групп\w+|'
    r'плацебо|независимо\s+друг|подавал\w+|подсчит\w+|переписал\w+|обзор\s+прочёл)', re.I)
CHEM = re.compile(
    r'(по\s+шкале|балл\w*|чувствительност\w+|специфичност\w+|дол[яюи]\s+\w+|'
    r'площад\w+\s+под\s+кривой|минут\w*\s+труда|из\s+ста\b|на\s+сто\b|'
    r'время\s+(в|до|выведения)|частот\w+\s+\w+)', re.I)

CHASTI = (('КТО и сколько', KTO), ('ЧТО ДЕЛАЛИ', CHTO), ('ЧЕМ МЕРИЛИ', CHEM))

SLOMANNYY = ('Инструмент выдали, процедуру работы с ним — нет. '
             'Подсказка приходила в готовом виде.')
CHISTYY = ('Пятьдесят практикующих врачей читали по пять описаний случаев и строили '
           'рассуждение; оценивали слепо по шкале диагностического рассуждения.')


def razbor(text):
    return [(name, bool(pat.search(text))) for name, pat in CHASTI]


def vidimyy(f):
    v = polnyy(f)
    return v if isinstance(v, str) else '\n'.join(
        str(x) for x in (v if isinstance(v, (list, tuple)) else v.values()))


def selftest():
    bed = 0
    got = dict(razbor(SLOMANNYY))
    ok = not all(got.values())
    print(f'  {"НАШЛА пробел" if ok else "ПРОПУСТИЛА"} на обстановке без опыта: '
          f'{ {k: v for k, v in got.items()} }')
    bed += 0 if ok else 1
    got = dict(razbor(CHISTYY))
    ok = all(got.values())
    print(f'  {"молчит" if ok else "ЛОЖНАЯ ТРЕВОГА"} на настоящем описании опыта: '
          f'{ {k: v for k, v in got.items()} }')
    bed += 0 if ok else 1
    print(f'\nсамопроверка: {"ПРОЙДЕНА" if not bed else f"ПРОВАЛЕНА ({bed})"}')
    return 0 if not bed else 2


def progon(tseli):
    faily = sorted(glob.glob('slides/s*.md'))
    if not faily:
        print('кадров не найдено — запускать из deck/'); return 2
    bez, objavleno, s_opisaniem, vsego = [], [], 0, 0
    for f in faily:
        sid = f.split('/')[-1].split('-')[0]
        if tseli and sid not in tseli:
            continue
        fm = yaml.safe_load(open(f, encoding='utf-8').read().split('---')[1])
        # ОТБОР — по ссылке на работу, а не по метке `type`. Первая версия
        # смотрела `type: case` и пропустила ровно тот кадр, на который
        # показал владелец: `s05` помечен `summary`, а предъявляет замер
        # пятидесяти врачей. Метка описывает место кадра в рассказе, а не то,
        # ссылается ли он на чей-то опыт. Это тот же разбор, что в решении О20
        # («полоса написана по работе кадра, а не по метке») — и здесь он
        # куплен тем, что проверка пропустила кадр, отвергнутый владельцем.
        ist = str(fm.get('source') or '').strip()
        if ist in ('', '—', '-'):
            continue
        # ОБЪЯВЛЕННОЕ ОТСУТСТВИЕ — по образцу `pol_snyat`. Есть кадры, у
        # которых своего опыта нет ПО ПРИРОДЕ: карта стадии, словарь форм,
        # свод чужих опытов, таблица нескольких замеров, классический режим
        # без собственного замера. Поставить туда «пятьдесят врачей» значит
        # озеленить прогон и испортить кадр. Поэтому отсутствие ОБЪЯВЛЯЕТСЯ
        # полем `opyt_net: "<причина>"` — и тогда оно считается отдельно, а
        # не молчит: необъявленное отсутствие и названное решение обязаны
        # выглядеть по-разному, иначе следующий круг ищет их заново.
        if fm.get('opyt_net'):
            objavleno.append((sid, str(fm['opyt_net'])))
            continue
        vsego += 1
        est = razbor(vidimyy(f))
        if all(ok for _n, ok in est):
            s_opisaniem += 1
        else:
            bez.append((sid, [n for n, ok in est if not ok]))
    print(f'прочитано: кадров {len(faily)} из slides/, из них ссылаются на работу — {vsego}'
          + (f' (отбор {" ".join(sorted(tseli))})' if tseli else ''))
    print(f'несут все три части описания опыта: {s_opisaniem} · не несут: {len(bez)}'
          f' · своего опыта нет ПО РЕШЕНИЮ: {len(objavleno)}')
    for sid, net in bez:
        print(f'  {sid:7s} нет: {", ".join(net)}')
    if objavleno:
        print('\nСВОЕГО ОПЫТА НЕТ ПО ОБЪЯВЛЕННОМУ РЕШЕНИЮ — это записанное '
              'решение, не пробел:')
        for sid, why in objavleno:
            print(f'  {sid:7s} {why}')
    if not bez:
        print('\nНоль означает: на каждом кадре-примере НАЙДЕНЫ признаки всех трёх частей.')
        print('Он НЕ означает, что три части про один и тот же опыт, — это читают глазами.')
    return 1 if bez else 0


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    sys.exit(selftest() if '--selftest' in sys.argv else progon(set(args)))

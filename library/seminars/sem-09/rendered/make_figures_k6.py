#!/usr/bin/env python3
"""Две схемы Кейса 6 — чтение фотографии и порог, завязанный на высоту символа.

Такты Кейса 6 разнесены по занятию, и схем поэтому две, а не одна. Их
нельзя поменять местами: первая стоит ДО прогонов и чисел не несёт вовсе,
вторая стоит ПОСЛЕ них и без чисел не читается.

── `k6-shema-chtenie-i-sverka.png` — такт `n68`, решение слоя 1 ────────────

Устройство чтения: фотография → распознавание → модель работает с текстом →
сверка в коде. Несущая мысль кадра — не сам конвейер (он очевиден), а
ВТОРОЕ число, которое приходит в сверку мимо снимка: сумму из текста заявки
клиент набрал словами, распознавание к ней не прикасалось. Именно поэтому
сравнение является проверкой: будь оба числа добыты из одной картинки, оно
подтверждало бы само себя.

Отсюда композиция: два входа сходятся в сверку буквой «игрек», и золотом
помечен не узел сверки, а источник второго числа — то, из-за чего схема
нарисована. Исходов два, и оба настоящие: совпали — обычный порядок,
разошлись — Ольге на ручную сверку.

**Измеренных чисел на этой схеме нет ни одного** — ни порога, ни долей, ни
разрешений. Такт идёт ДО прогонов, и любое число здесь было бы развязкой,
вскрытой за несколько экранов до своего кадра.

── `k6-shema-vysota-simvola.png` — такт `n72`, механизм порога ─────────────

**Третья редакция (2026-10-27, починка протечки промта, issue #299).** Первые
две редакции этой схемы стояли на утёкшем результате: промт `k6_read()`
содержал РЕАЛЬНУЮ сумму `receipt-01` (`18990.00`) как «пример формата» поля
`sum_rub`, и модель копировала число из инструкции, а не читала фотографию —
отсюда «сумма не ломается никогда». Честный повтор (`results-k6-resolution.
json`, executions 1075–1104, после починки промта в `sborka.py`) показал: **сумма
ТОЖЕ ломается** — на `thirtysecond` (53×64 px, высота цифры суммы 1,5 px,
0 из 5 верно), держась до `sixteenth` (3,1 px, 5 из 5). Дата своим числом
протечкой не задета (поле `date` в промте никогда не несло примера-значения) и
ломается там же, где и раньше, — на `eighth` (0 из 5), держась до `quarter`
(5 из 5). Главный тезис схемы изменился: не «сумма не ломается вовсе, дата
ломается на 6,1 px», а **«оба поля ломаются, но при разной высоте символа:
порог суммы ниже порога даты»**.

Слева — одна квитанция, на которой два поля набраны РАЗНЫМ кеглем, и кегль
этот не нарисован «примерно»: слово «Сумма» набрано ровно вдвое крупнее
слова «Дата», как на самой квитанции (64 пикс. против 32). Справа — те же
шесть разрешений двумя дорожками: что стало с суммой и что стало с датой.
**Порог у каждого поля свой** — две отдельные золотые черты, каждая против
своей дорожки, не одна сквозная линия на обе: у суммы порог проходит между
пятым и шестым разрешением (`sixteenth`/`thirtysecond`), у даты — между
третьим и четвёртым (`quarter`/`eighth`). Это ДРУГАЯ пара столбцов — до
починки казалось, что порог общий, но это была случайность протечки (сумма
тогда вообще не ломалась, и никакого порога у неё не было видно).

**Числа на плашке — измеренная высота символа КАЖДОГО поля на его
собственном пороге, не агрегат «N из 30».** Высота символа суммы на пороге
лежит между 1,5 и 3,1 пикс. (между `thirtysecond` и `sixteenth`); высота
символа даты на пороге — между 2,9 и 5,8 пикс. (между `eighth` и `quarter`,
`measure_date_glyph_height.py` — отдельный замер, не пропорция от суммы).
**Эти два диапазона ЧАСТИЧНО ПЕРЕСЕКАЮТСЯ** (у обоих есть общая зона
2,9–3,1 пикс.) — это сказано на кадре честно, а не спрямлено до «ровно
вдвое» или любого другого искусственно чистого вывода, которого шесть точек
измерения на одной квитанции не дают.

**`15 из 15` на кадре НЕТ.** Это развязка следующего такта — там, где
сравниваются два способа поймать неверную дату. Здесь её бы вскрыли рано.

**Цифр на квитанции нет умышленно.** Протокол замера даёт высоту символа и
долю верных прочтений, но не даёт самих значений; нарисовать правдоподобную
сумму значило бы поставить на кадр выдуманное число рядом с измеренными. На
квитанции стоят названия полей, набранные теми же двумя кеглями, — это ровно
то, что измерено, и ничего сверх.

Оговорка, обязательная к этому примеру (сетка, такт «Нюансы», п. 5):
квитанции синтетические, и на этом материале ломаются ОБА поля — сумма и
дата, — просто на разных шагах сжатия. Оговорка стоит на самом кадре, а не
только в заметках.

**Про высоту символа даты — отдельный замер, не пропорция.** Дата набрана
вдвое мельче суммы по кеглю (32 против 64), но её высота символа в
пикселях — 23,0 на полном размере против 49,0 у суммы — не ровно вдвое
меньше: bbox шрифта не масштабируется идеально линейно из-за хинтинга на
разных кеглях. Это измерено `measure_date_glyph_height.py` тем же методом
(`ImageFont.getbbox`), что и у суммы, а не домножено на 0,5.

Запуск: `python3 make_figures_k6.py` (из `rendered/`).
"""
from make_figures_common import *

H = 842

# ── Схема 1: чтение и сверка (такт n68) ────────────────────────────────────
AX, AW, AGAP = 60, 360, 40             # цепочка снимка: три узла в ряд
A_Y, A_H = 150, 200
SV_X, SV_W, SV_Y, SV_H = 1480, 380, 240, 320      # узел сверки
B_Y, B_H = 465, 170                    # второй источник — текст заявки
OUT_X, OUT_W = 1920, 420               # два исхода

# ── Схема 2: высота символа (такт n72) ─────────────────────────────────────
KX, KW = 60, 700                       # квитанция
PX, PW = 820, 1520                     # правая колонка
TICK_X0, TICK_W = 1110, 800            # поле шести столбцов
POROG_DATA = 3                         # с четвёртого разрешения (eighth) дата ломается
POROG_SUMMA = 5                        # с шестого разрешения (thirtysecond) ломается сумма
# — честный повтор 2026-10-27 (results-k6-resolution.json, executions 1075-1104);
# до починки протечки промта казалось, что у суммы порога нет вовсе (POROG_SUMMA
# отсутствовал бы / был 6).


# ═══════════════════════════════════════════════════════════════════════════
#  Схема 1 — `k6-shema-chtenie-i-sverka.png`
# ═══════════════════════════════════════════════════════════════════════════
def _ax(i):
    return AX + i * (AW + AGAP)


def chtenie_i_sverka():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Сверку делает второе число, пришедшее мимо снимка",
        34, MID, b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "фотографию читает распознавание; сумму из текста заявки "
        "набрал сам клиент — к сравнению приходят два значения, добытые "
        "разными путями", 26, LIGHT, limit=CW - 120, where="подзаголовок")

    # ── верхний путь: что происходит со снимком ────────────────────────────
    tsepochka = (
        ("Фотография квитанции", "вложение в заявке, снято телефоном"),
        ("Распознавание", "переводит снимок в строки текста"),
        ("Модель", "работает с распознанным текстом, пикселей перед ней уже нет"),
    )
    for i, (t_, s_) in enumerate(tsepochka):
        node(d, _ax(i), A_Y, AW, A_H, t_, s_, where=f"цепочка · {t_}")
        if i < 2:
            arrow(d, _ax(i) + AW + 6, A_Y + A_H / 2, _ax(i + 1) - 8,
                  A_Y + A_H / 2, col=LIGHT, wd=5)

    # ── нижний путь: второе число, добытое не из картинки ──────────────────
    node(d, AX, B_Y, _ax(2) + AW - AX, B_H,
         "Сумма, которую клиент написал текстом заявки",
         "это значение в снимок не заглядывало: клиент набрал его словами, и "
         "распознавание к нему не прикасалось",
         fill=W, stroke=GOLD, sw=6, where="второй источник")

    # ── сверка: два входа сходятся буквой «игрек» ──────────────────────────
    arrow(d, _ax(2) + AW, A_Y + A_H / 2, SV_X - 6, SV_Y + SV_H / 2 - 55,
          col=LIGHT, wd=5)
    arrow(d, _ax(2) + AW, B_Y + B_H / 2, SV_X - 6, SV_Y + SV_H / 2 + 55,
          col=GOLD, wd=5)
    mid_x = (_ax(2) + AW + SV_X) / 2
    ctxt(d, mid_x, A_Y + A_H / 2 + 2, "число из снимка", 25, LIGHT, limit=250,
         where="подпись верхнего входа")
    ctxt(d, mid_x, B_Y + B_H / 2 - 27, "число из текста", 25, GOLD, b=True,
         limit=250, where="подпись нижнего входа")

    card(d, SV_X, SV_Y, SV_W, SV_H, fill=SURF, stroke=MID, sw=4)
    ctxt(d, SV_X + SV_W / 2, SV_Y + 28, "Сверка в коде", 34, DEEP, b=True,
         limit=SV_W - 44, where="сверка · название")
    d.line([SV_X + 34, SV_Y + 84, SV_X + SV_W - 34, SV_Y + 84], fill=LIGHT, width=2)
    wrapped(d, SV_X + 30, SV_Y + 106, "сравнивает два числа и решает, можно ли "
            "принимать заявку", 25, DEEP, SV_W - 60,
            center=SV_X + SV_W / 2, where="сверка · пояснение")
    ctxt(d, SV_X + SV_W / 2, SV_Y + SV_H - 76, "совпали?", 34, MID, b=True,
         limit=SV_W - 44, where="сверка · развилка")

    # ── два исхода ─────────────────────────────────────────────────────────
    for y_, zagl, pod, col in (
        (250, "Совпали", "заявка идёт дальше обычным порядком", TEAL),
        (410, "Разошлись", "заявка уходит Ольге на ручную сверку", GOLD),
    ):
        arrow(d, SV_X + SV_W, y_ + 75, OUT_X - 6, y_ + 75, col=col, wd=5)
        card(d, OUT_X, y_, OUT_W, 150, fill=SURF, stroke=col, sw=4)
        ctxt(d, OUT_X + OUT_W / 2, y_ + 24, zagl, 32, col, b=True,
             limit=OUT_W - 44, where=f"исход · {zagl}")
        wrapped(d, OUT_X + 28, y_ + 74, pod, 25, DEEP, OUT_W - 56,
                center=OUT_X + OUT_W / 2, where=f"исход · {zagl} · пояснение")

    card(d, 60, 690, CW - 120, 130, fill=SURF, stroke=TEAL, sw=5)
    wrapped(d, 110, 714, "Сверка держится на том, что второе число пришло другим "
            "путём. Прочитать тот же снимок второй раз значит повторить ту же "
            "ошибку вторым голосом.", 28, DEEP, CW - 220, center=CW / 2,
            where="вывод схемы")
    save(im, "k6-shema-chtenie-i-sverka.png")


# ═══════════════════════════════════════════════════════════════════════════
#  Схема 2 — `k6-shema-vysota-simvola.png`
# ═══════════════════════════════════════════════════════════════════════════
def tick_cx(i):
    return TICK_X0 + TICK_W / 6 * (i + 0.5)


def pole(d, cx, y, slovo, kegl, podpis, col):
    """Поле квитанции: слово нужным кеглем, мерная скоба вплотную слева от
    него и подпись ПОД ним.

    Подпись стояла СПРАВА от скобы и налезала на само слово: ширины карточки
    на «высота символа 64 пикс.» плюс «Сумма» в 54 px не хватало, и схема
    выезжала за холст. Скоба обязана стоять вплотную к измеряемому слову —
    иначе непонятно, что именно измерено; значит двигать надо подпись."""
    fo = f(kegl, True)
    w_ = d.textlength(slovo, font=fo)
    d.text((cx - w_ / 2, y), slovo, font=fo, fill=DEEP)
    x = cx - w_ / 2 - 26
    d.line([x, y + 3, x, y + kegl], fill=col, width=3)
    d.line([x, y + 3, x + 13, y + 3], fill=col, width=3)
    d.line([x, y + kegl, x + 13, y + kegl], fill=col, width=3)
    ctxt(d, cx, y + kegl + 14, podpis, 25, col, limit=560,
         where=f"подпись поля · {slovo}")


def dorozhka(d, y, h, nazvanie, do_poroga, col_ok, col_bad):
    card(d, PX, y, 260, h, fill=SURF, stroke=LIGHT, sw=3)
    ctxt(d, PX + 130, y + h / 2 - 18, nazvanie, 30, DEEP, b=True, limit=230,
         where=f"дорожка · {nazvanie}")
    for i in range(6):
        cx = tick_cx(i)
        if i < do_poroga:
            tick(d, cx, y + h / 2 - 4, 20, col_ok, wd=6)
        else:
            cross(d, cx, y + h / 2 - 4, 18, col_bad, wd=6)


def vysota_simvola():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Порог чтения завязан на высоту символа, а не на размер файла",
        34, MID, b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "одна и та же квитанция в шести разрешениях — чистое уменьшение "
        "одного файла, от полного размера до 53×64 пикс.", 26, LIGHT,
        limit=CW - 120, where="подзаголовок")

    # ── слева: одна квитанция, два кегля ───────────────────────────────────
    card(d, KX, 110, KW, 340, fill=SURF, stroke=LIGHT, sw=3)
    ctxt(d, KX + KW / 2, 126, "квитанция при полном размере", 25, LIGHT,
         limit=KW - 40, where="квитанция · шапка")
    d.line([KX + 40, 166, KX + KW - 40, 166], fill=LIGHT, width=2)

    cxk = KX + KW / 2 + 20
    pole(d, cxk, 196, "Сумма", 54, "высота символа 64 пикс.", MID)
    pole(d, cxk, 330, "Дата", 27, "высота символа 32 пикс.", GOLD)

    ctxt(d, KX + KW / 2, 470, "сумма набрана ровно вдвое крупнее даты", 28, DEEP,
         b=True, limit=KW, where="квитанция · вывод")

    card(d, KX, 512, KW, 150, fill=W, stroke=GOLD, sw=4)
    wrapped(d, KX + 28, 534, "Квитанции синтетические: на каждой одна сумма и одна "
            "дата. Ломаются ОБА поля — но на разных шагах сжатия: дата раньше, "
            "сумма позже.", 25, DEEP, KW - 56, center=KX + KW / 2,
            where="квитанция · оговорка")

    # ── справа: шесть разрешений, две дорожки ──────────────────────────────
    txt(d, PX, 110, "Что стало с каждым полем по мере уменьшения снимка", 29, DEEP,
        b=True, limit=PW, where="дорожки · название")
    arrow(d, TICK_X0 + 20, 186, TICK_X0 + TICK_W - 10, 186, col=LIGHT, wd=4)
    txt(d, TICK_X0 + 20, 150, "полный размер", 25, LIGHT, limit=320,
        where="ось · слева")
    ctxt(d, TICK_X0 + TICK_W - 80, 150, "53×64 пикс.", 25, LIGHT, limit=300,
         where="ось · справа")

    dorozhka(d, 210, 110, "сумма", POROG_SUMMA, TEAL, GOLD)
    dorozhka(d, 344, 110, "дата", POROG_DATA, TEAL, GOLD)

    # Порог у каждого поля свой — две отдельные черты, каждая напротив своей
    # дорожки, НЕ одна сквозная линия на обе (так стояло до починки: тогда
    # казалось, что порог общий, потому что у суммы порога вообще не было
    # видно — она не ломалась ни разу из-за протечки промта).
    xp_summa = (tick_cx(POROG_SUMMA - 1) + tick_cx(POROG_SUMMA)) / 2
    xp_data = (tick_cx(POROG_DATA - 1) + tick_cx(POROG_DATA)) / 2
    # y=194, НЕ y=150 — на y=150 уже стоит правая подпись оси "53×64 пикс."
    # (TICK_X0+TICK_W-80=1830), и "порог суммы" на xp_summa=1777 с ней
    # налезал (поймано визуальной проверкой первой версии этой правки).
    ctxt(d, xp_summa, 192, "порог суммы", 22, GOLD, b=True, limit=220,
         where="подпись порога · сумма")
    ctxt(d, xp_data, 192, "порог даты", 22, GOLD, b=True, limit=220,
         where="подпись порога · дата")
    for y0 in range(200, 326, 26):
        d.line([xp_summa, y0, xp_summa, y0 + 16], fill=GOLD, width=5)
    for y0 in range(334, 460, 26):
        d.line([xp_data, y0, xp_data, y0 + 16], fill=GOLD, width=5)

    # Оба числа — одной парной плашкой: порог без величины порога не порог.
    # Это высота символа КАЖДОГО поля на его собственном пороге (между
    # последним читаемым и первым нечитаемым разрешением этого поля), не
    # агрегат «N из 30» — после починки протечки агрегат уже не несёт
    # механизма (оба поля ломаются, вопрос только где).
    plashka_para(d, PX, 490, PW, 172,
                 ("1,5–3,1 пикс.", "высота символа суммы на её пороге (1/16 → 1/32)"),
                 ("2,9–5,8 пикс.", "высота символа даты на её пороге (четверть → восьмая)"),
                 "Диапазоны пересекаются частично (2,9–3,1 пикс.) — порог "
                 "суммы ниже порога даты, но не вдвое и не раздельными зонами.",
                 gold_idx=0, where="числа замера")

    card(d, 60, 700, CW - 120, 120, fill=SURF, stroke=TEAL, sw=5)
    wrapped(d, 110, 724, "Сжатие ломает оба поля — но на разной высоте символа: "
            "порог суммы ниже порога даты. И ломается уверенно: на сломанном "
            "разрешении все повторы поля сходятся на одном и том же неверном "
            "значении.", 28, DEEP, CW - 220,
            center=CW / 2, where="вывод схемы")
    save(im, "k6-shema-vysota-simvola.png")


if __name__ == "__main__":
    chtenie_i_sverka()

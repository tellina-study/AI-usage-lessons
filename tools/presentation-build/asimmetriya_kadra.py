"""Асимметрия кадра: смещение центра тяжести, поворот, выход за лист.

ПЕРЕНЕСЕНО из `notes/research/dizayn-metodika/proba-R1-lec-08/priyomka/
chernoviki-zamera/asimmetriya.py` (issue #307, круг R3 пробы). Считающая
часть перенесена БЕЗ ИЗМЕНЕНИЙ; правки переноса — в шапке.

ЧТО МЕРЯЕТ, тремя числами на колоду:
  * СМЕЩЕНИЕ ЦЕНТРА ТЯЖЕСТИ содержания от середины листа, долей полуширины
    (0 — ровно по центру, 1 — у кромки). Вес фигуры — её ширина;
  * ПОВЁРНУТЫЕ ФИГУРЫ — сколько фигур колоды имеют ненулевой `rotation`;
  * ВЫХОДЫ ЗА ЛИСТ — фигуры с отрицательным левым краем или правым краем
    за кромкой.

ЗАЧЕМ ЗАВЕДЕНА. Владелец после трёх кругов пробы: «асимметричных паттернов
так и не хватает, и вёрстка скучная». До этого замера просьба считалась
исполнимой перерисовкой кадров. Замер показал, что она не исполнима ВОВСЕ
(запись Т-39 журнала трения) — и это перевело задачу «меню композиции
кадра» (#313) из улучшения в УСЛОВИЕ: четвёртый круг дал бы четвёртую
симметричную колоду, как дали три первых.

ЗАМЕР 2026-11-03, этой программой, на файлах репозитория:

    колода        смещение, медиана   макс    повёрнутых   выходов за лист
    lec-06              0,011         0,154        0              0
    lec-07              0,010         0,292        0              0
    проба R1            0,009         0,023        0              0
    проба R2            0,015         0,276        0              5
    проба R3            0,010         0,265        0              3
    проба R4            0,011         0,312        0              0
    проба R5            0,011         0,312        0              0

Числа журнала (Т-39: lec-06 0,011 · lec-07 0,010 · проба R1·R2·R3 =
0,009 · 0,015 · 0,010, повёрнутых ноль) воспроизводятся ДОСЛОВНО. Внешний
эталон-5 (там 0,012 и тоже ноль поворотов) перемерить было нечем: файлов
эталонов в репозитории нет, в `tools/metodika-podachi/etalony/`
лежат только паспорта.

ЧТО ЭТИ ЧИСЛА ЗНАЧАТ. Содержание стоит ровно по центру во ВСЕХ семи
колодах, включая доставленные лекции курса. Повёрнутых фигур — НОЛЬ на
~4700 фигур. Это не склонность дизайнера: слова `rotation` не было ни в
одном из модулей ядра (37 у пробы, 62 на ветке Лекции 8). Поворот не
«редко применяли» — его нечем было применить. Заплата R4 завела общий
примитив `prims.rotate` (см. `notes/research/dizayn-metodika/proba-R1-lec-08/yadro-ZAPLATY.md`).

Столбец «выходов за лист» читается ОТДЕЛЬНО и в обратную сторону: у R2 и
R3 стоит дефект Т-37, а вовсе не замысел: подпись засечки центрировалась по
метке и уезжала за левую кромку (−30,4 и −25,1 пт). У R4/R5 ноль: поле сведено
к одному числу, и отрицательная координата стала невозможной. То есть
столбец служит сразу двум вопросам, и который из двух — решают знак и кадр.
Одного числа для ответа мало.

ЧЕМ МОЖЕТ ПРОТУХНУТЬ. `rotation` в PowerPoint поворачивает фигуру ВОКРУГ
ЦЕНТРА, а `left`/`top`/`width`/`height` при этом не меняются. Значит как
только повёрнутые фигуры в колодах появятся, столбцы «смещение» и «выход
за лист» перестанут описывать то, что увидит зал, — а программа этого не
скажет.

Запуск:  python3 asimmetriya_kadra.py <файл.pptx> [ещё.pptx ...]
Связанные записи: `notes/research/dizayn-metodika/proba-R1-lec-08/00-ZHURNAL-TRENIYA-part4.md` Т-37, Т-39.
"""
import sys, statistics
from pptx import Presentation
for path in sys.argv[1:]:
    prs = Presentation(path); W = prs.slide_width/12700.0
    smesh, povorot, polnyy_vynos = [], 0, 0
    for s in prs.slides:
        xs, ws, m = [], [], 0.0
        for sh in s.shapes:
            if None in (sh.left, sh.width): continue
            l = sh.left/12700.0; w = sh.width/12700.0
            if w < 6 or w >= W - 1: continue
            try:
                if sh.rotation: povorot += 1
            except Exception: pass
            if l < 0 or l + w > W: polnyy_vynos += 1
            xs.append(l + w/2); ws.append(w)
        if not xs: continue
        c = sum(x*w for x, w in zip(xs, ws)) / sum(ws)
        smesh.append(abs(c - W/2) / (W/2))     # 0 = ровно по центру, 1 = у края
    print(f"{path.split('/')[-1]:26s} смещение центра тяжести: медиана {statistics.median(smesh):.3f} · "
          f"макс {max(smesh):.3f} · кадров со смещением >0,10: {sum(1 for v in smesh if v>0.10)}/{len(smesh)} · "
          f"повёрнутых фигур {povorot} · выходов за лист {polnyy_vynos}")

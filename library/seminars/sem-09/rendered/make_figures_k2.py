#!/usr/bin/env python3
"""Две схемы Кейса 2 («Оптимизация промта», переименован К2-1, разбор
владельца 2026-10-29).

**Разделены 2026-10-26, третьим кругом; ПРАВЛЕНЫ 2026-10-29, четвёртым, под
перепрогнанный замер кэша (К2-19) и поправку К2-15.** Прежняя редакция
`kesh()` несла слово «ловушка» в докстроке и подписи, и — хуже — несла на
САМОЙ КАРТИНКЕ ложное обобщение: «дописать пункт в конец списка —
сбрасывается весь накопленный кэш целиком». Перепрогон на живом стенде
(`stend/zamery-k2-kesh/README.md`, Таблица 5) показал: это верно ТОЛЬКО для
одной раскладки блоков (справочник одним куском текста) и НЕВЕРНО как общее
правило — при той же правке, но с базой, разбитой на несколько блоков и
точкой на новом последнем, кэш уцелевает почти целиком (разница в цене
одного и того же вызова — 9,8 раза). Слово «ловушка» снято: явление не
капкан, а следствие того, как текст перед контрольной точкой разбит на
блоки — и это можно выставить осознанно.

- `k2-shema-promt-i-kesh.png` → такт `n22`: СТРОЕНИЕ промта сверху вниз и
  правило порядка. Устройство, без единого измеренного исхода.
- `k2-shema-kesh-lovushka.png` → такт `n25b` (прежде `n26`, слайд
  переименован и перестроен той же правкой, см. `slides/n25b-k2-kesh-
  tochka-validatsii.md`): сравнение ДВУХ раскладок одной и той же правки —
  один блок текста (кэш сгорает) против четырёх блоков с переехавшей
  точкой (кэш уцелевает). Имя файла на диске не меняется (закреплено БРИФ
  §5), меняется то, что на нём нарисовано.

Два столбца теперь различаются не «база не тронута / база с дописанным
пунктом», а раскладкой блоков ПРИ ОДНОЙ И ТОЙ ЖЕ правке: левый — справочник
одним куском, правый — справочник четырьмя блоками с точкой, переставленной
на новый блок. Это и есть содержание поправки: решает не само дописывание,
а то, как текст был разбит ДО него.

**Цены на схеме — измеренные, не из прайс-листа.** `anthropic/claude-haiku-
5.5`, одна и та же дописанная правка: один блок — 0 прочитано, 3834
записано, цена 1,271× прямого чтения; четыре блока — 3762 прочитано, 68
записано, цена 0,129×. Числа — `stend/zamery-k2-kesh/README.md`, Таблица 5,
собственный прогон (119 вызовов на пяти провайдерах), не документация
провайдера «как есть».

Запуск: `python3 make_figures_k2.py` (из `rendered/`).
"""
from make_figures_common import *

H = 800

# Высоты пересчитаны после первого прогона: одиннадцатая строка базы вылезала
# ЗА нижнюю грань своего же блока, пунктир контрольной точки ложился на неё
# сверху, а боковые метки «запоминается»/«меняется каждый раз» наезжали на
# столбцы. Метки сняты — то же самое теперь сказано одной подписью под самим
# пунктиром, где оно и читается.
PUNKTY = ("пункт 1 · оплата", "пункт 2 · перенос",
          "пункт 3 · документы", "пункт 10 · связь с преподавателем")


def dashline(d, x1, x2, y, col, *, seg=22, gap=14, wd=5):
    """Пунктир поперёк столбца. Прежде рисовался `dashbox` высотой в четыре
    пикселя — приём не для этого, и концы линии выходили скруглёнными."""
    x = x1
    while x < x2:
        d.line([x, y, min(x + seg, x2), y], fill=col, width=wd)
        x += seg + gap


# Общий «пол» содержательной области, одинаковый у обоих столбцов: короче
# заголовок/раскладка — ниже остаётся воздух, а не сжатие. Так контрольная
# точка у обоих столбцов рисуется на ОДНОЙ высоте (иначе читатель ищет
# смысл в разнице высот, которого там нет — разница только в раскладке
# блоков, не в месте точки относительно вопроса клиента).
CONTENT_TOP = 250
CONTENT_BOTTOM = 540


def stolb(d, x, w, zagolovok, verdikt, *, blocks):
    """Один столбец — промт сверху вниз: указание, база, контрольная точка,
    вопрос клиента. Один и тот же дописанный 11-й пункт в обоих столбцах —
    различие ровно в том, СКОЛЬКО блоков у базы. `blocks=1` — весь
    справочник плюс новый пункт нарисованы одной рамкой (точка «видит»
    это как один объект, и правка внутри меняет весь объект). `blocks=4`
    — старые десять пунктов остаются в своей рамке, новый 11-й пункт
    нарисован ОТДЕЛЬНОЙ рамкой с зазором — так на картинке видно то же,
    что измерено: старое не задето, трогают только новый блок."""
    title_h = wrapped(d, x, 108, zagolovok, 27, DEEP, w, b=True,
                       center=x + w / 2, where=f"столбец · {zagolovok[:18]}")
    top = 108 + title_h + 18

    card(d, x, top, w, 50)
    ctxt(d, x + w / 2, top + 13, "указание процессу", 25, LIGHT, limit=w - 40,
         where="сегмент · указание")
    top += 50 + 14

    if blocks == 1:
        y2, h2 = top, CONTENT_BOTTOM - top
        card(d, x, y2, w, h2, stroke=GOLD, sw=3)
        ctxt(d, x + w / 2, y2 + 10, "один блок: 10 старых + новый", 23,
             DEEP, b=True, limit=w - 30, where="сегмент · база единым блоком")
        ry = y2 + 44
        for i, p in enumerate(PUNKTY + ("пункт 11 · дописан в конец",)):
            col = GOLD if i == 4 else MID
            card(d, x + 18, ry, w - 36, 30, fill=W, stroke=LIGHT, sw=2, r=7)
            ctxt(d, x + w / 2, ry + 2, p, 22, col, b=(i == 4), limit=w - 60,
                 where=f"пункт базы {i}")
            ry += 34
    else:
        old_h = 44 + 4 * 34 + 6
        y2 = top
        card(d, x, y2, w, old_h, stroke=LIGHT, sw=3)
        ctxt(d, x + w / 2, y2 + 10, "блок 1–3: старые 10 (не задеты)", 23,
             DEEP, b=True, limit=w - 30, where="сегмент · старые блоки")
        ry = y2 + 44
        for i, p in enumerate(PUNKTY):
            card(d, x + 18, ry, w - 36, 30, fill=W, stroke=LIGHT, sw=2, r=7)
            ctxt(d, x + w / 2, ry + 2, p, 22, MID, limit=w - 60,
                 where=f"пункт базы {i}")
            ry += 34
        gap_y = y2 + old_h + 16
        new_h = CONTENT_BOTTOM - gap_y
        card(d, x, gap_y, w, new_h, stroke=GOLD, sw=4)
        ctxt(d, x + w / 2, gap_y + 10, "блок 4 (новый): пункт 11 · дописан",
             22, GOLD, b=True, limit=w - 30, where="сегмент · новый блок")
        ctxt(d, x + w / 2, gap_y + 36, "точка переставлена сюда", 22, LIGHT,
             limit=w - 30, where="подпись · точка на новом блоке")

    q_top = CONTENT_BOTTOM + 48
    card(d, x, q_top, w, 54, fill=W)
    ctxt(d, x + w / 2, q_top + 13, "вопрос клиента", 25, DEEP, limit=w - 40,
         where="сегмент · вопрос")

    v_top = q_top + 54 + 20
    card(d, x, v_top, w, 108, fill=W, stroke=GOLD if blocks == 1 else TEAL, sw=5)
    wrapped(d, x + 20, v_top + 16, verdikt, 23, DEEP, w - 40, center=x + w / 2,
            where=f"вывод столбца · {zagolovok[:18]}")


def kesh():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Одна и та же правка, два разных исхода: решает раскладка блоков",
        34, MID, b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "кэш читается только тогда, когда начало промта до точки совпало "
        "с прошлым вызовом знак в знак", 26, LIGHT, limit=CW - 120, where="подзаголовок")

    stolb(d, 90, 560, "Справочник одним блоком текста",
          "весь блок изменился — прочитано 0, записано 3834, цена 1,271×",
          blocks=1)
    stolb(d, 700, 560, "Справочник четырьмя блоками, точка на новом",
          "старые блоки найдены по хэшу — прочитано 3762, цена 0,129×",
          blocks=4)

    # Контрольная точка — у обоих столбцов на ОДНОЙ высоте (CONTENT_BOTTOM):
    # это не два разных места, это одно и то же место в строении промта,
    # по-разному заполненное изнутри.
    yk = CONTENT_BOTTOM
    dashline(d, 90, 650, yk, GOLD)
    dashline(d, 700, 1260, yk, GOLD)
    ctxt(d, 675, yk + 10, "контрольная точка — выше читается кэш, ниже — нет",
         24, GOLD, b=True, limit=1170, where="подпись контрольной точки")

    # Правая колонка: условие кэша прямой формой, числа — измеренные.
    px, pw = 1360, 960
    card(d, px, 112, pw, 360, fill=SURF, stroke=LIGHT)
    txt(d, px + 36, 134, "Условие кэша", 32, DEEP, b=True, limit=pw - 72,
        where="правая колонка · название")
    uslovia = (
        "начало промта до контрольной точки совпадает знак в знак",
        "решает раскладка блоков, сложившаяся до правки",
        "кэш живёт минуты (у части провайдеров — час) и истекает сам",
    )
    y = 190
    for i, u in enumerate(uslovia):
        d.ellipse([px + 40, y + 9, px + 54, y + 23], fill=GOLD)
        y += wrapped(d, px + 74, y, u, 27, DEEP, pw - 120,
                     where=f"условие {i}") + 22

    card(d, px, 504, pw, 240, fill=W, stroke=GOLD, sw=5)
    txt(d, px + 36, 526, "Разница по цене — 9,8 раза", 32, DEEP, b=True, limit=pw - 72,
        where="правило порядка · название")
    wrapped(d, px + 36, 582, "Одна и та же дописанная правка: один блок — 1,271× "
            "цены прямого чтения, весь кэш сгорел. Четыре блока с точкой на новом "
            "— 0,129×, старое уцелело. Измерено на модели с явным кэшем, 27 "
            "вызовов этой серии.", 28, DEEP, pw - 72, where="правило порядка · текст")
    save(im, "k2-shema-kesh-lovushka.png")



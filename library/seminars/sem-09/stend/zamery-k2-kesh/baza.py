def render_items(items):
    return "\n\n".join(f"{k}. {t}\n{b}" for k, t, b in items)


def instruction(nonce=None):
    """Указание. `nonce` — метка опыта в САМОМ НАЧАЛЕ промта.

    Зачем метка. Кэш живёт минутами и переживает прогоны, поэтому «холодный» вызов,
    повторяющий текст предыдущего опыта, холодным не будет — он прочитает кэш, оставшийся
    от прошлого опыта, и число записи в кэш окажется нулём не потому, что кэш не работает,
    а потому, что замер попал в чужой тёплый след. Уникальная метка в первых символах
    промта меняет префикс целиком и делает первый вызов опыта гарантированно холодным.
    Внутри одного опыта метка одна и та же, поэтому прогрев и замер остаются сравнимыми.
    """
    if nonce is None:
        return INSTRUCTION
    return f"Код опыта: {nonce}.\n" + INSTRUCTION


def base_text(items=None, nonce=None):
    """Полный кэшируемый кусок: указание + справочник."""
    return (instruction(nonce) + "\n\nСПРАВОЧНИК ЦЕНТРА\n\n"
            + render_items(items if items is not None else KB_ITEMS))


def items_for(kind):
    """Четыре состояния справочника: без правки / дописан в конец / вставлен в середину /
    правка в начале."""
    items = list(KB_ITEMS)
    if kind == "bez_pravki":
        return items
    if kind == "dopisan_v_konets":
        return items + [NEW_ITEM]
    if kind == "vstavlen_v_seredinu":
        mid = len(items) // 2
        return items[:mid] + [NEW_ITEM] + items[mid:]
    if kind == "pravka_v_nachale":
        return [NEW_ITEM] + items
    raise ValueError(kind)


def variant(kind, nonce=None):
    return base_text(items_for(kind), nonce=nonce)



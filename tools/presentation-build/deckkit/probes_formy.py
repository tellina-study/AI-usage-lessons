"""НАРОЧНО СЛОМАННЫЕ ВХОДЫ и общая раскладка пробного кадра для трёх новых
форм: таймлайн · нижняя плашка-вывод · пиктограммная сетка.

Правило пакета то же, что у `probes.py`: ПРОВЕРКА, НЕ ПРОВЕРЕННАЯ НА
СЛОМАННОМ ВХОДЕ, — НЕ ПРОВЕРКА. Прогон, показавший ноль, ничего не значит,
пока не доказано, что проверка умеет находить.

Раскладка здесь ОДНА на три самопроверки, и это не экономия строк: кадры
трёх проб обязаны отличаться только формой, иначе глаз, сравнивающий
снимки, спорит с полями, а не со схемой. Раскладка нарочно самая простая —
заголовок, золотая черта, форма во всю ширину тела; настоящая дека кладёт
форму в свою геометрию (`refdeck.Geometry`), и чем проба проще, тем меньше
шансов, что найденное в ней окажется свойством пробы.

Словари входов ключуются «тег слово»: слово после тега отличает одну
проверку от другой внутри одного тега.
"""
from pptx.enum.text import PP_ALIGN

from . import metrics, prims, report
from .theme import DEEP, GOLD, LIGHT, SLIDE_H, SLIDE_W, WHITE

MX = 0.55
TITLE_Y = 0.40
TITLE_H = 0.92
TICK_Y = 1.24
BODY_TOP = 1.58
FOOT_Y = 6.94
FULL_W = SLIDE_W - 2 * MX


def page(p, title, note=""):
    """Пробный кадр: белый фон, заголовок, золотая черта. Возвращает
    (кадр, верх тела, левый край, ширина тела)."""
    s = prims.blank(p)
    prims.rect(s, 0, 0, SLIDE_W, SLIDE_H, WHITE, count="фон")
    sz = metrics.fit_size(title, FULL_W, TITLE_H, hi=27.0, lo=19.0,
                          floor=15.0, bold=True, ls=1.08,
                          tag="проба/заголовок")
    prims.text_box(s, MX, TITLE_Y, FULL_W, TITLE_H, title, size=sz,
                   bold=True, color=DEEP, ls=1.08, tag="проба/заголовок")
    prims.rect(s, MX, TICK_Y, 1.05, 0.055, GOLD, count="акцент")
    if note:
        prims.text_box(s, MX, FOOT_Y, FULL_W, 0.42, note, size=11.0,
                       italic=True, color=LIGHT, ls=1.12,
                       tag="проба/подвал", quiet=True)
    return s, BODY_TOP, MX, FULL_W


def ruler(s, y, x=MX, w=FULL_W, label=""):
    """Тонкая мерная черта: где кончилась форма по СВОЕЙ мере.

    Нужна приёмке глазами: снимок показывает, где форма кончилась НА
    САМОМ ДЕЛЕ, а эта черта — где она обещала кончиться. Расхождение
    между ними и есть дефект меры, и увидеть его иначе нечем."""
    prims.rect(s, x, y, w, 0.012, LIGHT, count=None)
    if label:
        prims.text_box(s, x, y + 0.02, w, 0.20, label, size=9.0,
                       italic=True, color=LIGHT, align=PP_ALIGN.RIGHT,
                       ls=1.0, tag="проба/мера", quiet=True)


def clean_run(fn):
    """Прогон на ЧИСТОМ входе: вернуть список предупреждений."""
    report.reset()
    fn()
    return list(report.WARNINGS)



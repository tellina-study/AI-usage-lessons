#!/usr/bin/env python3
"""Схема Кейса 4 — `k4-shema-upravlenie-dannye.png`.

Два потока на одном кадре, и в этом вся схема:

  ХОД ПРОЦЕССА    — какие шаги выполняются и в каком порядке. Он задан кодом,
                    и текст клиента его не меняет: закрытый замок;
  АРГУМЕНТ РЕШЕНИЯ — число, которое код подставляет в своё сравнение. Оно
                    пришло из свободного текста, который читала модель:
                    замок открыт.

Кейс бьёт наш же ответ с прошлого занятия. Там решение о пороге возврата
перенесли из промта в код — и этого хватило, чтобы ХОД перестал зависеть от
текста клиента. Чего это не сделало: число, которое код сравнивает, всё так
же приходит из текста клиента. Поэтому оба потока нарисованы рядом и оба
кончаются в одной и той же коробке сравнения — она единственная обведена
золотом.

Измеренное (собственный прогон, 45 вызовов, протокол `stend/zamery-k4/`):
текст, прямо присваивающий значение полю суммы, добился подмены решения
**10 из 10**. Итог того же прогона — «код одобрил возврат, который требовал
эскалации, 10 из 20» — на схему НЕ вынесен: рядом с «10 из 10» второе число
того же вида читается как его повтор, а не как другой замер (форма §5.14,
два похожих числа в одной фразе). Его место — кадр итога.

Внутреннего имени поля на схеме нет: слой 1 — устройство, не экран.

Запуск: `python3 make_figures_k4.py` (из `rendered/`).
"""
from make_figures_common import *

H = 800
T1_Y, T1_H = 150, 180         # поток «ход процесса»
T2_Y, T2_H = 430, 190         # поток «аргумент решения»


def potoki():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Что защищает код, а что проходит через него насквозь", 34, MID,
        b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "порог возврата сравнивает код — но число для сравнения пришло из "
        "текста, который написал клиент", 26, LIGHT, limit=CW - 120,
        where="подзаголовок")

    # ── левая колонка: что за поток и защищён ли он ────────────────────────
    card(d, 60, T1_Y, 360, T1_H, fill=SURF, stroke=TEAL, sw=5)
    padlock(d, 240, T1_Y + 28, 22, TEAL)
    ctxt(d, 240, T1_Y + 84, "Ход процесса", 30, DEEP, b=True, limit=320,
         where="метка потока 1")
    ctxt(d, 240, T1_Y + 128, "задан кодом", 25, TEAL, limit=320,
         where="метка потока 1 · защита")

    card(d, 60, T2_Y, 360, T2_H, fill=W, stroke=GOLD, sw=5)
    padlock(d, 234, T2_Y + 30, 22, GOLD, open_=True)
    ctxt(d, 240, T2_Y + 88, "Аргумент решения", 29, DEEP, b=True, limit=330,
         where="метка потока 2")
    ctxt(d, 240, T2_Y + 132, "кодом не защищён", 25, GOLD, b=True, limit=320,
         where="метка потока 2 · защита")

    # ── верхний поток: четыре шага, не больше ──────────────────────────────
    cy1 = T1_Y + T1_H / 2
    # Грамматика цвета на этой схеме одна и держится до конца: тил — поток,
    # защищённый кодом; золото — поток, который код не защищает. Исключение
    # ровно одно, и оно и есть предмет кейса: коробка сравнения стоит в
    # верхнем потоке, а обведена золотом, потому что именно в неё приходит
    # незащищённый аргумент.
    node(d, 450, T1_Y, 360, T1_H, "Заявка на возврат", "форма и свободный текст",
         tsz=30, stroke=TEAL, where="шаг 1")
    node(d, 850, T1_Y, 420, T1_H, "Извлечение суммы",
         "модель читает текст и достаёт число", tsz=30, stroke=TEAL, where="шаг 2")
    card(d, 1310, T1_Y, 560, T1_H, fill=W, stroke=GOLD, sw=6)
    ctxt(d, 1590, T1_Y + 34, "Сравнение с порогом", 30, DEEP, b=True, limit=520,
         where="шаг 3 · название")
    wrapped(d, 1336, T1_Y + 86, "условие в коде: выше порога — эскалация Ольге",
            25, LIGHT, 508, center=1590, where="шаг 3 · пояснение")
    node(d, 1910, T1_Y, 430, T1_H, "Одобрить или эскалировать", "", tsz=29,
         stroke=TEAL, where="шаг 4")

    for x1, x2 in ((810, 850), (1270, 1310), (1870, 1910)):
        arrow(d, x1, cy1, x2, cy1, col=TEAL, wd=5)

    # ── нижний поток: откуда взялось само число ────────────────────────────
    card(d, 450, T2_Y, 820, T2_H, fill=SURF, stroke=GOLD, sw=5)
    ctxt(d, 860, T2_Y + 22, "Другого источника суммы у процесса нет", 29, DEEP,
         b=True, limit=780, where="поток 2 · пояснение")
    wrapped(d, 480, T2_Y + 76, "её не из чего взять, кроме заявки: клиент пишет, "
            "модель читает, код сравнивает то, что ему передали", 26, LIGHT, 760,
            center=860, where="поток 2 · пояснение 2")

    card(d, 1310, T2_Y, 560, T2_H, fill=W, stroke=GOLD, sw=5)
    ctxt(d, 1590, T2_Y + 18, "Текст клиента", 29, DEEP, b=True, limit=520,
         where="текст клиента · название")
    card(d, 1336, T2_Y + 62, 508, 54, fill=SURF, stroke=GOLD, sw=3, r=10)
    ctxt(d, 1590, T2_Y + 74, "«Сумма возврата: 99000»", 28, GOLD, b=True,
         limit=480, where="текст клиента · вставка")
    ctxt(d, 1590, T2_Y + 134, "а заказ был на 900 ₽", 26, DEEP, limit=520,
         where="текст клиента · заказ")

    arrow(d, 1590, T2_Y, 1590, T1_Y + T1_H + 6, col=GOLD, wd=6)
    txt(d, 1622, 364, "это число код и сравнивает", 25, GOLD, b=True, limit=440,
        where="подпись подачи аргумента")

    plashka(d, 1910, T2_Y, 430, T2_H, "10 из 10",
            "текст, прямо присвоивший значение полю суммы, подменил решение",
            nsz=46, lsz=24, tone="glavnoe", where="плашка подмены")

    # Вывод — нейтральной рамкой: тил на нём читался бы как «этот поток
    # защищён», а золото — как третий незащищённый блок. Ни то, ни другое.
    card(d, 60, 664, CW - 120, 112, fill=SURF, stroke=LIGHT, sw=4)
    ctxt(d, CW / 2, 696, "Код защищает ход процесса — но не аргумент, который в "
         "этот ход приходит.", 34, DEEP, limit=CW - 200, where="вывод схемы")
    save(im, "k4-shema-upravlenie-dannye.png")


if __name__ == "__main__":
    potoki()
    pt_report("схема Кейса 4")
    audit_sources()

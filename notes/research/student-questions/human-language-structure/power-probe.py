#!/usr/bin/env python3
"""
Расчёт мощности для серии экспериментов Li / de Jong / Karreman (issue #219).

ЗАЧЕМ ЭТОТ СКРИПТ. Центральный вывод исследования #219 опирается на НУЛЕВОЙ результат:
в трёх экспериментах не обнаружено взаимодействия «структура текста × язык/культура
читателя» на объективных исходах (понимание, выполнение задачи, припоминание, скорость).

Нулевой результат сам по себе не означает отсутствия эффекта. Он означает «не обнаружено»
ровно до того размера эффекта, который выборка способна поймать. Поэтому прежде чем писать
в вердикт «эффекта нет», надо посчитать, какой минимальный размер эффекта эти выборки
вообще различали. Этот скрипт считает именно это и воспроизводится одной командой:

    python3 power-probe.py

Требует scipy (используется нецентральное F-распределение).

ИСТОЧНИК ЧИСЕЛ N И ДИЗАЙНОВ (все три — см. файл 02-cross-language-interaction.md):
  * Li, de Jong & Karreman 2015, Technical Communication 62(3), 163-182 — N=80,  дизайн 2x2
  * Li, de Jong & Karreman 2021, Technical Communication 68(1)          — N=127, дизайн 3x2
  * Li, Karreman & de Jong 2020, J. of Business and Technical Comm. 34  — N=158, дизайн 2x3
    (DOI 10.1177/1050651920932192)
N для 2021 (=127) и дизайн сверены оркестратором по полному тексту открытого PDF;
N=80 и N=158 — по чтению субагентом полного текста/диссертации.

КОНВЕНЦИЯ. Нецентральность lambda = f^2 * N (конвенция Коэна, та же, что в G*Power для
«as in SPSS»). partial eta^2 пересчитывается из f^2 как f^2/(1+f^2). Знаменательные степени
свободы = N - (число оцениваемых средних по клеткам).
"""

from scipy import stats, optimize

ALPHA = 0.05
TARGET_POWER = 0.80


def power_f(f2: float, n: int, df1: int, n_cells: int, alpha: float = ALPHA) -> float:
    """Мощность F-теста для эффекта взаимодействия с df1 степенями свободы в числителе."""
    df2 = n - n_cells
    lam = f2 * n
    crit = stats.f.ppf(1 - alpha, df1, df2)
    return 1 - stats.ncf.cdf(crit, df1, df2, lam)


def min_detectable(n: int, df1: int, n_cells: int, target: float = TARGET_POWER):
    """Минимальный обнаружимый эффект при заданной мощности: возвращает (f^2, partial eta^2)."""
    f2 = optimize.brentq(lambda x: power_f(x, n, df1, n_cells) - target, 1e-6, 5.0)
    return f2, f2 / (1 + f2)


def eta_to_f2(eta: float) -> float:
    return eta / (1 - eta)


STUDIES = [
    # (подпись, N, df1 взаимодействия, число клеток)
    ("Li 2015, 2x2 (N=80)", 80, 1, 4),
    ("Li 2021, 3x2 (N=127)", 127, 2, 6),
    ("Li 2020, 2x3 (N=158)", 158, 2, 6),
    ("гипотетический пул трёх (N=365)", 365, 2, 6),
]


def main() -> None:
    print(f"alpha = {ALPHA}, целевая мощность = {TARGET_POWER}\n")

    print("1. Минимальный обнаружимый эффект взаимодействия")
    print(f"{'исследование':<34}{'f^2':>9}{'partial eta^2':>15}")
    for label, n, df1, cells in STUDIES:
        f2, eta = min_detectable(n, df1, cells)
        print(f"{label:<34}{f2:>9.4f}{eta:>15.3f}")

    print("\n2. Мощность против эффектов конкретного размера")
    print("   (partial eta^2 = .01 малый, .06 средний, .14 большой — конвенция Коэна)")
    print(f"{'исследование':<34}" + "".join(f"{f'eta2={e}':>13}" for e in (0.01, 0.02, 0.05, 0.06)))
    for label, n, df1, cells in STUDIES:
        row = "".join(f"{power_f(eta_to_f2(e), n, df1, cells):>13.2f}" for e in (0.01, 0.02, 0.05, 0.06))
        print(f"{label:<34}{row}")

    print("""
ВЫВОД, который идёт в вердикт (00-verdict.md, часть про границы):

  Каждый из трёх экспериментов надёжно различал только взаимодействие СРЕДНЕГО и большего
  размера. Против МАЛОГО взаимодействия (partial eta^2 = .01-.02) мощность каждой отдельной
  выборки — от 0.14 до 0.34, то есть такой эффект был бы пропущен в двух случаях из трёх
  и чаще.

  Поэтому корректная формулировка — «взаимодействия среднего и большего размера не
  обнаружено», а НЕ «взаимодействия не существует». Малое взаимодействие структуры с языком
  на объективных исходах этими данными не исключено.

  Почему вывод для практики от этого не меняется: эффекты структуры ВНУТРИ одного языка,
  измеренные в той же литературе, крупные (см. файлы 01 и 03 — например, 0% против 54.7%
  правильных решений на несогласованных формулировках под вычислительной нагрузкой,
  Bestgen 2009). Если языко-специфичная поправка существует, она на порядок меньше самого
  эффекта структуры — то есть писать понятно важнее, чем писать «по-русски» или
  «по-китайски».""")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Волна 2в «конфетки» Семинара 8 (issue #292) — ДВЕ новые фигуры.

    figures/tg-k4-gen-razbor.png       три колонки: карточка, которую
                                       нарисовала модель; две строки её
                                       собственного текста крупно; подпись к
                                       тому же фото, собранная шаблоном
    figures/tg-k4-kartochka-shiroko.png  тот же кадр карточки Кейса 4, что и
                                       `tg-k4-kartochka.png`, но в ШИРОКОМ окне
                                       клиента

ЗАЧЕМ ОТДЕЛЬНАЯ ФИГУРА, А НЕ ГОТОВЫЙ `tg-k4-gen-kartochka.png`. Готовый кадр
волны 1г — вертикальный мокап чата, 1400×1333, пропорция 1,05. На слайде он
упирается в потолок высоты приёма (`deck_kit.FIG_NATURAL_H` = 4,3″) и занимает
4,5″ из 12,23″ — 37% полосы, то есть ловит `СХЕМА ЗАЖАТА` и оставляет две
трети экрана пустыми. Здесь из ТОГО ЖЕ файла вырезаны три прямоугольника и
поставлены в ряд: пропорция 2,80, полоса занята на 98%, высота на слайде 4,30″
вместо 3,13″, а строка текста, ради которой кадр и ставится, читается 19 pt
вместо 10 pt. Все четыре числа печатает сам `main()` при запуске.

НИ ОДИН ПИКСЕЛЬ НЕ ПЕРЕРИСОВАН. Источник — `figures/tg-k4-gen-kartochka.png`
(волна 1г, `make_figures_k4gen.py`): рамка чата рисованная, но сама карточка
в ней — файл, скачанный ОБРАТНО из Telegram по `file_id` доставленного
сообщения выполнения 600, а подпись — поле `result.caption` того же
сообщения, слово в слово. Рисуются поверх только полосы подписей
(`caption_bar` из `make_figures_k4gen`), и они явно нарисованы, а не вырезаны
из интерфейса. Опечатки «зяявка» и «заняятия» в кадре НЕ исправляются: это
измеренный результат шага, и подрисовать буквы значило бы подделать ровно то
место, ради которого кадр и стоит (см. `k4-generatsiya-izmereniya-2026-10-22.md`,
раздел «Что оценка не предвидела вовсе», пункт 1).

ЧТО НЕ ТРОГАЕТСЯ. Скрипт пишет ДВА НОВЫХ имени и ни одного существующего.
`make_figures_k4gen.py` и `make_figures_telegram.py` импортируются ради раскладки подписей и констант —
их `main()` закрыты `if __name__`, то есть импорт ничего не перерисовывает
([#292-3]: две рисовалки не должны писать одно имя).

Запуск: `python3 make_figures_w2v.py` (из `rendered/`).
"""
from pathlib import Path

from PIL import Image

import make_figures_k4gen as G
import make_figures_telegram as T

HERE = Path(__file__).resolve().parent
OUT = HERE / "figures"
SRC = OUT / "tg-k4-gen-kartochka.png"
RAW = HERE.parent / "stend" / "n8n-screenshots-raw"

# Ширина окна клиента для кадра карточки Кейса 4. Мокап волны 1в собран при
# `make_figures_telegram.W = 1400` — пропорция 1,45, и на слайде кадр берёт
# 6,23″ из 12,23″ (51% полосы, `СХЕМА ЗАЖАТА`): чат с ФОТОГРАФИЕЙ внутри
# пузыря высок по построению, и потолок высоты приёма (4,3″) упирается в него
# при любом содержании слайда. Ширина окна — не измеренный факт, а размер окна
# на экране получателя: 2300 px даёт пропорцию 2,38 и 84% полосы. Пузырь при
# этом НЕ меняется ни на пиксель (его ширина — `BUB_MAX`, не доля холста), то
# есть на слайде он того же физического размера, что и прежде; шире становится
# пустая часть чата — ровно так и выглядит Telegram Desktop в развёрнутом окне.
WIDE_W = 2300

# Прямоугольники по исходнику 1400×1333. Границы найдены замером по пикселям,
# не на глаз: карточка — область синего градиента (строки 266–1192, столбцы
# 70–996); строки белого текста внутри карточки — 623–672, 696–746, 784–833;
# подпись под фотографией — 1213–1232 по строкам, 73–777 по столбцам.
# Взяты первая и третья строки текста: в них обе опечатки («зяявка»,
# «заняятия»). Вторая строка («Олег: тема») набрана верно, и показывать её
# крупно значило бы занять место ничем.
CARD = (70, 266, 997, 1193)
LINE_1 = (190, 612, 825, 682)
LINE_3 = (178, 773, 890, 843)
CAPTION = (62, 1200, 800, 1246)

# Размеры подобраны ЗАМЕРОМ, а не на глаз, и каждый упирается в свой порог.
# Общая ширина композита решает кегль полос подписи (они набираются
# фиксированными 25/21 px): при 2900 px подпись выходила 7,6/6,4 pt — ниже
# пола 7,5 pt (план §3.6). При 2000 px — 11,0/9,2 pt. Пропорция решает,
# сколько кадр займёт на слайде: 2,95 даёт полную полосу и высоту 4,15″ (при
# 3,91 было 3,13″ и треть экрана пустовала). Числа печатает сам `main()`.
CARD_SIDE = 568        # сторона карточки в композите
ZOOM = 0.88            # масштаб строк текста модели
CAP_ZOOM = 1.01        # масштаб подписи (её кегль в мокапе вдвое мельче)
STRIP_GAP = 16         # две строки одного текста — просвет как между строк


def _scaled(src, box, k):
    c = src.crop(box)
    return c.resize((int(c.width * k), int(c.height * k)), Image.LANCZOS)


def _stack(parts, gap=STRIP_GAP):
    w = max(p.width for p in parts)
    h = sum(p.height for p in parts) + gap * (len(parts) - 1)
    out = Image.new("RGB", (w, h), G.W)
    y = 0
    for p in parts:
        out.paste(p, (0, y))
        y += p.height + gap
    return out


def razbor():
    src = Image.open(SRC).convert("RGB")
    card = src.crop(CARD).resize((CARD_SIDE, CARD_SIDE), Image.LANCZOS)
    lines = _stack([_scaled(src, LINE_1, ZOOM), _scaled(src, LINE_3, ZOOM)])
    cap = _scaled(src, CAPTION, CAP_ZOOM)
    return G.compose([
        (card, "Карточка, которую нарисовала модель",
         "доставлена в Telegram, выполнение 600"),
        (lines, "Текст внутри картинки — рисует модель",
         "«зяявка» · «заняятия»: так во всех пяти карточках"),
        (cap, "Подпись к тому же фото — собирает шаблон",
         "верна слово в слово"),
    ])


def kartochka_shiroko():
    """Кадр карточки Кейса 4 в широком окне клиента.

    Текст подписи, фотография и время берутся из `make_figures_telegram`
    БЕЗ изменений — это та же константа `T_K4` (поле `result.caption`
    выполнения 594) и тот же файл, скачанный обратно из Telegram по
    `file_id`. Меняется ровно одно число — ширина холста, и меняется она
    на время вызова: модульная `W` возвращается на место в `finally`,
    иначе следующий импорт `make_figures_telegram` в этом же процессе
    собрал бы ЧУЖИЕ кадры другой ширины."""
    photo = Image.open(
        RAW / "k4-card-photo-exec594-telegram-delivered.jpg").convert("RGB")
    saved = T.W
    try:
        T.W = WIDE_W
        return T.canvas(T.CHAT_NAME, T.CHAT_SUB, [
            dict(text=T.T_K4, time_s="13:12", sender=T.BOT_NAME, photo=photo),
        ])
    finally:
        T.W = saved


def main():
    wide = kartochka_shiroko()
    wide.save(OUT / "tg-k4-kartochka-shiroko.png")
    w_in_wide = min(G.BAND_IN, G.FIG_MAX_H_IN * wide.width / wide.height)
    print(f"tg-k4-kartochka-shiroko.png {wide.size}  "
          f"пропорция {wide.width / wide.height:.2f}; на слайде "
          f"{w_in_wide:.2f}″ ({w_in_wide / G.BAND_IN:.0%} полосы; пол 80%)")

    im = razbor()
    im.save(OUT / "tg-k4-gen-razbor.png")
    print(f"tg-k4-gen-razbor.png {im.size}  пропорция {im.width / im.height:.2f}")
    w_in = min(G.BAND_IN, G.FIG_MAX_H_IN * im.width / im.height)
    print(f"   на слайде {w_in:.2f}″ из {G.BAND_IN}″ "
          f"({w_in / G.BAND_IN:.0%} полосы; пол приёма 80%)")
    # Кегль текста карточки на экране зала: строка белого текста внутри
    # карточки высотой 50 px исходника, увеличенная ZOOM раз.
    pt = w_in * 72 / im.width
    print(f"   строка текста модели: {50 * ZOOM * pt:.1f} pt; "
          f"та же строка внутри карточки: {50 * CARD_SIDE / 927 * pt:.1f} pt; "
          f"подпись: {20 * CAP_ZOOM * pt:.1f} pt (пол 7,5 pt)")


if __name__ == "__main__":
    main()

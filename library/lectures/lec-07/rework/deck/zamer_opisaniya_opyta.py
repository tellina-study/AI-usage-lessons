#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ОПИСАНИЕ ОПЫТА на кадре-примере: кто и сколько · что делали · чем мерили.

Повод (владелец, 2026-10-15, глядя на восьмой слайд): «в кейсах не хватает
собственно описания кейса. Сразу про ошибку, а что они делали то? Нету только
голосом. Обязательно слайд должен читаться и без голоса, и ключевая информация
должна быть понятна». Сказано ВТОРОЙ раз: первый круг ответил блоком «Что
делали», который описывал ОБСТАНОВКУ («подсказка приходила в готовом виде»), а
не ОПЫТ («пятьдесят врачей читали по пять описаний случаев и строили
рассуждение; оценивали слепо по шкале»). Разница между обстановкой и опытом —
это и есть то, что зал не может восстановить без голоса.

ЧТО СЧИТАЕТСЯ ОПИСАНИЕМ ОПЫТА — три части, все три на ВИДИМОМ слое:
  1. КТО и СКОЛЬКО — «пятьдесят практикующих врачей», «717 изделий»,
     «10 343 пациента». Не «врачи», не «клиницисты» без числа.
  2. ЧТО ДЕЛАЛИ — действие участника, глаголом: читали · оценивали · вели ·
     распределяли вслепую · каждый дважды. Не «инструмент выдали».
  3. ЧЕМ МЕРИЛИ — названная величина со знаменателем: доля верных заключений ·
     чувствительность · балл по шкале · минуты труда · процедуры из ста.

ТРИ ВЕЩИ, КОТОРЫЕ ПУТАЮТ С ОПИСАНИЕМ ОПЫТА — ни одну прогон не различает:
  * **обстановка** — «подсказка приходила в готовом виде, и никто не учил
    врачей». Описывает условия, не замер;
  * **классический режим** — «шкалу считали руками: баллы по таблице, сумма,
    порог; тревогу разбирает дежурная смена». Описывает, КАК РАБОТАЛИ БЕЗ
    МОДЕЛИ, и это обязательная часть разбора по §5.13 — но это НЕ тот опыт,
    из которого взялись числа кадра. Замерено на `s58`: кадр уже правили в
    этом круге, он получил описание работы и всё равно остался без описания
    замера, давшего «18 и 12 из ста»;
  * **разряд свидетельства** — «рандомизированное», «метаанализ». Отвечает на
    вопрос «насколько верить», а не «что делали» (печатается справкой ниже).
Все три выглядят как описание и читаются на кадре естественно. Отличает их
один вопрос: **откуда взялось число, которое стоит рядом?**

ЧЕГО ЭТОТ ПРОГОН НЕ УМЕЕТ — читать прежде, чем поверить его числу:
  * Он ищет ПРИЗНАКИ по шаблонам, а не понимает текст. «Сорок клиницистов
    читали снимки, каждый дважды» он засчитает; «группа специалистов провела
    серию чтений» — нет, и будет прав по делу, но не по формальному признаку.
    Поэтому выход читают, а не считают: он называет, ЧЕГО не нашёл.
  * Три части он проверяет по отдельности и НЕ проверяет, что они про один и
    тот же опыт. Кадр, где «717 изделий» из одного замера, а «доля верных
    заключений» из другого, он пропустит. Это ловится только чтением.
  * Он молчит про кадры, где описание опыта не нужно вовсе (заземление, свод,
    дивайдер) — смотрит только `type: case`.

Шаблоны — Python `re`, не `grep -P`: на кириллице `-P` даёт ложный ноль.

    python3 zamer_opisaniya_opyta.py --selftest
    python3 zamer_opisaniya_opyta.py            # прогон по slides/s*.md
    python3 zamer_opisaniya_opyta.py s05 s45    # по отдельным кадрам
"""
import glob
import re
import sys

import yaml

sys.path.insert(0, '.')
from vidimyy_sloy_polnyy import polnyy

CHISLO = r'(\d[\d \s]{0,7}|сорок|пятьдесят|тридцать|двадцать|сто|двести|' \
         r'триста|тысяч[аи]?|десять|одиннадцать|двенадцать|пятнадцать|шестнадцать|' \
         r'семнадцать|восемнадцать|девятнадцать)'
# ЛОЖНЫЙ ПРОБЕЛ ДОРОЖЕ ЛОЖНОГО ЗАЧЁТА, и это стоит знать тому, кто будет
# расширять шаблоны. Ложный зачёт — тихая недоработка: кадр остался без
# описания, никто ничего не испортил. Ложный пробел — ПРИКАЗ ИСПОРТИТЬ КАДР:
# исполнитель дописывает то, что уже стоит, тратя слова там, где их нет.
# Замерено на `s35a`: кадр стоит на 145 словах с тонким запасом кегля, и
# дописать ему «кто» значило бы заплатить кеглем за ошибку шаблона.
# Поэтому при сомнении шаблон расширяют в сторону ЗАЧЁТА, а спорное ловят
# чтением — прогон для того и печатает, чего он не умеет.

# ЕДИНИЦА НАБЛЮДЕНИЯ В ЭТОЙ ДЕКЕ — НЕ ТОЛЬКО ЛЮДИ. Список собран по тому, что
# реально стоит на кадрах, а не по тому, что кажется: `s30` печатался пробелом
# «КТО и сколько», хотя счёт на кадре стоял — «656 ИЗОБРАЖЕНИЙ с биопсией:
# 208 светлых · 241 средних · 207 тёмных». Найдено исполнителем подстановкой,
# 2026-10-15. Эта половина ошибки ДОРОЖЕ обратной: она гонит дописывать то,
# что уже стоит, то есть тратить слова на кадре, где их и так нет.
# `патолог` — ТОЛЬКО человек. «восемнадцать ПАТОЛОГИЙ» — находки прибора,
# и на `s01d` кадр красился зелёным, хотя никакого «кто и сколько» на нём
# не было. Лечится не списком, а формой слова: окончания патологии
# отсекаются, окончания патолога остаются.
LYUDI = r'(врач|клиницист|радиолог|патолог(?!и[йяиею]|ическ)|участник|человек|пациент|специалист|' \
        r'хирург|ординатор|эндоскопист|испытуем|издели|случа|процедур|снимк|' \
        r'маммограмм|программ|больниц|центр|смен|изображени|визит|клиник|' \
        r'госпитализац|обращени|приём|приема|заметк|прочтени|пациенто-|' \
        r'выписк|эпикриз|тревог|колоноскопи|операц|образц|пробы|пробами|' \
        r'женщин|мужчин|работ|публикац|исследовани|задач|вопрос)'

# Между числом и существительным помещается определение: «пятьдесят
# ПРАКТИКУЮЩИХ врачей», «717 радиологических изделий». Самопроверка поймала
# это на первом же прогоне: шаблон без зазора объявил ложную тревогу на
# образцовом описании опыта. Зазор — до двух слов, дальше начинается другая мысль.
KTO = re.compile(CHISLO + r'\s+(?:[а-яёa-z]+\s+){0,2}' + LYUDI + r'\w*', re.I)
# ЛЕВАЯ ГРАНИЦА У КАЖДОГО ГЛАГОЛА — не украшение. Без неё `читал\w+` ловится
# внутри слова «по-с-ЧИТАЛ-и», и кадр получает зачёт по части «ЧТО ДЕЛАЛИ» за
# слово в собственном заголовке («исправление посчитали и не применили»).
# Найдено исполнителем на `s32` при работе ПО этому прогону, 2026-10-15. Класс
# известен каноном курса и уже стоил ложных находок: односторонний якорь
# `[Рр]ол[ьияею]\b` находил «роля» внутри «контроля» (`CLAUDE.md` §8.6).
CHTO = re.compile(
    r'(?<![а-яё])('
    r'читал\w+|оценивал\w+|разбирал\w+|строил\w+|назначал\w+|выполнял\w+|'
    r'проводил\w+|сравнивал\w+|распредел\w+|вели(?![а-яё])|каждый\s+дважды|'
    r'независимо\s+друг|подавал\w+|подсчит\w+|переписал\w+|прочёл|прочли|'
    r'снимал\w+|заполнял\w+|вводил\w+|размечал\w+|опрашивал\w+|'
    r'выявлял\w+|выявляли|распределял\w+|подсчитал\w+|отбирал\w+|'
    r'наблюдал\w+|опубликовал\w+)', re.I)
CHEM = re.compile(
    r'(по\s+шкале|балл\w*|чувствительност\w+|специфичност\w+|дол[яюи]\s+\w+|'
    r'площад\w+\s+под\s+кривой|c-статистик\w*|с-статистик\w*|минут\w*\s+труда|'
    r'из\s+ста\b|на\s+сто\b|'
    r'время\s+(в|до|выведения)|частот\w+\s+\w+)', re.I)

# ПРИЗНАКИ ДИЗАЙНА — НЕ ДЕЙСТВИЕ УЧАСТНИКА, и держать их внутри «ЧТО ДЕЛАЛИ»
# было ошибкой устройства, а не списка. Нашла её полоса Входа 2026-10-15:
# `s47` получал зачёт за слово «рандомизированное» в подписи плашки — а это
# РАЗРЯД СВИДЕТЕЛЬСТВА, которым в этой деке размечена добрая половина кадров,
# и стоит оно прилагательным рядом со специфичностью. `рандомизир\w+` ловит и
# глагол («рандомизировали»), и прилагательное; второе встречается чаще.
# Часть заводилась со словами «действие участника, ГЛАГОЛОМ» — значит, зачёт
# за прилагательное противоречит её собственному определению.
# Теперь они печатаются СПРАВКОЙ: сигнал полезный, зачёта не даёт.
DIZAYN = re.compile(
    r'(?<![а-яё])(рандомизир\w+|вслепую|слепо|плацебо|контрольн\w+\s+групп\w+|'
    r'случайным\s+распределением|жребием?|двойн\w+\s+слеп\w+|проспективн\w+|'
    r'ретроспективн\w+|метаанализ\w*)', re.I)

CHASTI = (('КТО и сколько', KTO), ('ЧТО ДЕЛАЛИ', CHTO), ('ЧЕМ МЕРИЛИ', CHEM))

SLOMANNYY = ('Инструмент выдали, процедуру работы с ним — нет. '
             'Подсказка приходила в готовом виде.')
CHISTYY = ('Пятьдесят практикующих врачей читали по пять описаний случаев и строили '
           'рассуждение; оценивали слепо по шкале диагностического рассуждения.')
# Два входа, купленные находками исполнителя 2026-10-15 (см. комментарии выше).
LOZHNYY = 'Пример 3, цена: исправление посчитали и не применили.'
# Один признак дизайна без единого действия участника зачёта давать НЕ должен.
TOLKO_DIZAYN = 'Рандомизированное; специфичность 98,5 в обоих плечах.'
# Величина, названная со шкалой, обязана засчитываться: кадр делает больше,
# чем часть требует, и ложный пробел на нём — приказ дописать в 138 слов.
S_STATISTIKA = ('Сорок клиницистов читали случаи; c-статистика: '
                '0,5 — монетка, 1,0 — без промаха.')
# «восемнадцать патологий» — не «кто и сколько»: это находки прибора.
PATOLOGII = 'Страница в браузере: восемнадцать патологий и строка «не для диагностики».'
# «женщины» — единица наблюдения лекции про скрининг, и её в списке не было.
ZHENSHCHINY = ('80 033 женщины распределяли случайно между двумя режимами чтения; '
               'считали чувствительность на сто обследованных.')
EDINITSA = ('656 изображений с биопсией: 208 светлых, 241 средних, 207 тёмных; '
            'размечали независимо друг от друга, доля верных из ста.')


def razbor(text):
    return [(name, bool(pat.search(text))) for name, pat in CHASTI]


def vidimyy(f):
    v = polnyy(f)
    return v if isinstance(v, str) else '\n'.join(
        str(x) for x in (v if isinstance(v, (list, tuple)) else v.values()))


def selftest():
    bed = 0
    got = dict(razbor(SLOMANNYY))
    ok = not all(got.values())
    print(f'  {"НАШЛА пробел" if ok else "ПРОПУСТИЛА"} на обстановке без опыта: '
          f'{ {k: v for k, v in got.items()} }')
    bed += 0 if ok else 1
    got = dict(razbor(CHISTYY))
    ok = all(got.values())
    print(f'  {"молчит" if ok else "ЛОЖНАЯ ТРЕВОГА"} на настоящем описании опыта: '
          f'{ {k: v for k, v in got.items()} }')
    bed += 0 if ok else 1
    # «посчитали» НЕ должно читаться как «читали» — левая граница у глаголов.
    got = dict(razbor(LOZHNYY))
    ok = not got['ЧТО ДЕЛАЛИ']
    print(f'  {"не спутала" if ok else "СПУТАЛА"} «посчитали» с «читали»')
    bed += 0 if ok else 1
    got = dict(razbor(TOLKO_DIZAYN))
    ok = not got['ЧТО ДЕЛАЛИ']
    print(f'  {"не спутала" if ok else "СПУТАЛА"} разряд замера '
          f'(«рандомизированное») с действием участника')
    bed += 0 if ok else 1
    got = dict(razbor(S_STATISTIKA))
    ok = got['ЧЕМ МЕРИЛИ']
    print(f'  {"засчитала" if ok else "ПРОПУСТИЛА"} величину, названную со шкалой '
          f'(«c-статистика: 0,5 — монетка»)')
    bed += 0 if ok else 1
    got = dict(razbor(PATOLOGII))
    ok = not got['КТО и сколько']
    print(f'  {"не спутала" if ok else "СПУТАЛА"} «патологий» (находки прибора) '
          f'с «патологами» (люди)')
    bed += 0 if ok else 1
    got = dict(razbor(ZHENSHCHINY))
    ok = all(got.values())
    print(f'  {"засчитала" if ok else "ПРОПУСТИЛА"} «женщин» — единицу наблюдения '
          f'лекции про скрининг: { {k: v for k, v in got.items()} }')
    bed += 0 if ok else 1
    # Единица наблюдения — изображения, а не люди: счёт обязан засчитываться.
    got = dict(razbor(EDINITSA))
    ok = all(got.values())
    print(f'  {"засчитала" if ok else "ПРОПУСТИЛА"} счёт в единицах наблюдения '
          f'(изображения): { {k: v for k, v in got.items()} }')
    bed += 0 if ok else 1
    print(f'\nсамопроверка: {"ПРОЙДЕНА" if not bed else f"ПРОВАЛЕНА ({bed})"}')
    return 0 if not bed else 2


def progon(tseli):
    faily = sorted(glob.glob('slides/s*.md'))
    if not faily:
        print('кадров не найдено — запускать из deck/'); return 2
    bez, objavleno, s_opisaniem, vsego, s_razryadom = [], [], 0, 0, 0
    for f in faily:
        sid = f.split('/')[-1].split('-')[0]
        if tseli and sid not in tseli:
            continue
        fm = yaml.safe_load(open(f, encoding='utf-8').read().split('---')[1])
        # ОТБОР — по ссылке на работу, а не по метке `type`. Первая версия
        # смотрела `type: case` и пропустила ровно тот кадр, на который
        # показал владелец: `s05` помечен `summary`, а предъявляет замер
        # пятидесяти врачей. Метка описывает место кадра в рассказе, а не то,
        # ссылается ли он на чей-то опыт. Это тот же разбор, что в решении О20
        # («полоса написана по работе кадра, а не по метке») — и здесь он
        # куплен тем, что проверка пропустила кадр, отвергнутый владельцем.
        ist = str(fm.get('source') or '').strip()
        if ist in ('', '—', '-'):
            continue
        # ОБЪЯВЛЕННОЕ ОТСУТСТВИЕ — по образцу `pol_snyat`. Есть кадры, у
        # которых своего опыта нет ПО ПРИРОДЕ: карта стадии, словарь форм,
        # свод чужих опытов, таблица нескольких замеров, классический режим
        # без собственного замера. Поставить туда «пятьдесят врачей» значит
        # озеленить прогон и испортить кадр. Поэтому отсутствие ОБЪЯВЛЯЕТСЯ
        # полем `opyt_net: "<причина>"` — и тогда оно считается отдельно, а
        # не молчит: необъявленное отсутствие и названное решение обязаны
        # выглядеть по-разному, иначе следующий круг ищет их заново.
        if fm.get('opyt_net'):
            objavleno.append((sid, str(fm['opyt_net'])))
            continue
        vsego += 1
        est = razbor(vidimyy(f))
        if all(ok for _n, ok in est):
            s_opisaniem += 1
        else:
            bez.append((sid, [n for n, ok in est if not ok]))
        if DIZAYN.search(vidimyy(f)):
            s_razryadom += 1
    print(f'прочитано: кадров {len(faily)} из slides/, из них ссылаются на работу — {vsego}'
          + (f' (отбор {" ".join(sorted(tseli))})' if tseli else ''))
    print(f'несут все три части описания опыта: {s_opisaniem} · не несут: {len(bez)}'
          f' · своего опыта нет ПО РЕШЕНИЮ: {len(objavleno)}')
    print(f'СПРАВКА (зачёта не даёт): разряд замера назван на {s_razryadom} '
          f'кадрах из {vsego} — рандомизация, слепота, плацебо, тип работы.')
    for sid, net in bez:
        print(f'  {sid:7s} нет: {", ".join(net)}')
    if objavleno:
        print('\nСВОЕГО ОПЫТА НЕТ ПО ОБЪЯВЛЕННОМУ РЕШЕНИЮ — это записанное '
              'решение, не пробел:')
        for sid, why in objavleno:
            print(f'  {sid:7s} {why}')
    if not bez:
        print('\nНоль означает: на каждом кадре-примере НАЙДЕНЫ признаки всех трёх частей.')
        print('Он НЕ означает, что три части про один и тот же опыт, — это читают глазами.')
    return 1 if bez else 0


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    sys.exit(selftest() if '--selftest' in sys.argv else progon(set(args)))

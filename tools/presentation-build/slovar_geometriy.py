"""Словарь геометрий колоды: из чего она физически нарисована.

ЗАВЕДЕНА ЭТИМ ПЕРЕНОСОМ (issue #307). Прежде такой программы не было —
замер по кругам R4-R5 пробы дизайн-методики делался разовыми прогонами, и
числа жили только в журнале трения. Это та из трёх перенесённых мер,
которой НЕ существовало файлом.

ЧТО МЕРЯЕТ. Считает в сохранённом `.pptx` каждую готовую геометрию формата
(`a:prstGeom prst="…"`) и каждый свой контур (`a:custGeom`), печатает
словарь по убыванию и число РАЗЛИЧНЫХ геометрий. Фигуры без геометрии
(надписи поверх, картинки, группы-обёртки) в счёт не идут: программа
отвечает на вопрос «из чего нарисовано». Числа объектов в файле она
не даёт.

ЗАЧЕМ ЗАВЕДЕНА. Владелец после круга R4: «почему в презе не используются
другие виды фигур? в PowerPoint можно же столько сделать комбинацией
разных фигур, их наложением и объединением. а у тебя только прямоугольники
и палки». Замер (запись Т-40 журнала трения) ответил числом: формат даёт
182 готовые геометрии (`len(MSO_SHAPE)`, проверено прогоном), курс
пользуется ТРЕМЯ. И это не склонность дизайнера — в каталоге 33 форм не
было ни одной записи про геометрию: каталог описывает, что форма
утверждает и какие у неё слоты, и молчит о том, из чего она сложена.
Поэтому любая новая форма собиралась из того, что лежит под рукой, — а под
рукой прямоугольник.

ЭТАЛОННЫЕ ЧИСЛА — ими программа и проверяется. Прогон 2026-11-03:

    library/lectures/lec-07/rendered/lec-07.pptx
        2552 фигуры · 3 геометрии
        rect 1794 · roundRect 569 · rightArrow 189
    notes/research/dizayn-metodika/proba-R1-lec-08/rendered/proba-R4.pptx
        424 фигуры · 5 геометрий
        rect 338 · roundRect 75 · line 6 · ellipse 3 · rightArrow 2
    notes/research/dizayn-metodika/proba-R1-lec-08/rendered/proba-R5.pptx
        412 фигур · 6 геометрий
        rect 332 · roundRect 59 · ellipse 12 · custGeom 5 · homePlate 2 · chevron 2

Все три воспроизведены этой программой до единицы. Расхождение с журналом
одно и оно в журнале: таблица Т-40 называет у круга R4 «425» фигур против
424 здесь — разница в одну фигуру, разряда находки не меняет (три
геометрии против 182) и в сторону ЗАВЫШЕНИЯ прежнего числа.

КАК ЧИТАТЬ РЕЗУЛЬТАТ. Число различных геометрий — не цель и не порог.
Лекция 7 на трёх геометриях — это 189 отдельных стрелок из 2552 фигур,
то есть КАЖДАЯ ТРИНАДЦАТАЯ фигура колоды существует только чтобы сказать
«дальше направо». Круг R5 убрал их тем, что клетка конвейера сама
указывает вперёд (`homePlate` первая, `chevron` дальше) — одна фигура
вместо трёх на переход. Падение числа фигур при РОСТЕ числа геометрий и
есть то, что эта мера показывает; обратное — рост геометрий ради
разнообразия — она показать не умеет и порогом здесь не поможет.

И ГЛАВНОЕ ОГРАНИЧЕНИЕ, названное записью Т-42. Эта программа отвечает
«чем нарисовано», и НЕ отвечает «правильно ли». Готовая геометрия может
называться верно и вести себя неверно: `wedgeRoundRectCallout` — выноска
с хвостом, то самое, что нужно, — снята по замеру, потому что её хвост не
настраивается и основание вышло 0,69" при высоте бокса 1,83". Три таких
клина закрыли бы снимку ещё около десятой доли площади сверх тех 27%, на
которые форма уже ругается. В словаре геометрий такая выноска выглядела
бы как успех. Каталог может назвать тело-кандидата; принять его может
только приёмка — см. графу «из чего сложена» в
`tools/metodika-podachi/kadr/02-KATALOG-FORM-TELA.md`.

Запуск:  python3 slovar_geometriy.py <файл.pptx> [ещё.pptx ...]
Связанные записи: `notes/research/dizayn-metodika/proba-R1-lec-08/00-ZHURNAL-TRENIYA-part4.md` Т-40,
`…-part5.md` Т-42; ловушка округления `build_freeform` —
`notes/mcp-limitations.md` [#307-1].
"""
import sys
from collections import Counter
from pptx import Presentation

NS = "{http://schemas.openxmlformats.org/drawingml/2006/main}"


def slovar(path):
    """Счётчик геометрий одного файла: {имя геометрии: сколько фигур}.

    Обход идёт по всему дереву фигур кадра (`iter`), включая вложенные:
    геометрия живёт на фигуре ЛЮБОЙ глубины, и фигура внутри группы
    рисуется на кадре ровно так же, как фигура верхнего уровня. Перебор
    только верхнего уровня потерял бы сгруппированное молча.

    Свой контур (`custGeom`) считается отдельным именем. Разносить его по
    тому, на что он похож, было бы неверно: в формате это ОДНА вещь — результат объединения
    фигур, записанный списком точек, — и весь смысл графы «из чего
    сложена» в том, чтобы он был виден как свой контур.
    """
    prs = Presentation(path)
    c = Counter()
    for s in prs.slides:
        tree = s.shapes._spTree
        for g in tree.iter(f"{NS}prstGeom"):
            c[g.get("prst")] += 1
        for _ in tree.iter(f"{NS}custGeom"):
            c["custGeom"] += 1
    return c


def main(argv):
    if not argv:
        print(__doc__.strip().splitlines()[-2])
        return 2
    for path in argv:
        c = slovar(path)
        vsego = sum(c.values())
        print(f"{path.split('/')[-1]:26s} фигур с геометрией {vsego:5d} · "
              f"различных геометрий {len(c):3d}")
        print(f"{'':26s}   " + " · ".join(f"{k} {v}" for k, v in c.most_common()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

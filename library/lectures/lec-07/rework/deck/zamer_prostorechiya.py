#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Просторечие и разговорные обороты на ВИДИМОМ слое деки — по заказу владельца.

Повод (2026-10-15, по деке Лекции 7): «Так же слишком много просторечных и
разговорных оборотов на слайдах». Отдельно от `scan_deck_visible.py`: тот ищет
ПРОТЕЧКИ рабочего словаря (наши слова — «разбор», «кадр», «прочерк», «ось»),
а это другой вопрос — ТОН. Слово «ерунда» не протечка: оно никому не служебное,
оно просто не стоит на учебном кадре.

ЧЕГО ЭТОТ ПРОГОН НЕ УМЕЕТ — читать до того, как поверить его нулю:
  1. Он ищет ПО СПИСКУ. Разговорный оборот, которого в списке нет, он пропустит,
     и ноль будет честным ответом на вопрос «есть ли в деке ЭТИ обороты», а не
     на вопрос «хорош ли тон». Тон читается глазами; это сито, не судья.
  2. Он не различает просторечие от омонима. «Короче и связнее» — сравнительная
     степень, а не частица «короче»; «сдал полосу» — не «сдал» о человеке.
     Поэтому он печатает КОНТЕКСТ каждой находки, и находки читают, а не считают
     (`CLAUDE.md` §8.6: смотреть контекст совпадений, а не счёт).
  3. Он смотрит только видимый слой. Заметки лектора — речь, им разговорность
     местами К ЛИЦУ, и мерить их этим списком нельзя (`tools/editorial/` §4).

Шаблоны — Python `re`, НЕ `grep -P`: на кириллице `-P` даёт ложный ноль, и
ложный ноль здесь выглядел бы как подтверждение чистоты (`CLAUDE.md` §8.6).
Якорь с ДВУХ сторон у каждого класса — односторонний находит «роля» внутри
«контроля» (5 ложных срабатываний в этом производстве).

    python3 zamer_prostorechiya.py --selftest   # доказать, что умеет находить
    python3 zamer_prostorechiya.py              # прогон по slides/s*.md
"""
import glob
import re
import sys

sys.path.insert(0, '.')
from vidimyy_sloy_polnyy import polnyy

KLASSY = {
    'разговорные частицы и вводные':
        r'(?<![а-яё])(мол|дескать|вроде\s+бы|как\s+бы|типа|вообще-то|в\s+общем|'
        r'короче говоря|по сути|в принципе|так вот|авось|небось|поди|знай\s+себе)(?![а-яё])',
    'фамильярная оценка':
        r'(?<![а-яё])(ерунда|чепуха|бред|тупо|халтур\w*|разгильдяй\w*|косяк\w*|'
        r'дурац\w*|нелеп\w*|наплева\w*|по-быстрому|на глазок|на коленке|с потолка)(?![а-яё])',
    'просторечные глаголы':
        r'(?<![а-яё])(загнул\w*|влип\w*|вляпа\w*|проворон\w*|прошляп\w*|угроб\w*|'
        r'накосяч\w*|наворот\w*|запил\w*|впихн\w*|сляпа\w*)(?![а-яё])',
    'обращение и панибратство':
        r'(?<![а-яё])(ребят\w*|друзья|смотрите сами|сами понимаете|согласитесь|'
        r'поверьте|честно говоря|между нами)(?![а-яё])',
    'усилители-штампы':
        r'(?<![а-яё])(очень\s+очень|прямо-таки|всего-навсего|как\s+раз\s+наоборот)(?![а-яё])',
}

# Вход, на котором проверка ОБЯЗАНА закричать, — по одному на класс.
SLOMANNYY = [
    ('разговорные частицы и вводные', 'Модель, типа, читает снимок первой.'),
    ('фамильярная оценка',            'Порог назначили на глазок, и это халтура.'),
    ('просторечные глаголы',          'Разработчики прошляпили сдвиг населения.'),
    ('обращение и панибратство',      'Согласитесь, ребята, так никто не делает.'),
    ('усилители-штампы',              'Результат прямо-таки обратный обещанному.'),
]
# Вход, на котором проверка обязана МОЛЧАТЬ: омонимы тех же корней.
CHISTYY = [
    'Эпикриз короче и связнее — 3,67 против 3,77 балла.',
    'Полоса сдана: тело на 15,0 пт, блокирующих ноль.',
    'В принципиальном режиме осмотра — сто пятьдесят шесть тысяч единиц.',
    'Обход занимает две-три минуты у постели.',
]


def nahodki(text):
    out = []
    for klass, pat in KLASSY.items():
        for m in re.finditer(pat, text, re.I):
            out.append((klass, m.group(0).strip(),
                        text[max(0, m.start() - 45):m.end() + 35].replace('\n', ' ')))
    return out


def selftest():
    bed = 0
    for klass, stroka in SLOMANNYY:
        got = [k for k, _, _ in nahodki(stroka)]
        ok = klass in got
        print(f'  {"НАШЛА " if ok else "ПРОПУСТИЛА"} [{klass}] {stroka!r}')
        bed += 0 if ok else 1
    for stroka in CHISTYY:
        got = nahodki(stroka)
        ok = not got
        print(f'  {"молчит" if ok else "ЛОЖНО СРАБОТАЛА"} {stroka!r}'
              + ('' if ok else f'  ← {got}'))
        bed += 0 if ok else 1
    print(f'\nсамопроверка: {"ПРОЙДЕНА" if not bed else f"ПРОВАЛЕНА ({bed})"}'
          f' — {len(SLOMANNYY)} сломанных входов, {len(CHISTYY)} чистых')
    return 0 if not bed else 2


def progon():
    kadry = sorted(glob.glob('slides/s*.md'))
    if not kadry:
        print('кадров не найдено — запускать из deck/'); return 2
    vsego = []
    for f in kadry:
        v = polnyy(f)
        t = v if isinstance(v, str) else '\n'.join(
            str(x) for x in (v if isinstance(v, (list, tuple)) else v.values()))
        for klass, slovo, ctx in nahodki(t):
            vsego.append((f.split('/')[-1].split('-')[0], klass, slovo, ctx))
    print(f'кадров пройдено: {len(kadry)} · находок: {len(vsego)}')
    for kadr, klass, slovo, ctx in vsego:
        print(f'  {kadr:7s} [{klass}] «{slovo}» … {ctx}')
    if not vsego:
        print('\nНоль означает ровно одно: перечисленных в списке оборотов на видимом слое нет.')
        print('Он НЕ означает, что тон хорош, — список закрытый, тон читается глазами.')
    else:
        print('\nНаходки ЧИТАТЬ, а не считать: омоним даёт срабатывание, которое правкой не является.')
    return 0


if __name__ == '__main__':
    sys.exit(selftest() if '--selftest' in sys.argv else progon())

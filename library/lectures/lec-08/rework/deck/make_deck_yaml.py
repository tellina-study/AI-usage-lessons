def timing(d):
    """timing_min как число -- 0.0, если поле отсутствует во фронтматтере кадра.

    13 кадров Раздела 4 (s38-s50, те же, что несут собственный комментарий с адресом
    в главе) фронтматтер `timing_min` не несут вовсе -- не опечатка одного файла, вся
    волна правок Раздела 4 была написана без этого поля. Подставлять число самому
    значило бы выдумывать хронометраж там, где его не назвал автор кадра; честный
    счёт -- 0.0 за такой кадр и отдельная графа `timing_missing` в `totals`, а не
    тихо округлённая общая сумма."""
    v = (d.get('timing_min') or '').strip()
    try:
        return float(v)
    except ValueError:
        return 0.0



#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Предгейтовый проход по СОБРАННОМУ pptx: строительные фразы, тайминг, методкомментарии.

Независимый от сессий, которые правили кадры: читает собранный пакет, а не файлы кадров,
потому что самоотчёт правившего здесь не принимается (канон курса, Pre-USER-GATE §5).

Два слоя разделены и считаются отдельно: ВИДИМЫЙ (то, что на экране у зала) и ЗАМЕТКИ.
Часть запретов действует только на видимом слое — тайминг и методкомментарий в заметках
законны, во `speech.md` тоже; на экране — нет.

Кириллица: `grep -P` на этих шаблонах даёт ЛОЖНЫЙ НОЛЬ (`\b`/`\w` в PCRE считают по
байтам), поэтому всё ищется Python `re`, шаблоны якорятся с ДВУХ сторон, и прогон
печатает КОНТЕКСТ каждого совпадения, а не только счёт: решает глаз, а не число.

    python3 pregeyt_skan.py --selftest        # доказать, что находит каждый вид
    python3 pregeyt_skan.py lec-07-karkas.pptx
"""
import re
import sys
from pathlib import Path

# ── группа 1: строительные фразы. Запрещены на ОБОИХ слоях ──────────────────
LESA = {
    "обращение к лектору": r"(?<![\w-])(Лектор[уа]|Преподавател[юя]|Вы\s+здесь)(?![\w-])",
    "служебная метка сверки": r"\[VERIFY-DAY-OF\]|\[FACT-CHECK\]|\[VFY[^\]]*\]",
    "код учебной цели": r"(?<![\w-])LO[1-9][a-z]?(?![\w-])",
    "адрес параграфа главы": r"§\s*[0-9]",
    "ссылка на свой же кадр": r"→\s*s[0-9]+|\(s[0-9][0-9]\)",
    "точка возврата": r"(?<![\w-])точк\w*\s+возврата(?![\w-])",
    "отсылка в главу/материалы": r"—\s*в\s+главе(?![\w-])|в\s+материалах\s+лекции(?![\w-])",
    "payoff": r"(?<![\w-])это\s+payoff(?![\w-])",
    "возвращаемся N": r"(?<![\w-])возвраща\w+\s+[0-9N](?![\w-])",
    "не вводим нового": r"(?<![\w-])не\s+вводи\w*\s+нов",
}
# ── группа 2: тайминг. Запрещён на ВИДИМОМ слое ─────────────────────────────
TAYMING = {
    "минуты на экране": r"(?<![\w-])\d+\s*мин(ут[аыу]?)?(?![\w-])",
    "слово «тайминг»": r"(?<![\w-])(Тайминг|Время\s+раздел\w*|Длительност\w+)(?![\w-])",
    "значок часов": r"⏱|⏰",
}
# ── группа 3: методкомментарии. Запрещены на ВИДИМОМ слое ───────────────────
METOD = {
    "методическое/педагогическое": r"(?<![\w-])(методическ\w+|педагогическ\w+)(?![\w-])",
    "обращение к студенту": r"На\s+этом\s+этапе\s+студент|Здесь\s+студент\s+усваивает",
    "зачем это в лекции": r"Зачем\s+это\s+в\s+Лекци|Этот\s+раздел\s+учит",
    "для инженера это означает": r"(?<![\w-])для\s+инженера\s+это\s+означает(?![\w-])",
}
# ── курсовое правило: превосходные формы на ВИДИМОМ слое ────────────────────
PREVOSKHOD = {
    "превосходная форма": r"(?<![\w-])(главн\w+|самы[йяоеих]\w*|лучш(?:ий|ая|ее|ие|его|ему|им|их|ими|ем|ей)|важнейш\w+|ключев\w+)(?![\w-])",
}
# Ложные срабатывания, названные ПРИЧИНОЙ, а не «похоже на ложное». Каждое снимается
# только там, где причина проверяема по тексту совпадения.
ISKLYUCHENIYA = [
    (r"\d+\s*мин(ут[аыу]?)?\s*\d+\s*с(ек)?", "измеренная длительность работы, а не метка тайминга"),
    (r"(?:против|и)\s+\d+\s*секунд|\d+\s*мин(ут[аыу]?)?\s+против", "измеренная длительность в сравнении режимов"),
    (r"(?<![\w-])(тот\s+же\s+самый|те\s+же\s+самые|самых?\s+тёмн|самы[йх]\s+(?:тёмн|светл))", "указательное «тот же самый» либо названная категория, не превосходная форма"),
    (r"не\s+самы[ех]", "отрицание превосходной формы"),
    (r"(?:заместител\w+\s+)?главн\w+\s+врача", "должность «заместитель главного врача», не превосходная форма"),
    (r"лучш(?:ей|его)\s+из\s+(?:двух|обеих)", "сравнение двух сторон: «лучшая из двух» — методическая формулировка, не нажим"),
    (r"«[^»]*лучш[^»]*»\s*(?:этими\s+данными\s+)?не\s+держится", "цитата чужого утверждения, которую кадр опровергает"),
    (r"лучш\w+\s+(?:модель|моделью)\s+не\s+лечится", "сравнительная степень в отрицании"),
]


def slides(pptx):
    """По кадру: (номер, видимый текст, заметки)."""
    from pptx import Presentation
    for i, sl in enumerate(Presentation(pptx).slides, 1):
        vis = []
        for sh in sl.shapes:
            if sh.has_text_frame:
                vis.append(sh.text_frame.text)
            if getattr(sh, "has_table", False) and sh.has_table:
                for row in sh.table.rows:
                    vis.extend(c.text for c in row.cells)
        notes = ""
        if sl.has_notes_slide and sl.notes_slide.notes_text_frame is not None:
            notes = sl.notes_slide.notes_text_frame.text
        yield i, "\n".join(vis), notes


def excused(frag):
    for pat, why in ISKLYUCHENIYA:
        if re.search(pat, frag, re.I):
            return why
    return None


def scan(pptx):
    groups = [("1. строительные фразы", LESA, ("видимый", "заметки")),
              ("2. тайминг", TAYMING, ("видимый",)),
              ("3. методкомментарии", METOD, ("видимый",)),
              ("4. превосходные формы", PREVOSKHOD, ("видимый",))]
    pages = list(slides(pptx))
    print(f"кадров в собранном пакете: {len(pages)}\n")
    itog = {}
    for gname, pats, layers in groups:
        real, false = [], []
        for n, vis, notes in pages:
            for lay in layers:
                txt = vis if lay == "видимый" else notes
                for pname, pat in pats.items():
                    for m in re.finditer(pat, txt, re.I):
                        frag = txt[max(0, m.start() - 70):m.end() + 70].replace("\n", " ")
                        why = excused(frag)
                        (false if why else real).append((n, lay, pname, frag, why))
        itog[gname] = (len(real), len(false))
        print(f"── {gname}: настоящих {len(real)} · ложных со снятой причиной {len(false)}")
        print(f"   слои: {', '.join(layers)} · шаблонов {len(pats)}")
        for n, lay, pname, frag, _ in real:
            print(f"   НАСТОЯЩЕЕ  кадр {n:3d} [{lay}] {pname}: …{frag}…")
        for n, lay, pname, frag, why in false[:6]:
            print(f"   ложное     кадр {n:3d} [{lay}] {pname}: …{frag[:90]}…  ← {why}")
        if len(false) > 6:
            print(f"   … ещё {len(false) - 6} ложных того же вида")
        print()
    print("ИТОГ по группам:", " · ".join(f"{g}: {r}" for g, (r, _) in itog.items()))
    print("\nЧем ноль получен, если он получен: чтением СОБРАННОГО pptx (видимый слой "
          "фигур и таблиц + заметки), Python `re` с двусторонними якорями, по "
          f"{sum(len(p) for _, p, _ in groups)} шаблонам четырёх групп, с печатью контекста "
          "каждого совпадения.\nЧто ноль НЕ исключает: англицизмы (отдельный прогон "
          "deep_latin_scan.py), отсутствие базы у числа (выборочная проверка глазами), "
          "смысловые запреты без словесного следа.")
    return sum(r for r, _ in itog.values())


def selftest():
    cases = [
        ("Лектору: скажите здесь про риск", LESA, "обращение к лектору", True),
        ("Разбор занял [VERIFY-DAY-OF] проверить", LESA, "служебная метка сверки", True),
        ("Цель LO3 закрыта", LESA, "код учебной цели", True),
        ("см. § 3.9 главы", LESA, "адрес параграфа главы", True),
        ("дальше → s48 и обратно", LESA, "ссылка на свой же кадр", True),
        ("14 минут на раздел", TAYMING, "минуты на экране", True),
        ("Тайминг раздела", TAYMING, "слово «тайминг»", True),
        ("методическая рамка раздела", METOD, "методическое/педагогическое", True),
        ("На этом этапе студент должен понять", METOD, "обращение к студенту", True),
        ("это главный вывод", PREVOSKHOD, "превосходная форма", True),
    ]
    bad = 0
    for txt, pats, pname, want in cases:
        got = bool(re.search(pats[pname], txt, re.I))
        ok = got == want
        print(f"  {'ок ' if ok else 'СБОЙ'} {pname:28s} {txt[:44]!r}")
        bad += not ok
    print("\n  — снятие ложных по названной причине:")
    for txt, want_why in (("разбор 2 мин 12 с против 48 секунд", "измеренная длительность"),
                          ("тот же самый режим", "указательное"),
                          ("двести семь самых тёмных", "названная категория"),
                          ("не самые трудные из шести", "отрицание")):
        why = excused(txt)
        ok = why is not None
        print(f"  {'ок ' if ok else 'СБОЙ'} {txt[:40]!r} → {why}")
        bad += not ok
    # и обратное: настоящая метка тайминга НЕ должна сниматься
    for txt, want_why in (("Заместитель главного врача — председатель", "должность"),
                          ("против лучшей из двух сторон", "сравнение двух"),):
        why = excused(txt)
        ok = why is not None
        print(f"  {'ок ' if ok else 'СБОЙ'} {txt[:40]!r} → {why}")
        bad += not ok
    for txt in ("это главный вывод", "самый точный способ"):
        ok = excused(txt) is None and re.search(PREVOSKHOD["превосходная форма"], txt, re.I)
        print(f"  {'ок ' if ok else 'СБОЙ'} настоящий нажим остаётся: {txt!r}")
        bad += not ok
    for txt in ("пара лучше обеих сторон", "стал лучше"):
        ok = not re.search(PREVOSKHOD["превосходная форма"], txt, re.I)
        print(f"  {'ок ' if ok else 'СБОЙ'} сравнительная «лучше» не ловится: {txt!r}")
        bad += not ok
    for txt in ("14 минут на раздел", "Тайминг раздела"):
        ok = excused(txt) is None
        print(f"  {'ок ' if ok else 'СБОЙ'} настоящее НЕ снимается: {txt!r}")
        bad += not ok
    print(f"\nсамотест: сбоев {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    p = sys.argv[1] if len(sys.argv) > 1 else "lec-07-karkas.pptx"
    if not Path(p).exists():
        sys.exit(f"нет файла {p} — сначала сборка")
    # СВЕЖЕСТЬ ПАКЕТА. Прогон по устаревшему pptx даёт числа о прошлом круге и читается
    # как «чисто»: пробный прогон 2026-10-14 шёл по пакету на 32 минуты старше кадров и
    # показывал подвалы с DOI у кадров, у которых поле source уже стало «—».
    import subprocess
    newest = max((f.stat().st_mtime for f in Path("slides").glob("s*.md")), default=0)
    if Path(p).stat().st_mtime < newest:
        print(f"!! ПАКЕТ УСТАРЕЛ: {p} собран раньше последней правки кадра.")
        print("   Числа ниже — о прошлой сборке. Пересоберите и прогоните снова.\n")
    sys.exit(0 if scan(p) == 0 else 2)

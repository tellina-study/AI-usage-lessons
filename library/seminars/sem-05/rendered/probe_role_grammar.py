#!/usr/bin/env python3
"""Грамматика плашек: какой формой выходит каждый блок-цитата деки.

Зачем отдельный файл. Форму плашки назначает `build_sem05.quote_role`, и
ошибается она МОЛЧА: слайд собирается, переполнения нет, предупреждений нет —
просто вывод нарисован не той формой, что соседний вывод. Ни одна сборочная
проверка этого не видит, потому что меряют они место, а не работу блока.
Поймала это сверка круга 4 глазами (SVERKA-POLNOTY §9): вывод свидетельств
третьего случая («Откуда берутся минуты: 40 правок × 1 275 мс = 51 с») выходил
пунктирной оговоркой, а выводы разборов рядом — золотой планкой.

Два режима.

    python3 probe_role_grammar.py              # перепись всей деки по ролям
    python3 probe_role_grammar.py --self-test  # прогон на нарочно сломанном входе

`--self-test` — не формальность. Правило «оговорка» ловилось подстрокой в любом
месте блока, и на этом оно дважды сработало вхолостую: на подводке вопроса,
которая ПЕРЕСКАЗЫВАЕТ чужой текст («…со словом „никогда“ и отдельной оговоркой
про мелочи»), и на выводе, внутри которого стоит сообщение об ошибке в кавычках
(«она отвечает „манифест не найден“»). Оба случая — в списке ниже, и правило,
которое снова начнёт их ловить, упадёт здесь, а не на показе.

Код возврата 1 при любом расхождении — проверка годится для сборочной цепочки.
"""
import sys

sys.path.insert(0, ".")
import build_sem05 as B  # noqa: E402
import slide_parts as SP  # noqa: E402
import yaml  # noqa: E402
from pathlib import Path  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

# (текст блока, приём слайда, ожидаемая роль, за что отвечает случай)
CASES = [
    ("Честный пробел: сколько это стоит в живом проекте, мы не мерили.",
     "evidence_table_with_gap", "caveat",
     "настоящая оговорка на слайде свидетельств остаётся пунктиром"),
    ("Оговорка про обратную величину. 64,6% — это доля тех же испытаний.",
     "evidence_table_with_gap", "caveat",
     "жанровое слово в начале блока — оговорка"),
    ("Честно про силу утверждения: направление подтверждено, размер — нет.",
     "failure_vignette", "caveat",
     "третий жанровый оборот деки"),
    ("Всё выше проверено по документации поставщиков, а запуском не проверено.",
     "answer_breakdown_table", "caveat",
     "признание пробела по смыслу, без жанрового слова"),
    ("Откуда берутся минуты: 40 правок × 1 275 мс = 51 с (замер).",
     "evidence_table_with_gap", "formula",
     "ВЫВОД свидетельств — золотая планка, как у выводов разбора"),
    ("Инструкция написана настолько громко, насколько возможно: заглавными, "
     "со словом «никогда» и отдельной оговоркой про мелочи.",
     "question_with_option_cards", "fact",
     "пересказ ЧУЖОГО текста со словом «оговорка» внутри — не оговорка слайда"),
    ("Машина находит фронтматтер, который не читается; на голом каталоге "
     "она отвечает «манифест не найден».",
     "code_artifact", "formula",
     "сообщение об ошибке в кавычках — не признание пробела"),
    ("Из сочетания колонок: первые две строки законны обе.",
     "answer_breakdown_table", "formula",
     "вывод разбора — эталон грамматики"),
    ("Что поставить рядом с такой инструкцией?",
     "question_with_option_cards", "question",
     "вопрос остаётся вопросом и внутри приёма вопроса"),
    ("«Две строки заполнены. Три остаются на следующее занятие.»",
     "recap_table", "speech",
     "реплика в кавычках остаётся репликой"),
]


def self_test():
    bad = 0
    for text, pattern, want, why in CASES:
        got = B.quote_role([text], pattern)
        ok = got == want
        bad += not ok
        print(f"  {'OK  ' if ok else 'СБОЙ'}  ждали={want:8} вышло={got:8}  {why}")
    print()
    if bad:
        print(f"сломанный вход: {bad} расхождений — правило ролей сдвинулось")
        return 1
    print(f"сломанный вход: все {len(CASES)} случая прошли")
    return 0


def census():
    slides = yaml.safe_load((ROOT / "deck.yaml").read_text(encoding="utf-8"))["slides"]
    counts = {}
    for s in slides:
        pattern = (s.get("visual") or {}).get("pattern", "")
        md = (ROOT / s["file"]).read_text(encoding="utf-8")
        _title, _assertion, visual, _notes = SP.sections(md)
        for kind, b in SP.blocks(visual):
            if kind != "quote":
                continue
            role = B.quote_role(b, pattern)
            counts[role] = counts.get(role, 0) + 1
            body = " ".join(x.strip() for x in b)
            print(f"{s['id']}\t{role:8}\t{B.K.plain(body)[:84]}")
    print()
    print("  ".join(f"{k}: {v}" for k, v in sorted(counts.items())))
    return 0


if __name__ == "__main__":
    sys.exit(self_test() if "--self-test" in sys.argv else census())

"""Производственный язык и методические оговорки на кадре — греп по §11.6,
§6.3 и §7.1 `tools/presentation-build/trebovaniya-k-soderzhaniyu-forma.md`.

ПОЧЕМУ PYTHON, А НЕ `grep -P`. Замерено производством Семинара 6
(`tools/seminar-production/README.md` §8.6): `grep -P` по кириллице даёт
НОЛЬ там, где совпадения есть, потому что `\\b`/`\\w` в PCRE здесь считают по
байтам. Ложный ноль выглядит как подтверждение чистоты — и один раз уже был
за него принят. Модуль `re` Питона считает по символам, поэтому греп живёт
здесь.

ЧТО СКАНИРУЕТСЯ — ТРИ СЛОЯ, И ТРЕТИЙ ВАЖНЕЕ ВСЕГО. Видимый текст кадра,
заметки лектора И ВИДИМЫЕ ПОЛЯ ФРОНТМАТТЕРА. Третий слой добавлен не для
полноты: `title`, `blocks` (подпись, значение, оговорка каждой плашки),
`scheme` (подписи рядов, шагов и сама подпись схемы) и `source` — всё это
НАБРАНО НА КАДРЕ, но лежит во фронтматтере, и греп по разделу «Видимый
текст слайда» их не видит. Замерено на этом же круге: шаг схемы `s18b`
гласил «Выборка — кадром раньше» — прямая ссылка на наш собственный кадр,
стоящая на экране, и первая редакция этого грепа её пропустила, потому что
отрезала фронтматтер целиком.

Бухгалтерия сборки (`pol_slov`, `razbor_part`, `media_note`, `assertion`,
`opyt_net`, комментарии) НЕ сканируется: зал её не видит, и производственный
язык в ней уместен — это и есть место, где мы пишем о своей работе.

    python3 grep_proizvodstvennyy.py                 # весь раздел 1
    python3 grep_proizvodstvennyy.py s16 s18         # отдельные кадры
    python3 grep_proizvodstvennyy.py --selftest      # проверить сам греп
"""
import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SLIDES = HERE / "slides"

# Раздел по умолчанию. Кадры называются по своему `id`, порядок — показа.
RAZDEL_1 = ["s11", "s11a", "s12", "s13", "s13a", "s13b", "s15", "s15a",
            "s16", "s16a", "s18", "s18a", "s18b", "s20"]

# ── Шаблоны: (выражение, имя правила, слои) ────────────────────────────
#
# СЛОИ НЕ ОДИНАКОВЫ У ВСЕХ ПРАВИЛ, и это не придирка к оформлению.
# §11.6/§6.3 запрещают производственный язык на ОБОИХ слоях — прошлый круг
# показал, что снятое с кадра утекает в заметки, а заметки владелец читает.
# §7.1 устроен ровно наоборот: оговорка о том, как сделан замер, С КАДРА
# СНИМАЕТСЯ И УХОДИТ В ЗАМЕТКИ — там она обязана быть. Греп, который ловил
# бы её в заметках, требовал бы снять то, что правило требует туда положить;
# ровно тот сторож, который «возвращает отменённое» (seminar-production §8.3).
# Каждый шаблон якорится С ОБЕИХ СТОРОН там, где это возможно: односторонний
# якорь `[Рр]ол[ьияею]\b` находил «роля» внутри «контроля» (§8.6, пять ложных
# срабатываний за одно производство).
# «кадр» — видимые поля фронтматтера: заголовок, плашки, схема, подвал.
OBA = ("тело", "заметки", "кадр")
TELO = ("тело", "кадр")

SHABLONY = [
    # §11.6, дословно из канона — оба слоя
    (r"[Ии]мени\s+\S+\s+не\s+(получил|назвал|называет|печатает)", "§11.6 «Имени … не получила»", OBA),
    (r"[Пп]рибор\s+\S+\s+не\s+назван", "§11.6 «Прибор … не назван»", OBA),
    (r"кадром\s+(следом|раньше|перед\s+этим)", "§11.6 «кадром следом»", OBA),
    (r"\bкадр[еа]\s+(перед\s+этим|следом)", "§11.6 «на кадре перед этим»", OBA),
    (r"[Рр]аздел\s+(берёт|закрыл|закрывает)", "§11.6 «Раздел берёт/закрыл»", OBA),
    (r"подмножеств\w*", "§11.6 «подмножество»", OBA),
    (r"\bразряд\w*", "§11.6/§6.3 «разряд»", OBA),
    (r"\bсвод\b", "§11.6 «свод»", OBA),
    (r"по\s+этой\s+паре", "§11.6 «по этой паре»", OBA),
    (r"\(опционально\)", "§11.6 «(опционально)»", OBA),
    (r"та\s+же\s+работ\w+", "§11.6 «та же работой»", OBA),
    (r"\bдостроить\b", "§11.6 «достроить»", OBA),
    # §6.3 — протечки процесса
    (r"\bрычаг\w*", "§6.3 «рычаг»", OBA),
    (r"несущ\w+\s+ос[ьи]", "§6.3 «несущая ось»", OBA),
    (r"вклад\s*№", "§6.3 «вклад №»", OBA),
    (r"по\s+постановке", "§6.3 «по постановке»", OBA),
    (r"см\.\s*разбор", "§6.3 «см. разбор»", OBA),
    (r"(?<![A-Za-zА-Яа-я0-9])s\d{1,3}[a-z]?(?![A-Za-zА-Яа-я0-9])", "§6.3 имя нашего кадра", OBA),
    (r"chapter-part\w*|research/\d|research\s*#\d|rework/", "§11.5 самоссылка на репозиторий", OBA),
    # §7.1 — методические оговорки о том, как устроен наш замер
    (r"[Дд]ругое\s+измерение", "§7.1 оговорка о замере", TELO),
    (r"в\s+одну\s+бухгалтерию", "§7.1 оговорка о замере", TELO),
    (r"не\s+одна\s+шкала|одна\s+шкала", "§7.1 оговорка о замере", TELO),
    (r"взят[ыа]?\s+с\s+разных\s+программ", "§7.1 оговорка о замере", TELO),
    (r"разные\s+величины\s+в\s+двух\s+валютах", "§7.1 оговорка о замере", TELO),
    (r"не\s+складыва\w+", "§7.1 оговорка о замере", TELO),
    (r"значимости\s+не\s+достигла|оценка\s+регистратора", "§7.1 оговорка о замере", TELO),
    (r"[Сс]мешанн\w+|частично-?bucket", "§7.1 оговорка о нашей разметке", TELO),
    # § No Timing / No Methodology — те же два разряда, что уже ENFORCED
    (r"(методическ|педагогическ)\w*", "§ No Methodology", OBA),
    # ТАЙМИНГ ЛЕКЦИИ, а не всякая минута. Широкий шаблон `\d+\s*мин` ловил
    # измеренные длительности («арбитраж — 2 минуты 12 секунд»), то есть сам
    # материал разбора: запрещён бюджет показа на кадре, а не единица времени
    # в данных. Ловится то, чем бюджет и выглядит: минуты в скобках, минуты
    # через разделитель у названия раздела, «Время раздела», «Тайминг», часы.
    (r"\(\s*\d+\s*мин", "§ No Timing", OBA),
    (r"\b\d+\s*мин(ут\w*)?\s*(·|на\s+раздел|лекци|Q&A|слот)", "§ No Timing", OBA),
    (r"[Вв]рем[яи]\s+раздел|Тайминг|Длительность\s+кадра|⏱|⏰", "§ No Timing", OBA),
    (r"Лектору|Преподавателю|Вы\s+здесь", "§ No Methodology", OBA),
]
SKOMPILIROVANO = [(re.compile(p), imya, sloi) for p, imya, sloi in SHABLONY]


# Поля фронтматтера, которые НАБИРАЮТСЯ НА КАДРЕ. Всё остальное — наша
# бухгалтерия, и её греп не трогает.
VIDIMYE_POLYA = ("title", "blocks", "scheme", "source", "columns",
                 "row_blocks", "ladder", "tracks")


def _tekst_iz(uzel):
    """Весь текст вложенной структуры YAML одной строкой."""
    if isinstance(uzel, str):
        return uzel
    if isinstance(uzel, dict):
        return " ".join(_tekst_iz(v) for v in uzel.values())
    if isinstance(uzel, (list, tuple)):
        return " ".join(_tekst_iz(v) for v in uzel)
    return ""


def sloi(put):
    """Три слоя кадра: видимый текст · заметки · видимые поля фронтматтера."""
    t = put.read_text(encoding="utf-8")
    m = re.match(r"\A---\n(.*?)\n---\n", t, flags=re.S)
    kadr = ""
    if m:
        try:
            import yaml
            meta = yaml.safe_load(m.group(1)) or {}
            kadr = " ".join(_tekst_iz(meta.get(k)) for k in VIDIMYE_POLYA
                            if meta.get(k) is not None)
        except Exception as e:          # разбор не вышел — сказать, не смолчать
            kadr = ""
            print(f"  [!] {put.name}: фронтматтер не разобран ({e}); "
                  "плашки и схема этим прогоном НЕ проверены")
        t = t[m.end():]
    telo, _, zametki = t.partition("## Заметки лектора")
    telo = telo.replace("## Видимый текст слайда", "")
    return telo, zametki, kadr


def skan(put, tiho=False):
    telo, zametki, kadr = sloi(put)
    naydeno = []
    for sloy, tekst in (("тело", telo), ("заметки", zametki),
                        ("кадр", kadr)):
        for rx, imya, gde in SKOMPILIROVANO:
            if sloy not in gde:
                continue
            for m in rx.finditer(tekst):
                levo = max(0, m.start() - 34)
                kontekst = " ".join(tekst[levo:m.end() + 34].split())
                naydeno.append((sloy, imya, m.group(0), kontekst))
    if naydeno and not tiho:
        print(f"\n{put.name} — {len(naydeno)}")
        for sloy, imya, chto, kontekst in naydeno:
            print(f"  [{sloy:8}] {imya:34} «{chto}»")
            print(f"             …{kontekst}…")
    return naydeno


def selftest():
    """Греп обязан найти то, что мы сами подложили, и не найти соседнее.

    Отдельно проверяется ложное срабатывание односторонних якорей: «контроля»
    и «показал» не должны ловиться шаблонами «роль» и «разряд» (§8.6).
    """
    proba = (
        "---\n"
        "id: s99\n"
        "title: \"Проба\"\n"
        "scheme:\n"
        "  rows:\n"
        "    - {label: \"До\", steps: [\"Выборка — кадром раньше\"]}\n"
        "pol_slov: 10   # разряд, рычаг и кадром следом тут уместны\n"
        "---\n\n"
        "## Видимый текст слайда\n\n"
        "Имени система не получила; прибор испытания не назван. "
        "Арбитраж — кадром следом, разряд выше слов участника, "
        "по этой паре видно. 14 минут на раздел, методически важно.\n\n"
        "## Заметки лектора\n\n"
        "Здесь чисто: контроля достаточно, показал зал, парадигма не в счёт. "
        "Значимости не достигла — и этой оговорке место именно здесь (§7.1).\n"
    )
    put = Path("/tmp/_proba_grep.md")
    put.write_text(proba, encoding="utf-8")
    naydeno = skan(put, tiho=True)
    telo = [n for n in naydeno if n[0] in ("тело", "кадр")]
    zam = [n for n in naydeno if n[0] == "заметки"]
    kadr = [n for n in naydeno if n[0] == "кадр"]
    ok = len(telo) >= 8 and len(zam) == 0 and len(kadr) == 1
    print(f"selftest: в подложенных теле и кадре найдено {len(telo)} "
          f"(ждём ≥8, из них в схеме {len(kadr)} — ждём 1), "
          f"в чистых заметках {len(zam)} (ждём 0); "
          "бухгалтерия `pol_slov` не сканируется")
    for _, imya, chto, _ in telo:
        print(f"  тело: {imya} — «{chto}»")
    for _, imya, chto, k in zam:
        print(f"  ЛОЖНОЕ СРАБАТЫВАНИЕ в заметках: {imya} — «{chto}» …{k}…")
    print("selftest ПРОШЁЛ — нулю этого грепа можно верить" if ok
          else "selftest ПРОВАЛЕН — нулю этого грепа верить НЕЛЬЗЯ")
    put.unlink()
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("kadry", nargs="*", help="id кадров; пусто — весь раздел 1")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()

    nuzhny = a.kadry or RAZDEL_1
    vsego = 0
    for sid in nuzhny:
        fayly = sorted(SLIDES.glob(f"{sid}-*.md"))
        if not fayly:
            print(f"{sid}: файла нет")
            continue
        for f in fayly:
            vsego += len(skan(f))
    print(f"\nкадров {len(nuzhny)} · совпадений {vsego} · "
          f"шаблонов {len(SHABLONY)} (Python re, не grep -P)")
    if vsego == 0:
        print("ЧИСТО на обоих слоях — теле и заметках.")
    return 1 if vsego else 0


if __name__ == "__main__":
    sys.exit(main())

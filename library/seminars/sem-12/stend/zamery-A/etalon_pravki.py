#!/usr/bin/env python3
"""Правки эталона FUNSD, найденные чтением промахов глазами и подтверждённые
вырезкой скана (issue #351, 2026-11-26, по прямому решению владельца «правь дефекты»).

ПОЧЕМУ ЭТОТ ФАЙЛ, А НЕ ПРАВКА `korpus/vyborka.json`.
Эталон правится ЗДЕСЬ, а не в корпусе, по трём причинам:
  1. `build_korpus.py` пересобирает `vyborka.json` из исходной разметки FUNSD —
     правка в корпусе была бы молча стёрта следующей пересборкой;
  2. прежнее значение должно остаться видимым. Занятие учит тому, что истина,
     по которой меряют, сама грязная; таблица «было -> стало» с обоснованием —
     само свидетельство, а не служебная запись;
  3. так уже устроены все прежние поправки эталона (GT_EXCLUDE, склейки дат) —
     они живут в грейдере, названные, а не в данных.

ЧТО ПОДТВЕРЖДЕНИЕМ СЧИТАЛОСЬ. Для каждой строки: вырезка области «вопрос+ответ» по
боксам разметки, увеличение x3..x10, чтение глазами. Ни одна правка не внесена по
рассуждению о правдоподобии. Отвергнутое — тоже названо (см. ниже NE_PRAVLENO).

Правки применяются НА ВСЕХ ступенях лестницы нормализации, включая нулевую: это
исправление того, ЧЕМ является истина, а не способа сравнения с ней. Лестница
`state_of_count.py` меряет выбор способа счёта — эталон на всех её ступенях один.
"""

# --- Дефекты транскрипции: разметчик FUNSD прочёл символ неверно ---------------
# ключ: (форма, текст подписи, СТАРЫЙ текст ответа) -> (НОВЫЙ текст, чем подтверждено)
GT_FIX = {
    ("87528321", "Date", "B-17-88"): (
        "8-17-88",
        "вырезка x3: цифра 8, не буква B. Та же дата на этой же форме размечена "
        "верно ещё дважды (field_2 «DATE», field_3 «Date Prepared» — обе «8-17-88»)."),
    ("91372360", "FAX PHONE NUMBER:", "(400) 840- 0639"): (
        "(405) 840- 0639",
        "вырезка x3: «(405)». Строкой выше на бланке — «OFFICE: Oklahoma City, OK»; "
        "405 — код Оклахома-Сити, а 400 кодом NANP не бывает вовсе."),
    ("86328049_8050", "Name:", "Ever Hurwitz"): (
        "Even Hurwitz",
        "вырезка x3: четвёртая буква — n, не r."),
    ("82562350", "Telephone:", "(952) 694-2238"): (
        "(952) 894-2238",
        "вырезка x8: первая цифра номера — 8 (замкнутая верхняя петля), не 6. "
        "Поле «Fax:» той же формы размечено «952 894- 9690» — тот же узел 894."),
    ("11508234", "Date:", "3433/ 3/ 95"): (
        "3/ 3/ 95",
        "вырезка x3: от руки «3/3/95». Разметчик прочёл ведущее «3/» как «3433/». "
        "Два соседних поля «Date:» той же формы размечены «3/ 3/ 95» верно."),
    ("00920294", "To:", "RJR IR - Suz /Art"): (
        "RJR IR - Suzi/Art",
        "вырезка x5: «Suzi/Art», i с точкой читается ясно."),
    ("71202511", "Date:", "B 90"): (
        "3/17/98",
        "вырезка x5: от руки «3/17/98». «B 90» — мусорное чтение рукописи."),
}

# --- Поля, снятые из счёта: эталон сломан, но истину со скана не установить -----
# Тот же приём, что уже применён к «zbulan» в score.py::GT_EXCLUDE: сравнение с
# заведомо испорченным эталоном не может быть ни «верно», ни «неверно».
GT_EXCLUDE_NEW = {
    ("91372360", "NAME:", "R F"):
        "вырезка x10 с растяжением контраста: на бланке «R. F. W…sh» (Walsh/Welsh) — "
        "подпись бледная, фамилия до буквы не читается. Эталон «R F» СЛОМАН (фамилии "
        "в нём нет вовсе, третий словобокс разметки пуст), но верное значение со "
        "скана не устанавливается. Поэтому поле СНЯТО, а не исправлено: подставить "
        "«Walsh» значило бы внести догадку под видом истины. Знаменатель 364 -> 363.",
}

# --- Склейка дат: прежняя правка была НЕПОЛНОЙ ---------------------------------
# Найдено в этом круге, в прежних прогонах не замечено.
MERGE_FIX = {
    "83553333_3334": (
        "November 12, 1999",   # было «November 1999»
        "вырезка x5: на бланке «November 12, 1999». Блок «12,» в разметке СУЩЕСТВУЕТ "
        "(id=5), но помечен label='other', а не 'answer', и потому не попал в linking "
        "вопроса «Date». Прежняя склейка (November + 1999) воспроизвела эту потерю: "
        "три метода из четырёх прочли скан ВЕРНО («November 12, 1999») и были "
        "засчитаны неверными. Склеенный эталон исправлен до значения со скана."),
}

# --- Названо и НЕ применено ----------------------------------------------------
NE_PRAVLENO = {
    ("71190280", "Date", "10/22/98 10/22/98"):
        "НЕ дефект транскрипции. Вырезка x5: дата действительно написана на бланке "
        "ДВАЖДЫ, в две строки, и разметка добросовестно связала оба блока с одним "
        "вопросом. Эталон скану соответствует. Остаётся артефакт подсчёта (метод, "
        "ответивший датой один раз, помечен неверным) — он бьёт по всем четырём "
        "методам одинаково, и чинить его значило бы менять способ счёта, а не эталон. "
        "Вне задания этого круга; названо, чтобы не выглядело незамеченным.",
}


def fix_a_text(fid, q_text, a_text):
    """Возвращает исправленный эталон поля (или исходный, если правки нет)."""
    hit = GT_FIX.get((fid, q_text, a_text))
    return hit[0] if hit else a_text


def is_excluded_new(fid, q_text, a_text):
    return (fid, q_text, a_text) in GT_EXCLUDE_NEW


if __name__ == "__main__":
    print(f"правок транскрипции: {len(GT_FIX)}")
    for (fid, q, old), (new, why) in GT_FIX.items():
        print(f"  {fid:16} {q:22} {old!r:20} -> {new!r}")
    print(f"снято из счёта: {len(GT_EXCLUDE_NEW)}")
    for (fid, q, a) in GT_EXCLUDE_NEW:
        print(f"  {fid:16} {q:22} {a!r}")
    print(f"склейка исправлена: {len(MERGE_FIX)}")
    for fid, (new, why) in MERGE_FIX.items():
        print(f"  {fid:16} -> {new!r}")
    print(f"названо и НЕ применено: {len(NE_PRAVLENO)}")

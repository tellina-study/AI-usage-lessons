# -*- coding: utf-8 -*-
"""ОБТЕКАНИЕ БОКОВОЙ ИЛЛЮСТРАЦИИ: тело забирает полную ширину под кадром.

ЧТО БЫЛО СЛОМАНО. Боковая иллюстрация стоит в правом столбце и занимает его
НЕ до низа кадра: вертикальный снимок берёт 3,4" высоты из шести с лишним.
Тело при этом сужалось на всю свою высоту — и ниже кадра правый столбец
оставался пустым. Замерено на собранной деке Лекции 7: мёртвого белого
10,3 кв. дюйма на `s55` и на `s75` (2,39" под кадром на 4,30" ширины), 7,0
на `s12`. Кадр с полосой плашек под этим не страдал: он отжимает тело ниже
снимка, и полная ширина возвращается сама (`y >= media_bot`) — то есть
боковой снимок на кадре БЕЗ плашек платил дважды, столбцом и дырой под ним.

ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Настоящего обтекания — строки, огибающей угол
картинки, — в PowerPoint у надписи нет: `wrap` в OOXML обтекает фигуру
текстом СЛАЙДА только в Word. Поэтому обтекание здесь делается ровно так,
как его может сделать дека: тело режется на ДВЕ надписи по границе блока —
узкая рядом со снимком, широкая под ним. Граница блока, а не строки: строки
разъехались бы по кеглю (надписи мерятся порознь), а блок — это то, что
читается целиком, и разрез по нему не рвёт ни предложения, ни буллита.

ОТКУДА БЕРЁТСЯ РАЗРЕЗ. Прогон тела у деки склеен из блоков через
прогон-РАЗДЕЛИТЕЛЬ — пустой словарь с `newpara` и отбивкой (`space_before`).
Эти разделители и есть единственные законные места разреза; разделитель сам
в надписи не остаётся, поэтому нижняя часть начинается с обычного прогона, а
не с пустого абзаца (пустой абзац `prims.text_runs` превратил бы в лишнюю
строку, и мера с рендером разошлись бы на эту строку).

КАКОЙ РАЗРЕЗ ВЫБИРАЕТСЯ. Самый НИЖНИЙ из тех, при которых верхняя часть ещё
влезает рядом со снимком. Высоты складываются, то есть «влезает» монотонно
по разрезу: ниже разрез — выше верхняя часть и ниже нижняя. Значит, если при
самом нижнем влезающем разрезе нижняя часть не влезла, не влезет она ни при
каком — перебирать нечего, и этот отказ честный, а не «не нашли».
Побочно это же правило закрывает дыру: любой разрез выше оставил бы между
концом верхней части и низом снимка пустое место большей высоты.

ВЫРОЖДЕННЫЙ СЛУЧАЙ — `fit_pushed` ниже: полоска рядом со снимком такая
узкая, что ни один блок в неё не входит. Тогда резать нечего, и тело целиком
уходит ПОД снимок во всю ширину. Это тот же обмен, доведённый до края.

ЧТО ЭТО ПОКУПАЕТ. Не красоту, а КЕГЛЬ: тело, которому вернули полную ширину
на нижней половине кадра, укладывается крупнее. Величина замерена пробой
`[обтекание]` и по кадрам Лекции 7 — см. `README.md`.
"""
from . import metrics, report

# Выключатель обтекания — на деку и на пробу. Проба на САМО обтекание иначе
# невозможна: она обязана собрать тот же вход дважды и показать разницу, а
# «разницу» не с чем сравнивать, пока второго режима нет. Дека, которой
# обтекание не нужно, гасит его тем же флагом — и тогда её геометрия
# побитово та же, что была до этой работы (проба `[обтекание-геометрия]`).
ENABLED = True


def cut_points(runs):
    """Места разреза тела: индексы прогонов-разделителей блоков.

    Разделитель узнаётся по двум признакам сразу — он начинает абзац и не
    несёт текста. Одного `newpara` мало: абзац может начинать и обычный
    прогон со словами (так склеена обложка `refdeck`), а разрезать по нему
    значило бы потерять его отбивку или его текст."""
    return [i for i, r in enumerate(runs)
            if r.get("newpara") and not str(r.get("text") or "").strip()]


def split_at(runs, i):
    """Тело на две части по разделителю `i`. Сам разделитель не идёт никуда:
    его работа — отбивка МЕЖДУ блоками одной надписи, а между двумя
    надписями отбивку задаёт их геометрия."""
    return runs[:i], runs[i + 1:]


def _fits(part, w, h, ls):
    return bool(part) and metrics.runs_h(part, w, ls) <= h


def best_cut(runs, w_top, h_top, w_bot, h_bot, ls):
    """Самый нижний разрез, при котором ОБЕ части влезают. None — такого нет.

    Верхняя часть обязана быть непустой: пустая значит «рядом со снимком не
    поместился ни один блок», и тогда резать нечего — это не обтекание, а
    обычное тело под снимком, и решает его вызывающий."""
    for i in reversed(cut_points(runs)):
        top, bot = split_at(runs, i)
        if not _fits(top, w_top, h_top, ls):
            continue
        return i if _fits(bot, w_bot, h_bot, ls) else None
    return None


def fit_runs_wrap(runs, w_top, h_top, w_bot, h_bot, w_plain, h_plain, *,
                  hi=1.0, lo=0.72, floor=0.58, ls=1.26, tag="",
                  grid=metrics.GRID_PT, step=metrics.K_STEP, proj_base=None,
                  proj_pt=metrics.PROJ_PT):
    """Крупнейший масштаб, при котором тело ложится в УГОЛ: узкая часть
    рядом со снимком, широкая под ним.

    `w_plain × h_plain` — та самая узкая рамка, которой кадр обходился до
    обтекания. Она здесь НЕ для справки: обтекание берётся только тогда,
    когда кегль от него НЕ ПАДАЕТ. Разрез идёт по границе блока, и остаток
    узкой части ниже разреза пропадает — на входе, где всё тело и так
    укладывалось рядом со снимком, эта потеря перевешивала выигрыш ширины.
    Замерено пробой: три блока рядом с широким снимком давали 13,0 пт одной
    надписью и 12,5 пт обтеканием. Поэтому поиск ограничен снизу масштабом
    обычной раскладки (`metrics.scan_scale`, молча), и равный кегль
    обтекание ВЫИГРЫВАЕТ: при том же кегле оно убирает дыру под снимком, а
    дыра — то, ради чего всё это и делается.

    Возвращает `(масштаб, разрез, верх, низ)` либо `None`, если обтекание
    не складывается или складывается мельче, — и тогда вызывающий собирает
    кадр как прежде, одной узкой надписью. Отказ здесь молчаливый нарочно:
    кадр от этого не ломается, он просто остаётся тем, чем был, а
    предупреждение об узком теле выдаст обычный путь своим `[проекция]`.

    Выключенное `ENABLED` — не «ошибка», а отказ: тот же `None`, что и при
    неукладывающемся разрезе, и вызывающий собирает кадр прежним путём.

    Правит `runs` на месте, как `metrics.fit_runs`, — НО ТОЛЬКО ПРИ УСПЕХЕ.
    Отказ обязан вернуть кегли ровно такими, какими их отдал вызывающий:
    он собирается звать `metrics.fit_runs` теми же словарями, а та берёт
    текущие кегли ЗА ИСХОДНЫЕ. Без возврата кадр, у которого обтекание не
    сложилось, набирался бы от уже ужатой основы — замерено на `s55`: тело
    село на 8,5 пт вместо 15,0, и ни одно предупреждение этого не назвало,
    потому что по своей новой основе прогон укладывался при масштабе 1,00."""
    if not ENABLED:
        return None
    k_plain = metrics.scan_scale(runs, w_plain, h_plain, hi=hi, floor=floor,
                                 ls=ls, grid=grid, step=step)
    bottom = floor if k_plain is None else max(floor, k_plain)
    k = hi
    base = [r.get("size", 15.0) for r in runs]
    seen = None
    while k >= bottom - 1e-9:
        sizes = metrics.apply_scale(runs, base, k, grid)
        if sizes != seen:                 # на ступени соседние масштабы дают
            seen = sizes                  # один и тот же набор кеглей
            i = best_cut(runs, w_top, h_top, w_bot, h_bot, ls)
            if i is not None:
                top, bot = split_at(runs, i)
                metrics.check_proj(k, tag, proj_base, proj_pt, grid)
                if k < lo - 1e-9:
                    report.warn(
                        f"[кегль] {tag}: прогон ужат до {k:.2f} от рабочего "
                        "кегля — предел плотности кадра")
                for part, w, h, side in ((top, w_top, h_top, "рядом"),
                                         (bot, w_bot, h_bot, "под")):
                    paras = metrics.runs_paras(part)
                    metrics.check_thin_margin(
                        [(pieces, w) for pieces, _sb in paras], h,
                        metrics.runs_h(part, w, ls),
                        max((pc[1] for pieces, _sb in paras for pc in pieces),
                            default=15.0) * ls * metrics.LH / 72.0
                        * metrics.SAFE, f"{tag}/{side}")
                return k, i, top, bot
        k -= step
    for r, b0 in zip(runs, base):
        r["size"] = b0               # вернуть ровно то, что было: не
    return None                      # `grid_pt(b0)`, а сам `b0`


def fit_pushed(runs, w_push, h_push, w_plain, h_plain, *, hi=1.0, lo=0.72,
               floor=0.58, ls=1.26, tag="", grid=metrics.GRID_PT,
               step=metrics.K_STEP, proj_base=None,
               proj_pt=metrics.PROJ_PT):
    """Вырожденный случай обтекания: рядом со снимком не помещается НИ ОДИН
    блок, и тело целиком уходит ПОД него, во всю ширину.

    Это не «ещё одна раскладка», а тот же обмен, доведённый до края: полоска
    рядом со снимком бывает такой узкой, что разрезать по ней нечего.
    Замерено на `s55` Лекции 7: тело начиналось на 0,22" выше нижней грани
    снимка — то есть практически под ним, — и за эти 0,22" высоты платило
    4,64" ширины на всю оставшуюся высоту кадра, оставляя под снимком
    10,3 кв. дюйма мёртвого белого.

    Условие взятия то же, что у `fit_runs_wrap`, и по той же причине: кегль
    от обмена НЕ ПАДАЕТ. Отказ возвращает кегли нетронутыми.

    Возвращает масштаб либо `None`."""
    if not ENABLED:
        return None
    base = [r.get("size", 15.0) for r in runs]
    k_plain = metrics.scan_scale(runs, w_plain, h_plain, hi=hi, floor=floor,
                                 ls=ls, grid=grid, step=step)
    bottom = floor if k_plain is None else max(floor, k_plain)
    k = metrics.scan_scale(runs, w_push, h_push, hi=hi, floor=bottom, ls=ls,
                           grid=grid, step=step)
    if k is None:
        for r, b0 in zip(runs, base):
            r["size"] = b0
        return None
    metrics.apply_scale(runs, base, k, grid)
    metrics.check_proj(k, tag, proj_base, proj_pt, grid)
    if k < lo - 1e-9:
        report.warn(f"[кегль] {tag}: прогон ужат до {k:.2f} от рабочего "
                    "кегля — предел плотности кадра")
    paras = metrics.runs_paras(runs)
    metrics.check_thin_margin(
        [(pieces, w_push) for pieces, _sb in paras], h_push,
        metrics.runs_h(runs, w_push, ls),
        max((pc[1] for pieces, _sb in paras for pc in pieces), default=15.0)
        * ls * metrics.LH / 72.0 * metrics.SAFE, f"{tag}/под")
    return k

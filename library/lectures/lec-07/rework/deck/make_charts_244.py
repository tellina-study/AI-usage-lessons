#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Диаграммы трёх кадров допуска (#244) — на шаблоне `tools/presentation-build/analitika.py`.

Рисует две картинки, по одной на кадр:

  assets/s01ab-strany-i-priznaki.png  — страны, у каждой строки назван признак отбора
  assets/s0Xc-potok-za-god.png        — столбцы потока за год по странам и системам

ЧТО ИЗМЕНИЛОСЬ ПРИ ВОЗВРАТЕ `s01ab` (#293, Этап E). Прежде страны и линии
накопленного счёта складывались в одну картинку `s0Xb-strany-i-dinamika.png`,
потому что поле `media:` у кадра одно. Линии сняты (их число живёт строкой
тела на `s01aa`), страны взяли полосу целиком и получили по признаку отбора в
имени строки. Прежний файл на диске оставлен, но ни одним кадром больше не
читается.

ОТКУДА ЧИСЛА — из исследования, не из головы. Страновой ряд и его
знаменатели: `research/11-dinamika-po-stranam-realno-novye.md` §3 и
`research/13-koreya-kitay-proverka.md` §3. Накопленный счёт по годам:
`research/10-II-FDA-PERVICHNYY-SCHET.md` (таблица по годам, разобранная с
самой страницы FDA). Поток за год: `research/14-vnedrenie-agregaty.md` §2–3.

ЧТО СЧИТАНО ЗДЕСЬ, А НЕ ВЗЯТО ГОТОВЫМ — накопленный ряд короткого пути.
В исследовании он лежит по годам, а не накоплением; сложено здесь, и
проверка стоит прогоном: сумма 2014–2025 плюс остаток до 2014 обязана дать
1 377 — счёт короткого пути на конец 2025 года (1 553 всего минус 176 за
неполный 2026-й). Точки 2010 года у короткого пути нет: погодовой разбивки
до 2014-го в первичной таблице нет, и линия начинается там, где начинаются
данные, — пустое место честнее дорисованного.

ЕДИНИЦЫ. У кадра про поток единица у каждого столбца СВОЯ — случаи, решения,
сводки, исследования. Поэтому она стоит подписью под каждым столбцом, а не
одна на диаграмму: ряд из разных единиц без подписи и есть та склейка
выборок, на которой этот круг спотыкался трижды.

    python3 make_charts_244.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / "tools" / "presentation-build"))

import analitika as A  # noqa: E402

ASSETS = HERE / "assets"
VREMENNO = Path("/tmp/charts-244")

# ── кадр об изделиях: страны ──────────────────────────────────────────────
# ПЕРЕРАБОТАНО ПРИ ВОЗВРАТЕ `s01ab` (#293, Этап E, решение владельца 2026-10-22:
# «зря потерял статистику по мед изделиям верни, можно как-то переработанно»).
#
# Снят кадр был потому, что строки считаны по РАЗНЫМ признакам новизны, а честная
# оговорка об этом на кадре запрещена §7.1 (рассуждение о замере). Переработка
# закрывает это не оговоркой, а ДАННЫМИ: признак отбора встал В ИМЯ СТРОКИ, рядом
# с полосой, и читается как часть подписи, а не как извинение под ней. §5.17
# требует называть пробел содержательно на кадре — «весь реестр, разбивки нет»
# это и есть.
#
# Корея стоит ДВУМЯ строками намеренно. Это не дубль страны: два её собственных
# признака дают 1,70 и 0,95, то есть разброс внутри одной страны шире, чем
# расстояние между половиной стран ряда. Ряд, где это видно, честнее ряда, где
# выбран один из двух и выбор не назван.
#
# ЗНАМЕНАТЕЛЬ ЕДЕТ С ЧИСЛОМ, А НЕ ВТОРОЙ СТРОКОЙ ПОД ИМЕНЕМ, и это замер, не
# вкус: шесть строк по две строки подписи в полосе 216 точек НАЕЗЖАЮТ друг на
# друга — проверено рендером, «88 из 549» легло на имя следующей страны. Признак
# отбора занял ту строку, которую прежде занимал знаменатель, поэтому знаменатель
# переехал к концу полосы («1,70 · 88 из 549») — тем же приёмом, которым кадр
# потока ставит свою единицу.
STRANY = [
    ("Корея · инновационный статус", 1.70, None),
    ("Корея · возмещение по страховке", 0.95, None),
    ("Россия · весь реестр, разбивки нет", 0.39, None),
    ("США · без предшественника", 0.18, None),
    ("Япония · пересчёт доли", 0.11, None),
    ("Китай · собственное испытание", 0.08, None),
]
STRANY_PODPISI = ["1,70 · 88 из 549", "0,95 · 49 из 549", "0,39 · 57 из 57",
                  "0,18 · 61 из 1 614", "0,11 · ≈14 из 51", "0,08 · 118 из 154"]

# ── динамика накопленным счётом: БОЛЬШЕ НЕ РИСУЕТСЯ, но проверяется ───────
# Ряды оставлены вместе с `proverka_ryada()` ниже, хотя линий на кадрах больше
# нет: проверка сходится с числами, которые СТОЯТ НА ВИДИМОМ СЛОЕ `s01aa` —
# «1 553 из 1 614» плашкой и «56 к концу 2025 года против 7 к 2010-му» строкой
# тела. Снять её заодно с рисунком значило бы снять единственный прогон, который
# эти два числа сверяет с погодовой таблицей первоисточника.
GODY = [2010, 2014, 2018, 2021, 2024, 2025]
NOVYE = [7, 11, 23, 31, 50, 56]
KOROTKIY = [None, 25, 129, 444, 1048, 1377]

# ── кадр о применении: поток за год ───────────────────────────────────────
# Единица у каждой строки СВОЯ, поэтому она едет с числом, а не с именем:
# в полосе высотой три дюйма двухстрочная подпись слева не помещается.
POTOK = [
    ("США · Aidoc", 60, None),
    ("США · оплата", 53, None),
    ("Россия · СберМедИИ", 30, None),
    ("Россия · Москва", 16, None),
    ("20 стран · Qure.ai", 7, None),
    ("Великобритания · NHS", 2.8, None),
]
POTOK_PODPISI = ["60 млн случаев", "53 млн решений", "30 млн сводок",
                 "16 млн исследований", "7 млн обследований",
                 "2,8 млн рентгенограмм"]


def proverka_ryada():
    """Накопленный ряд короткого пути обязан сойтись с первичным счётом."""
    po_godam = [5, 6, 17, 23, 58, 80, 113, 122, 160, 219, 225, 329]  # 2014–2025
    assert sum(po_godam) == 1357, sum(po_godam)
    assert 1553 - 176 == 1377                      # всего минус неполный 2026-й
    do_2014 = 1377 - 1357
    assert do_2014 == 20, do_2014
    nakoplenno = do_2014
    po_letam = {}
    for god, n in zip(range(2014, 2026), po_godam):
        nakoplenno += n
        po_letam[god] = nakoplenno
    for god, zhdem in ((2014, 25), (2018, 129), (2021, 444),
                       (2024, 1048), (2025, 1377)):
        assert po_letam[god] == zhdem, (god, po_letam[god], zhdem)
    print("  проверка ряда: накопленный счёт короткого пути сходится "
          "с первичным (1 377 на конец 2025)")


def main():
    proverka_ryada()
    VREMENNO.mkdir(parents=True, exist_ok=True)

    strany = A.stolbtsy(
        "Изделия, допущенные как новые: сколько их у страны",
        STRANY,
        "изделий на миллион населения · признак отбора назван в строке",
        zoloto=2, drobnaya=True, kegl_zagolovka=14,
        gorizontal=True, podpisi_znacheniy=STRANY_PODPISI)
    potok = A.stolbtsy(
        "Поток за год через названные системы",
        POTOK, "за год · единица у каждого столбца своя, названа у числа",
        zoloto=0, drobnaya=False, kegl_zagolovka=14,
        gorizontal=True, podpisi_znacheniy=POTOK_PODPISI)

    # ПОЛОСА ВО ВСЮ ШИРИНУ (880×216), а не половина сводной картинки.
    # До возврата страны занимали левую половину `s0Xb-strany-i-dinamika.png`,
    # вторую держали линии накопленного счёта. Линии сняты: число, которое они
    # несли («3,1 по-настоящему новых изделия в год: 56 к концу 2025 против 7
    # к 2010-му»), при слиянии Этапа A переехало строкой тела на `s01aa` и
    # стоит там; рисовать его второй раз — тот самый двойной счёт, который §5.12
    # запрещает на соседних кадрах. Освободившаяся половина ушла строкам: шесть
    # строк с названным признаком отбора в полосе 435 точек не читаются, в 880
    # читаются — проверено рендером.
    strany_png = A.narisovat(strany, ASSETS / "s01ab-strany-i-priznaki.png",
                             shirina_pt=880, vysota_pt=216)
    pot = A.narisovat(potok, ASSETS / "s0Xc-potok-za-god.png",
                      shirina_pt=880, vysota_pt=216)

    from PIL import Image
    for p in (strany_png, pot):
        im = Image.open(p)
        print(f"  {p.name}: {im.width}×{im.height} пикс · "
              f"пропорция {im.width / im.height:.2f} · {p.stat().st_size} Б")
    return 0


if __name__ == "__main__":
    sys.exit(main())

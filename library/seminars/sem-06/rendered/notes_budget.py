#!/usr/bin/env python3
r"""Замер заметки по контракту «заметки на сайт»: связный текст, не шпаргалка.

## Что отменено и почему этот файл переписан целиком

Прежняя версия мерила заметку ДВУМЯ числами: произносимую речь (120–180 слов) и
блок справки «Если спросят…» (180–270), и считала хронометраж слайда по речи на
темпе 130 слов/мин. Весь этот контракт отменён заданием `ZADANIE-ZAMETKI-NA-SAYT.md`
(issue 225) вместе с жанром, под который он был написан.

Жанр сменился так. Заметка была шпаргалкой человека, стоящего у экрана: сначала
то, что он произносит, потом заготовки ответов на вопросы из зала. Теперь заметка —
текст, который читает человек, не бывший на занятии: он открыл страницу курса,
видит слайд и читает под ним связный рассказ. Лектора рядом нет, зала нет,
вопросов из зала нет.

Отсюда три следствия, и каждое ломало прежнюю проверку насквозь:

1. **Шва больше нет.** Справка растворена по месту — нет ни оборота «Если
   спросят», ни черты `---` с заголовком `**Справка.**`. Прежний код искал шов
   двумя шаблонами по очереди и на деке нынешнего жанра не находил ни одного:
   все 68 заметок уходили в «речь» целиком и все 68 получали приговор «справки
   нет вовсе» плюс «речь втрое длиннее нормы». Проверка, которая ругается на
   каждый файл, не отличает годный файл от сломанного.
2. **Заметка перестала быть мерой времени.** Сколько ведущий говорит вслух,
   определяет слот слайда, а не длина текста под ним: `duration_min` этим кругом
   не тронут ни у одного слайда. Поэтому темпа 130 слов/мин здесь больше нет, и
   слот в расчёт коридора не входит. Пересчёт заметки в минуты — та самая
   ошибка, из-за которой `CUT-ORDER.md` предлагал «сократить речь» там, где
   сокращать было нечего.
3. **Запреты шпаргалки переехали в заметку.** Пока заметка была шпаргалкой,
   «Если спросят» и «зал» были в ней законны — `audit_sluzhebnoe.py` прямо
   говорит, что заметок не проверяет, потому что место таких вещей именно в них.
   Теперь заметку читает студент, и в ней они запрещены ровно так же, как на
   печатаемом слое. Эту половину запрета не проверял никто: разделение труда
   осталось прежним (`audit_sluzhebnoe.py` читает видимый слой готового `.pptx`,
   этот файл — заметки исходников), но вторая половина теперь не пуста.

## Чем мерит

Одним числом — словами связного текста. Коридор зависит от того, что слайд
делает, и только от этого:

| Класс слайда    | Слов     | Почему столько |
|---|---|---|
| разделитель     | 250–450  | поворот одной мысли, механизма не несёт |
| голосование     | 300–550  | разбираются ответы, которые читатель даёт сам, — их три-четыре |
| содержательный  | 400–600  | ориентир задания |
| опорный экран   | 500–750  | держит механизм целиком, читатель приходит на него из нескольких мест |

Класс берётся из `type` во фронтматтере, кроме опорных экранов: «опорность» —
свойство замысла, а не типа слайда (`n09` и `n38` оба `mechanics_map`, как и
`n16`, `n23`, `n49`, которые опорными не являются). Поэтому опорные перечислены
явно и каждый — с причиной, по которой он опорный; списком, который нельзя
молча расширить под длину текста. См. `ANCHOR` ниже.

## Что ещё проверяет

Остатки прежнего жанра — обращения к ведущему («Если спросят», «Если
прозвучит», «Лектору», «Преподавателю», «Остаток себе», «вызвать два-три
голоса»), «зал» как действующее лицо, вернувшийся двухчастный шов — и слово
«окно», запрещённое по всему занятию в пользу «контекста» (прежний круг заменил
63 вхождения; проверки на возврат не было).

**Про границы слов на кириллице.** Поиск «зал» и «окно» по `\b` в этом окружении
ненадёжен, и ошибка не теоретическая: «зал» — настоящая подстрока «покаЗАЛ»,
«расскаЗАЛ», «свяЗАЛ»; «окон» — подстрока «подОКОНник» и «ОКОНный». Границы
здесь задаются явным просмотром назад и вперёд по классу «любая буква»
(`[^\W\d_]`, юникодный по умолчанию для строковых шаблонов), а не `\b`. Ровно
эти ложные примеры стоят в `--self-test` и падают, если шаблон ослабить.

## Как запускать

    python3 notes_budget.py ../slides/n*.md        # замер по исходникам
    python3 notes_budget.py --pptx sem-06.pptx     # заметки доехали целиком?
    python3 notes_budget.py --self-test            # проверка самой проверки

`--pptx` сверяет слово в слово то, что лежит в заметках собранной деки, с тем,
что лежит в исходниках. Нужно потому, что объём заметок вырос втрое, а обрезка
заметки незаметна: на слайде она не видна, в PDF не печатается, и единственный,
кто её обнаружит, — читатель сайта, у которого текст кончается на полуслове.

`--self-test` гоняет проверку на нарочно сломанном входе И на нарочно
каверзном годном: заметка со словами «показал», «рассказал», «связал»,
«подоконник», «оконный», «залог» обязана пройти чисто. Проверка, которая на них
ругается, так же мертва, как та, которая молчит на «зал».
"""
import re
import sys
from pathlib import Path

# ── Коридоры ────────────────────────────────────────────────────────────────
#
# Задание называет 400–600 ОРИЕНТИРОМ, не порогом, и проверка обязана читать это
# слово буквально: приговор за расхождение в три слова — не находка, а шум,
# из-за которого проверку перестают запускать. Поэтому у краёв коридора есть
# допуск в 5%: попадание в него ПЕЧАТАЕТСЯ знаком `~` с точным числом, но кодом
# возврата не считается дефектом. Допуск узкий намеренно — 5% от 400 это 20
# слов, то есть одна фраза, а не абзац.
#
# На нынешней деке в допуске стоит РОВНО ОДИН слайд — `n13` (397 слов при
# ориентире 400). Он назван здесь по имени, чтобы допуск нельзя было задним
# числом выдать за общее послабление: если в допуске окажется третий и
# четвёртый слайд, это уже дрейф жанра, и видно это будет сразу.
TOLERANCE = 0.05

BANDS = {
    "разделитель":    (250, 450),
    "голосование":    (300, 550),
    "содержательный": (400, 600),
    "опорный":        (500, 750),
}

DIVIDER_TYPES = {"section_divider", "section_divider_macro"}
QUESTION_TYPES = {"reflection_question", "question_with_option_cards"}

# Опорные экраны — перечислены явно, с причиной на каждого. Список закрыт:
# расширять его под слайд, который просто вышел за 600 слов, значит подгонять
# проверку под текст вместо того, чтобы править текст.
ANCHOR = {
    "n08": "схема «где что стоит» — расставляет фигуры, которые одностраничник разбирает по частям",
    "n09": "одностраничник MCP — блок возвращается к нему трижды (n15, n23, n32)",
    "n12": "разбор пяти способов доступа — пять карточек, у каждой своя цена и своя граница",
    "n37": "база ступени субагента со схемой контекстов",
    "n38": "одностраничник роли — блок возвращается к нему четырежды (n36, n41, n43, n53)",
    "n46": "практика: читатель раскладывает задачу сам, и разбор раскладки лежит здесь же",
    "n62": "провал-самоизобличение — единственная опора кейса 6, которую читатель проверяет сам",
}

# ── Шаблоны остатков прежнего жанра ─────────────────────────────────────────
LET = r"[^\W\d_]"          # любая буква, юникодный класс (не `\w`: цифры и `_` вне)


def _w(body: str) -> str:
    """Шаблон со границами слова, заданными явно, а не через `\\b`.

    `\\b` на кириллице в этом окружении ненадёжен — см. преамбулу. Просмотр
    назад фиксированной ширины 1 допустим в `re`, поэтому форма рабочая.
    """
    return rf"(?<!{LET})(?:{body})(?!{LET})"


ZAL = re.compile(_w(r"[Зз]ал|[Зз]ал[аеуыом]|[Зз]алами|[Зз]алах"))
OKNO = re.compile(_w(r"[Оо]кн[оаеуы]|[Оо]кном|[Оо]кон|[Оо]кнами|[Оо]кнах|[Оо]кошк[оаеуи]"))

VEDUSHCHEMU = [
    ("обращение к ведущему", re.compile(
        r"(?i)Если\s+спросят"
        r"|Если\s+прозвучит"
        r"|Если\s+кто-нибудь\s+спросит"
        r"|(?<!\w)Лектору(?!\w)"
        r"|(?<!\w)Преподавател"
        r"|Остаток\s+себе"
        r"|вызват[ьи]\s+(?:два|две|три)"
        r"|спрашива[ю|ем],?\s+у\s+кого"
        r"|поднимите\s+рук"
        r"|спросите\s+у\s+сосед")),
    ("вернувшийся шов справки", re.compile(
        r"(?m)^[ \t]*(?:\*\*Справка\.?\*\*|Справка\.)[ \t]*$")),
    ("«зал» как действующее лицо", ZAL),
    ("«окно» вместо «контекста»", OKNO),
]


# ── Разбор файла ────────────────────────────────────────────────────────────
def frontmatter_end(md: str) -> int:
    m = re.match(r"(?s)^---\n.*?\n---\n", md)
    return m.end() if m else 0


def slide_type(md: str) -> str:
    m = re.search(r"(?m)^type:\s*(\S+)\s*$", md)
    return m.group(1) if m else ""


def notes_of(md: str) -> str:
    """Заметка — всё после `## Speaker notes`, фронтматтер заведомо отрезан.

    Отрезан он не на всякий случай: «окно» в служебных полях (`learning_goal`,
    `visual.backup` — записи прежних кругов о том, что слово заменено) законно и
    остаётся, а в тексте для читателя запрещено. Проверка, читающая файл
    целиком, ругалась бы на историю правок.
    """
    body = md[frontmatter_end(md):]
    m = re.search(r"(?ms)^##\s+Speaker notes\s*$(.*)", body)
    return m.group(1).strip() if m else ""


def classify(sid: str, md: str) -> str:
    if sid in ANCHOR:
        return "опорный"
    t = slide_type(md)
    if t in DIVIDER_TYPES:
        return "разделитель"
    if t in QUESTION_TYPES:
        return "голосование"
    return "содержательный"


def words(text: str) -> int:
    """Слова связного текста: разметка снята, числа и номера не считаются.

    Тот же счёт, что был в прежней версии, — чтобы «стало» сравнивалось с
    «было» одной линейкой, хотя коридоры сменились.
    """
    text = re.sub(r"[*_`>]", " ", text)
    return len(re.findall(r"[^\W\d_]+(?:-[^\W\d_]+)*", text, re.UNICODE))


def check(path: Path):
    md = path.read_text(encoding="utf-8")
    sid = path.stem[:3]
    notes = notes_of(md)
    cls = classify(sid, md)
    lo, hi = BANDS[cls]
    n = words(notes)
    bad, soft = [], []
    if not notes:
        bad.append("заметки нет вовсе")
    elif n < lo:
        where = soft if n >= lo * (1 - TOLERANCE) else bad
        where.append(f"{n} слов — ниже {lo} ({cls})")
    elif n > hi:
        where = soft if n <= hi * (1 + TOLERANCE) else bad
        where.append(f"{n} слов — выше {hi} ({cls})")
    # Остатки прежнего жанра допуска не имеют: одно «Если спросят» — это
    # вернувшаяся шпаргалка, а не отклонение на проценты.
    for name, rx in VEDUSHCHEMU:
        found = {m.group(0) for m in rx.finditer(notes)}
        if found:
            bad.append(f"{name}: {', '.join(sorted(found)[:4])}")
    return sid, cls, n, bad, soft


# ── Заметки доехали в деку целиком? ─────────────────────────────────────────
def check_pptx(pptx_path: Path, slides_dir: Path):
    """Слово в слово: заметка исходника против заметки собранной деки.

    `deck_kit.write_notes` превращает `**жирный**`, `` `моноширинный` `` и
    `*курсив*` в оформление и сами звёздочки выбрасывает — то есть разметка в
    деке не лежит, а слова лежат все. Значит счёт слов обеих сторон обязан
    совпасть ТОЧНО, и расхождение в одно слово — уже обрезка, а не округление.
    """
    from pptx import Presentation

    prs = Presentation(str(pptx_path))
    srcs = sorted(slides_dir.glob("n*.md"))
    by_id = {p.stem[:3]: p for p in srcs if re.fullmatch(r"n\d\d", p.stem[:3])}
    order = sorted(by_id)
    if len(prs.slides) != len(order):
        print(f"⚠ слайдов в деке {len(prs.slides)}, исходников {len(order)} — сверка слепая")
    worst = 0
    for i, sl in enumerate(prs.slides):
        sid = order[i] if i < len(order) else f"#{i + 1}"
        want = words(notes_of(by_id[sid].read_text(encoding="utf-8"))) if sid in by_id else 0
        got = words(sl.notes_slide.notes_text_frame.text) if sl.has_notes_slide else 0
        if want != got:
            worst = 1
            print(f"⚠ {sid}: в исходнике {want} слов, в деке {got} — расхождение {got - want:+}")
    if not worst:
        print(f"· заметки всех {len(prs.slides)} слайдов доехали слово в слово")
    return worst


# ── Проверка проверки ───────────────────────────────────────────────────────
_CLEAN = "слово " * 480          # содержательный, внутри 400–600


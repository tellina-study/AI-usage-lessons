# ============================================================
# Измерение: сколько места ТЕКСТ реально займёт. Первая калибровка (122/114
# символа на дюйм ширины) систематически ЗАНИЖАЛА число строк — см.
# notes/mcp-limitations.md [#212-6]: реальная плотность в LibreOffice на этом
# хосте ближе к ~104 символам на дюйм, и на шагах механизма это давало
# наползание соседних строк друг на друга при пустом WARN. Константа
# приведена к факту; SF оставлен маленьким остаточным запасом.
# ============================================================
WARN = []
_TOP = [TOP]
_SID = [""]
_TAIL = [0.0]
_BAND = ["", 0.0]          # подпись текущей полосы и её нижняя граница


def est_lines(text, size, w, *, bold=False):
    k = (98.0 if bold else 104.0) / max(size, 1.0)
    n = 0
    for para in text.split("\n"):
        plain = para.replace("**", "")
        n += max(1, math.ceil(len(plain) / max(1.0, w * k)))
    return n


def est_h(text, size, w, *, bold=False, ls=1.15, extra=0.05):
    return est_lines(text, size, w, bold=bold) * size * ls * 1.09 / 72.0 + extra


# Запас против систематического занижения est_h на кегле выше 10,5 pt
# (notes/mcp-limitations.md [#212-6]): высоту полос и шагов считаем с ним,
# а сторож _check оставляем на голой оценке — иначе он молчит там, где текст
# реально вылезает.
SF = 1.04


def fit_h(text, size, w, *, bold=False, ls=1.15, extra=0.05):
    return est_h(text, size, w, bold=bold, ls=ls, extra=extra) * SF


def _check(need, given, y, what):
    """Ругаемся в консоль сборки, а не молча обрезаем: переполнение на этих
    слайдах — главный риск, и видеть его надо числом, а не глазами."""
    if need > given + 0.02:
        WARN.append(f"{_SID[0]} {_BAND[0]}: {what} не влезает — надо {need:.2f}\", "
                    f"дано {given:.2f}\"")
    if y + need > _BAND[1] + 0.02 and _BAND[1] > 0:
        WARN.append(f"{_SID[0]} {_BAND[0]}: {what} вылезает за полосу на "
                    f"{y + need - _BAND[1]:.2f}\"")


def free_slide(sid, label=""):
    """Адресация сторожа для слайда этой полосы, собранного БЕЗ карточных
    полос (сейчас такой один — s45a).

    `_SID` / `_BAND` — модульные глобальные: их выставляет `head()` и `row()`,
    то есть карточная форма. Слайд, который их не вызывает, наследовал имя и
    нижнюю границу полосы ПРЕДЫДУЩЕЙ карточки, и переполнение в нём
    докладывалось под чужим адресом (предупреждение про легенду s45a приходило
    как «s38b ГДЕ НЕ РАБОТАЕТ» — ровно то, что и случилось, issue #212).
    Здесь имя ставится явно, а нижняя граница обнуляется: полосы нет, значит
    проверять выход за её границу нечего, и `_check` оставляет только честную
    сверку «текст против высоты своей коробки».
    """
    _SID[0] = sid
    _BAND[0] = label
    _BAND[1] = 0.0


class Cursor:
    """Полосы карточки укладываются сверху вниз сами: у слайда задаётся
    только высота содержания полосы, вертикальная бухгалтерия — здесь."""

    def __init__(self, top=None):
        self.y = _TOP[0] if top is None else top

    def band(self, slide, kind, label, h):
        x, y, w, hh = row(slide, self.y, h, kind, label)
        self.y += h + RGAP
        return x, y, w, hh

    def text(self, slide, kind, label, text, *, size=10.5, bold=False,
             bold_color=MID, min_h=0.0, pad=0.10):
        ch = max(min_h, fit_h(text, size, CW - 2 * PAD, bold=bold) + pad)
        x, y, w, h = self.band(slide, kind, label, ch + 2 * PAD_Y)
        md_box(slide, x, y, w, h, text, size=size, base_bold=bold,
               color=DEEP, bold_color=(DEEP if bold else bold_color),
               line_spacing=1.14, anchor=MSO_ANCHOR.MIDDLE)
        return x, y, w, h

    def edge(self, slide, text, *, size=10.0, label="ГДЕ НЕ РАБОТАЕТ",
             min_h=0.0):
        return self.text(slide, "edge", label, text, size=size, bold=True,
                         min_h=min_h)


def row(slide, y, h, kind, label):
    """Одна полоса карточки: подпись слева + контейнер содержания справа.
    Возвращает (x, y, w, h) внутренней области содержания."""
    k = KIND[kind]
    ocean_box(slide, X0, y, LBL_W, h, fill=k["lab"], stroke=k["lab"],
              stroke_pt=1.0)
    text_box(slide, x=X0 + 0.05, y=y, w=LBL_W - 0.10, h=h, text=label,
             size=9.5, bold=True, color=k["labc"], align=PP_ALIGN.CENTER,
             anchor=MSO_ANCHOR.MIDDLE, line_spacing=1.02)
    ocean_box(slide, CX, y, CW, h, fill=k["fill"], stroke=k["stroke"],
              stroke_pt=k["pt"])
    _BAND[0] = label
    _BAND[1] = y + h - PAD_Y
    return CX + PAD, y + PAD_Y, CW - 2 * PAD, h - 2 * PAD_Y



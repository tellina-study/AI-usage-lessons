# -*- coding: utf-8 -*-
"""ПОЛ КЕГЛЯ ВИДИМОГО СЛОЯ — один порог на ВСЕ классы текста, не на тело.

ЧТО БЫЛО СЛОМАНО. Пол 12 пт в этом пакете был, и о нём отчитывались:
`metrics.check_proj` печатает `[проекция]`, когда тело набрано мельче. Но он
меряет ОДНО число — масштаб прогона тела, умноженный на номинальный кегль
деки, — и больше ничего. Всё остальное, что зал читает, мимо него проходило:
подпись плашки (10 пт капителью), оговорка под числом (10,5 пт курсивом),
подпись схемы, подпись под иллюстрацией, строка источника в подвале. Отчёт
сборки говорил «ниже 12 пт — один кадр», а по СОБРАННОМУ PDF той же деки
мельче 12 пт набрано 19,7% всех видимых знаков на 95 кадрах из 122
(замер `deckkit.pdfmeasure`, круг #229).

Хуже того, где именно: оговорка плашки — это место, где у этой лекции живут
все «но». «промежуточный анализ, 80 033 женщины», «величина ОПРОСНАЯ:
сказали сами участники, телеметрии нет», «знаменатель другой». Клауза,
которая делает число честным, была самым мелким текстом кадра.

ПОЧЕМУ ЭТОТ МОДУЛЬ НАЗЫВАЕТ, А НЕ ЧИНИТ. Поднять кегль — значит раздуть
рамку, а рамка у плашки и схемы считается по содержимому и отнимает высоту у
тела. Там, где поднять нельзя, выбор не между раскладками, а между «срезать
текст кадра» и «оставить мелко», и это решение владельца, не сборки. Поэтому
`pt` ничего не трогает: она СМОТРИТ и называет кадр, класс и кегль. Ровно
тот же договор, что у `[запас]` и `[проекция]`, и по той же причине тег не
блокирующий.

ЧТО ЭТОТ МОДУЛЬ ЗАКРЫВАЕТ ИЗ ПЕРЕЧНЯ ПРИБЛИЖЕНИЙ. Пункт 15 README («пол
проекции мерится по ОДНОМУ названному кеглю»): `check_runs` смотрит кегли,
КОТОРЫЕ НА САМОМ ДЕЛЕ ПОСТАВЛЕНЫ прогонам после подбора, все до одного, а не
номинал деки, умноженный на масштаб. Отсюда и находка круга: подпись внутри
тела набрана от основы 12 пт, и при любом сжатии прогона она уходит под пол,
тогда как номинал тела 15 пт при том же сжатии остаётся ровно на 12,0 — то
есть старая проверка молчала ПО ПОСТРОЕНИЮ, а не по недосмотру.
"""
from . import report

# Порог проекции курса: ниже — «с задних рядов не читается» (anti-pattern
# #22). Число то же, что `metrics.PROJ_PT`, и это НЕ дубль: там оно порог
# одной проверки тела, здесь — порог видимого слоя целиком. Сведены они
# ссылкой, а не общим именем, нарочно: деке, которая захочет поднять свой
# пол видимого слоя, не должно приходиться двигать порог чужой проверки.
VIS_PT = 12.0


def _floor(given):
    """Порог этого вызова: названный — или нынешний `VIS_PT`.

    Читается В МОМЕНТ ВЫЗОВА нарочно. Было `floor=VIS_PT` значением по
    умолчанию — то есть порог застывал при импорте, и `floor.VIS_PT = 13`
    не делал РОВНО НИЧЕГО: ни эффекта, ни отказа. А шапка этого модуля
    обещает деке ровно такую возможность («деке, которая захочет поднять
    свой пол видимого слоя»). Ручка, которая молча не работает, — тот же
    класс дефекта, что проверка, которая молча не проверяет; обещание и
    поведение сведены здесь, в одном месте, а не в шести подписях."""
    return VIS_PT if given is None else given

# Классы, которым пол НЕ применяется, и почему именно им. Список закрытый:
# каждое исключение названо вслух, иначе исключения расползаются.
#
#   (сегодня пуст)
#
# Строка источника в подвале под исключение НЕ попала, хотя соблазн был:
# это библиографическая ссылка, её читают не из зала. Но читают — и если
# она не нужна на экране, её место в заметках, а не в шестой кегле.
EXEMPT = ()


def pt(size, tag, what, *, floor=None):
    """Назвать кегль ниже пола. Возвращает `size` НЕТРОНУТЫМ.

    `what` — класс текста словами («оговорка плашки», «подпись схемы»):
    по тегу кадра одного не видно, а правит владелец именно класс."""
    floor = _floor(floor)
    if what in EXEMPT or size >= floor - 1e-9:
        return size
    report.warn(
        f"[пол] {tag}: {what} набрана {size:.1f} пт — ниже пола видимого "
        f"слоя {floor:.0f} пт, с задних рядов не читается. Кадр не сломан: "
        "это наибольший кегль, при котором текст держится в своей рамке. "
        "Поднять его можно, только срезав текст — решение владельца, не "
        "сборки")
    return size


def check_runs(runs, tag, what="тело", *, floor=None):
    """Пол по НАСТОЯЩИМ кеглям прогона — всем, какие в нём стоят.

    Зовётся ПОСЛЕ подбора масштаба, то есть видит ровно те числа, которые
    уйдут в XML. Называет САМЫЙ МЕЛКИЙ: кадр правят по нему, а список из
    четырёх кеглей одного кадра — это тот же один дефект, сказанный
    четырежды.

    Возвращает самый мелкий кегль прогона (или None на пустом) — числом,
    чтобы вызывающий мог его замерить, а не только прочесть в отчёте."""
    floor = _floor(floor)
    sizes = [float(r.get("size", 0.0)) for r in runs
             if str(r.get("text") or "").strip()]
    if not sizes:
        return None
    lo = min(sizes)
    pt(lo, tag, what, floor=floor)
    return lo


def fit_floor(hi, lo, fits, *, step=0.5, floor=None, tag="", what=""):
    """Наибольший кегль от `hi` вниз, при котором `fits(кегль)` истинно, но
    НЕ НИЖЕ пола. Дошли до пола и всё равно не влезает — `[пол]` с тем, что
    кадр перебрал, и возвращается сам пол.

    Это вторая половина договора: `pt` называет кегль, который УЖЕ выбран
    мельче пола, а эта — не даёт его выбрать и говорит, что места не
    хватило. Одно место на обе половины затем, чтобы класс текста, у
    которого подбор свой, не завёл себе третьей трактовки пола."""
    floor = _floor(floor)
    bottom = max(floor, lo)
    f = hi
    while f > bottom + 1e-9:
        if fits(f):
            return f
        f -= step
    if not fits(bottom):
        report.warn(
            f"[пол] {tag}: {what} не укладывается и на полу видимого слоя "
            f"{bottom:.0f} пт — дальше её не уменьшают, а сокращают. Что "
            "именно сократить, решает владелец")
    return bottom

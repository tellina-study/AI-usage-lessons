#!/usr/bin/env python3
"""Проверка промтов этого замера на протечку правильного ответа — issue #303.

Зачем отдельный скрипт, а не абзац в README. В этом же семинаре 2026-10-27 нашлась
протечка ровно этого класса: промт Замера K6 описывал формат поля суммы примером
`например 18990.00`, и это число было РЕАЛЬНОЙ суммой единственной квитанции, на которой
стояло измерение. Модели не надо было читать фотографию — достаточно было скопировать
число из собственной инструкции, и 30 вызовов измеряли копирование подсказки
(`../zamery-k5-k6/README.md`, «Протечка промта обнаружена и исправлена 2026-10-27»).
Абзац «я проверил» в README — это самоотчёт; проверка, которую можно перепрогнать, — нет.

Что проверяется (всё — по собранным файлам сценариев `n4-*.json`, то есть по тому самому
тексту, который уйдёт на стенд, а не по константам в памяти):

  1. Ни один текст заявки из корпуса не присутствует в промте.
  2. В промте нет ярлыков разметки корпуса (класс заявки, «возврат положен», «ожидаемый
     ответ») и нет ни одного имени приёма манипуляции из корпуса.
  3. В промте нет примера ЗАПОЛНЕННОГО решения: описание формата перечисляет три
     допустимых значения `decision`, и это не подсказка (оно не говорит, какое из трёх
     верно для конкретной заявки), но рядом с полем `reason` не должно стоять ни одного
     готового образца вроде «клиент подтверждён».
  4. Ни одно ФИО из корпуса классов C/D/E (тех, кого в базе нет) не попало в список
     клиентов внутри промта — иначе «не клиент» перестал бы быть «не клиентом».
  5. Ни одно ФИО из базы не несёт в промте пометки «в окне 30 дней» — считать 30 дней
     обязан решающий, а не входные данные.
  6. В тело HTTP-запроса к стенду уходят ровно два поля — `name` и `text`.

С флагом `--stend` те же проверки прогоняются по ВЫЛОЖЕННЫМ на стенд сценариям
(`GET /workflows/<id>`), а не по локальным файлам: выложить можно не то, что собрано, и
в этом семинаре уже приходилось отдельно подтверждать прямым чтением, что исправленный
промт действительно доехал до стенда.

Что НЕ является протечкой и почему — два случая, на которые наивная проверка ругается:

  - Имена семейств приёмов («прямая инъекция», «поддельная системная пометка») лежат
    внутри узла механической проверки. Это ярлыки её собственных шаблонов; модель их не
    видит никогда — узел кода не входит ни в один промт. На ловимость это влияет (см.
    README, «ловимость механики — верхняя граница»), но правильного ответа для конкретной
    заявки оттуда не вычитать.
  - Слова «правильный ответ» встречаются в КОММЕНТАРИИ внутри кода разбора ответа модели
    (объяснение, почему нераспознанный ответ не записывается как `otkaz`). Комментарий в
    узле кода — тоже не промт.

Поэтому обе проверки смотрят ИМЕННО на поля промтов, а не на файл сценария целиком.
"""
import json
import re
import sys
from pathlib import Path

import korpus

HERE = Path(__file__).parent
KONFIGI = ["0", "p", "r", "c", "pr", "pc", "rc", "prc"]


def promty_iz_fayla(path):
    """Вынуть из собранного сценария все литеральные тексты промтов — ровно так, как их
    прочитает n8n: поля узла «Сборка запроса»."""
    wf = json.loads(path.read_text(encoding="utf-8"))
    out = {}
    for n in wf["nodes"]:
        if n["name"] != "Сборка запроса":
            continue
        for a in n["parameters"]["assignments"]["assignments"]:
            out[a["name"]] = a["value"]
    # Плюс тела запросов — там собирается пользовательское сообщение.
    for n in wf["nodes"]:
        if n["type"] == "n8n-nodes-base.httpRequest":
            out["__body__" + n["name"]] = n["parameters"]["jsonBody"]
    return out


def promty_so_stenda(code):
    """То же, что `promty_iz_fayla`, но с живого стенда — чтобы «протечки нет» относилось
    к тому тексту, который модель реально получит, а не к собранному файлу рядом."""
    import os
    import urllib.request
    api, key = os.environ["N8N_API_URL"], os.environ["N8N_API_KEY"]
    wid = json.loads((HERE / "stend-ids.json").read_text(encoding="utf-8"))[code]
    req = urllib.request.Request(f"{api}/workflows/{wid}",
                                  headers={"X-N8N-API-KEY": key})
    wf = json.loads(urllib.request.urlopen(req, timeout=60).read().decode("utf-8"))
    out = {}
    for n in wf["nodes"]:
        if n["name"] == "Сборка запроса":
            for a in n["parameters"]["assignments"]["assignments"]:
                out[a["name"]] = a["value"]
        if n["type"] == "n8n-nodes-base.httpRequest":
            out["__body__" + n["name"]] = n["parameters"]["jsonBody"]
    return out, wid


def main():
    k = korpus.korpus()
    so_stenda = "--stend" in sys.argv
    bada = []
    peresecheniya = {}

    for code in KONFIGI:
        if so_stenda:
            promty, wid = promty_so_stenda(code)
            print(f"  читаю со стенда: {code} -> {wid}")
        else:
            promty = promty_iz_fayla(HERE / f"n4-{code}.json")
        ves = "\n".join(promty.values())
        ves_low = ves.lower()

        # 1 — текст заявки в промте
        for z in k:
            # сравниваем по первым 40 значимым символам текста: полное совпадение ловит
            # копипасту, а 40 символов ловят и пересказ куска заявки
            probe = re.sub(r"\s+", " ", z["text"])[:40].lower()
            if probe and probe in ves_low:
                bada.append(f"{code}: текст заявки {z['id']} присутствует в промте")

        # 2 — ярлыки разметки корпуса. Слова «возврат положен» / «возврат не положен»
        # сами по себе ярлыком НЕ являются: первое — формулировка правила центра (то, что
        # модель и должна знать), второе — определение значения `otkaz` в описании
        # формата. Ярлык — это привязка вердикта к КОНКРЕТНОЙ заявке или к классу.
        for marker in ("ожидаемый ответ", "правильный ответ", "vozvrat_polozhen",
                       "класс заявки", "класс a", "класс b", "класс c", "класс d",
                       "класс e", "заявок в корпусе", "корпус заявок"):
            if marker in ves_low:
                bada.append(f"{code}: ярлык разметки «{marker}» в промте")

        # 2б — НЕ отказ, а замер: насколько формулировки защит пересекаются с каталогом
        # приёмов корпуса. Это не протечка класса K6 (ответ для конкретной заявки из
        # промта не вычитывается), но это причина, по которой ловимость всех трёх защит —
        # верхняя граница, а не ожидание на новых приёмах. Число идёт в README.
        peresech = sorted({z["priem"] for z in k
                           if z["priem"] and z["priem"].lower() in ves_low})
        if peresech:
            peresecheniya[code] = peresech

        # 3 — образец заполненного решения
        for obrazets in ("клиент подтверждён", '"reason": "клиент',
                         '"decision": "vozvrat"', '"decision": "otkaz"',
                         '"decision": "menedzher"', "например vozvrat", "например otkaz"):
            if obrazets.lower() in ves_low:
                bada.append(f"{code}: образец заполненного решения «{obrazets}» в промте")

        # 4 — чужие ФИО в списке клиентов
        v_baze = {f for f, _, _, _ in korpus.BAZA}
        for z in k:
            if z["name"] in v_baze:
                continue
            if z["name"] in promty.get("sys_main", ""):
                bada.append(f"{code}: ФИО не-клиента «{z['name']}» попало в список промта")

        # 5 — пометка «в окне» рядом с ФИО
        sm = promty.get("sys_main", "")
        start = sm.find("Список клиентов")
        blok = sm[start:sm.find("\n\n", start)] if start >= 0 else ""
        if len(blok.splitlines()) != len(korpus.BAZA) + 1:
            bada.append(f"{code}: блок списка клиентов в промте прочитан неверно "
                        f"({len(blok.splitlines())} строк вместо {len(korpus.BAZA) + 1}) "
                        f"— проверка пометок ниже недостоверна")
        for pometka in ("в окне", "подходит", "не подходит", "можно вернуть",
                        "нельзя вернуть", "положен", "истёк", "свеж"):
            if pometka in blok.lower():
                bada.append(f"{code}: пометка «{pometka}» внутри списка клиентов")

        # 6 — промт классификатора не знает ни базы, ни правила 30 дней: его задача —
        # только текст. Иначе фильтр решал бы задачу вместо решающей модели.
        if "sys_klf" in promty:
            sk = promty["sys_klf"]
            for utechka in ("Абрамова", "Белозёров", "список клиентов учебного центра",
                            "30 дней"):
                if utechka.lower() in sk.lower():
                    bada.append(f"{code}: в промте фильтра есть «{utechka}»")

    # 6b — что реально уходит на стенд в теле запроса
    from run_zamer import telo_zayavki
    for z in k[:3]:
        telo = telo_zayavki(z)
        if set(telo.keys()) != {"name", "text"}:
            bada.append(f"тело запроса на стенд несёт лишние поля: {sorted(telo.keys())}")
            break

    if bada:
        print("ПРОТЕЧКА НАЙДЕНА:")
        for b in bada:
            print("  -", b)
        sys.exit(1)
    print("Протечки не найдено"
          + (" (проверено по ВЫЛОЖЕННЫМ на стенд сценариям)." if so_stenda else "."))
    print("Проверено:")
    print(f"  - 8 конфигураций × {len(k)} заявок на присутствие текста заявки в промте")
    print("  - ярлыки разметки, имена 31 приёма манипуляции")
    print("  - образцы заполненного решения рядом с описанием формата")
    print("  - ФИО не-клиентов в списке промта; пометки «в окне» внутри списка")
    print("  - промт фильтра не содержит ни базы клиентов, ни правила 30 дней")
    print("  - тело запроса на стенд несёт ровно поля name и text")
    print()
    print("ОТДЕЛЬНО (не протечка, но оговорка замера): формулировки защит пересекаются")
    print("с каталогом приёмов корпуса — ловимость защит поэтому верхняя граница.")
    vse = sorted({p for v in peresecheniya.values() for p in v})
    print(f"  пересечений по именам приёмов: {len(vse)} из "
          f"{len({z['priem'] for z in k if z['priem']})}")
    for p_ in vse:
        print("   -", p_)


if __name__ == "__main__":
    main()

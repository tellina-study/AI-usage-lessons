#!/usr/bin/env python3
"""Лестница дуги С7–С12 на экране Семинара 8 — та же геометрия, что у
Семинара 7 (`sem-07/rendered/make_figures_lestnitsa.py`), с двумя точечными
правками подписи занятий.

**Почему не просто скопирован PNG.** Семинар 7 выложил его с `SEGODNYA`-
строкой «Цепочка… — С7 · сегодня» и следующей строкой «Маршрут… — С8». На
Семинаре 8 это уже неверно по собственному своду дуги
(`sem-07/KONTSEPTSIYA-7-12.md` §6, таблица распределения, строки «С7»/«С8»/
«С9», обновлена каскадом правки Фазы 1 С8 2026-10-18): **С8 не вводит
маршрут — он остаётся на ступени «цепочка», углубляя её** («С8 не вводит
цепочку с нуля»), а ступень «маршрут» (ветвление по условию, слияние)
достаётся **С9** («следующее занятие — ветвление», SETKA-KEYSOV-S8.md,
«Закрытие»). Скопировать PNG как есть значило бы напечатать на слайде
С8 чужую, уже устаревшую карту дуги — поэтому строки 1 и 2 переписаны, а
не перерисованы с нуля: геометрия, палитра и все остальные семь строк
взяты без изменений.

Запуск: `python3 make_figures_lestnitsa.py` (из `rendered/` папки Семинара 8).
EN-прогон (issue #172/#274, первый круг EN-трека этого занятия):
`python3 make_figures_lestnitsa.py --lang en` — тот же `fig_toolkit.set_lang`/`T()`
механизм, что уже стоит в `make_figures_n02.py` (superседированном, но
задавшем образец). Словарь переводов — `fig_strings_en.py` рядом, строки
STUPENI и подпись оси. Сегодняшнее занятие переведено как «S8», соседние —
«S7»/«S9»/… (сжатая форма: русская подпись укладывается в 290 px, и
«Seminar 7 → Seminar 8 · today» туда не влезает)."""
import sys as _sys
from pathlib import Path as _Path
_sys.path.insert(0, str(_Path(__file__).resolve().parents[4] / "tools" / "seminar-build"))

from fig_toolkit import *

# Ступень → (текст, занятие). Порядок снизу вверх.
#
# Правки против версии Семинара 7 — ровно две строки, обе по таблице
# распределения KONTSEPTSIYA-7-12.md §6 (строки С7/С8/С9):
#   1. «Цепочка…» — было «С7 · сегодня», стало «С7 → С8 · сегодня»: та же
#      ступень, занятие сегодня — С8, С7 уже прошёл по ней и остаётся на ней
#      же (С8 углубляет, не покидает).
#   2. «Маршрут…» — было «С8», стало «С9»: ступень «маршрут» (ветвление по
#      условию, слияние) переехала на следующее занятие этим же пересмотром.
# Остальные семь строк не трогались — для них подтверждающей правки в своде
# дуги нет, менять их значило бы гадать, а не переносить уже принятое решение.
STUPENI = [
    ("Хватит одного вызова: ответ модели, поиск по своим документам", "до С7"),
    ("Цепочка: шаги в известном порядке, данные между ними", "С7 → С8 · сегодня"),
    ("Маршрут: путь задаёт категория входа", "С9"),
    ("Параллель: независимые проверки одного входа", "С9"),
    ("Цикл: повтор по элементам, проверка выхода", "С10"),
    ("Подпроцесс: дирижёр и несколько исполнителей", "С10"),
    ("Агент: порядок шагов выбирает сам", "С11"),
    ("Несколько агентов вместе", "С12"),
    ("Выключить: вернуться к ручному процессу", "С12"),
]
SEGODNYA = 1   # индекс сегодняшней ступени — та же «цепочка», что и у С7


def lestnitsa():
    W, H = 2400, 760
    im = Image.new("RGB", (W, H), W_ := (255, 255, 255))
    d = ImageDraw.Draw(im)
    pitch, rh, x_right = 74, 62, 2060

    def x_left(i): return 120 + i * 92
    def y_top(i):  return 650 - i * pitch

    pts = [(x_left(0) - 7, 712)]
    for i in range(9):
        pts.append((x_left(i) - 7, y_top(i) - 4))
        if i < 8:
            pts.append((x_left(i + 1) - 7, y_top(i) - 4))
    d.line(pts, fill=LIGHT, width=3, joint="curve")

    for i, (text, zan) in enumerate(STUPENI):
        x, y = x_left(i), y_top(i)
        w = x_right - x
        today = (i == SEGODNYA)
        past = (i < SEGODNYA)
        if today:
            fill, line, wd, tx = WARM, GOLD, 5, DEEP
        elif past:
            fill, line, wd, tx = SURF, LIGHT, 3, MUTE
        else:
            fill, line, wd, tx = W_, GREY_FILL, 3, GREY_TX
        d.rounded_rectangle([x, y, x + w, y + rh], radius=14, fill=fill,
                            outline=line, width=wd)
        clabel(d, x + 26 + (w - 52) / 2, y + 16, T(text), 29, tx, b=today,
               where=f"ступень {i}", limit=w - 56)
        col = GOLDINK if today else (MUTE if past else GREY_TX)
        clabel(d, x_right + 150, y + 18, T(zan), 27, col, b=today,
               where=f"занятие {i}", limit=290)

    clabel(d, 1200, 22, T("выше — сложнее процесс; каждое занятие закрывает свою ступень"),
           26, MUTE, where="подпись оси")
    save(im, "lestnitsa-dugi.png")


def main():
    if "--lang" in _sys.argv:
        set_lang(_sys.argv[_sys.argv.index("--lang") + 1])
    lestnitsa()
    report()


if __name__ == "__main__":
    main()

def blockhead(n, x, y, title, w):
    """Номер в кружке и название блока. Над подложкой, не внутри неё."""
    box(d, x, y, 40, 40, str(n), DEEP, sz=27, r=20, pad=4, where=f"+n12 номер {n}")
    fo = f(29, True)
    tline(x + 54, y + 4, title, fo, DEEP, w - 54, f"n12 название блока {n}")


def panel(x, y, w, h, fc=SURF, where="?"):
    """Подложка блока — то, чем блоки отделены друг от друга.

    В проверку наложений не заявляется («+»): на ней по построению лежит всё
    содержимое блока, и без «+» каждая коробка внутри читалась бы как
    столкновение. Сетка подложек проверена ассертами выше.
    """
    CL.claim(x, y, w, h, "+" + where)
    d.rounded_rectangle([x, y, x + w, y + h], radius=14, fill=fc)


def tline(x, y, txt, fo, col, limit, where, claim=True):
    """Строка текста, которая ЗАЯВЛЯЕТ занятое место, а не только рисуется.

    Проверка столкновений видит ТОЛЬКО коробки: `box`/`lbox`/`panel` зовут
    `CL.claim`, а `d.text` — нет. Прогон с нарочно сломанным входом (круг 4,
    сессия механики: конвейер блока 5 растянут с 72 px до 110 и наехал на
    подпись под ним) прошёл МОЛЧА — подпись нарисована голым `d.text`, места
    не занимает, наезжать на неё нечему. Все подписи и пояснения этой схемы
    теперь идут отсюда, и такой наезд проверка называет.
    """
    fit(d, txt, fo, limit, where)
    if claim:
        CL.claim(x, y, max(d.textlength(txt, font=fo), 1), fo.size, where)
    d.text((x, y), txt, font=fo, fill=col)


def keyline(x, y, key, gloss, kw=400, sz=30, where="?"):
    """Строка «ключ моноширинным — что он делает словами».
    Сквозное правило А9: рядом с каждой командой — что она делает."""
    km = f(sz, False, True)
    tline(x, y, key, km, INK, kw, f"n12 ключ {where}")
    gf = f(sz)
    d.text((x + kw + 6, y), "—", font=gf, fill=MUTE)
    tline(x + kw + 42, y, gloss, gf, MUTE, 1100 - kw - 46, f"n12 пояснение {where}")



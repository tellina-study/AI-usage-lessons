def prompt_q1_kombinatsiya():
    """Порядок: примеры → база знаний → описание (тот же порядок, что у каждого приёма
    был в своём одиночном варианте)."""
    return ("Ты — ассистент поддержки учебного центра. Ниже база знаний, которой можно "
            "пользоваться для ответа.\n\n" + Q1_FEWSHOT_PREFIX + KB_TEXT + Q1_DESC_SUFFIX +
            f"\n\nВопрос клиента: {Q1_QUESTION}" + TAIL)


def grade_q1(text):
    """Дословно grade() из run_fewshot_desc.py."""
    if not text:
        return "нет ответа"
    has_no = bool(re.search(r"\bобычн|не\s+(будет|пройдёт|через)|не\s+выше|нет\b", text, re.I))
    has_yes = bool(re.search(r"\bда\b.{0,20}руководител|через руководителя", text, re.I))
    if has_no and not has_yes:
        return "верно (обычный порядок)"
    if has_yes:
        return "НЕВЕРНО (через руководителя)"
    return "неясно — проверить вручную"



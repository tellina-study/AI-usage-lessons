#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Правка СЧЁТЧИКОВ прозы после слияния разделов 2+3 (#229).

Каждая правка здесь -- со своим числом, а не одной заменой «восемь»->«семь» по
деке: три счётчика считают ТРИ РАЗНЫЕ ВЕЩИ, и общая замена испортила бы два из
трёх. Семантика проверена чтением кадра, а не выведена из слова рядом:

  s101 «за восемь разделов»  -- стадийных разделов деки было 8, стало 7.
  s73j «занято за семь разделов» -- разделов, ПРОЙДЕННЫХ до этого кадра: он
       стоял в разделе 7, стал в разделе 6, значит шесть.
  s73j «пятый подряд»        -- разделов подряд, не прибавивших клетки: было
       3,4,5,6,7 (пять), стало 3,4,5,6 (четыре) -- бывший раздел 3 (диагноз)
       уехал ВНУТРЬ слитого раздела 2, а тот клетки прибавлял.
  s87  «остальные семь разделов» -- кроме своего: было 8-1=7, стало 7-1=6.

И ярлыки слитого раздела в накопительной сетке `s101`: «диагностика» и
«диагноз» были двумя разделами и стали одним, иначе сетка считает слитый
раздел дважды.
"""
import io

PRAVKI = [
    ('slides/s101-kletki-uznavaemye-protsedury-drugie.md', [
        ('за восемь разделов', 'за семь разделов', 5),
        ('в восемь за восемь разделов', 'в восемь за семь разделов', 0),
        ('скрининг · диагностика · диагноз', 'скрининг · исследование и диагноз', 1),
        ('скрининг · диагноз · надзор', 'скрининг · исследование и диагноз · надзор', 1),
        ('скрининг · диагноз · документы', 'скрининг · исследование и диагноз · документы', 1),
        ('диагностика · наблюдение · лекарство',
         'исследование и диагноз · наблюдение · лекарство', 1),
    ]),
    ('slides/s73j-mesto-razdela-vne-okna.md', [
        ('Занято за семь разделов', 'Занято за шесть разделов', 1),
        ('занято 4 за семь разделов', 'занято 4 за шесть разделов', 1),
        ('Занято за семь разделов', 'Занято за шесть разделов', 0),
        ('пятый подряд', 'четвёртый подряд', 1),
        ('пятый раздел подряд', 'четвёртый раздел подряд', 0),
    ]),
    ('slides/s87-vyvod-lekarstvo.md', [
        ('Остальные семь разделов', 'Остальные шесть разделов', 1),
    ]),
]


def main():
    itogo = 0
    for p, pravki in PRAVKI:
        t = io.open(p, encoding='utf-8').read()
        for staro, novo, _ in pravki:
            n = t.count(staro)
            if n:
                t = t.replace(staro, novo)
                itogo += n
                print('  %-50s %-34s -> %-34s x%d'
                      % (p.split('/')[-1].split('-')[0], staro[:34], novo[:34], n))
        io.open(p, 'w', encoding='utf-8').write(t)
    print('исправлено вхождений: %d' % itogo)
    # сторож: ни одного прежнего счётчика не осталось
    for p, _ in PRAVKI:
        t = io.open(p, encoding='utf-8').read()
        for bad in ('за восемь разделов', 'за семь разделов' if 's73j' in p else '\0',
                    'Остальные семь разделов', 'пятый подряд'):
            assert bad not in t, 'остался прежний счётчик %r в %s' % (bad, p)
    print('сторож: прежних счётчиков в этих трёх кадрах не осталось')


if __name__ == '__main__':
    main()

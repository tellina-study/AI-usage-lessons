#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Диаграмма кадра s12a — охват скрининговых программ ПО СТРАНАМ.

ПОЧЕМУ ЭТОТ ФАЙЛ ПЕРЕПИСАН (§10.1 и §11.4 `tools/presentation-build/
trebovaniya-k-soderzhaniyu-forma.md`). Прежний прогон рисовал десять строк
вида «Лёгкое · США», «Лёгкое · Великобритания», отсортированных по величине,
и собственный подзаголовок диаграммы признавался: «знаменатель у каждой
строки свой». Две беды разом. Первая: десять столбцов разных оснований
счёта, выстроенных по длине, визуально ранжируют несравнимое. Вторая, и она
хуже: на вопрос «как дела в стране X» такая диаграмма не отвечает вовсе —
строки одной страны разбросаны по всей высоте. Прожарка вернула это как
нарушение §10.1 и отдельно отметила, что обоснование отказа лежало в поле
`media_needed`, которое при приёмке никто не читает (§11.4).

ЧТО ВМЕСТО. Строка — СТРАНА; внутри строки по столбцу на каждую
программу, у которой есть измеренный охват; порядок программ одинаков у
всех стран, поэтому глаз сравнивает по цвету, а не по длине. Знаменатель
стоит подписью у конца КАЖДОГО столбца — «18,7% из 12,8 млн», «43% из 256
тыс. приглашённых», — то есть разные основания названы прямо на кадре
каждое своим, а не одной общей оговоркой под диаграммой.

ОТСУТСТВИЕ ПРОГРАММЫ НУЛЁМ НЕ РИСУЕТСЯ. Нулевой столбец читается как
измеренный ноль охвата, а «популяционной программы нет» — другое
утверждение: в США это осознанный отказ регулятора от скрининга простаты, в
Нидерландах — непостроенная программа при доказанной эффективности метода.
Оба случая названы словами в теле кадра и в заметках (`gruppy` принимает на
их месте `None` и столбца не рисует вовсе).

ОТКУДА ЧИСЛА. Сводная таблица `research/15-skrining-po-stranam.md` и те же
числа в `chapter-part1b.md`; у каждого числа в исследовательском файле стоит
ВНЕШНИЙ первоисточник, и на кадр в поле `source` идут именно они, а не наш
собственный файл (§11.5 — самоссылка на репозиторий как источник запрещена).

ЧТО СЧИТАНО ЗДЕСЬ, А НЕ ВЗЯТО ГОТОВЫМ — середина диапазона для длины
столбца там, где источник даёт два числа ОДНОГО измерения:

    Великобритания, лёгкое   32,4–36%             → 34,2
    США, колоректальный      63,5–67,4%           → 65,5
    Швеция, шейка матки      83–85%               → 84,0
    Япония, колоректальный   49,1% муж/42,8% жен  → 46,0

Подпись у конца столбца несёт исходную пару дословно, то есть зал видит
числа источника, а середина живёт только в длине столбца и на кадр как
факт не попадает ни разу.

ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Корейского колоректального охвата: источник даёт
74,4% как охват ШЕСТЬЮ видами скрининга совместно, а не колоректальным
отдельно, и выдать это за колоректальную строку значило бы подставить
чужой знаменатель. Польши и Хорватии: у них есть факт встроенного ИИ, но
знаменателя охвата источники не публикуют — обе стоят плашкой на кадре,
где измерено участие модели, а не долей на диаграмме охвата.

    python3 make_chart_s12a.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / "tools" / "presentation-build"))

import analitika as A  # noqa: E402

ASSETS = HERE / "assets"

# Страны в порядке убывания полноты: сперва те, у кого измеренных программ
# больше. Это свойство самой страны, а не наша сортировка по длине столбца.
# ПЯТЬ СТРАН, А НЕ СЕМЬ, И ЭТО ЗАМЕР, А НЕ ВКУС. Полоса кадра `analitika`
# высотой 3,00" при обязательной пропорции 4,07 даёт 216 точек, из них под
# группы остаётся около 145: заголовок берёт 45, ось — 25. Семь групп по два
# столбца — это 10 точек на столбец, и подпись в 10,5 пт на них наезжает
# (проверено прогоном, наезд виден глазом на «Великобритания» и
# «Нидерланды»). Пять групп дают 29 точек на группу и 14 на столбец —
# подписи встают чисто.
#
# ЧТО ВЫПАЛО И ПОЧЕМУ ИМЕННО ОНО: Корея (лёгкое, 51,2–58,6%) и Австралия
# (шейка матки, 74,2%) несут по ОДНОМУ столбцу каждая, и обе программы уже
# показаны на диаграмме другими странами — то есть выпадает повтор вида
# программы, а не единственное свидетельство о ней. Оба числа названы в
# заметках кадра. ЭТО ОТХОД ОТ «обзор по странам» в полном составе, и он
# вынесен владельцу вопросом (а не оставлен молча, §11.4): либо принять
# пять, либо отдать обзору второй кадр, либо поднять полосу типа.
STRANY = ["Нидерланды", "США", "Великобритания", "Швеция", "Япония"]

# Ряд = программа. `None` — у этой страны такой программы нет либо охват
# не опубликован; столбец не рисуется.
RYADY = [
    ("Лёгкое",          [None, 18.7, 34.2, None, None], A.DEEP),
    ("Шейка матки",     [54.4, None, 68.8, 84.0, None], A.MID),
    ("Колоректальный",  [67.1, 65.5, None, None, 46.0], A.LIGHT),
    ("Простата",        [None, None, None, 43.0, None], A.TEAL),
]

# Подпись у конца столбца — знаменатель этой страны по этой программе,
# дословно по источнику. Ключ — (индекс ряда, индекс страны).
# Имя программы стоит В ПОДПИСИ столбца, а не в легенде: полоса кадра
# `analitika` высотой 3,00" не держит и легенду, и семь групп так, чтобы
# подписи остались читаемыми. Подписанный столбец читается без сверки с
# легендой вовсе — это выигрыш, а не уступка месту.
PODPISI = {
    (0, 1): "Лёгкое — 18,7% из 12,8 млн",
    (0, 2): "Лёгкое — 32,4–36% приглашено из ≈7,5 млн",
    (1, 0): "Шейка матки — 54,4%",
    (1, 2): "Шейка матки — 68,8% из 16,5 млн",
    (1, 3): "Шейка матки — 83–85%",
    (2, 0): "Колоректальный — 67,1%, 1,5 млн человек",
    (2, 1): "Колоректальный — 63,5–67,4%, два замера",
    (2, 4): "Колоректальный — 49,1% муж / 42,8% жен",
    (3, 3): "Простата — 43% из 256 тыс. приглашённых",
}


def proverka_seredin():
    """Середина диапазона обязана быть настоящей серединой пары источника."""
    para = {34.2: (32.4, 36.0), 65.5: (63.5, 67.4),
            84.0: (83.0, 85.0), 46.0: (49.1, 42.8)}
    for seredina, (a, b) in para.items():
        assert abs(round((a + b) / 2, 1) - seredina) <= 0.15, (seredina, a, b)
    print("  середины: все четыре совпадают с парой чисел источника")


def proverka_podpisey():
    """У каждого НАРИСОВАННОГО столбца обязан быть свой знаменатель.

    Доля без знаменателя на кадре не принимается, а диаграмма — первое
    место, где знаменатель теряется. Проверка идёт по данным, а не по
    памяти: столбец есть — подпись обязана быть, столбца нет — подписи
    быть не должно."""
    bez = []
    lishnie = []
    for i, (_, znach, _) in enumerate(RYADY):
        for g, z in enumerate(znach):
            if z is not None and (i, g) not in PODPISI:
                bez.append((RYADY[i][0], STRANY[g]))
            if z is None and (i, g) in PODPISI:
                lishnie.append((RYADY[i][0], STRANY[g]))
    assert not bez, f"столбец без знаменателя: {bez}"
    assert not lishnie, f"подпись без столбца: {lishnie}"
    narisovano = sum(1 for _, zn, _ in RYADY for z in zn if z is not None)
    print(f"  знаменатели: {narisovano} столбцов, у всех своя подпись")


def main():
    proverka_seredin()
    proverka_podpisey()
    for _, znach, _ in RYADY:
        assert len(znach) == len(STRANY)

    spec = A.gruppy(
        "Охват скрининговых программ по странам",
        STRANY, RYADY,
        "% целевой группы, замеры 2022–2025",
        # КЕГЛЬ 10,5 ВЫБРАН ЗАМЕРОМ, А НЕ ПО УМОЛЧАНИЮ, и ниже сказано, чего
        # он стоит. Полоса `analitika` ставит
        # картинку не во всю ширину тела, а внутрь рамки кадра: замер по
        # собранному PDF — 792 × 194,4 пт против логических 880 × 216, то
        # есть масштаб 0,90. Значит 11,5 пт логических дают на кадре 10,4, а
        # прежние 10,5 давали 9,45. Двенадцати на кадре этим путём не
        # достать вовсе (нужно 13,3 логических, а при них пять групп в 216
        # точек не укладываются) — врезка полосы общая для всех кадров
        # `analitika` этой деки, и поднимать её отдельной правкой здесь я не
        # стал: это свойство типа, а не этого кадра.
        # ИСКЛЮЧЕНИЕ ИЗ ПОЛА КЕГЛЯ ОБЪЯВЛЕНО (#293, Этап D). Умолчание
        # шаблона поднято до 13 пт, и на ЭТОМ рисунке 13 не держится:
        # проверено прогоном и рендером — подписи значений наехали друг
        # на друга и на столбцы. Полосу выше 216 точек не сделать, см.
        # замер пропорции ниже. Причина объявляется шаблону и печатается
        # в прогоне, а не прячется молчаливым кеглем.
        kegl=10.5,
        kegl_nizhe_pola=("пять стран по два-три столбца в полосе 216 точек: "
                         "при 13 пт подписи значений ложатся на соседний столбец "
                         "(проверено рендером #293, Этап D)"),
        kegl_zagolovka=14, podpisi_znacheniy=PODPISI,
        legenda=False,
        # Группа занимает свою клетку ЦЕЛИКОМ: просвет между группами съедал
        # шаг между столбцами, а подписи 10,5 пт требуют не меньше 14 точек
        # шага — иначе подпись верхнего столбца ложится на нижний (замерено
        # прогоном при dolya_gruppy=0,78). Столбцы внутри страны стоят
        # вплотную, и это читается как «это одна страна».
        dolya_gruppy=1.0, dolya_stolbtsa=0.62)

    # 880×216 точек — ПРОПОРЦИЯ 4,07 ОБЯЗАТЕЛЬНА: полоса идёт во всю ширину тела (12,23" = 880 пт) и
    # берёт ровно 3,00" — столько, сколько тип кадра отдаёт полосе
    # (`build_lec07.POLOSA_H`). Выше рисовать нельзя не из-за вкуса: сборщик
    # кладёт картинку как `w = h * пропорция` при `h = min(3,00; ширина/
    # пропорция)`, поэтому картинка с меньшей пропорцией встаёт УЖЕ полной
    # ширины, а вместе с шириной ужимается и кегль подписей — при 880×330
    # (пропорция 2,67) полоса выходила 9,27" вместо 12,23", то есть подписи
    # 10,5 пт садились на кадр восемью. Проверено сборкой: та же картинка
    # давала блокирующее [высота] «полоса диаграммы и плашки съели кадр». Семь стран по два-три столбца внутри каждой
    # проверены прогоном: подписи читаются и не наезжают (замер
    # `tools/presentation-build/nalozhenie_bbox.py` по собранному PDF).
    out = A.narisovat(spec, ASSETS / "s12a-ohvat-po-stranam.png",
                      shirina_pt=880, vysota_pt=216)

    from PIL import Image
    im = Image.open(out)
    print(f"  {out.name}: {im.width}×{im.height} пикс · "
          f"пропорция {im.width / im.height:.2f} · {out.stat().st_size} Б")
    return 0


if __name__ == "__main__":
    sys.exit(main())

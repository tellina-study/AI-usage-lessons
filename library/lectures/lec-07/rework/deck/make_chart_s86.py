#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""График депозитария для кадра s86 — две линии по данным открытого архива.

РЯДЫ взяты из главы (`rework/chapter-part4e.md`, § 9.9), а не придуманы и не
подогнаны: депозиты по методам, 2020 → 2024, счёт по дате ДЕПОНИРОВАНИЯ — тот
же счёт, из которого взяты числа плашек этого кадра (2 385 → 5 787). Второй
ряд той же главы, считанный по дате ПУБЛИКАЦИИ, отличается на несколько
десятков записей и направления кривых не меняет; он здесь не рисуется, чтобы
на кадре и на графике стояли одни и те же числа.

ПРОПОРЦИЯ 2,22:1 выбрана замером, и замер пришлось повторить. Полоса плашек
этого кадра при суженном теле занимает 2,04", то есть тело начинается с
3,70". Коробка иллюстрации обязана кончиться ВЫШЕ этой черты — иначе
`build_lec07.content` оставляет тело в узкой колонке (`y >= media_bot`). При
2:1 низ коробки выходил 3,76" — промах на шесть сотых дюйма, и кадр терял
3,6 пт кегля. При 2,22:1 низ 3,56", тело возвращается на полную ширину.

КЕГЛИ заданы не в единицах фигуры, а в тех, которыми они встанут НА СЛАЙДЕ
(`fs`). Разница не косметическая: первый прогон был нарисован фигурой 7"
шириной, а на кадр она садится 4,0" — и подписи, набранные пятнадцатым
кеглем, вышли на экране 8,6 пт. Видно это только на собранном кадре.

ЧЕГО ЗДЕСЬ НЕ ДОСТИГНУТО — названо, а не обойдено. Слот даёт графику 4,0"
ширины и около 1,8" высоты. Прогон с именами рядов в 13,5 пт экранных сделан
и просмотрен: «рентгеновская кристаллография» на такой ширине длиннее самого
поля графика и вылезает за край. Требование «подписи осей не мельче 14 пт» в
слоте этого размера физически невыполнимо, и выбор идёт не между «крупно» и
«мельче», а между «мельче» и «нет графика». Взято: деления 11 пт, имена рядов
11 пт в одну строку, значения на концах 10 пт. Держится это на одном: ОБА
имени и ОБА числа стоят на том же кадре в плашках рядом, набранные полным
кеглем, — график показывает ФОРМУ (плато и рост), а имена и величины зал
читает слева.

НАЧЕРТАНИЕ — DejaVu Sans: Liberation/Arial этому matplotlib на машине
недоступен. Это не начертание деки (Arial/Liberation Sans), и буквы на
графике и на кадре рядом слегка разные.

    python3 make_chart_s86.py
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
OUT = HERE / "assets" / "s86-grafik-depozitariya-2020-2024.png"

DEEP, MID, LIGHT, TEAL = "#21295C", "#065A82", "#1C7293", "#028090"
OUTLINE = "#D9E2EC"

GODY = [2020, 2021, 2022, 2023, 2024]
RENTGEN = [11189, 9236, 9818, 9582, 9193]     # рентгеновская кристаллография
KRIO = [2385, 2951, 4104, 4575, 5787]         # криоэлектронная микроскопия

FIG_W = 4.4           # ширина фигуры, дюймы
SLIDE_W_IN = 4.00     # во сколько дюймов она садится на кадре (замер)
AR = 2.224


def fs(na_slayde):
    """Кегль фигуры, который на кадре станет заданным."""
    return na_slayde * FIG_W / SLIDE_W_IN


plt.rcParams["font.family"] = "DejaVu Sans"

fig, ax = plt.subplots(figsize=(FIG_W, FIG_W / AR), dpi=320)
fig.patch.set_facecolor("white")
ax.set_facecolor("white")

ax.plot(GODY, RENTGEN, color=MID, lw=2.2, marker="o", ms=4.5, zorder=3)
ax.plot(GODY, KRIO, color=TEAL, lw=2.2, marker="o", ms=4.5, zorder=3)

# Имена рядов стоят У САМИХ ЛИНИЙ, а не в рамке легенды: легенда заставила бы
# зал сличать цвета и съела бы то же место. Верхнее имя идёт НАД своей линией,
# нижнее — в просвете между линиями: это два единственных места на поле, где
# строка в одну высоту ни на что не наезжает (проверено на готовом PNG).
ax.text(2022, 12850, "рентгеновская кристаллография", color=MID,
        fontsize=fs(11.0), fontweight="bold", ha="center", va="center")
ax.text(2022, 7250, "криоэлектронная микроскопия", color=TEAL,
        fontsize=fs(11.0), fontweight="bold", ha="center", va="center")

# Значения подписаны только у НИЖНЕГО ряда, и это не упущение: у верхнего
# подпись конца пришлась бы ровно на имя ряда, а само плато читается по
# делениям 9 000 и 12 000 — плашка кадра рядом называет его словами
# («плато 9–10 тысяч депозитов в год»). Прогон с четырьмя подписями сделан и
# просмотрен: «11 189» легло поверх имени верхнего ряда, «9 193» — поверх
# имени нижнего.
ax.annotate("2 385", (2020, 2385), xytext=(10, -17), textcoords="offset points",
            color=TEAL, fontsize=fs(10.0), ha="left")
ax.annotate("5 787", (2024, 5787), xytext=(-2, -18), textcoords="offset points",
            color=TEAL, fontsize=fs(10.0), ha="right")

ax.set_ylim(0, 14000)
ax.set_xlim(2019.55, 2024.45)
ax.set_xticks(GODY)
ax.set_yticks([0, 3000, 6000, 9000, 12000])
ax.set_yticklabels(["0", "3 000", "6 000", "9 000", "12 000"])
ax.tick_params(axis="both", labelsize=fs(11.0), colors=DEEP, length=0, pad=4)

ax.grid(axis="y", color=OUTLINE, lw=0.9)
ax.set_axisbelow(True)
for side in ("top", "right", "left"):
    ax.spines[side].set_visible(False)
ax.spines["bottom"].set_color(OUTLINE)
ax.spines["bottom"].set_linewidth(1.0)

fig.tight_layout(pad=0.3)
OUT.parent.mkdir(parents=True, exist_ok=True)
fig.savefig(OUT, facecolor="white")
print(f"{OUT.name}: записан, {fig.get_size_inches()}")

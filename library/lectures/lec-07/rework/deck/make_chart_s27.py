#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Диаграмма кадра `s27` — обзор инструментальной диагностики по странам.

РЕШЕНИЕ ВЛАДЕЛЬЦА (2026-10-19, вариант 1 из четырёх предъявленных): три панели
в одном PNG, у каждой своя ось и подписанная единица. Отменяет прежний отказ
строить диаграмму, записанный в поле `media_needed` кадра — отказ, который
`trebovaniya-k-soderzhaniyu-forma.md` §11.4 прямо называет тем, чего сессия
делать не вправе: «отказ от прямого указания владельца — не решение
сессии-исполнителя».

ЧЕМ ОТКАЗ БЫЛ ВЕРЕН И ЧЕМ НЕВЕРЕН. Верен по существу: единицы у трёх стран
разные (миллионы исследований · доля развёрнутого от профинансированного ·
кумулятивная доля одобрений за три десятилетия), и в один ряд на одной оси
они не складываются — это ровно та склейка выборок, которую лекция разбирает.
Неверен по выводу: «одна диаграмма — одна единица» есть ограничение примитива
`stolbtsy`, а не кадра. Рендерер `analitika` берёт в `media` любой готовый PNG
во всю ширину полосы, и три панели рядом — три разные оси с тремя подписанными
единицами, ни одно число не стоит на чужой шкале.

ЕДИНИЦА ПОДПИСАНА У КАЖДОЙ ПАНЕЛИ ВТОРОЙ СТРОКОЙ ЗАГОЛОВКА, а знаменатель —
второй строкой под каждым столбцом. Это то же правило, что уже стоит в
`make_charts_244.py`: диаграмма — первое место, где знаменатель теряется.

ЧИСЛА — из главы (`chapter-part1c.md` § «Диагностическая визуализация и
лабораторная диагностика по странам»), и ни одно здесь не выведено арифметикой
из другого, кроме одного, названного ниже.

ЧТО ПОСЧИТАНО ЗДЕСЬ: разбивка 1 430 кумулятивных авторизаций на радиологию и
остальное. Глава даёт долю (76,5 процента) и итог (1 430); столбцам нужны
абсолютные, поэтому 1 430 × 0,765 = 1 094 и остаток 336. Деление названо на
самой панели подписью «76,5% от 1 430», чтобы проценту не пришлось верить на
слово. Обратная проверка стоит прогоном.

ЧЕГО НА ДИАГРАММЕ НЕТ И ПОЧЕМУ. Российская панель не даёт доли охвата:
знаменателя «всего лучевых исследований в год» нет ни в одном источнике
(пробел назван в главе прямо). Поэтому панель показывает абсолютный поток по
двум контурам и двум срезам — и срезы подписаны, потому что год и квартал в
один столбец не складываются.

    python3 make_chart_s27.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / "tools" / "presentation-build"))

import analitika as A  # noqa: E402

ASSETS = HERE / "assets"
VREMENNO = Path("/tmp/chart-s27")

# ── панель 1: Россия, абсолютный поток по двум контурам ──────────────────
ROSSIYA = [
    ("Город", 4.0, "2024 год"),
    ("Федерация", 0.9, "2024 год"),
    ("Город", 2.0, "I квартал 2026"),
    ("Федерация", 3.2, "I квартал 2026"),
]

# ── панель 2: Британия, разрыв «профинансировано / работает» ─────────────
# Подписи короткие НЕ для красоты: при длинных («Профинансировано», «свыше 40 —
# это 63–67%») колонка имён съедала поле панели, и QuickChart обрезал их слева —
# на первом прогоне вышло «финансировано» и «·0 — это 63–67%». Поймано просмотром
# PNG, прогоном не ловится. Доля вынесена в заголовок панели, где ей и место.
BRITANIYA = [
    ("Оплачено", 66, "трастов фонда"),
    ("Работает", 40, "свыше 40"),
]

# ── панель 3: США, кумулятивные авторизации ──────────────────────────────
VSEGO_SSHA = 1430
DOLYA_RADIO = 0.765
RADIO = round(VSEGO_SSHA * DOLYA_RADIO)
PROCHEE = VSEGO_SSHA - RADIO
SSHA = [
    ("Радиология", RADIO, "76,5% от 1 430"),
    ("Все прочие", PROCHEE, "остаток"),
]


def main():
    # Обратная проверка деления: доля, пересчитанная из столбцов, обязана
    # вернуться к той, что стоит в главе. Назначить её числом и не проверить —
    # ровно тот способ, которым число на слайде уезжает от числа в главе.
    assert RADIO + PROCHEE == VSEGO_SSHA, (RADIO, PROCHEE)
    assert abs(RADIO / VSEGO_SSHA - DOLYA_RADIO) < 0.001, RADIO / VSEGO_SSHA

    VREMENNO.mkdir(parents=True, exist_ok=True)
    SHIR, VYS = 165, 200          # точки слайда на панель

    p1 = A.narisovat(
        A.stolbtsy("Россия: поток через модель", ROSSIYA,
                   "млн исследований · город и федерация порознь",
                   gorizontal=True, kegl=10, kegl_zagolovka=11, drobnaya=True,
                   zoloto=0),
        VREMENNO / "p1.png", shirina_pt=SHIR + 60, vysota_pt=VYS)
    p2 = A.narisovat(
        A.stolbtsy("Британия: оплачено и работает", BRITANIYA,
                   "трастов службы здравоохранения · работает 63–67%",
                   gorizontal=True, kegl=10, kegl_zagolovka=11, zoloto=1),
        VREMENNO / "p2.png", shirina_pt=SHIR + 60, vysota_pt=VYS)
    p3 = A.narisovat(
        A.stolbtsy("США: где сосредоточены допуски", SSHA,
                   "кумулятивных авторизаций, 1995–2025",
                   gorizontal=True, kegl=10, kegl_zagolovka=11, zoloto=0),
        VREMENNO / "p3.png", shirina_pt=SHIR + 45, vysota_pt=VYS)

    para = A.ryadom(p1, p2, VREMENNO / "p12.png", zazor_pt=8)
    out = A.ryadom(para, p3, ASSETS / "s27-tri-paneli-po-stranam.png",
                   zazor_pt=8)
    from PIL import Image
    im = Image.open(out)
    print(f"готово: {out}  {im.width}×{im.height} px, "
          f"соотношение {im.width / im.height:.2f}")
    print(f"США: радиология {RADIO} + прочие {PROCHEE} = {VSEGO_SSHA}, "
          f"доля {RADIO / VSEGO_SSHA:.3f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

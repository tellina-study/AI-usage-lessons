#!/usr/bin/env python3
"""Генератор `refund-requests-extra.json` — ДОПОЛНИТЕЛЬНЫЕ 50 запросов Кейса 3, сложнее
исходных 50 (`_gen_refund_requests.py`). Три группы, по мотивам голосовой правки владельца
2026-10-20 (issue #274): «3 ошибки на N запросов» звучит недостаточно представительно, нужны
более сложные формулировки — неоднозначные, с двумя числами в тексте, значения очень близкие
к порогу.

Детерминированный seed (82) — набор воспроизводим, не меняется при перегенерации. Не прогон,
только подготовка данных (как и `_gen_refund_requests.py`) — прогон делает `run_refund_extra.py`
через живой стенд.

Группы:
  A. tight_border   (15) — суммы в пределах ±20₽ от порога 3000, плотнее исходного кластера.
  B. two_numbers    (20) — в тексте ДВА числа: сумма-отвлечение (напр. цена занятия/курса) и
                           целевая сумма возврата; корректный ответ — по целевой сумме, не по
                           первой встреченной.
  C. ambiguous      (15) — непрямая формулировка: «около/примерно», либо сумма не названа
                           числом напрямую, а выводится арифметикой («два занятия по 1500»).

Каждая строка несёт `target_amount_rub` (число, с которого считается `expected_by_rule_B`) и
`group`, чтобы в протоколе легко увидеть, на какой группе каждая схема спотыкается.
"""
import json
import random
from pathlib import Path

HERE = Path(__file__).parent
random.seed(82)
THRESHOLD = 3000

rows = []
i = 1

# --- A. tight_border: плотный кластер вокруг порога, шире по обе стороны, чем исходные 50 ---
tight_amounts = [2980, 2985, 2990, 2992, 2995, 2997, 2998, 2999,
                 3001, 3002, 3003, 3005, 3008, 3012, 3020]
tight_templates = [
    "прошу вернуть {a} рублей, занятие отменили в последний момент",
    "верните, пожалуйста, {a} руб. — я оплатил, но не смог присутствовать",
    "хочу возврат {a} рублей за абонемент, использовал только одно занятие",
    "сделайте возврат на {a} рублей, курс не подошёл по расписанию",
]
for a in tight_amounts:
    t = random.choice(tight_templates)
    rows.append({
        "id": i, "group": "tight_border", "target_amount_rub": a,
        "text": t.format(a=a),
        "expected_by_rule_B": "одобрить" if a <= THRESHOLD else "эскалировать",
        "note": "граница ±20₽ от порога — плотнее исходного кластера",
    })
    i += 1

# --- B. two_numbers: decoy + целевая сумма в одном тексте ---
two_number_templates_target_first = [
    "занятие стоило {decoy} рублей, но прошу вернуть только {target} — за пропущенную часть",
    "курс обошёлся в {decoy} руб., хочу возврат {target} рублей за один блок",
    "оплата была {decoy} рублей, однако прошу вернуть {target}, остальное оставляю за уже пройденные уроки",
]
two_number_templates_target_second = [
    "у меня было два платежа: {decoy} рублей в прошлом месяце и сейчас — прошу вернуть {target} рублей",
    "предыдущий возврат был на {decoy} рублей, а по этой заявке прошу вернуть {target} рублей",
    "абонемент на {decoy} рублей не трогаю, а вот за отдельное занятие прошу вернуть {target} рублей",
]
two_number_pairs = [
    (12000, 2400), (8000, 3100), (15000, 2950), (6000, 3050), (9000, 2700),
    (20000, 3300), (5000, 2990), (10000, 3400), (7000, 2850), (18000, 3600),
    (4000, 3700), (25000, 2600), (6500, 3150), (13000, 2999), (30000, 4200),
    (9500, 3001), (11000, 2750), (16000, 3900), (8500, 2900), (22000, 5000),
]
for idx, (decoy, target) in enumerate(two_number_pairs):
    first = idx % 2 == 0
    t = random.choice(two_number_templates_target_first if first else two_number_templates_target_second)
    rows.append({
        "id": i, "group": "two_numbers", "target_amount_rub": target,
        "decoy_amount_rub": decoy,
        "text": t.format(decoy=decoy, target=target),
        "expected_by_rule_B": "одобрить" if target <= THRESHOLD else "эскалировать",
        "note": "два числа в тексте — decoy {}, целевая {}".format(decoy, target),
    })
    i += 1

# --- C. ambiguous: непрямая формулировка, сумма не всегда прямым числом ---
ambiguous_rows = [
    ("хочу вернуть примерно 2900 рублей, может чуть больше за комиссию", 2900),
    ("прошу возврат около 3000 — точную сумму скажет бухгалтерия, но ориентируюсь на эту цифру", 3000),
    ("занятие стоило 1500 рублей, прошу вернуть за два таких занятия", 3000),
    ("курс состоял из трёх блоков по 1100 рублей, пропустил два — прошу возврат", 2200),
    ("прошу вернуть сумму одного занятия из абонемента на пять занятий по 700 рублей", 700),
    ("хочу возврат половины от оплаченных 6000 рублей за курс", 3000),
    ("вернуть, пожалуйста, всё за минус один использованный визит по тысяче рублей, оплатил четыре по 1000", 3000),
    ("прошу эскалировать сразу — сумма большая, где-то в районе 7-8 тысяч", 7500),
    ("возврат за неиспользованные две трети абонемента, абонемент был на 4500 рублей", 3000),
    ("оплатил 3 занятия по 999 рублей, прошу вернуть за все", 2997),
    ("хочу вернуть сумму чуть выше трёх тысяч, не помню точно, около 3050", 3050),
    ("прошу возврат ровно половины от 5900 рублей", 2950),
    ("занятие отменили, стоимость была тысяча рублей, умножить на три пропущенных", 3000),
    ("верните деньги за месяц занятий — это четыре встречи по 800 рублей каждая", 3200),
    ("прошу вернуть сумму чуть ниже трёх тысяч, примерно 2960-2970", 2965),
]
for text, target in ambiguous_rows:
    rows.append({
        "id": i, "group": "ambiguous", "target_amount_rub": target,
        "text": text,
        "expected_by_rule_B": "одобрить" if target <= THRESHOLD else "эскалировать",
        "note": "непрямая формулировка — сумма не дана одним явным числом",
    })
    i += 1

out = {
    "status": "ПОДГОТОВЛЕНО, НЕ ПРОГНАНО — прогон см. run_refund_extra.py / refund-extra-results.json",
    "threshold_rub": THRESHOLD,
    "count": len(rows),
    "groups": {"tight_border": 15, "two_numbers": 20, "ambiguous": 15},
    "requests": rows,
}
(HERE / "refund-requests-extra.json").write_text(
    json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print("написано", len(rows), "строк")

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Слияние разделов 2 и 3 и ПЕРЕНУМЕРАЦИЯ остальных (#229, указание А владельца).

ПОЧЕМУ ПЕРЕНУМЕРАЦИЯ ОБЯЗАТЕЛЬНА, а не «оставим как есть». Разделы подписаны
«N. Название» на дивайдерах и в поле `section`. Слияние 2+3 в один оставляет
последовательность 1, 2, 4, 5, 6, 7, 8, 9, 10 -- пропуск читается залом как
раздел, который обещали и не показали. Поэтому 4-10 съезжают на 3-9.

ЧЕГО ЭТО СЛИЯНИЕ НЕ ДЕЛАЕТ -- и это важнее самой правки. Оно НЕ сливает две
СТАДИИ ЦИКЛА. Цикл оказания помощи -- предмет лекции, в нём девять стадий, и
инструментальная диагностика с постановкой диагноза остаются двумя разными
стадиями: так они и названы на карте цикла `s01a`, и её «девять стадий»
править НЕЛЬЗЯ. Слит РАЗДЕЛ ДЕКИ -- наше изложение, -- и слитый раздел
покрывает две стадии. Правка карты цикла под номера разделов была бы
утверждением о медицине, выведенным из нашей вёрстки.

    python3 pereimenovat_razdely.py --proba   # показать, не записывая
    python3 pereimenovat_razdely.py
"""
import glob
import re
import sys

NOVOE = '2. Исследование и постановка диагноза'
KARTA = [
    ('2. Инструментальная и лабораторная диагностика', NOVOE),
    ('3. Постановка диагноза', NOVOE),
    ('4. Динамическое наблюдение и клинические тревоги',
     '3. Динамическое наблюдение и клинические тревоги'),
    ('5. Ведение медицинской документации', '4. Ведение медицинской документации'),
    ('6. Допуск, надзор и ответственность', '5. Допуск, надзор и ответственность'),
    ('7. Профессиональная квалификация: поддержание и износ',
     '6. Профессиональная квалификация: поддержание и износ'),
    ('8. Разработка лекарственных средств', '7. Разработка лекарственных средств'),
    ('9. Сборка', '8. Сборка'),
    ('10. Закрытие', '9. Закрытие'),
]


def main():
    proba = '--proba' in sys.argv
    # порядок замен: сначала БОЛЬШИЕ номера, иначе «4.» -> «3.» затем «3.» -> NOVOE
    # перепишет уже переписанное. Самая частая ошибка такой правки.
    poryadok = sorted(KARTA, key=lambda kv: -int(kv[0].split('.')[0]))
    vsego = 0
    for p in sorted(glob.glob('slides/s*.md')):
        t = open(p, encoding='utf-8').read()
        orig = t
        for staro, novo in poryadok:
            # поле section
            t = re.sub(r'^(section:\s*)"%s"$' % re.escape(staro),
                       r'\1"%s"' % novo, t, flags=re.M)
            # заголовок дивайдера и его первая строка тела
            t = re.sub(r'^(title:\s*)"%s"$' % re.escape(staro),
                       r'\1"%s"' % novo, t, flags=re.M)
            t = re.sub(r'^# %s$' % re.escape(staro), '# %s' % novo, t, flags=re.M)
        if t != orig:
            vsego += 1
            if proba:
                for staro, novo in poryadok:
                    if staro in orig and staro not in t:
                        print('  %-54s %s -> %s' % (p.split("/")[-1][:54], staro, novo))
            else:
                open(p, 'w', encoding='utf-8').write(t)
    print('%s файлов: %d' % ('затронуто (проба)' if proba else 'переписано', vsego))


if __name__ == '__main__':
    main()

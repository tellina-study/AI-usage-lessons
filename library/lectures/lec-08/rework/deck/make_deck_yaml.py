        W("\n")
        W("totals:\n")
        W("  slides: %d\n" % tot_slides)
        W("  timing_min: %.2f               # сложено по файлам кадров; курс пока не зафиксировал плановый слот-бюджет для Лекции 8 (нет аналога CUT-ORDER.md Лекции 7) -- счёт честный по арифметике, без подгонки под ожидаемое число\n" % tot_min)

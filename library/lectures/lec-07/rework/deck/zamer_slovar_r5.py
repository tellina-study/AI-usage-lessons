#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Замер производственного словаря и разговорных оборотов по видимому слою
кадров Входа и разделов 1-5 (issue #229).

Видимый слой берётся импортом из scan_deck_visible.visible_lines — один источник
извлечения, а не вторая копия. Шаблоны — Python re, якорь с двух сторон:
grep -P на кириллице даёт ложный ноль (notes/mcp-limitations.md [#229-12]).
Печатается КОНТЕКСТ каждого попадания, а не счёт.

    python3 zamer_slovar_r5.py            # сводка по словам
    python3 zamer_slovar_r5.py --context  # с контекстом каждого попадания
"""
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from vidimyy_sloy_polnyy import polnyy as visible_lines, kadry_polosy  # noqa: E402

MOI = ("0. Вход", "1. Первичный скрининг", "2. Инструментальная",
       "3. Постановка диагноза", "4. Динамическое наблюдение",
       "5. Ведение медицинской документации")

# Клинические употребления «разбора» — термины предмета, а не наш жаргон.
# Развод обязателен: на полосе Входа и разделов 1-5 из 24 вхождений нашими
# были 14, предметными 10, и счёт их не отличает. Куплено разбором каждого
# совпадения глазами; шаблон ниже — его запись, а не догадка.
KADR_SNIMKA = re.compile(r"(?:качеств\w*|годност\w*|поток\w*)\s+кадр"
                         r"|кадр\w*\s+(?:видео|потока)", re.I)

PREDMETNYY = re.compile(
    r"разбор\w*\s+(карты|случая|расхожд|тревог|потока\s+тревог|ложных)"
    r"|(?:назначенн|шаг)\w*\s+разбор"
    r"|разбор\w*\s+и\s+отклонение"
    r"|разбира(ет|ют|л|ть)\b"
    # «при разборе оценивают действия человека» — разбор случая после исхода,
    # тот же клинический термин без своего дополнения рядом.
    r"|при\s+разборе\s+оценива",
    re.I)

SLOVAR = {
    "разбор (наш)": re.compile(r"(?<![а-яё])разбор\w*(?![а-яё])", re.I),
    "кадр (=слайд)": re.compile(
        r"(?<![а-яё])(?:кадр|кадра|кадре|кадром|кадров|кадрами|кадрах)"
        # «поток кадров», «качество кадра» — кадр съёмки, предмет, не слайд.
        r"(?![а-яё])(?!\s+(?:видео|потока))", re.I),
    # Отрицательный просмотр назад не выражается в `re` одним шаблоном, поэтому
    # кадр-снимок снимается тем же механизмом, что предметный «разбор».
    "ступень":     re.compile(r"(?<![а-яё])ступен\w*(?![а-яё])", re.I),
    "прочерк":     re.compile(r"(?<![а-яё])прочерк\w*(?![а-яё])", re.I),
    "свод":        re.compile(r"(?<![а-яё])свод(?![а-яё])|(?<![а-яё])свод[аыуе](?![а-яё])", re.I),
    "адрес оси":   re.compile(r"адрес\w*\s+ос[ие]|иллюстрац\w*\s+ос[ии]", re.I),
    "упоминание":  re.compile(r"(?<![а-яё])упоминан\w*(?![а-яё])", re.I),
    "замера нет":  re.compile(r"замера\s+нет", re.I),
    "вечер":       re.compile(r"(?<![а-яё])вечер(?![а-яё])|(?<![а-яё])вечер[ауом](?![а-яё])", re.I),
}

# СЖАТАЯ форма сопоставления — «X, не Y», без союза «а». Канонический греп её
# не ловит (он требует «а»), и это не придирка: на полосе Входа и разделов 1-5
# её 12 вхождений, на разделах 6-10 — 15.
#
# ИСКЛЮЧЕНИЕ, и оно не послабление. На подписях плашек и единиц эта фигура
# ПРЕДПИСАНА решением О19 и курсовым слоем редактуры: формула «назвать верную
# единицу и отвести неверную» («единица: выписки, а не 1 274 выданные сводки»)
# и есть она. Три таких подписи поставлены в этом же круге по прямому заказу.
# Без исключения прогон зовёт чинить то, что сам же круг и заказал, — а это
# ровно `CLAUDE.md` §8.3: сторож требует отменённого.
#
# Критерий для ОСТАЛЬНЫХ вхождений решается глазами, не шаблоном: второй член
# сообщает проверяемое различение («названо, не измерено», «решающие деревья,
# не нейросеть») или только нажимает («дешёвый ход, не разгильдяйство»)?
# Первые остаются и являются сильнейшим приёмом деки, вторые переписываются.
# Замерено: из 12 на этой полосе нажимающих ноль, одно ложное (деепричастие
# «закрываете, не читая» — шаблон поймал запятую).
SZHATAYA = re.compile(r"[а-яё]{3,},\s+не\s+[а-яё]{3,}", re.I)
GDE_PREDPISANA = ("плашка", "схема/unit", "схема/base", "число кадра")

RAZGOVOR = {
    "не X, а Y":        re.compile(r"(?<![а-яё])не\s+[^,.;:!?]{1,60},\s*а\s+(?![а-яё]*\s*(ли|бы)\b)", re.I),
    "хвостовое «, а не»": re.compile(r",\s*а\s+не(?![а-яё])", re.I),
    "дело не в":        re.compile(r"дело\s+не\s+в\b", re.I),
    "с одной стороны":  re.compile(r"с\s+одной\s+стороны|с\s+другой\s+стороны", re.I),
    "в общем":          re.compile(r"(?<![а-яё])в\s+общем(?![а-яё])", re.I),
    "как бы":           re.compile(r"(?<![а-яё])как\s+бы(?![а-яё])", re.I),
    "штука в том":      re.compile(r"штука\s+(в\s+том|тут)", re.I),
    "по сути":          re.compile(r"(?<![а-яё])по\s+сути(?![а-яё])", re.I),
    "грубо говоря":     re.compile(r"грубо\s+говоря|проще\s+говоря|попросту\s+говоря", re.I),
    "на самом деле":    re.compile(r"на\s+самом\s+деле", re.I),
    "вот":              re.compile(r"(?<![а-яё])вот(?![а-яё])", re.I),
    "мол/дескать":      re.compile(r"(?<![а-яё])(мол|дескать|типа|вроде\s+как)(?![а-яё])", re.I),
    "ровно то же":      re.compile(r"(?<![а-яё])ровно\s+(то|так|тот|та)(?![а-яё])", re.I),
    "стоит сказать":    re.compile(r"стоит\s+(сказать|назвать|заметить|отметить)", re.I),
}


def sek(path):
    raw = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n?", raw, re.S)
    if not m:
        return ""
    return str((yaml.safe_load(m.group(1)) or {}).get("section", ""))


def proyti(nabor, zagolovok, context):
    moi = kadry_polosy(MOI)
    itogo = {}
    snyato = []
    for name, rx in nabor.items():
        hits = []
        for f in moi:
            for where, text in visible_lines(f):
                for m in rx.finditer(text):
                    rec = (f.stem.split("-")[0], where, m.group(0), text)
                    # Предметное употребление снимается ПОПАДАНИЕМ, не строкой:
                    # на одном кадре рядом стоят и термин, и протечка.
                    straz = {"разбор (наш)": PREDMETNYY,
                             "кадр (=слайд)": KADR_SNIMKA}.get(name)
                    if straz is not None and any(
                            x.start() <= m.end() and m.start() <= x.end()
                            for x in straz.finditer(text)):
                        snyato.append((name, rec[0], m.group(0)))
                        continue
                    hits.append(rec)
        itogo[name] = hits
    print(f"── {zagolovok} · кадров в полосе: {len(moi)} ──")
    for name, hits in itogo.items():
        kadry = sorted({h[0] for h in hits})
        print(f"{name:<18} всего {len(hits):>3}  кадров {len(kadry):>2}  {' '.join(kadry)}")
        if context:
            for sid, where, got, text in hits:
                print(f"    {sid:<8} [{where}] …{text[:150]}")
    if nabor is RAZGOVOR:
        szh, osv = [], []
        for f in moi:
            for where, text in visible_lines(f):
                for m in SZHATAYA.finditer(text):
                    (osv if where.startswith(GDE_PREDPISANA) else szh).append(
                        (f.stem.split("-")[0], m.group(0)))
        print(f"\nсжатая «X, не Y» (греп канона её НЕ ловит): {len(szh)} "
              f"в повествовании + {len(osv)} на подписях")
        print("  на подписях форма ПРЕДПИСАНА решением О19 — не чинить: "
              + (", ".join(f"{s} «{g}»" for s, g in osv) or "нет"))
        print("  в повествовании — решать глазами, не шаблоном "
              "(различает или только нажимает):")
        for s, g in szh:
            print(f"    {s:<8} «{g}»")
    if snyato:
        print(f"\nснято как термин предмета: {len(snyato)} — "
              + ", ".join(f"{s} «{g}»" for _n, s, g in snyato))
    print("ЧЕГО ЭТОТ ПРОГОН НЕ ЗНАЕТ: он читает только видимый слой. "
          "Жаргон в заметках\nлектора (речь залу!) им не ловится — "
          "для них считайте отдельно.")
    return itogo


if __name__ == "__main__":
    c = "--context" in sys.argv
    proyti(SLOVAR, "ПРОИЗВОДСТВЕННЫЙ СЛОВАРЬ", c)
    print()
    proyti(RAZGOVOR, "РАЗГОВОРНЫЕ ОБОРОТЫ", c)

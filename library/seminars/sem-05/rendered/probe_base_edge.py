def build(name, md):
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(K.W_IN), Inches(K.H_IN)
    sl = prs.slides.add_slide(prs.slide_layouts[6])
    title, assertion, visual, _notes = SP.sections(md)
    # s08 — первый Такт Б по раскадровке, он и даёт раздел в надзаголовке («Хук»)
    B.g_base_edge(sl, "s08", title or TITLE, SP.blocks(visual), "base_and_edge", assertion)
    out = HERE / "preview" / f"probe-{name}.pptx"
    out.parent.mkdir(exist_ok=True)
    prs.save(out)
    return out


def main():
    which = sys.argv[1:] or list(PROBES)
    M.reset()
    for name in which:
        pptx = build(name, PROBES[name])
        for p in Q.render(pptx, ["s08"], order=["s08"]):
            print("•", p)
        (HERE / "preview" / "s08.png").replace(HERE / "preview" / f"probe-{name}.png")
        print(f"проба «{name}» → preview/probe-{name}.png")
    for w in M.report():
        print("⚠", w)


if __name__ == "__main__":
    main()

# -*- coding: utf-8 -*-
"""Промах поля: отступы, которые не сетка и не замысел.

Заведено после находки владельца по кругу R3 (2026-11-02): «визуальные
вертикали границ не бьются на слайде». Три первых показателя её НЕ поймали
(запись Т-36 в журнале трения):

  1. число различных левых/правых краёв на кадре — у эталона те же 9/10,
     что и у пробы; не разделяет;
  2. дрожь (пары краёв, разведённые на 0,5-9 пт) — у пробы МЕНЬШЕ, чем у
     эталона и у лекций курса; не разделяет;
  3. разброс полей по горизонтальным полосам кадра — ловит беглецов, но
     мешает их с намеренным выносом за поле.

Ловит четвёртый: доля фигур, чей левый край отстоит от поля колоды на
1-20 пт. Ноль — фигура на сетке; больше двадцати — осознанный отступ или
вынос; между — промах, и глаз видит именно его.

Замер 2026-11-02 (пт, поле MX = 39,6):

    lec-06       4,7%   8 значений   медиана 1,0 на кадр
    эталон-5    17,6%   6 значений   медиана 3,0
    lec-07      20,3%  10 значений   медиана 3,0
    проба R1    27,5%   6 значений   медиана 2,5
    проба R2    27,8%  10 значений   медиана 2,0
    проба R3    24,8%  13 значений   медиана 3,5

lec-06 показывает, что 5% достижимы на том же ядре, — значит это дефект
вёрстки, а не предел инструмента.

Запуск:  python3 polya.py <файл.pptx> [ещё.pptx ...]
"""
import sys, statistics
from collections import Counter
from pptx import Presentation
MX = 39.6
LO, HI = 1.0, 20.0
for path in sys.argv[1:]:
    prs = Presentation(path); W = prs.slide_width/12700.0
    melkie = Counter(); vsego = 0; po_kadram = []
    for s in prs.slides:
        nk = set()
        for sh in s.shapes:
            if None in (sh.left, sh.width): continue
            l = sh.left/12700.0; w = sh.width/12700.0
            if w < 6 or w >= W - 1: continue
            vsego += 1
            # ОБА края, не только левый: блок, стоящий ровно по левому полю и
            # выступающий вправо, по одному левому краю неотличим от ровного
            # (находка владельца 02.11 на кадре 2: блок 29,5-930,5 против
            # 39,6-920,4 у соседей — вылезал на 10,1 пт в КАЖДУЮ сторону).
            for d in (l - MX, (W - MX) - (l + w)):
                if LO <= abs(d) <= HI:
                    melkie[round(d)] += 1; nk.add(round(d))
        po_kadram.append(len(nk))
    n = sum(melkie.values())
    print(f"{path.split('/')[-1]:26s} мелких промахов поля: {n:4d}/{vsego} = {n/max(vsego,1)*100:5.1f}% · "
          f"разных значений {len(melkie):2d} · на кадре медиана {statistics.median(po_kadram):.1f}")
    print(f"{'':26s}   значения: {', '.join(f'{k:+d}пт×{v}' for k,v in melkie.most_common(8))}")

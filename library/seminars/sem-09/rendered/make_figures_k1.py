#!/usr/bin/env python3
"""Две схемы Кейса 1 — где принимается решение «отвечаю или передаю человеку».

    k1-shema-samootchet.png   решение живёт ВНУТРИ свободного текста модели:
                              отдельного значения нет, предъявить нечего
    k1-shema-geyt.png         то же решение вынесено в поле, которое читает
                              код: на него можно сослаться

Схемы — пара, и нарисованы одной геометрией нарочно: четыре узла в ряд, одна
и та же ширина холста, одна и та же высота. Различие между версиями тогда
видно как РАЗНИЦА, а не как две непохожие картинки — а различие ровно одно и
стоит в третьем узле.

**Довод кейса стоит не на частоте ошибки, а на проверяемости** — так он
записан в `SETKA-KEYSOV-S9.md`, такт «Решение», и так нарисован здесь.
Поэтому у каждой версии на схеме названа СВОЯ цена, измеренная на одном и том
же наборе из пятнадцати трудных вопросов (тема в базе есть, спрошенная деталь
другая, прогоны `619`–`648`):

    версия 1 — 6 уверенно неверных ответов из 15;
    версия 2 — 4 из 15 прошли проверку с неверно применённым пунктом,
               ещё 2 из 15 оборвались до любого ответа вовсе.

У версии 1 рядом стоит лёгкий случай — 0 из 3, тема в базе отсутствует вовсе
(прогоны `606`–`611`). Без него схема обвиняет самоотчёт в том, чего замер не
показал: на грубо не покрытом вопросе модель честно призналась все три раза.
Это и есть база, без которой «6 из 15» не читается.

Внутренних имён полей и значений (`grounded_in_item`, `kb1`…`kb10`) на схеме
нет умышленно: слой 1 — устройство решения, а не экран инструмента. Настоящие
имена зал увидит на снимке панели, снятом со стенда.

Запуск: `python3 make_figures_k1.py` (из `rendered/`).
"""
from make_figures_common import *

H = 800
ROW_Y, ROW_H = 112, 196
CY = ROW_Y + ROW_H / 2
ZAGOLOVOK = "Где принимается решение «ответить самому или передать человеку»"


def shapka(d, podzag):
    txt(d, 60, 16, ZAGOLOVOK, 34, MID, b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 64, podzag, 26, LIGHT, limit=CW - 120, where="подзаголовок")


def samootchet():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    shapka(d, "версия 1 — модель получает базу знаний целиком и отвечает свободным текстом")

    node(d, 60, ROW_Y, 340, ROW_H, "Вопрос клиента", "свободный текст заявки",
         where="узел 1")
    node(d, 450, ROW_Y, 660, ROW_H, "Узел модели",
         "база знаний, десять пунктов, целиком в промте · указание «если не "
         "уверена — напиши, что не знаешь»", ssz=25, where="узел 2")

    # Третий узел — сердце схемы: ответ и решение слиты в одном абзаце.
    x3, w3 = 1160, 740
    card(d, x3, ROW_Y, w3, ROW_H, fill=SURF, stroke=LIGHT)
    ctxt(d, x3 + w3 / 2, ROW_Y + 18, "Один свободный текст", 34, DEEP, b=True,
         limit=w3 - 44, where="узел 3 · название")
    dashbox(d, x3 + 26, ROW_Y + 66, w3 - 52, ROW_H - 92, GOLD, width=4, bg=SURF)
    wrapped(d, x3 + 50, ROW_Y + 84, "внутри текста — и ответ, и решение: "
            "отвечаю сам или отдаю человеку", 25, DEEP, w3 - 100,
            center=x3 + w3 / 2, where="узел 3 · решение внутри")

    x4, w4 = 1950, 390
    card(d, x4, ROW_Y, w4, ROW_H)
    person(d, x4 + w4 / 2, ROW_Y + 74, 30, LIGHT)
    ctxt(d, x4 + w4 / 2, ROW_Y + 96, "Клиент", 34, DEEP, b=True, limit=w4 - 44,
         where="узел 4 · название")
    wrapped(d, x4 + 22, ROW_Y + 142, "получает текст как есть", 25, LIGHT,
            w4 - 44, center=x4 + w4 / 2, where="узел 4 · пояснение")

    for x1, x2 in ((400, 450), (1110, 1160), (1900, 1950)):
        arrow(d, x1, CY, x2, CY, col=MID, wd=5)

    card(d, 60, 368, CW - 120, 96, fill=W, stroke=GOLD, sw=5)
    # Одной строкой, а не полутора: висячее «вопросе.» на второй строке
    # читалось обрывком, а не продолжением.
    ctxt(d, CW / 2, 400, "Решение нигде не записано отдельно: код не может его ни "
         "прочитать, ни сверить, ни предъявить.", 34, DEEP, limit=CW - 200,
         where="вывод схемы")

    plashka(d, 360, 512, 760, 206, "0 из 3",
            "тема в базе отсутствует вовсе: ни одного уверенно неверного ответа",
            where="плашка лёгкого случая")
    plashka(d, 1280, 512, 760, 206, "6 из 15",
            "тема в базе есть, спрошенная деталь другая: уверенно неверные ответы",
            tone="glavnoe", where="плашка трудного случая")
    save(im, "k1-shema-samootchet.png")


def geyt():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    shapka(d, "версия 2 — модель заполняет отдельное поле, решение принимает код")

    node(d, 60, ROW_Y, 330, ROW_H, "Вопрос клиента", "свободный текст заявки",
         where="узел 1 гейта")
    node(d, 440, ROW_Y, 620, ROW_H, "Узел модели",
         "относит вопрос к одному из заранее заданных пунктов базы — либо "
         "не относит ни к одному", ssz=25, where="узел 2 гейта")

    # Поле — не абзац, а значение: тиловая плашка с замком, потому что
    # именно его читает код, а не пересказ модели.
    x3, w3 = 1130, 520
    card(d, x3, ROW_Y, w3, ROW_H, fill=SURF, stroke=TEAL, sw=5)
    ctxt(d, x3 + w3 / 2, ROW_Y + 16, "Поле «опора на пункт базы»", 28, DEEP, b=True,
         limit=w3 - 30, where="узел 3 гейта · название")
    card(d, x3 + 48, ROW_Y + 64, w3 - 96, 62, fill=W, stroke=TEAL, sw=3)
    ctxt(d, x3 + w3 / 2, ROW_Y + 76, "пункт базы № 7", 32, TEAL, b=True,
         limit=w3 - 120, where="узел 3 гейта · значение")
    padlock(d, x3 + 62, ROW_Y + 148, 17, TEAL)
    txt(d, x3 + 96, ROW_Y + 146, "это значение читает код", 25, DEEP,
        limit=w3 - 130, where="узел 3 гейта · замок")

    node(d, 1700, ROW_Y, 640, ROW_H, "Условие в коде",
         "значение входит в список известных пунктов?", ssz=25,
         where="узел 4 гейта")

    for x1, x2 in ((390, 440), (1060, 1130), (1650, 1700)):
        arrow(d, x1, CY, x2, CY, col=MID, wd=5)

    # Развилка: две ветки под четвёртым узлом, обе названы исходом.
    d.line([2020, ROW_Y + ROW_H, 2020, 338], fill=MID, width=5)
    d.line([1410, 338, 2020, 338], fill=MID, width=5)
    arrow(d, 1410, 338, 1410, 364, col=MID, wd=5)
    arrow(d, 2020, 338, 2020, 364, col=MID, wd=5)
    # Метки ветвей стоят ВЫШЕ перемычки, а не вплотную к ней: на первом
    # прогоне «да» читалось продолжением соседней подписи, а не меткой.
    txt(d, 1432, 288, "да", 25, MID, b=True, limit=90, where="метка ветви «да»")
    txt(d, 2042, 288, "нет", 25, MID, b=True, limit=90, where="метка ветви «нет»")
    node(d, 1130, 368, 560, 104, "Ответить по найденному пункту", "",
         tsz=29, where="ветка «да»")
    card(d, 1740, 368, 600, 104)
    person(d, 1808, 400, 26, LIGHT)
    ctxt(d, 2050, 384, "Передать Ольге", 29, DEEP, b=True, limit=520,
         where="ветка «нет» · название")
    ctxt(d, 2050, 424, "вопрос уходит человеку", 24, LIGHT, limit=520,
         where="ветка «нет» · пояснение")

    card(d, 60, 368, 1020, 104, fill=W, stroke=GOLD, sw=5)
    wrapped(d, 90, 386, "Решение записано отдельным значением — код проверяет его "
            "одинаково на любом следующем вопросе.", 29, DEEP, 960,
            center=570, where="вывод схемы гейта")

    plashka_para(d, 500, 520, 1400, 206,
                 ("4 из 15", "прошли проверку с неверно применённым пунктом"),
                 ("2 из 15", "оборвались до ответа: клиент не получил ничего"),
                 "цена версии 2 на тех же пятнадцати трудных вопросах",
                 gold_idx=0, where="плашка цены гейта")
    save(im, "k1-shema-geyt.png")


if __name__ == "__main__":
    samootchet()
    geyt()
    pt_report("схемы Кейса 1")
    audit_sources()

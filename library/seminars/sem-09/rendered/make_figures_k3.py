#!/usr/bin/env python3
"""Схема Кейса 3 — `k3-shema-tsikl.png`.

Генератор → проверяющий → переделка, с потолком попыток и ветвью «не сошлось».

ПЕРЕРИСОВАНО 2026-10-29 (issue #303, правка владельца, минуты 27:50-28:36):
прежняя версия сводила обе развилки в один Т-образный перекрёсток — «сошлось»
уходило ВНИЗ, а «потолок исчерпан» и «попытка не последняя» были двумя
подписанными спусками с одной и той же горизонтальной перемычки, без
отдельной второй развилки. Владелец прочитал это как матрицу, а не цепочку:
«передать Ольге отправку клиента, она внизу, ты такая матрица получилась...
давай замкнуть цепочку». Новое устройство — ДВЕ последовательные развилки
по одной и той же схеме «да — направо, нет — вниз»:

  РАЗВИЛКА 1 «Сошлось?»          да → ВПРАВО → Отправка клиенту
                                  нет → ВНИЗ → развилка 2

  РАЗВИЛКА 2 «Потолок исчерпан?» да (потолок исчерпан) → ВПРАВО → Передать Ольге
                                  нет (попытка не последняя) → ВЛЕВО → Переделка

Четыре вещи, без которых цикл на кадре — просто четыре коробки по кругу, и
каждая из них на схеме названа:

  ВХОД     — золотая точка у вопроса клиента: видно, откуда круг начинается;
  ВОЗВРАТ  — стрелка от переделки обратно в генератор, подписанная тем, что
             на самом деле происходит: заново проверяются и те требования,
             которые уже проходили (те самые «якоря» из сетки, такт
             «Решение»);
  ПОТОЛОК  — три попытки, выставленные вручную: у встроенного цикла нет
             предохранителя по умолчанию, и без счётчика он не остановится
             сам (сетка, такт «Нюансы», п. 2);
  ВЫХОД «НЕ СОШЛОСЬ» — вопрос уходит Ольге, а не висит в круге.

Нижняя строка говорит об устройстве, а не об исходе: проверяющий — такой же
участник, как генератор, и ошибается он так же. Измеренный случай, которым
это подтверждено на стенде (точного совпадения подстроки не хватило, чтобы
узнать верный по смыслу ответ в другом падеже), со схемы СНЯТ: он принадлежит
такту нюансов, а схема идёт на такте устройства, за девять кадров до него.

Судьи-модели на схеме нет умышленно: она не часть устройства решения, она
измеренная АЛЬТЕРНАТИВА ему, и её числа живут на кадрах разбора версий
(n36-n40), а не внутри схемы цикла. Настройки судьи-модели — отдельный кадр
n35a, настоящий снимок панели (БРИФ §3: реальные снимки не стилизуются).

Запуск: `python3 make_figures_k3.py` (из `rendered/`).
"""
from make_figures_common import *

# ── Схема сцены — `k3-shema-postanovka.png` (issue #303, С1) ───────────────
# Сплошное — процесс, не меняющийся в этом кейсе: заявка → классификация →
# модель пишет ответ → ответ уходит клиенту. Пунктир — то, что этот кейс
# строит: проверка перед отправкой, встающая между тем, что написала
# модель, и тем, что получает человек.
POST_H = 560
POST_R1_Y, POST_R1_H = 120, 170
POST_R2_Y, POST_R2_H = 300, 220


def postanovka():
    im = Image.new("RGB", (CW, POST_H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Куда в потоке встанет проверка перед отправкой", 34, MID,
        b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "заявка, классификация и ответ модели не меняются — "
        "между ответом и отправкой пока никого нет", 26, LIGHT,
        limit=CW - 120, where="подзаголовок")

    gap = 50
    n = 4
    node_w = (CW - 120 - gap * (n - 1)) // n
    xs = [60 + i * (node_w + gap) for i in range(n)]
    nodes = (
        ("Заявка", "вопрос клиента произвольным текстом"),
        ("Классификация", "вопрос относится к пункту справочника"),
        ("Модель пишет ответ", "по найденному пункту, свободным текстом"),
        ("Ответ уходит клиенту", "без второго чтения"),
    )
    cy1 = POST_R1_Y + POST_R1_H / 2
    for i, (title, sub) in enumerate(nodes):
        node(d, xs[i], POST_R1_Y, node_w, POST_R1_H, title, sub, tsz=29,
             ssz=27, stroke=TEAL, where=f"шаг {i + 1}")
        if i:
            arrow(d, xs[i - 1] + node_w, cy1, xs[i], cy1, col=TEAL, wd=5)

    gap_cx = (xs[2] + node_w + xs[3]) / 2
    dash_w, dash_h = 900, POST_R2_H
    dash_x = gap_cx - dash_w / 2
    card(d, dash_x, POST_R2_Y, dash_w, dash_h, fill=SURF, stroke=GOLD, sw=4)
    ctxt(d, gap_cx, POST_R2_Y + 30, "Строим: проверка перед отправкой", 30,
         DEEP, b=True, limit=dash_w - 60, where="новое · название")
    wrapped(d, dash_x + 30, POST_R2_Y + 94, "встаёт между тем, что написала "
            "модель, и тем, что получает человек, проверяя ответ до "
            "отправки", 27, LIGHT, dash_w - 60, center=gap_cx,
            where="новое · пояснение")
    target_cx = xs[3] + node_w / 2
    arrow(d, gap_cx, POST_R2_Y, target_cx, POST_R1_Y + POST_R1_H, col=GOLD,
          wd=5, dash=True)

    save(im, "k3-shema-postanovka.png")


H = 820
R1_Y, R1_H = 120, 170          # ряд 1: вопрос → генератор → проверяющий → развилка 1
R2_Y, R2_H = 360, 170          # ряд 2: переделка ← развилка 2 → Ольге
JUNC = 330                     # высота перемычки возврата «переделка → генератор»
INFO_Y = 600                   # нижний ряд: потолок + оговорка

# Колонки общие для обоих рядов — так «да» направо и «нет» налево на
# развилке 2 выглядят зеркально развилке 1, а не случайным расположением.
COL_VOPROS = (60, 280)          # 60-340
COL_GEN = (400, 360)            # 400-760  (ряд 1: генератор)
COL_PROV = (820, 400)           # 820-1220 (ряд 1: проверяющий; ряд 2: переделка)
COL_RAZV = (1280, 340)          # 1280-1620 (обе развилки)
COL_ISHOD = (1680, 660)         # 1680-2340 (оба положительных исхода: клиенту / Ольге)


def tsikl():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Цикл проверки ответа перед отправкой", 34, MID, b=True,
        limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "две развилки одной формы: сошлось — направо; иначе — вниз",
        26, LIGHT, limit=CW - 120, where="подзаголовок")

    cy1 = R1_Y + R1_H / 2
    cy2 = R2_Y + R2_H / 2

    # Вход помечен золотом и стоит НАД названием, а не под ним.
    vx, vw = COL_VOPROS
    card(d, vx, R1_Y, vw, R1_H)
    d.ellipse([vx + 62, R1_Y + 36, vx + 86, R1_Y + 60], fill=GOLD)
    txt(d, vx + 96, R1_Y + 34, "вход", 24, GOLD, b=True, limit=140,
        where="метка входа")
    wrapped(d, vx + 22, R1_Y + 86, "Вопрос клиента", 28, DEEP, vw - 40, b=True,
            center=vx + vw / 2, where="вход · название")

    gx, gw = COL_GEN
    node(d, gx, R1_Y, gw, R1_H, "Генератор", "модель пишет ответ клиенту",
         ssz=23, where="генератор")
    px, pw = COL_PROV
    node(d, px, R1_Y, pw, R1_H, "Проверяющий",
         "код сверяет пять заранее записанных требований", ssz=22,
         where="проверяющий")

    rx, rw = COL_RAZV
    card(d, rx, R1_Y, rw, R1_H, fill=SURF, stroke=TEAL, sw=5)
    ctxt(d, rx + rw / 2, R1_Y + 46, "Сошлось?", 32, DEEP, b=True, limit=rw - 30,
         where="развилка 1 · название")
    ctxt(d, rx + rw / 2, R1_Y + 90, "код сверяет условия", 22,
         LIGHT, limit=rw - 30, where="развилка 1 · пояснение")

    # Главный ряд: вопрос → генератор → проверяющий → развилка 1.
    for x1, x2 in ((vx + vw, gx), (gx + gw, px), (px + pw, rx)):
        arrow(d, x1, cy1, x2, cy1, col=MID, wd=5)

    # РАЗВИЛКА 1, «да» — ВПРАВО, в ту же строку: владелец явно просил эту
    # ветвь прямой, не нырять вниз («сошлось, да, будет идти просто вправо
    # отправка клиенту»).
    ix, iw = COL_ISHOD
    arrow(d, rx + rw, cy1, ix, cy1, col=MID, wd=5)
    ctxt(d, (rx + rw + ix) / 2, R1_Y - 34, "да", 24, MID, b=True, limit=90,
         where="метка «да» · развилка 1")
    node(d, ix, R1_Y, iw, R1_H, "Отправка клиенту",
         "ответ уходит обратившемуся", ssz=22, tsz=30, stroke=TEAL, sw=5,
         where="исход «отправка»")

    # РАЗВИЛКА 1, «нет» — ВНИЗ, к развилке 2 (та самая цепочка, которую
    # владелец попросил замкнуть).
    rcx = rx + rw / 2
    arrow(d, rcx, R1_Y + R1_H, rcx, R2_Y, col=MID, wd=5)
    txt(d, rcx + 24, (R1_Y + R1_H + R2_Y) / 2 - 14, "нет", 24, MID, b=True,
        limit=90, where="метка «нет» · развилка 1")

    # РАЗВИЛКА 2 — «Потолок исчерпан?», прямо под развилкой 1, той же формы.
    card(d, rx, R2_Y, rw, R2_H, fill=SURF, stroke=TEAL, sw=5)
    ctxt(d, rx + rw / 2, R2_Y + 32, "Потолок исчерпан?", 28, DEEP, b=True,
         limit=rw - 24, where="развилка 2 · название")
    ctxt(d, rx + rw / 2, R2_Y + 76, "считает счётчик попыток", 22,
         LIGHT, limit=rw - 30, where="развилка 2 · пояснение")

    # РАЗВИЛКА 2, «да» (потолок исчерпан) — ВПРАВО, к Ольге: зеркально
    # развилке 1, чтобы «направо = выход из круга» читалось одним правилом.
    arrow(d, rx + rw, cy2, ix, cy2, col=MID, wd=5)
    ctxt(d, (rx + rw + ix) / 2, R2_Y - 34, "да", 24, MID, b=True, limit=90,
         where="метка «да» · развилка 2")
    node(d, ix, R2_Y, iw, R2_H, "Передать Ольге", "вопрос уходит человеку",
         ssz=22, tsz=30, stroke=TEAL, sw=5, where="исход «Ольге»")
    person(d, ix + 70, R2_Y + 58, 24, LIGHT)

    # РАЗВИЛКА 2, «нет» (попытка не последняя) — ВЛЕВО, к переделке.
    arrow(d, rx, cy2, px + pw, cy2, col=MID, wd=5)
    ctxt(d, (rx + px + pw) / 2, R2_Y - 34, "попытка не последняя", 22, MID,
         limit=320, where="метка «нет» · развилка 2")
    node(d, px, R2_Y, pw, R2_H, "Переделка", "знает, что не прошло", ssz=22,
         tsz=30, where="переделка")

    # Возврат — переделка поднимается и уходит налево, в генератор, а не
    # висит сама по себе. Подпись говорит, ЧТО именно повторяется.
    rex = px + pw / 2
    gcx = gx + gw / 2
    d.line([rex, R2_Y, rex, JUNC], fill=GOLD, width=5)
    d.line([gcx, JUNC, rex, JUNC], fill=GOLD, width=5)
    arrow(d, gcx, JUNC, gcx, R1_Y + R1_H + 6, col=GOLD, wd=5)
    wrapped(d, 60, JUNC - 30, "снова — и все уже пройденные требования заново",
            23, GOLD, 460, where="подпись возврата")

    plashka(d, 60, INFO_Y, 700, 150, "три попытки",
            "потолок выставлен вручную: без счётчика цикл не остановится сам",
            nsz=40, tone="glavnoe", where="плашка потолка")
    card(d, 820, INFO_Y, 1520, 150, fill=SURF, stroke=LIGHT)
    wrapped(d, 860, INFO_Y + 28, "Цикл надёжен ровно настолько, насколько "
            "надёжен сам проверяющий: проверяющего нужно проверять тем же "
            "вниманием, что и генератора.", 27, DEEP, 1440,
            where="оговорка о проверяющем")
    save(im, "k3-shema-tsikl.png")


# ── Схема разбора — `k3-shema-kto-verdikt.png` (issue #303, Часть Б) ───────
# Кто выносит вердикт о годности ответа, относительно того, кто его
# сочинил, — то, чего таблица n32 (как делает/преимущество/недостатки/
# числа) не показывает одним взглядом.
RZ3_H = 400
RZ3_ROW_Y, RZ3_ROW_H = 140, 220


def razbor_kto_verdikt():
    im = Image.new("RGB", (CW, RZ3_H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Кто выносит вердикт о годности ответа", 32, MID, b=True,
        limit=CW - 120, where="заголовок")

    n = 4
    gap = 40
    col_w = (CW - 120 - gap * (n - 1)) // n
    cols = [60 + i * (col_w + gap) for i in range(n)]
    cells = (
        ("Тот же исполнитель", "модель перечитывает собственный ответ"),
        ("Другая модель", "судья получает пару ответов, выбирает"),
        ("Код", "формальный критерий — правило или тест, без модели"),
        ("Несколько исполнителей", "решатель выбирает лучший из трёх"),
    )
    for x, (title, sub) in zip(cols, cells):
        card(d, x, RZ3_ROW_Y, col_w, RZ3_ROW_H, fill=SURF, stroke=TEAL, sw=3)
        wrapped(d, x + 16, RZ3_ROW_Y + 24, title, 24, DEEP, col_w - 32,
                b=True, center=x + col_w / 2, where=f"ячейка · {title}")
        wrapped(d, x + 16, RZ3_ROW_Y + 100, sub, 22, LIGHT, col_w - 32,
                center=x + col_w / 2, where=f"ячейка · {title} · пояснение")

    save(im, "k3-shema-kto-verdikt.png")


if __name__ == "__main__":
    postanovka()

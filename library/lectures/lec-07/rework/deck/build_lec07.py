def fit_media(sl, root, w0=MEDIA_W):
    """Самая широкая боковая колонка, при которой кадр ещё собирается чисто.

    Тот же ход, каким `metrics.fit_size` подбирает кегль: не назначить размер
    и посмотреть, что вышло, а найти наибольший, который держится.
    Понадобился он на `s18` — две плашки, конвейер на два ряда и три абзаца.
    Там и работает: после перевода на ядро схема `s18` стала выше, слот в
    4,30" упёрся в блокирующее предупреждение, и подбор увёл колонку на
    3,70", где кадр собирается чисто. Разница между «снимок не влезает» и
    «слот назначен шире нужного» видна только замером.

    `w0` — откуда начинать поиск; меняет его только проба, которой нужно
    доказать сам механизм, а не нынешний исход (см. `selftest_lec07`).

    Пробная сборка идёт в отдельную презентацию, а состояние отчёта
    снимается и возвращается: проба не имеет права попасть в отчёт."""
    if str(sl.meta.get("type")) not in CONTENT_TYPES:
        return
    if not media.media_path(sl.meta, root, sl.sid) or sl.meta.get("media_hero"):
        return
    keep = report.snapshot()
    chosen, w = None, w0
    while w >= MEDIA_W_FLOOR - 1e-9:
        sl.media_w = w
        report.WARNINGS[:] = []
        report.PRIM.clear()
        report.GOLD_SEEN.clear()
        try:
            content(prims.new_deck(), sl, root)
        except Exception:                            # noqa: BLE001
            break
        if not report.blocking():
            chosen = w
            break
        w = round(w - 0.10, 2)
    report.restore(keep)
    sl.media_w = chosen or MEDIA_W
    if chosen is None:
        report.warn(
            f"[кадр] {sl.sid}: боковая иллюстрация не умещается ни при какой "
            f"ширине до {MEDIA_W_FLOOR:.2f}\" — кадру нечего ей отдать")


def _scheme_on_disk(ref, sd):
    """Несёт ли кадр `ref` свою схему — по файлу на диске, а не по сборке.

    Нужно ОДНОМУ случаю: частичной сборке (`--only s49_1`), где названный
    кадр в пакет не попал и спросить его в сборке нельзя. На полном прогоне
    эта ветка не берётся ни разу — ref резолвится по собранным кадрам.

    Читает фронтматтер сам, а не через `slidefile.read_slide`: тот на каждом
    чтении складывает в отчёт свои предупреждения (`[ссылка]`, `[файл]`), и
    кадр-цель получил бы их ВТОРОЙ раз — один раз за себя, второй за то, что
    на него сослались. Возвращает None, если файла нет вовсе."""
    hit = [f for f in sorted(Path(sd).glob("s*.md"))
           if f.name.split("-")[0] == ref]
    if not hit:
        return None
    m = re.match(r"^---\n(.*?)\n---", hit[0].read_text(encoding="utf-8"), re.S)
    if not m:
        return None
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        return None
    return bool(meta.get("scheme"))


def check_scheme_refs(refs, built, sd):
    """`scheme_ref: <sid>` — разбор, чья схема стоит на ДРУГОМ кадре.

    Заведено под `s49_1` (issue #293, Этап E). `s49` разрезан надвое под
    игру-предсказание: на первой половине постановка опыта и схема порядка
    чтения, на второй — вскрытие. Схема у разреза одна по построению, и
    ставить её дублем на вторую половину запрещено прямо (§5.12: два
    написания одного содержания на соседних кадрах). Но сторож `[схема]`
    видит только своё поле и называет вторую половину кадром разбора без
    схемы — то есть требует ровно того, что запрещено.

    Поэтому ссылка, а не отмена сторожа и не исключение по имени кадра:
    `scheme_ref` ПЕРЕАДРЕСУЕТ проверку, и проверяется она целиком. Битый
    ref — то же блокирующее `[схема]`, с уточнением, чем именно он битый:
    названного кадра нет · кадр есть, а схемы на нём нет · ссылка на себя.
    Ссылка, по которой ничего не лежит, хуже отсутствия поля: отсутствие
    видно, а мёртвая ссылка читается как сделанная работа."""
    for sid, ref in refs:
        if ref == sid:
            report.warn(
                f"[схема] {sid}: `scheme_ref: {ref}` ссылается на сам кадр — "
                "схема не может стоять на кадре, у которого её нет")
            continue
        has = built.get(ref)
        where = "в сборке"
        if has is None:
            has = _scheme_on_disk(ref, sd)
            where = "ни в сборке, ни в каталоге кадров"
        if has is None:
            report.warn(
                f"[схема] {sid}: `scheme_ref: {ref}` — кадра `{ref}` нет "
                f"{where}; схему переадресовали в пустоту")
        elif not has:
            report.warn(
                f"[схема] {sid}: `scheme_ref: {ref}` — кадр `{ref}` есть, но "
                "своей схемы не несёт; переадресовывать проверку некуда")


def build(only=None, out=OUT, slides_dir=None, root=None):
    sd = slides_dir or SLIDES_DIR
    root = root or LEC_ROOT
    p = prims.new_deck()
    n = 0
    plotno = []
    # Схемы собранных кадров и отложенные ссылки на них: ref проверяется
    # ПОСЛЕ прогона, иначе кадр, стоящий раньше своей цели, судился бы по
    # ещё не прочитанной её половине.
    sch_built, sch_refs = {}, []
    for f in slidefile.slide_files(sd, only):
        sl = slidefile.read_slide(f)
        if sl is None:
            continue
        fit_media(sl, root)
        kind = str(sl.meta.get("type") or "case").strip()
        # §11.2/§11.3 канона формы: оба порога проверяются СБОРКОЙ, а не
        # напоминанием в наряде агента. Счёт идёт до отрисовки — чтобы
        # предупреждение стояло рядом со своим кадром в отчёте.
        slov, _ = plotnost.proverit_kadr(sl)
        plotno.append((sl.sid, slov, kind))
        sch_built[sl.sid] = bool(sl.meta.get("scheme"))
        if kind == "case" and not sl.meta.get("scheme"):
            ref = str(sl.meta.get("scheme_ref") or "").strip()
            if ref:
                sch_refs.append((sl.sid, ref))
            else:
                report.warn(
                    f"[схема] {sl.sid}: кадр разбора без поля `scheme` — "
                    "схема решения и есть главный носитель инженерного "
                    "содержания, текст к ней пояснение (§10.3). Если схема "
                    "стоит на соседней половине разреза — назовите её "
                    "кадром в `scheme_ref`")
        s = BUILDERS.get(kind, content)(p, sl, root)
        markup.notes_with_links(s, sl.notes)
        if sl.sid not in report.GOLD_SEEN:
            report.warn(f"[золото] {sl.sid}: золотого акцента на кадре нет")
        n += 1
    check_scheme_refs(sch_refs, sch_built, sd)
    plotnost.proverit_mediany(plotno)
    metrics.font_gaps()
    p.save(str(out))
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--only")
    a = ap.parse_args()
    if a.selftest:
        from selftest_lec07 import selftest
        return selftest()
    # ВЫПУСК ДЕКИ НЕ ПЕРЕЗАПИСЫВАЕТСЯ ЧАСТИЧНОЙ СБОРКОЙ (`notes/mcp-limitations.md`
    # [#229-14]). До 2026-10-15 `--only sNN` писал в тот же `lec-07-karkas.pptx`,
    # и 7,9 МБ деки молча становились 178 КБ одного кадра. Сессия круга
    # восстанавливала файл `git checkout` после каждой поштучной сборки и
    # предупредила об этом письмом; оркестратор прочёл предупреждение и через
    # час сам же в ловушку и попал. Значит, лечится это не памятью, а путём:
    # частичная сборка пишет в свой файл, и выпуск ей недоступен.
    vykhod = OUT if not a.only else HERE / "chastichnaya-sborka.pptx"
    n = build(only=a.only, out=vykhod)
    if a.only:
        print(f"[частичная сборка] {len(a.only.split(','))} кадров → "
              f"{vykhod.name}; выпуск {OUT.name} НЕ ТРОНУТ")
    # Проверки по СОХРАНЁННОМУ файлу: hero по порядку деки и пол контраста.
    # Зовутся здесь, а не из `build`, нарочно — см. `render.verify_built`:
    # обе про деку целиком, а `build` зовут однокадровые пробы.
    # `quiet=False`: строка контраста печатается КАЖДУЮ сборку, а не только
    # когда порог провален. Та же причина, по которой `report.report` всегда
    # печатает долю площади hero: молчание о «65 ниже порога» неотличимо от
    # молчания о том, что контраст вообще не мерился.
    rnd.verify_built(vykhod, partial=bool(a.only))
    report.report(n, vykhod.name)
    rnd.verify_links(vykhod)
    if a.render:
        rnd.render(vykhod, SNAPS)
    return 0



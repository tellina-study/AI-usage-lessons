"""Единственный источник шаблонов запрета «не X, а Y» (`tools/editorial/
README.md` §1). Вынесено из `audit_sopostavleniya.py` (issue #299, дыра 1
независимой проверки): до этого шаблоны жили ТОЛЬКО там и проверялись лишь
по собранному `.pptx`, а подписи внутри программных схем (PIL-картинки,
`make_figures_*.py`) рисуются пикселями — собранный файл их не видит, и
грепу-по-деке неоткуда взять этот запрет для них.

Теперь оба сторожа читают ОДИН список:
  - `audit_sopostavleniya.py` — по видимому слою и речи собранного `.pptx`;
  - `make_figures_common.py` (`audit_sources`) — по строкам, реально
    дошедшим до холста схемы (через патч `ImageDraw.text`).

Если бы шаблоны лежали в двух местах, второй список неизбежно отстал бы от
первого при следующей правке канона — третья дыра поверх уже найденных
двух. Править запрет теперь — править только здесь.

Граница слова (`\\bне\\b`) обязательна по канону §8.6 этого репозитория:
без неё регулярка ловит хвост любого слова на «-не» («на сторо**не**
платформы, а …»). Подробности и замеры на реальной деке — в докстринге
`audit_sopostavleniya.py`, который эти правила применяет первым.
"""
import re

FIGURY = [
    ("хвостовое «, а не»", re.compile(r",\s+а\s+не\b")),
    ("головное «не X, а Y»", re.compile(r"\bне\b[^,.;:!?]{2,45},\s+а\s+")),
    ("«дело не в X»", re.compile(r"\bдело\s+не\s+в\b", re.I)),
    ("«с одной стороны»", re.compile(r"\bс\s+одной\s+стороны\b", re.I)),
    # Та же фигура без союза «а» — вторая половина сопоставления введена
    # прямо тире или запятой. `\bне\b` — граница по обе стороны (§8.6: без
    # неё «стороне»/«показал» ловятся как «-не»-хвост слова).
    ("тире «X — не Y»", re.compile(r"[—–]\s*не\b[^,.;:!?]{2,45}")),
    ("запятая «X, не Y»", re.compile(r",\s*не\b[^,.;:!?]{2,45}")),
]

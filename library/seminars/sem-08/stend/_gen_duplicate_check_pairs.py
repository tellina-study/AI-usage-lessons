#!/usr/bin/env python3
"""Генератор `duplicate-check-test-pairs.json` для Кейса 2 (повторный проход, см.
`README.md` «Кейс 2 — измеренный результат (4 схемы)»).

Старые 20 пар первого прохода (хэш 15/20, TF-IDF 15/20, LLM-судья 19/20) нигде не сохранились —
временный workflow первого прохода был удалён вместе с данными. Это НОВЫЙ набор той же
структуры и того же размера: 10 настоящих дублей (5 буквальных повторов + 5 перефразировок в
духе пары Бориса — «когда можно оплатить занятие?» / «как мне внести оплату за курс», см.
`slides/n17-k2-vopros.md`) и 10 заведомо разных вопросов, часть — на близкую тему (возврат vs
расписание, курс vs курс, способ оплаты vs способ оплаты), для честной проверки ложных
срабатываний. Детерминированный набор — никакого random, чтобы при повторном запуске выходил
тот же файл байт в байт.
"""
import json
from pathlib import Path

HERE = Path(__file__).parent

# 5 буквальных повторов — та же строка приходит дважды (иногда с другим регистром/пробелами,
# чтобы заодно проверить, что хэш-схема нормализует, а не падает на мелочах).
LITERAL_REPEATS = [
    {
        "text_old": "когда начинается следующий курс по аналитике",
        "text_new": "когда начинается следующий курс по аналитике",
    },
    {
        "text_old": "можно перенести занятие в четверг на другое время",
        "text_new": "Можно перенести занятие в четверг на другое время",
    },
    {
        "text_old": "сколько стоит абонемент на три месяца",
        "text_new": "сколько стоит абонемент на три месяца",
    },
    {
        "text_old": "как связаться с преподавателем напрямую",
        "text_new": "как связаться с преподавателем напрямую  ",
    },
    {
        "text_old": "есть ли скидка для студентов",
        "text_new": "есть ли скидка для студентов",
    },
]

# 5 перефразировок — тот же вопрос, другими словами, ноль общих словоформ в духе пары Бориса.
PARAPHRASES = [
    {
        "text_old": "когда можно оплатить занятие?",
        "text_new": "как мне внести оплату за курс",
    },
    {
        "text_old": "хочу вернуть деньги за урок, который пропустил",
        "text_new": "можно оформить возврат средств, я был на одном пропущенном занятии",
    },
    {
        "text_old": "в какое время у нас урок в четверг",
        "text_new": "подскажите расписание четверга, когда начинается занятие",
    },
    {
        "text_old": "как записаться на курс по питону",
        "text_new": "хочу попасть на программу обучения python, что нужно сделать",
    },
    {
        "text_old": "можно ли перенести занятие на другой день",
        "text_new": "нельзя ли сместить урок на другую дату",
    },
]

# 10 заведомо разных вопросов — МЕНЬШИНСТВО (3 из 10) на близкую тему, для честной проверки
# ложных срабатываний, остальные 7 — ясно разные темы с низким пересечением слов (иначе тест
# превращается в полосу препятствий, заточенную против векторных методов, а не в
# представительную выборку обращений учебного центра). Первая пара — та самая, на которой в
# прошлом (утраченном) прогоне ошиблась LLM-судья (возврат за пропуск vs расписание четверга,
# см. n18-k2-razbor.md) — сохранена, чтобы проверить, повторяется ли то же ложное срабатывание
# на новом прогоне, а не потому что ответ предрешён.
DIFFERENT = [
    # 3 пары на близкую тему (ловушка для ложных срабатываний)
    {
        "text_old": "хочу возврат средств за урок, на который не попал",
        "text_new": "в какое время у нас урок в четверг",
    },
    {
        "text_old": "сколько стоит курс по питону",
        "text_new": "сколько стоит курс по аналитике данных",
    },
    {
        "text_old": "как оплатить занятие картой",
        "text_new": "можно ли оплатить занятие в рассрочку",
    },
    # 7 пар — ясно разные темы, низкое пересечение слов
    {
        "text_old": "подскажите адрес офиса для очных занятий",
        "text_new": "можно получить сертификат после прохождения курса",
    },
    {
        "text_old": "как удалить мои данные из системы",
        "text_new": "хочу сменить преподавателя",
    },
    {
        "text_old": "есть ли группа для начинающих",
        "text_new": "почему не пришло подтверждение записи на вебинар",
    },
    {
        "text_old": "сколько длится одно занятие по времени",
        "text_new": "расскажите про группу для продолжающих",
    },
    {
        "text_old": "почему не работает ссылка на зум для занятия",
        "text_new": "можно получить справку для бухгалтерии об оплате",
    },
    {
        "text_old": "хочу сменить время занятия",
        "text_new": "как изменить контактный телефон в анкете",
    },
    {
        "text_old": "подскажите, где можно распечатать материалы курса",
        "text_new": "сколько всего занятий в курсе",
    },
]


def main():
    rows = []
    i = 1
    for pair_type, group in (
        ("literal_repeat", LITERAL_REPEATS),
        ("paraphrase", PARAPHRASES),
        ("different", DIFFERENT),
    ):
        expected = pair_type != "different"
        for p in group:
            rows.append({
                "id": i,
                "pair_type": pair_type,
                "expected_duplicate": expected,
                "text_old": p["text_old"],
                "text_new": p["text_new"],
            })
            i += 1

    out = {
        "status": "ПОДГОТОВЛЕНО — набор для измерения 4 схем Кейса 2, см. README.md",
        "structure": "10 дублей (5 буквальных + 5 перефразировок) + 10 разных вопросов",
        "count": len(rows),
        "pairs": rows,
    }
    (HERE / "duplicate-check-test-pairs.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("написано", len(rows), "пар")


if __name__ == "__main__":
    main()

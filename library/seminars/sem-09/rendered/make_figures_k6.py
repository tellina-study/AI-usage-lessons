#!/usr/bin/env python3
"""Схема Кейса 6 — `k6-shema-vysota-simvola.png`.

Ожидание плана было «сумма сломается от сжатия». Она не сломалась ни разу:
26 прочтений из 26 верны на всех шести разрешениях, вплоть до 53×64 пикс.
Сломалась ДАТА — она набрана на той же квитанции вдвое мельче, — и сломалась
чисто и воспроизводимо, начиная с высоты символа 6,1 пикс.: 11 прочтений из
11 неверны.

Отсюда композиция кадра. Слева — одна квитанция, на которой два поля набраны
РАЗНЫМ кеглем, и кегль этот не нарисован «примерно»: слово «Сумма» набрано
ровно вдвое крупнее слова «Дата», как на самой квитанции (64 пикс. против
32). Справа — те же шесть разрешений двумя дорожками: что стало с суммой и
что стало с датой. Порог — вертикальная золотая черта между третьим и
четвёртым разрешением; дорожки её пересекают по-разному, и это и есть вся
находка.

**Цифр на квитанции нет умышленно.** Протокол замера даёт высоту символа и
долю верных прочтений, но не даёт самих значений; нарисовать правдоподобную
сумму значило бы поставить на кадр выдуманное число рядом с измеренными. На
квитанции стоят названия полей, набранные теми же двумя кеглями, — это ровно
то, что измерено, и ничего сверх.

**Долей верных прочтений на схеме нет — сняты во втором круге.** Первая
редакция несла две плашки, «26 из 26» и «11 из 11». Это итоги тактов
результата, и на кадре устройства им не место: правило второго круга —
схема показывает УСТРОЙСТВО, а чем дело кончилось, вскрывает свой такт.
Дорожки галочек и крестиков остались: они и есть механизм — одно и то же
уменьшение, два поля, разный исход.

**Открытый вопрос, который я не решаю сам.** Порог «6,1 пикс.» на кадре
остался, и уместен он ровно в одном такте — том, который называется так же,
как эта схема («высота символа»), и идёт ПОСЛЕ кадров результата. Если схему
поставят на такт решения слоя 1, порог придётся снять вместе с дорожками — и
тогда это будет уже другая схема: распознавание переводит фото в текст,
модель получает текст, код сверяет число с суммой из заявки. Такой схемы в
списке фигур нет, и завести её — решение не рисовальщика.

Оговорка, обязательная к этому примеру (сетка, такт «Нюансы», п. 5):
квитанции синтетические, и ломается на этом материале ДАТА, а не сумма.
Переносить «11 из 11» с даты на сумму нельзя — механизм тот же, число снято
на другом поле. Оговорка стоит на самом кадре, а не только в заметках.

Запуск: `python3 make_figures_k6.py` (из `rendered/`).
"""
from make_figures_common import *

H = 842
KX, KW = 60, 700                       # квитанция
PX, PW = 820, 1520                     # дорожки по шести разрешениям
TICK_X0, TICK_W = 1120, 1200           # поле шести столбцов
POROG = 3                              # с четвёртого разрешения дата ломается


def tick_cx(i):
    return TICK_X0 + TICK_W / 6 * (i + 0.5)


def pole(d, cx, y, slovo, kegl, podpis, col):
    """Поле квитанции: слово нужным кеглем, мерная скоба вплотную слева от
    него и подпись ПОД ним.

    Подпись стояла СПРАВА от скобы и налезала на само слово: ширины карточки
    на «высота символа 64 пикс.» плюс «Сумма» в 54 px не хватало, и схема
    выезжала за холст. Скоба обязана стоять вплотную к измеряемому слову —
    иначе непонятно, что именно измерено; значит двигать надо подпись."""
    fo = f(kegl, True)
    w_ = d.textlength(slovo, font=fo)
    d.text((cx - w_ / 2, y), slovo, font=fo, fill=DEEP)
    x = cx - w_ / 2 - 26
    d.line([x, y + 3, x, y + kegl], fill=col, width=3)
    d.line([x, y + 3, x + 13, y + 3], fill=col, width=3)
    d.line([x, y + kegl, x + 13, y + kegl], fill=col, width=3)
    ctxt(d, cx, y + kegl + 14, podpis, 24, col, limit=560,
         where=f"подпись поля · {slovo}")


def dorozhka(d, y, nazvanie, do_poroga, col_ok, col_bad):
    card(d, PX, y, 260, 104, fill=SURF, stroke=LIGHT, sw=3)
    ctxt(d, PX + 130, y + 36, nazvanie, 30, DEEP, b=True, limit=230,
         where=f"дорожка · {nazvanie}")
    for i in range(6):
        cx = tick_cx(i)
        if i < do_poroga:
            tick(d, cx, y + 52, 20, col_ok, wd=6)
        else:
            cross(d, cx, y + 52, 18, col_bad, wd=6)


def vysota_simvola():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Порог чтения завязан на высоту символа, а не на размер файла",
        34, MID, b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "одна и та же квитанция в шести разрешениях — чистое уменьшение "
        "одного файла, от полного размера до 53×64 пикс.", 26, LIGHT,
        limit=CW - 120, where="подзаголовок")

    # ── слева: одна квитанция, два кегля ───────────────────────────────────
    card(d, KX, 110, KW, 346, fill=SURF, stroke=LIGHT, sw=3)
    ctxt(d, KX + KW / 2, 126, "квитанция при полном размере", 25, LIGHT,
         limit=KW - 40, where="квитанция · шапка")
    d.line([KX + 40, 166, KX + KW - 40, 166], fill=LIGHT, width=2)

    cxk = KX + KW / 2 + 20
    pole(d, cxk, 196, "Сумма", 54, "высота символа 64 пикс.", MID)
    pole(d, cxk, 330, "Дата", 27, "высота символа 32 пикс.", GOLD)

    ctxt(d, KX + KW / 2, 476, "сумма набрана ровно вдвое крупнее даты", 28, DEEP,
         b=True, limit=KW, where="квитанция · вывод")

    card(d, KX, 528, KW, 160, fill=W, stroke=GOLD, sw=4)
    wrapped(d, KX + 28, 550, "Квитанции синтетические: на каждой одна сумма и одна "
            "дата. Сломалась здесь дата, а не сумма — переносить её число на сумму "
            "нельзя.", 25, DEEP, KW - 56, center=KX + KW / 2,
            where="квитанция · оговорка")

    # ── справа: шесть разрешений, две дорожки ──────────────────────────────
    txt(d, PX, 110, "Что стало с каждым полем по мере уменьшения снимка", 29, DEEP,
        b=True, limit=PW, where="дорожки · название")
    arrow(d, TICK_X0 + 20, 186, TICK_X0 + TICK_W - 20, 186, col=LIGHT, wd=4)
    txt(d, TICK_X0 + 20, 154, "полный размер", 25, LIGHT, limit=320,
        where="ось · слева")
    ctxt(d, TICK_X0 + TICK_W - 130, 154, "53×64 пикс.", 25, LIGHT, limit=300,
         where="ось · справа")

    dorozhka(d, 216, "сумма", 6, TEAL, GOLD)
    dorozhka(d, 340, "дата", POROG, TEAL, GOLD)

    # Порог — одна черта поперёк обеих дорожек: дорожки пересекают её
    # по-разному, и в этом вся находка.
    xp = (tick_cx(POROG - 1) + tick_cx(POROG)) / 2
    for y0 in range(206, 458, 26):
        d.line([xp, y0, xp, y0 + 16], fill=GOLD, width=5)
    wrapped(d, xp - 300, 470, "правее этой черты высота символа даты — 6,1 пикс. "
            "и меньше", 25, GOLD, 600, b=True, center=xp, where="подпись порога")

    card(d, PX, 538, PW, 150, fill=SURF, stroke=LIGHT, sw=3)
    wrapped(d, PX + 40, 568, "Уменьшение снимка само по себе ничего не решает: один "
            "и тот же файл несёт поля, набранные разной величиной, и порог у каждого "
            "поля свой.", 28, DEEP, PW - 80, center=PX + PW / 2,
            where="вывод дорожек")

    card(d, 60, 716, CW - 120, 104, fill=SURF, stroke=TEAL, sw=5)
    wrapped(d, 100, 736, "Ломается не файл, который сжали, а то, что на нём набрано "
            "мельче. И ломается уверенно: на каждом сломанном разрешении все повторы "
            "сходятся на одной и той же неверной дате.", 28, DEEP, CW - 200,
            center=CW / 2, where="вывод схемы")
    save(im, "k6-shema-vysota-simvola.png")


if __name__ == "__main__":
    vysota_simvola()
    pt_report("схема Кейса 6")
    audit_sources()

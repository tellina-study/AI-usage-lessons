#!/usr/bin/env python3
"""Схема Кейса 5 — `k5-shema-tri-ishoda.png`. Несущий кадр кейса.

Три вопроса, по десять повторов одного и того же текста при температуре ноль
и одной и той же базе в промте — три разных вида негодности к отправке
(собственный перемер, `stend/zamery-k5-povtorno/`, 30 вызовов, прогоны
`799`–`828`):

    разброс                  3 разных исхода из 10
    устойчивая ошибка        10 из 10 одинаковы — и все неверны
    устойчивое противоречие  10 из 10 противоречат сами себе

**Почему именно точками.** Ось кейса — «повторяемость и правильность
независимы», и её нельзя предъявить числом: три столбца цифр читаются как
три замера одного свойства. Десять точек читаются как десять повторов, и
тогда разница между столбцами видна ДО чтения подписей: слева полоса
пёстрая, справа две полосы одинаковые. А одинаковые — это и есть ловушка:
второй и третий столбцы выглядят как порядок, и оба негодны.

**Нижняя полоса обязательна, а не украшает.** Без базы «3 из 10» и «10 из 10»
читаются как «модель плохая». База — тот же процесс на вопросе, ответ на
который целиком лежит в базе: 25 повторов, 0 расхождений по существу.
Устойчивость есть там, где ответ надо НАЙТИ, и пропадает там, где его надо
СОСТАВИТЬ; без этой строки кадр говорит не то, что измерено.

Исходная гипотеза замера (решение у порога перекидывается между повторами)
НЕ подтвердилась и на схему не вынесена — вынесено измеренное.

Запуск: `python3 make_figures_k5.py` (из `rendered/`).
"""
from make_figures_common import *

# ── Схема сцены — `k5-shema-postanovka.png` (issue #303, С1) ───────────────
# Холст Кейса 1 — заявка → классификация → модель отвечает по справочнику →
# ответ — здесь НЕ меняется (сознательный сбой ритма этого кейса, канон
# §4.2 П4: новый узел сцена не вводит). Пунктир — не узел, а фокус разбора:
# дашбокс обводит сам узел модели, а не пристраивает рядом новый.
POST_H = 560
POST_R1_Y, POST_R1_H = 120, 170
POST_R2_Y, POST_R2_H = 300, 220


def postanovka():
    im = Image.new("RGB", (CW, POST_H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Тот же поток — сегодня разбираем настройки узла модели",
        34, MID, b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "заявка, классификация и ответ устроены как раньше — "
        "холст не меняется", 26, LIGHT, limit=CW - 120, where="подзаголовок")

    gap = 50
    n = 4
    node_w = (CW - 120 - gap * (n - 1)) // n
    xs = [60 + i * (node_w + gap) for i in range(n)]
    nodes = (
        ("Заявка", "вопрос клиента произвольным текстом"),
        ("Классификация", "вопрос относится к пункту справочника"),
        ("Модель отвечает", "по справочнику целиком, одним вызовом"),
        ("Ответ", "уходит обратившемуся напрямую"),
    )
    cy1 = POST_R1_Y + POST_R1_H / 2
    for i, (title, sub) in enumerate(nodes):
        node(d, xs[i], POST_R1_Y, node_w, POST_R1_H, title, sub, tsz=29,
             ssz=27, stroke=TEAL, where=f"шаг {i + 1}")
        if i:
            arrow(d, xs[i - 1] + node_w, cy1, xs[i], cy1, col=TEAL, wd=5)

    model_x, model_w = xs[2], node_w
    pad = 14
    dashbox(d, model_x - pad, POST_R1_Y - pad, model_w + 2 * pad,
            POST_R1_H + 2 * pad, GOLD, width=5, bg=W)

    model_cx = model_x + model_w / 2
    dash_w, dash_h = 900, POST_R2_H
    dash_x = model_cx - dash_w / 2
    card(d, dash_x, POST_R2_Y, dash_w, dash_h, fill=SURF, stroke=GOLD, sw=4)
    ctxt(d, model_cx, POST_R2_Y + 30, "Разбираем сегодня: настройки узла и "
         "промт", 30, DEEP, b=True, limit=dash_w - 60,
         where="новое · название")
    wrapped(d, dash_x + 30, POST_R2_Y + 94, "не новый узел — то, что внутри "
            "уже существующего узла решает, получит клиент на один и тот "
            "же вопрос один и тот же ответ или не получит", 27, LIGHT,
            dash_w - 60, center=model_cx, where="новое · пояснение")
    arrow(d, model_cx, POST_R2_Y, model_cx, POST_R1_Y + POST_R1_H + pad,
          col=GOLD, wd=5, dash=True)

    save(im, "k5-shema-postanovka.png")


# Высота подобрана под порог приёма: 842 px при ширине 2400 — последняя
# высота, при которой схема встаёт на слайд В ПОЛНУЮ ширину и не ужимается.
# На первом прогоне холст был 880 px: схема ужималась, пол кегля падал, а
# нижняя строка третьего столбца садилась на полосу сравнения.
H = 842
COL_W = 733
COL_X = (60, 833, 1606)

# Раскраска десяти повторов: «золото» — назван ответ, «пусто» — числа не дали,
# «тил» — ответ про другой пункт базы.
STOLBTSY = (
    dict(
        shapka="Разброс",
        vopros="заплатил 24 000 ₽ за 10 занятий, прошло 3 — сколько вернут? "
               "Формулы пересчёта в базе нет",
        tochki=("золото",) * 3 + ("пусто",) * 6 + ("тил",),
        pod="три разных ответа на один и тот же текст",
        chislo="3 исхода из 10",
        chislo_pod="повторов одного вопроса",
        klient="трое узнают сумму, шестеро слышат «обратитесь к администратору», "
               "один получает ответ не на свой вопрос",
    ),
    dict(
        shapka="Устойчивая ошибка",
        vopros="возврат ровно на 3000 ₽ — через руководителя или обычным порядком?",
        tochki=("золото",) * 10,
        pod="один и тот же ответ десять раз подряд",
        chislo="10 из 10",
        chislo_pod="ответов одинаковы — и все неверны",
        klient="в базе сказано «для сумм выше 3000», а ровно 3000 выше 3000 не "
               "является; один повтор вдобавок переврал сумму клиента",
    ),
    dict(
        shapka="Устойчивое противоречие",
        vopros="пропустил занятие без предупреждения — когда пересдача? В базе два "
               "пункта в напряжении",
        tochki=("золото",) * 10,
        pod="оба пункта названы устойчиво, ноль расхождений",
        chislo="10 из 10",
        chislo_pod="ответов противоречат сами себе",
        klient="«бесплатная пересдача не предоставляется. Пересдачи проводятся "
               "каждую вторую субботу месяца»",
    ),
)


def tochki(d, cx, y, vidy, r=18, shag=66):
    """Десять повторов — десятью точками. Пустая точка рисуется кольцом, а не
    бледной заливкой: бледного в палитре нет, и обводка честнее читается с
    задних рядов."""
    x0 = cx - (len(vidy) - 1) * shag / 2
    for i, v in enumerate(vidy):
        x = x0 + i * shag
        if v == "пусто":
            d.ellipse([x - r, y - r, x + r, y + r], outline=LIGHT, width=4)
        else:
            d.ellipse([x - r, y - r, x + r, y + r],
                      fill=GOLD if v == "золото" else TEAL)


def tri_ishoda():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Три вида негодности ответа, который уходит клиенту", 34, MID,
        b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "три вопроса, по десять повторов одного и того же текста, "
        "температура ноль, одна и та же база в промте", 26, LIGHT, limit=CW - 120,
        where="подзаголовок")

    for x, s in zip(COL_X, STOLBTSY):
        cx = x + COL_W / 2
        card(d, x, 110, COL_W, 64, fill=SURF, stroke=LIGHT, sw=4)
        ctxt(d, cx, 124, s["shapka"], 32, DEEP, b=True, limit=COL_W - 36,
             where=f"шапка · {s['shapka']}")

        card(d, x, 188, COL_W, 120, fill=W, stroke=LIGHT, sw=3)
        wrapped(d, x + 26, 206, s["vopros"], 25, DEEP, COL_W - 52, center=cx,
                where=f"вопрос · {s['shapka']}")

        # Полоса под точками: без неё десять кружков висят на голом белом и
        # читаются украшением, а не одним замером из десяти повторов.
        card(d, x, 322, COL_W, 58, fill=SURF, stroke=LIGHT, sw=2, r=12)
        tochki(d, cx, 351, s["tochki"])
        wrapped(d, x + 26, 386, s["pod"], 25, LIGHT, COL_W - 52, center=cx,
                where=f"подпись к точкам · {s['shapka']}")

        plashka(d, x, 432, COL_W, 146, s["chislo"], s["chislo_pod"],
                nsz=46, lsz=25, tone="glavnoe", where=f"плашка · {s['shapka']}")

        wrapped(d, x + 26, 600, s["klient"], 25, DEEP, COL_W - 52, center=cx,
                where=f"что получает клиент · {s['shapka']}")

    card(d, 60, 720, CW - 120, 98, fill=SURF, stroke=TEAL, sw=5)
    wrapped(d, 100, 740, "Для сравнения — тот же процесс на вопросе, ответ на который "
            "целиком лежит в базе: 25 повторов, 0 расхождений по существу. "
            "Устойчивость есть там, где ответ надо найти, и пропадает там, где его "
            "надо составить.", 28, DEEP, CW - 200, center=CW / 2,
            where="полоса сравнения")
    save(im, "k5-shema-tri-ishoda.png")


if __name__ == "__main__":
    postanovka()
    tri_ishoda()
    pt_report("схема Кейса 5")
    audit_sources()

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Диаграмма охвата кадра s13a (issue #278, §10.1 норматива переделки PR #278)
— на шаблоне `tools/presentation-build/analitika.py`.

ЗАЧЕМ ЭТОТ ФАЙЛ. Кадр s13a был `type: analitika` во фронтматтере, но внутри
нёс `row_blocks` — прозаический список по четырём программам (лёгкое, шейка
матки, колоректальный, простата), то есть переименованный набор кейсов, а
не статистику. Владелец (цитата §10.1 норматива): «обзорный кадр раздела
обязан быть статистикой: диаграмма/плашки по странам (охват программой,
участие ИИ, эффект), не перечень историй». Этот прогон рисует ровно эту
диаграмму — охват по странам; участие ИИ и честный пробел по эффекту
вынесены в плашки `blocks:` самого файла кадра, не сюда.

ОТКУДА ЧИСЛА. Каждое значение — из `research/15-skrining-po-stranam.md`,
сводная таблица «Сводная таблица — охват и периодичность классических
программ» (строки раздела), сверено построчно с тем же числом в
`chapter-part1b.md` § «Скрининговые программы по странам и участие ИИ».
Простата и Нидерланды-лёгкое НЕ попали в диаграмму намеренно: у простаты
популяционной программы нет вовсе (это не число охвата, а факт отказа от
программы — назван текстом на кадре, не нулевым столбцом, который читался
бы как измеренный ноль), у Нидерландов-лёгкого программы тоже нет, при
доказанной >10 лет назад эффективности метода (NELSON) — тот же случай.

ЧТО СЧИТАНО ЗДЕСЬ, А НЕ ВЗЯТО ГОТОВЫМ — середина диапазона для четырёх строк,
где источник даёт две цифры одного измерения, а не две разные величины:

    Великобритания, лёгкое      32,4–36%        → 34,2 (длина столбца)
    Корея, лёгкое                51,2–58,6%      → 54,9
    США, колоректальный          63,5–67,4%      → 65,5
    Швеция, шейка матки          83–85%          → 84,0
    Япония, колоректальный       49,1% муж/42,8% жен → 46,0 (среднее, НЕ сумма)

Середина нужна только для длины столбца на диаграмме; подпись у конца
столбца (`podpisi_znacheniy`) несёт исходный диапазон/обе цифры дословно —
то есть зал видит настоящие числа источника, а не середину, и округление
никогда не попадает на кадр как факт.

ЕДИНИЦА ОДНА — процент целевой группы/приглашённых по каждой стране, у
каждой строки свой знаменатель (человек/эглигибл-популяция/застрахованные),
и он стоит в подписи у конца столбца, а не в легенде.

    python3 make_chart_s13a.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / "tools" / "presentation-build"))

import analitika as A  # noqa: E402

ASSETS = HERE / "assets"
VREMENNO = Path("/tmp/chart-s13a")

# (имя строки, число для длины столбца, подпись-знаменатель — не используется
#  здесь как вторая строка оси: передаём None и несём весь текст через
#  podpisi_znacheniy, иначе двухстрочная подпись имени не помещается в
#  полосе высотой 3,0" при десяти строках).
RYADY = [
    ("Лёгкое · США", 18.7, None),
    ("Лёгкое · Великобритания", 34.2, None),
    ("Колоректальный · Япония", 46.0, None),
    ("Шейка матки · Нидерланды", 54.4, None),
    ("Лёгкое · Корея", 54.9, None),
    ("Колоректальный · США", 65.5, None),
    ("Колоректальный · Нидерланды", 67.1, None),
    ("Шейка матки · Великобритания", 68.8, None),
    ("Шейка матки · Австралия", 74.2, None),
    ("Шейка матки · Швеция", 84.0, None),
]

# Подпись у конца столбца — ДОСЛОВНО то, что даёт источник (знаменатель или
# диапазон), не середина, которой нарисована длина.
PODPISI = [
    "18,7% из 12,8 млн (2024)",
    "32,4–36% приглашено из ≈7,5 млн",
    "49,1% муж / 42,8% жен (2022)",
    "54,4% (2024)",
    "51,2–58,6%, два измерения (2023)",
    "63,5–67,4% (2023)",
    "67,1% · 1,5 млн человек (2024)",
    "68,8% из 16,5 млн (2024)",
    "74,2%, тренд снижается (2024)",
    "83–85% (2024)",
]


def proverka_seredin():
    """Середины диапазонов обязаны совпасть с тем, что видит зал на подписи —
    то есть быть настоящей серединой пары чисел источника, не округлением."""
    para = {
        34.2: (32.4, 36.0),
        54.9: (51.2, 58.6),
        65.5: (63.5, 67.4),
        84.0: (83.0, 85.0),
        46.0: (49.1, 42.8),
    }
    for seredina, (a, b) in para.items():
        sch = round((a + b) / 2, 1)
        assert abs(sch - seredina) <= 0.15, (seredina, sch, a, b)
    print("  проверка середин: все пять совпадают с парой чисел источника")


def main():
    proverka_seredin()
    assert len(RYADY) == len(PODPISI) == 10
    VREMENNO.mkdir(parents=True, exist_ok=True)

    spec = A.stolbtsy(
        "Охват скрининговых программ по странам",
        RYADY,
        "% целевой группы/приглашённых · знаменатель у каждой строки свой",
        kegl=10.5, kegl_zagolovka=12, gorizontal=True,
        podpisi_znacheniy=PODPISI)

    # ПРОПОРЦИЯ 4,07 (880×216 точек) — та же мера, что у `s0Xb`/`s0Xc`:
    # полоса аналитического кадра идёт во всю ширину тела (12,23") и берёт
    # 3,00" высоты. Десять строк при кегле 10,5 пт и однострочных подписях
    # имени (без второй строки знаменателя под именем — знаменатель весь
    # ушёл в подпись конца столбца) проверены прогоном: читаются без
    # наложения на полосе этой высоты.
    out = A.narisovat(spec, ASSETS / "s13a-ohvat-po-stranam.png",
                       shirina_pt=880, vysota_pt=216)

    from PIL import Image
    im = Image.open(out)
    print(f"  {out.name}: {im.width}×{im.height} пикс · "
          f"пропорция {im.width / im.height:.2f} · {out.stat().st_size} Б")
    return 0


if __name__ == "__main__":
    sys.exit(main())

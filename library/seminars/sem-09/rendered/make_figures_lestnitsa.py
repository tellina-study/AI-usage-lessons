#!/usr/bin/env python3
"""Лестница дуги С7–С12 для Семинара 9 — `lestnitsa-dugi.png`.

**Это не копия картинки Семинара 8.** Там нарисована ПРЕЖНЯЯ лестница —
девять ступеней в примитивах оркестратора («маршрут», «параллель», «вызов
сабфлоу»). Решением владельца от 2026-10-24 лестница переписана целиком
(`sem-07/KONTSEPTSIYA-7-12.md` §6): ось дуги — что процесс поручает модели и
чем за это ручается, ступеней шесть, по одной на занятие, и каждая ступень
формулируется ВОПРОСОМ, а не названием механизма. Прежние примитивы понижены
в статусе до справочника и осью больше не являются.

Названия шести ступеней и шесть вопросов взяты из таблицы §6 ДОСЛОВНО и
сверены построчно с её копией в `SETKA-KEYSOV-S9.md` («Открытие», экран 2).
Третья ступень — занятие С9 — выделена золотом: она и есть сегодняшняя.

Почему строка одна, а не две. Вопрос ступени — то, что студент унесёт; имя
ступени он забудет вместе с интерфейсом. Поставить вопрос мелкой второй
строкой под именем значило бы сделать несущее подписью к декоративному.
Поэтому имя и вопрос стоят В ОДНУ строку, разным начертанием: имя жирным,
вопрос обычным, через золотую точку.

Запуск: `python3 make_figures_lestnitsa.py` (из `rendered/`).
"""
from make_figures_common import *

# Ступень → (номер, имя, вопрос ступени, занятие). Порядок — снизу вверх.
# Все четыре поля каждой строки — дословно из KONTSEPTSIYA-7-12.md §6.
STUPENI = [
    ("1", "Один вызов",
     "процесс спросил модель и записал ответ — можно ли на это положиться", "С7"),
    ("2", "Цепочка решений",
     "где в цепочке решает модель, а где обязан решать код", "С8"),
    ("3", "Ответ человеку",
     "процесс написал человеку — кто поручится, что это можно отправлять", "С9"),
    ("4", "Знание вне промта",
     "откуда процесс берёт факты и почему считает их верными", "С10"),
    ("5", "Модель с полномочиями",
     "модель не только отвечает, но и действует", "С11"),
    ("6", "Качество и выключатель",
     "как узнать, что процесс испортился, и как его остановить", "С12"),
]
SEGODNYA = 2        # индекс ступени этого занятия (третья, С9)


def lestnitsa():
    H = 700
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)

    rh, pitch, step_in, x_right = 76, 92, 86, 2120

    def x_left(i): return 110 + i * step_in
    def y_top(i): return 530 - i * pitch

    # Подступёнки: ломаная, по которой лестница читается лестницей, а не
    # шестью съехавшими полосами.
    # Ломаная кончается НА нижней грани первой ступени: хвост ниже неё
    # читался оборванной линией, а не началом лестницы.
    pts = [(x_left(0) - 8, y_top(0) + rh)]
    for i in range(6):
        pts.append((x_left(i) - 8, y_top(i) - 8))
        if i < 5:
            pts.append((x_left(i + 1) - 8, y_top(i) - 8))
    d.line(pts, fill=LIGHT, width=3, joint="curve")

    for i, (num, name, vopros, zan) in enumerate(STUPENI):
        x, y = x_left(i), y_top(i)
        w = x_right - x
        today = i == SEGODNYA
        # Заливка — «курс сюда дошёл», включая сегодняшнюю ступень; золотая
        # обводка — «сегодня». Прежде сегодняшняя ступень была белой, как и
        # три будущих, и держалась на одной обводке: на снимке она читалась
        # скорее предстоящей, чем текущей.
        proydena = i <= SEGODNYA
        card(d, x, y, w, rh,
             fill=SURF if proydena else W,
             stroke=GOLD if today else LIGHT, sw=6 if today else 3)
        runs(d, x + 30, y + rh / 2 - 15,
             [(f"{num}. {name}", DEEP if today else MID, True),
              ("  ·  ", GOLD, True),
              (vopros, DEEP if today else LIGHT, False)],
             28, limit=w - 60, where=f"ступень {num}")
        ctxt(d, 2262, y + rh / 2 - 15, zan, 28, GOLD if today else LIGHT,
             b=today, limit=250, where=f"занятие {num}")

    ctxt(d, CW / 2, 20,
         "ось дуги снизу вверх: что процесс поручает модели и чем за это ручается",
         30, MID, b=True, limit=CW - 200, where="подпись оси")
    ctxt(d, CW / 2, 640,
         "золотом обведена ступень этого занятия; заполненные ступени курс уже прошёл",
         24, LIGHT, limit=CW - 200, where="пояснение к выделению")
    save(im, "lestnitsa-dugi.png")


if __name__ == "__main__":
    lestnitsa()
    pt_report("лестница дуги")
    audit_sources()

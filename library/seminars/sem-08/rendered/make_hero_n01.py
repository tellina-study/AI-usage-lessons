#!/usr/bin/env python3
"""Hero-полоса обложки Семинара 8 — `figures/hero-n01.png`.

План «конфетки» §5.2 (`qa/PLAN-KONFETKA-INSTRUKTSII-2026-10-22.md`): на обложке
должно стоять реальное изображение не меньше 40% площади, и первым источником
назван СОБСТВЕННЫЙ артефакт курса — лента уведомлений бота, а не фотография из
стока («Фото из стоков не нужно»). Волна 1в собирает именно это.

Что на полосе, слева направо:

  1. НАСТОЯЩИЙ кадр холста стенда — цепочка Кейса 3, процесс (B), снятая
     2026-10-22 после того, как на ветку «одобрено» добавлен узел отправки
     клиенту (`stend/n8n-screenshots-raw/case3-process-b-s-уzlom-...png`).
     Это не схема и не реконструкция: то, что видно в интерфейсе n8n.
  2. Золотая стрелка — единственный рисованный элемент между двумя кадрами.
  3. Лента Telegram с ДОСЛОВНЫМ текстом настоящего сообщения стенда —
     ровно того, которое отправил узел с кадра слева (выполнение 590).
     Рамка чата рисованная — см. честную пометку в шапке
     `make_figures_telegram.py`, разрешение владельца 2026-10-22.

     Пара подобрана так, чтобы стрелка между кадрами не врала: слева —
     цепочка Кейса 3, справа — сообщение, которое ОНА же и отправила, в том
     чате, куда оно в самом деле ушло (личная переписка с клиентом, не
     «Уведомления учебного центра» — туда идут сообщения координатору,
     Кейсы 1 и 4). Первый вариант полосы ставил рядом сообщение Кейса 1 под
     шапкой чата координатора — картинка была плотнее, но стрелка в ней
     утверждала причинность, которой нет.

Почему именно эта пара кадров. Обложка называет вопрос занятия — «где решает
модель, а где должен код». Слева на холсте этот вопрос виден буквально: узел
`Amount over threshold?` разводит ветки `true`/`false`, и ответ даёт условие в
коде, а не модель. Справа — то, что из этого вышло у человека в телефоне. Между
ними ничего не надо объяснять словами, и обложка их и не содержит: весь текст
на ней уже написан жанром `cover_centered`, hero идёт под ним.

ГЕОМЕТРИЯ. Жанр обложки (`tools/seminar-build/genres.py`, `_cover_bg`) кладёт
hero во ВСЮ ширину полотна снизу, а высоту берёт из пропорции самого файла:
`fh = 13.333 · ih / iw`. Отсюда пропорция здесь не вкусовая, а вычисленная:

    нужно fh ≥ 0,40 · 7,5 = 3,00″   (требование §5.2 «не меньше 40%»)
    нужно fh ≤ 7,5 − 3,60 − 0,20 ≈ 3,70″ (иначе hero съедает строку-интригу:
                                          подзаголовок начинается на y = 2,34″)
    выбрано fh = 3,15″ (42% высоты) ⇒ пропорция 13,333 / 3,15 = 4,233

При ширине 2800 px это 661 px высоты. Плотность получается 210 px на дюйм, и
кегль текста в ленте Telegram (28 px в исходном кадре 1400 px, после вписывания
в 1160 px — 23 px) выходит 7,9 pt — выше пола 7,5 pt, который план §3.6 держит
на скринах. Если менять ширину полосы или долю ленты, пересчитывать надо ОБА
числа: пропорцию и этот кегль.

Запуск: `python3 make_hero_n01.py` (из `rendered/`). Файл только пишется —
обложка `slides/n01-oblozhka.md` этим скриптом не трогается, постановку кадра
на слайд делает волна подключения.
"""
from pathlib import Path

from PIL import Image, ImageDraw

import make_figures_telegram as TG

HERE = Path(__file__).resolve().parent
RAW = HERE.parent / "stend" / "n8n-screenshots-raw"
OUT = HERE / "figures"

CANVAS_SHOT = RAW / "case3-process-b-s-uzlom-klientu-2026-10-22-krop.png"

W, H = 2800, 661
BG = (18, 30, 54)               # тёмная подложка под градиент обложки Ocean
GOLD = (0xF0, 0xAB, 0x00)

SHOT_W = 1400                   # ширина кадра холста на полосе
FEED_W = 1160                   # ширина ленты Telegram на полосе
MARGIN = 60


def rounded(img, radius):
    """Скругление углов вставляемого кадра: прямой угол на тёмной подложке
    читается как обрез, скруглённый — как карточка."""
    mask = Image.new("L", img.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, img.width - 1, img.height - 1),
                                           radius=radius, fill=255)
    out = Image.new("RGBA", img.size)
    out.paste(img.convert("RGB"), (0, 0), mask)
    return out


def arrow(dr, x0, x1, y):
    """Стрелка «отсюда — туда». Золото на обложке курса появляется ровно один
    раз (правило палитры), и это его единственное появление на полосе."""
    dr.line((x0, y, x1 - 26, y), fill=GOLD, width=7)
    dr.polygon([(x1, y), (x1 - 30, y - 17), (x1 - 30, y + 17)], fill=GOLD)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    img = Image.new("RGB", (W, H), BG)
    dr = ImageDraw.Draw(img)

    # ── слева: настоящий кадр холста стенда ────────────────────────────────
    shot = Image.open(CANVAS_SHOT).convert("RGB")
    sh = int(shot.height * SHOT_W / shot.width)
    shot = shot.resize((SHOT_W, sh), Image.LANCZOS)
    sy = (H - sh) // 2
    img.paste(rounded(shot, 16), (MARGIN, sy), rounded(shot, 16))

    # ── справа: лента Telegram с дословными текстами ───────────────────────
    # Сообщение клиенту с ветки «одобрено» (выполнение 590) — то самое, что
    # отправил узел `Notify client (Telegram)` с кадра слева. Текст берётся из
    # того же модуля, что и отдельные кадры: разной правды о тексте сообщения
    # в двух файлах быть не должно.
    feed = TG.canvas(TG.CHAT_NAME_CLIENT, TG.CHAT_SUB_CLIENT, [
        dict(text=TG.T_K3, time_s="13:04"),
    ], tail=28)
    fh = int(feed.height * FEED_W / feed.width)
    feed = feed.resize((FEED_W, fh), Image.LANCZOS)
    fx = W - MARGIN - FEED_W
    fy = (H - fh) // 2
    if fh > H - 2 * 24:                      # лента выше полосы — обрезать снизу,
        feed = feed.crop((0, 0, FEED_W, H - 48))   # шапка чата важнее последней строки
        fh = H - 48
        fy = 24
    img.paste(rounded(feed, 16), (fx, fy), rounded(feed, 16))

    # ── стрелка между ними ────────────────────────────────────────────────
    arrow(dr, MARGIN + SHOT_W + 24, fx - 24, H // 2)

    p = OUT / "hero-n01.png"
    img.save(p)
    w, h = Image.open(p).size
    fh_in = 13.333 * h / w
    print(f"{p.name}  {w}×{h}  пропорция {w / h:.3f}  "
          f"высота на слайде {fh_in:.2f}″ = {fh_in / 7.5 * 100:.0f}% высоты")


if __name__ == "__main__":
    main()

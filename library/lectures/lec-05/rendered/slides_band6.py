X0 = 0.55            # левый край полосы-подписи
LBL_W = 1.26         # ширина колонки-подписи
GAPX = 0.16
CX = X0 + LBL_W + GAPX          # левый край колонки содержания
RIGHT = 12.80
CW = RIGHT - CX                 # ≈ 10.83

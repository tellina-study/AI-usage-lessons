#!/usr/bin/env python3
"""Схема Кейса 3 — `k3-shema-tsikl.png`.

Генератор → проверяющий → переделка, с потолком попыток и ветвью «не сошлось».

Четыре вещи, без которых цикл на кадре — просто четыре коробки по кругу, и
каждая из них на схеме названа:

  ВХОД     — золотая точка у вопроса клиента: видно, откуда круг начинается;
  ВОЗВРАТ  — стрелка от переделки обратно в генератор, подписанная тем, что
             на самом деле происходит: заново проверяются и те требования,
             которые уже проходили (те самые «якоря» из сетки, такт
             «Решение»);
  ПОТОЛОК  — три попытки, выставленные вручную: у встроенного цикла нет
             предохранителя по умолчанию, и без счётчика он не остановится
             сам (сетка, такт «Нюансы», п. 2);
  ВЫХОД «НЕ СОШЛОСЬ» — вопрос уходит Ольге, а не висит в круге.

Нижняя строка говорит об устройстве, а не об исходе: проверяющий — такой же
участник, как генератор, и ошибается он так же. Измеренный случай, которым
это подтверждено на стенде (точного совпадения подстроки не хватило, чтобы
узнать верный по смыслу ответ в другом падеже), со схемы СНЯТ: он принадлежит
такту нюансов, а схема идёт на такте устройства, за девять кадров до него.

Судьи-модели на схеме нет умышленно: она не часть устройства решения, она
измеренная АЛЬТЕРНАТИВА ему, и её числа (ложно забраковала 5 из 5 верных
ответов, два вызова модели на попытку против одного) живут на кадрах разбора
версий, а не внутри схемы цикла.

Запуск: `python3 make_figures_k3.py` (из `rendered/`).
"""
from make_figures_common import *

H = 820
R1_Y, R1_H = 140, 190         # ряд процесса: четыре шага, не больше
R2_Y, R2_H = 440, 150         # ряд исходов и переделки
JUNC = 368                    # высота перемычки ветви «не сошлось»


def tsikl():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Цикл проверки ответа перед отправкой", 34, MID, b=True,
        limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "генератор пишет, проверяющий решает, переделка возвращает — "
        "и у круга есть потолок", 26, LIGHT, limit=CW - 120, where="подзаголовок")

    cy1 = R1_Y + R1_H / 2
    # Вход помечен золотом и стоит НАД названием, а не под ним: внизу он
    # жался к нижней грани и читался подписью к слову «клиента».
    card(d, 60, R1_Y, 300, R1_H)
    d.ellipse([122, R1_Y + 36, 146, R1_Y + 60], fill=GOLD)
    txt(d, 156, R1_Y + 34, "вход", 25, GOLD, b=True, limit=160, where="метка входа")
    wrapped(d, 82, R1_Y + 86, "Вопрос клиента", 30, DEEP, 256, b=True,
            center=210, where="вход · название")

    node(d, 420, R1_Y, 520, R1_H, "Генератор", "модель пишет ответ клиенту",
         where="генератор")
    node(d, 1000, R1_Y, 660, R1_H, "Проверяющий",
         "код сверяет пять заранее записанных требований к ответу", ssz=25,
         where="проверяющий")
    card(d, 1720, R1_Y, 600, R1_H, fill=SURF, stroke=TEAL, sw=5)
    ctxt(d, 2020, R1_Y + 50, "Сошлось?", 36, DEEP, b=True, limit=560,
         where="развилка · название")
    ctxt(d, 2020, R1_Y + 108, "решает код по заданным условиям", 25, LIGHT,
         limit=560, where="развилка · пояснение")

    for x1, x2 in ((360, 420), (940, 1000), (1660, 1720)):
        arrow(d, x1, cy1, x2, cy1, col=MID, wd=5)

    # Ветвь «да» — вниз, прямо под развилкой.
    arrow(d, 2120, R1_Y + R1_H, 2120, R2_Y - 6, col=MID, wd=5)
    txt(d, 2146, 378, "да", 25, MID, b=True, limit=100, where="метка «да»")
    # Два ИСХОДА круга обведены тилом — тем же, чем развилка: выход из цикла
    # читается как выход, а не как ещё один его шаг. Переделка остаётся
    # обычной: она не исход, она возврат.
    node(d, 1720, R2_Y, 600, R2_H, "Отправка клиенту", "", tsz=30,
         stroke=TEAL, sw=5, where="исход «отправка»")

    # Ветвь «не сошлось» — одна перемычка влево, два спуска с неё.
    d.line([1900, R1_Y + R1_H, 1900, JUNC], fill=MID, width=5)
    d.line([760, JUNC, 1900, JUNC], fill=MID, width=5)
    txt(d, 1788, 330, "нет", 25, MID, b=True, limit=110, where="метка «нет»")
    arrow(d, 1330, JUNC, 1330, R2_Y - 6, col=MID, wd=5)
    txt(d, 1356, 378, "потолок исчерпан", 25, MID, limit=320,
        where="метка ветви Ольги")
    arrow(d, 760, JUNC, 760, R2_Y - 6, col=MID, wd=5)
    txt(d, 786, 378, "попытка не последняя", 25, MID, limit=400,
        where="метка ветви переделки")

    card(d, 1000, R2_Y, 660, R2_H, stroke=TEAL, sw=5)
    person(d, 1098, R2_Y + 56, 26, LIGHT)
    ctxt(d, 1390, R2_Y + 38, "Передать Ольге", 30, DEEP, b=True, limit=520,
         where="исход «Ольге» · название")
    ctxt(d, 1390, R2_Y + 84, "вопрос уходит человеку", 25, LIGHT, limit=520,
         where="исход «Ольге» · пояснение")

    node(d, 420, R2_Y, 520, R2_H, "Переделка", "", tsz=30, where="переделка")

    # Возврат: стрелка снизу вверх и подпись, которая говорит, ЧТО именно
    # повторяется — иначе круг выглядит повтором одного шага.
    arrow(d, 560, R2_Y, 560, R1_Y + R1_H + 6, col=GOLD, wd=5)
    wrapped(d, 70, 352, "снова — и все уже пройденные требования заново", 25,
            GOLD, 420, where="подпись возврата")

    plashka(d, 60, 636, 700, 168, "три попытки",
            "потолок выставлен вручную: без счётчика цикл не остановится сам",
            nsz=44, tone="glavnoe", where="плашка потолка")
    card(d, 820, 636, 1500, 168, fill=SURF, stroke=LIGHT)
    # Вторая половина этой строки несла «1 случай из 6» — нюанс такта `n42`,
    # выложенный на кадре `n33`. Снято: утверждение об устройстве остаётся,
    # измеренный случай уходит в свой такт.
    wrapped(d, 860, 664, "Цикл надёжен ровно настолько, насколько надёжен сам "
            "проверяющий: проверяющего нужно проверять тем же вниманием, что и "
            "генератора.", 29, DEEP, 1420, where="оговорка о проверяющем")
    save(im, "k3-shema-tsikl.png")


if __name__ == "__main__":
    tsikl()
    pt_report("схема Кейса 3")
    audit_sources()

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Маркеры передачи -- из ТЕЛА и ЗАМЕТОК во ФРОНТМАТТЕР (#229).

ЗАЧЕМ. Маркеры `<!-- СЛИТО ИЗ sNN -->` я поставил в видимое тело, считая, что
html-комментарий сборка не напечатает. **НАПЕЧАТАЛА.** Прямая проверка текста
собранного PDF: маркер стоит на 6 страницах из 84 -- то есть зал читал бы
служебную записку, а каждый мой замер веса был завышен на её длину. Это ровно
тот класс, который `CLAUDE.md` запрещает отдельно («scaffold-фразы в visible
body»), и ровно тот, на котором этот круг уже ошибался: ЧИСЛО СВЕЖЕЕ, ВЕРНОЕ
И НЕ ПРО ТО -- мерилась страница вместе со строительными лесами.

Поймано не прогоном веса (он честно считал слова, включая маркер), а вопросом
«а что именно напечаталось» -- чтением текста PDF.

КУДА. Во фронтматтер строкой-комментарием: его разборщик пропускает по
построению (`^([a-z_]+):` не совпадает с `# ...`), в манифест он не попадает,
на экран тоже. Границу половин в теле обозначать нечем -- она восстанавливается
по файлу второй половины в `_snyato/`, как и говорит её README.
"""
import glob
import io
import os
import re

MARKER = re.compile(r'\n*<!--.*?-->\n*', re.S)


def main():
    vsego = 0
    for p in sorted(glob.glob('slides/s*.md')):
        t = io.open(p, encoding='utf-8').read()
        sh = t.split('---\n')
        fm, ost = sh[1], '---\n'.join(sh[2:])
        nashli = MARKER.findall(ost)
        if not nashli:
            continue
        # из чего собран кадр -- в одну служебную строку фронтматтера
        ids = sorted(set(re.findall(r'ИЗ (s\d+[a-z]*)', ' '.join(nashli))))
        ost2 = MARKER.sub('\n\n', ost)
        ost2 = re.sub(r'\n{3,}', '\n\n', ost2)
        if ids:
            nota = ('# СВЁРТКА (#229): тело кадра держит ДВЕ половины пары, '
                    'приписанные одна к другой и НЕ СЖАТЫЕ. Вторая пришла из %s '
                    '(файл в slides/_snyato/). Свести в одну форму §5.13 и '
                    'объявить pol_slov заново обязана сессия содержания.\n'
                    % ', '.join(ids))
        else:
            nota = ('# ПЕРЕДАЧА (#229): по этому кадру есть заказ сессии '
                    'содержания -- см. rework/PEREDACHA-SESSIYAM-SODERZHANIYA.md §5.\n')
        fm2 = nota + fm
        io.open(p, 'w', encoding='utf-8').write('---\n' + fm2 + '---\n' + ost2)
        vsego += len(nashli)
        print('  %-7s снято маркеров %d%s' % (os.path.basename(p).split('-')[0],
                                              len(nashli),
                                              ('  (из %s)' % ', '.join(ids)) if ids else ''))
    print('итого снято маркеров из тела и заметок: %d' % vsego)


if __name__ == '__main__':
    main()

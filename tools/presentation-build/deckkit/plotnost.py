# -*- coding: utf-8 -*-
"""ПЛОТНОСТЬ ТЕКСТА КАДРА — счёт слов видимого слоя прямо в сборке.

ЗАЧЕМ ЭТОТ МОДУЛЬ ЕСТЬ. Предел «≤90 слов медиана, ни одного кадра тяжелее
140» (`../trebovaniya-k-soderzhaniyu-forma.md` §5.12, ужесточён §11.2) был
записан как ЦЕЛЬ, которую никто не проверял перед докладом о готовности, —
и четыре круга правок раздела 1 Лекции 7 прошли с медианой 156 и максимумом
267. Канон после этого сказал прямо: «Сборка обязана считать слова видимого
слоя каждого кадра `case` и выдавать блокирующее предупреждение при медиане
>90 или кадре >140 — так же, как уже блокируют `[высота]`/`[кегль]`».

ЧТО СЧИТАЕТСЯ ВИДИМЫМ СЛОЕМ. Заголовок · тело кадра · подписи, значения и
оговорки плашек · подписи рядов, шагов и сама подпись схемы · столбцы ·
строчные блоки · лестница · дорожки · подвал источника. То есть всё, что
зал читает с экрана. НЕ считается бухгалтерия файла (`pol_slov`,
`razbor_part`, `media_note`, `assertion`, комментарии) и заметки лектора:
первое зал не видит, второе у заметок своя норма (500–800 слов,
`../../lecture-production/stroenie-i-povestvovanie.md` §10).

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ЗАМЕРА ПО PDF — и почему оба нужны. Здесь считается
ВХОД сборки, а `render_sec.py --zamer` считает ВЫХОД, собранный PDF. Это
разные числа по построению, и расхождение между ними невелико, но реально:
на разделе 1 Лекции 7 (14 кадров, 2026-10-19) счёт по входу дал медиану на
несколько слов ниже, чем счёт по PDF, потому что LibreOffice разбивает
часть длинных значений плашек переносом, а дефис в «8–21» PDF отдаёт одним
словом. **Решает PDF** — то же правило, что у пола кегля (§11 «мера берётся
с вывода, а не со входа»). Этот модуль нужен для другого: чтобы кадр,
переваливший предел, не доехал до рендера молча, а сказал об этом в той же
сборке, где его правят.

ПОЧЕМУ МЕДИАНА СЧИТАЕТСЯ ТОЛЬКО ПО `case`. Дивайдер, карта стадии и
аналитический кадр устроены иначе и в один знаменатель с разбором не
складываются; канон говорит про «каждого кадра `case`». Предел на ОДИН
кадр при этом применяется ко всем содержательным типам: 140 слов на экране
нечитаемы независимо от того, что на кадре написано в поле `type`.
"""
import re
import statistics

from . import report

PREDEL_KADR = 140       # ни один содержательный кадр не тяжелее
TSEL_MEDIANA = 90       # медиана кадров `case` раздела

# Типы, у которых предел на один кадр не применяется: обложка и дивайдер
# несут заголовок и две строки, и мерить их нечем.
BEZ_PREDELA = {"cover", "divider"}

# Поля фронтматтера, НАБРАННЫЕ НА КАДРЕ.
VIDIMYE_POLYA = ("title", "blocks", "scheme", "source", "columns",
                 "row_blocks", "ladder", "tracks", "media_label",
                 "media_2_label", "media_caption")


def _slova(uzel):
    """Слова вложенной структуры YAML — разметка снята."""
    if uzel is None:
        return 0
    if isinstance(uzel, bool):
        return 0
    if isinstance(uzel, (int, float)):
        return 1
    if isinstance(uzel, str):
        return len(re.sub(r"[*_#`]", " ", uzel).split())
    if isinstance(uzel, dict):
        return sum(_slova(v) for k, v in uzel.items()
                   if k not in ("ai", "arrows", "key", "kind"))
    if isinstance(uzel, (list, tuple)):
        return sum(_slova(v) for v in uzel)
    return 0


def slov_na_kadre(sl):
    """Слов видимого слоя одного кадра: фронтматтер плюс тело."""
    telo = re.sub(r"[*_#`]", " ", sl.body or "")
    return sum(_slova(sl.meta.get(k)) for k in VIDIMYE_POLYA) + len(telo.split())


def proverit_kadr(sl):
    """Предел на ОДИН кадр. Возвращает посчитанное число."""
    n = slov_na_kadre(sl)
    kind = str(sl.meta.get("type") or "case").strip()
    if kind not in BEZ_PREDELA and n > PREDEL_KADR:
        report.warn(
            f"[плотность] {sl.sid}: {n} слов видимого слоя при пределе "
            f"{PREDEL_KADR} — кадр читается не с экрана, а с листа; "
            "рассуждение о замере идёт в заметки (§7.1), знаменатель "
            "остаётся на кадре (§7.2)")
    return n, kind


def proverit_mediany(schet):
    """Медиана по кадрам `case`. `schet` — [(sid, слов, тип), …].

    Молчит, когда кадров `case` нет вовсе: медиана пустого множества —
    не ноль, а отсутствие замера, и объявлять её нулём значило бы отчитаться
    чистотой там, где не мерили.
    """
    razbory = [n for _, n, kind in schet if kind == "case"]
    if not razbory:
        return None
    m = statistics.median(razbory)
    if m > TSEL_MEDIANA:
        report.warn(
            f"[плотность] медиана кадров разбора {m:g} слов при цели "
            f"{TSEL_MEDIANA} (кадров {len(razbory)}, тяжелее "
            f"{PREDEL_KADR} — {sum(1 for n in razbory if n > PREDEL_KADR)})")
    return m

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Пол слов на кадре — по СОБРАННОМУ PDF, с объявленными полами и причинами.

Чего не делал ни один прогон до этого. `render_sec.py` печатает слова по
страницам и медиану, но ни с каким полом их не сравнивает. `ocenka.py`
сравнивает — по файлу кадра, то есть оценкой, а числа отчёта оценкой быть
не могут. Между ними пролегал ровно тот зазор, в котором и живёт вопрос
приёмки: «взят ли предел на каждом кадре».

ПОЧЕМУ ПОЛ ОТВЕЧАЕТ ПЕРЕД PDF, А НЕ ПЕРЕД ОЦЕНКОЙ. Иначе объявленный пол
начинает покрывать не кадр, а чужую погрешность: кадр `s12` весит 117 слов
по PDF и 122 по оценке, и пол ему пришлось бы объявить 125 — то есть
двадцать слов запаса там, где кадру нужно ноль. Пол — это РАЗРЕШЕНИЕ, и
лишнее разрешение кадр со временем зарастает.

ЧТО ПЕЧАТАЕТСЯ И ПОЧЕМУ ИМЕННО ТАК. Объявленный пол выводится ВМЕСТЕ С
ПРИЧИНОЙ. Решение О10 принимает человек, а прогон его исполняет; без
причины строка «кадр выше 75» читается как дефект там, где это записанное
решение, и приёмка начинает блокировать по решениям. Причина живёт в
комментарии YAML той же строки, поэтому читается сырая строка файла:
разбор YAML комментарии снимает.

    python3 pol_slov_po_pdf.py
    python3 pol_slov_po_pdf.py --pdf lec-07-karkas.pdf
"""
import argparse
import os
import statistics
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[4] / "tools" / "presentation-build"))

import ocenka                                                # noqa: E402

POL_PROCHIH = 75          # медиана деки; норма круга #229, замер 26 дек
ZAPAS_PREDEL = 8          # запас объявленного пола над замером по PDF
PREDEL = 140              # 95-й процентиль ЭТАЛОННЫХ страниц — отметка замера,
#                           НЕ предел нашей деки с 2026-10-15 (решение О20)


def kadrov_posle_sborki(pdf):
    """Сколько файлов кадров правлено ПОСЛЕ коммита, которым собран PDF."""
    def g(*a):
        return subprocess.run(["git", *a], capture_output=True, text=True,
                              cwd=str(HERE)).stdout.strip()
    kom = g("log", "-1", "--format=%h", "--", str(pdf))
    if not kom:
        return 0
    return len([x for x in g("diff", "--name-only", f"{kom}..HEAD",
                             "--", "slides/").splitlines() if x.strip()])


def proiskhozhdenie_pdf(pdf):
    """Чем и когда собран PDF, и сколько кадров правлено ПОСЛЕ него.

    Эту строку просили две сессии в один час, и обе — после того, как на
    ней обожглись. Цена названа живыми случаями: `s61` перевесил свой
    объявленный пол 132 на шесть слов, и ни один прогон этого не показал
    (строка разряда пришла через четыре минуты после сборки); `s97` был
    подтянут со 140 до 132 по весу 126, снятому до того, как слияние
    принесло кадру подвал в десять слов, — на свежем PDF он весит 137, и
    пол 140 давал норму. Три ложные находки за вечер, все три из одного
    места: число «по собранному PDF» ничего не значит, пока не сказано,
    КАКОЙ ПDF собран и что правлено после него.

    Поэтому возраст входа печатается не в минутах файла, а коммитом: минуты
    говорят, когда файл записан, а коммит — какое состояние кадров в нём
    застыло.

    И формулировка правила — от сессии разделов 7–10, она точнее первой моей.
    Различать надо не «посылал числа / не посылал», а **назвал ли голову
    входа**: с названной головой число остаётся предложением перемерить, без
    неё становится утверждением, по которому работают. Из пяти ложных находок
    вечера по четырём кто-то сработал, и ровно у этих четырёх голова названа
    не была; две остановились на перемере, потому что были названы
    проверяемыми. Числа с частичных сборок посылать НАДО — просто с головой."""
    def g(*a):
        return subprocess.run(["git", *a], capture_output=True, text=True,
                              cwd=str(HERE)).stdout.strip()
    kom = g("log", "-1", "--format=%h %ci", "--", str(pdf))
    if not kom:
        return "PDF не под версией — чем он собран, сказать нечем"
    sha = kom.split()[0]
    posle = g("diff", "--name-only", f"{sha}..HEAD", "--", "slides/")
    n = len([x for x in posle.splitlines() if x.strip()])
    s = f"PDF собран коммитом {kom}"
    if n:
        s += (f" · после него правлено кадров: {n} — веса ниже относятся к "
              f"тому состоянию, и мерить по ним нельзя")
    else:
        s += " · кадров после него не правлено"
    return s


def golova():
    """Голова, с которой считано, и расходится ли она со сводной.

    Зачем в выводе. Список заданий, собранный с устаревшей головы, СОЗДАЁТ
    работу вместо того, чтобы её закрывать: я разослала четырём сессиям
    полы, из которых раздел 6 объявил шесть ещё коммитом `cef39815`, а
    веса раздела 2 к тому времени подняла строка разряда — две сессии
    получили задание на уже сделанное. Проверка свежести печатает возраст
    PDF ровно по этой причине; голова дерева — та же мера для файлов."""
    def g(*a):
        return subprocess.run(["git", *a], capture_output=True, text=True,
                              cwd=str(HERE)).stdout.strip()
    nasha = g("rev-parse", "--short", "HEAD")
    gryaz = bool(g("status", "--porcelain", "--", str(HERE / "slides")))
    svod = g("rev-parse", "--short", "origin/issue-229-diyeta-svodka")
    slito = g("merge-base", "--is-merged", "origin/issue-229-diyeta-svodka") 
    otstala = g("rev-list", "--count", "HEAD..origin/issue-229-diyeta-svodka")
    s = f"считано с головы {nasha}" + (" + НЕЗАКОММИЧЕННЫЕ правки кадров" if gryaz else "")
    if svod:
        s += f" · сводная {svod}"
        if otstala and otstala != "0":
            s += (f" · ОТСТАЛА НА {otstala} коммитов — списки с этой головы "
                  "рассылать нельзя, они создадут работу на уже сделанном")
        else:
            s += " · совпадает со сводной"
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pdf", default="lec-07-karkas.pdf")
    a = ap.parse_args()
    pdf = HERE / a.pdf
    if not pdf.exists():
        print(f"ОТКАЗ: PDF {a.pdf} не найден — пол слов по файлам кадров "
              "не мерится, числа отчёта берутся только с собранного")
        return 2
    fayly = ocenka.files_for(set())
    stranitsy = ocenka.pdf_pages(str(pdf))
    print(f"прочитано: кадров {len(fayly)} · страниц PDF {len(stranitsy)} "
          f"({pdf.name})")
    print(f"  {golova()}")
    print(f"  {proiskhozhdenie_pdf(pdf)}")
    if kadrov_posle_sborki(pdf) and os.environ.get("PRIYOMKA_MERIT_USTAREVSHEE"):
        print("  ВНИМАНИЕ: замер идёт по УСТАРЕВШЕМУ PDF по явному "
              "требованию (PRIYOMKA_MERIT_USTAREVSHEE). Каждое число ниже "
              "относится к состоянию кадров на момент сборки, а не к "
              "нынешнему.")
    if len(stranitsy) != len(fayly):
        print(f"ОТКАЗ: страниц {len(stranitsy)}, кадров {len(fayly)} — "
              "сопоставить страницу с кадром нечем, сдвиг на один кадр "
              "дал бы замер по чужим страницам")
        return 2

    # Страница сопоставляется кадру ПОРЯДКОМ, и совпадение числа страниц
    # этого не доказывает: склейка из секционных кусков даёт то же число при
    # сдвиге на один кадр, и тогда все числа правдоподобны и все чужие.
    # Поэтому замер не начинается, пока сверка по заголовкам не прошла.
    # ── СВЕЖЕСТЬ — ТОЖЕ ПРЕДУСЛОВИЕ, а не строка, которую надо прочитать.
    # Довод сессии разделов 7–10, её же аргументом против себя: «отказ
    # сильнее печати головы — голову надо прочитать, а отказ читать не
    # надо». Она прочла строку про возраст PDF и всё равно смерила не тот
    # файл: её ложный запас +14 у `s97` пришёл из того, что подвал-рукоятку
    # кадру принесло слияние ПОСЛЕ сборки. Сверка по заголовку этого не
    # ловит по построению — заголовок там не менялся, менялся подвал, —
    # и это главный пробел, а не обратный: случаев «кадр изменился,
    # заголовок нет» большинство (подвал, плашки, тело).
    pravleno = kadrov_posle_sborki(pdf)
    if pravleno and not os.environ.get("PRIYOMKA_MERIT_USTAREVSHEE"):
        print(f"ОТКАЗ: после сборки этого PDF правлено кадров: {pravleno}. "
              "Веса относились бы к прошлому состоянию деки, и ни одна "
              "сверка по заголовку этого не поймает — заголовок при правке "
              "подвала, плашек или тела не меняется.")
        print("  Пересобрать деку. Если замер по устаревшему нужен "
              "осознанно — PRIYOMKA_MERIT_USTAREVSHEE=1, и каждое число "
              "в выводе будет помечено возрастом.")
        return 2

    import sverka_stranits
    rashozhdeniya, _pr = sverka_stranits.proverit(pdf, fayly)
    if rashozhdeniya:
        prichina = rashozhdeniya[0].get("prichina") or (
            f"{len(rashozhdeniya)} страниц стоят не на своём кадре")
        print(f"ОТКАЗ: {prichina} — мерить нельзя, замер пойдёт по чужим "
              "страницам. Подробности: python3 sverka_stranits.py")
        return 2

    rows = [ocenka.ves(f) for f in fayly]
    objavleno, vyshe_pola, vyshe_predela, bez_prichiny = [], [], [], []
    snyato = []
    for r, ves in zip(rows, stranitsy):
        pol, declared = ocenka.pol(r)
        # Три состояния, а не два. Кадр, у которого пол СНЯТ по решению и
        # причина записана полем `pol_snyat`, — это не недосмотр: так стоит
        # `s70`, которому ядро переделывает форму в параллельные дорожки, и
        # объявлять ему число сейчас значило бы оставить то, что никто не
        # перечитает. Прогон обязан различать «пол объявлен» · «пола нет по
        # решению, причина названа» · «пола нет вовсе».
        if not declared and r.get("pol_snyat"):
            snyato.append((r["id"], ves, r["pol_snyat"]))
            continue
        if declared:
            objavleno.append((r["id"], pol, ves, r["prichina"]))
            if not r["prichina"]:
                bez_prichiny.append(r["id"])
        if ves > pol:
            vyshe_pola.append((r["id"], ves, pol, declared, r["izmerennyh"]))
        if ves > PREDEL:
            vyshe_predela.append((r["id"], ves))

    med = statistics.median(stranitsy)
    print(f"\nмедиана {med:g} · максимум {max(stranitsy)} · "
          f"не тяжелее {POL_PROCHIH} — "
          f"{100 * sum(1 for x in stranitsy if x <= POL_PROCHIH) / len(stranitsy):.0f}%")

    print(f"\nПОЛ ОБЪЯВЛЕН у {len(objavleno)} кадров "
          f"(решение О10: принимает человек, прогон исполняет):")
    for sid, pol, ves, why in sorted(objavleno, key=lambda x: -x[2]):
        zapas = pol - ves
        print(f"  {sid:6} пол {pol:3} · вес {ves:3} · запас {zapas:+3} — "
              f"{why or 'ПРИЧИНА НЕ НАЗВАНА'}")

    if snyato:
        print(f"\nПОЛА НЕТ ПО РЕШЕНИЮ у {len(snyato)} кадров — это записанное "
              f"решение, не недосмотр:")
        for sid, ves, why in sorted(snyato, key=lambda x: -x[1]):
            print(f"  {sid:6} вес {ves:3} · пол не объявлен — {why}")

    # Пол с БОЛЬШИМ запасом опаснее отсутствующего: замечание на него не
    # печатается, потому что формально он объявлен. Так у `s97` стоял пол 140
    # при весе 126 — запас +14, и нашла его не проверка, а сессия раздела,
    # прогнав этот же прогон по своим кадрам и посмотрев сорок строк глазами.
    # Глаз для этого не нужен, если список печатать отдельно. Порог +8 взят
    # замером: подтянутые полы деки лежат в +0…+8.
    tolstye = [(s, p_, v, p_ - v) for s, p_, v, _w in objavleno
               if p_ - v > ZAPAS_PREDEL]
    zamechaniy = 0
    if tolstye:
        zamechaniy += len(tolstye)
        print(f"\nЗАМЕЧАНИЕ: запас объявленного пола больше +{ZAPAS_PREDEL} — "
              f"{len(tolstye)} кадров. Пол — это разрешение; пол, выданный с "
              f"запасом, кадр со временем зарастает, и замечания на него нет.")
        print(f"  Запас снят с этого PDF: {proiskhozhdenie_pdf(pdf)}")
        print("  Прежде чем подтягивать пол по этому списку — пересобрать: "
              "два из трёх подтягиваний за вечер оказались по старому весу.")
        for sid, p_, v, z in sorted(tolstye, key=lambda x: -x[3]):
            print(f"  {sid:6} пол {p_:3} при весе {v:3} — запас +{z}")
    if bez_prichiny:
        zamechaniy += len(bez_prichiny)
        print(f"\nЗАМЕЧАНИЕ: пол объявлен без причины — {bez_prichiny}. "
              "Пол без причины неотличим от запаса, взятого на всякий случай")
    ne_objavlen = [x for x in vyshe_pola if not x[3]]
    if ne_objavlen:
        zamechaniy += len(ne_objavlen)
        print(f"\nЗАМЕЧАНИЕ: выше предела {POL_PROCHIH}, пол не объявлен — "
              f"{len(ne_objavlen)} кадров:")
        for sid, ves, pol, _d, nz in ne_objavlen:
            hint = f" · измеренных блоков {nz}" if nz >= 2 else ""
            print(f"  {sid:6} {ves:3} при пределе {pol}{hint}")
    pereves = [x for x in vyshe_pola if x[3]]
    if pereves:
        zamechaniy += len(pereves)
        print("\nЗАМЕЧАНИЕ: тяжелее СВОЕГО ОБЪЯВЛЕННОГО пола — решение есть, "
              "а кадр его перевесил:")
        for sid, ves, pol, _d, _nz in pereves:
            print(f"  {sid:6} {ves} при объявленном {pol}")
    # РЕШЕНИЕ О20 (2026-10-15): предел 140 ДЛЯ НАШЕЙ ДЕКИ ОТМЕНЁН, и это
    # перестало быть замечанием. 140 — 95-й процентиль 26 публичных дек,
    # которые не предполагались читаемыми БЕЗ докладчика; владелец заказал
    # обратное («обязательно слайд должен читаться и без голоса»), и состав
    # обязательного вырос на 30-45 слов. Блокирует теперь ровно два:
    # кадр перевесил СВОЙ объявленный пол, и кадр выше 75 вообще без пола.
    # Список тяжёлых печатается по-прежнему — он измерение, а не порог.
    # Правка сторожа сделана В ТОМ ЖЕ КРУГЕ, что отмена правила: сторож,
    # переживший своё правило, возвращает отменённое (`CLAUDE.md` §8.3).
    if vyshe_predela:
        print(f"\nСПРАВКА (не замечание, решение О20): тяжелее отметки эталонов "
              f"{PREDEL} — {len(vyshe_predela)} кадров: {vyshe_predela}")
        print("  У каждого обязан быть объявленный пол с причиной — это и "
              "проверяется выше; сама тяжесть пределом больше не считается.")
    if med > POL_PROCHIH:
        # НЕ замечание и не блокирующее. Решение О10: норма ≤75 держится по
        # деке, а кадр обязательного состава живёт по своему объявленному
        # полу. Поэтому медиана предъявляется ВМЕСТЕ С арифметикой пола:
        # сколько кадров объявили пол, с какой причиной и с каким запасом.
        # Правка, снимающая базы у чисел ради медианы, — это та правка, за
        # которую деку возвращают, и прогон её не просит.
        sum_zapas = sum(p - v for _s, p, v, _w in objavleno)
        print(f"\nСПРАВКА: медиана {med:g} при норме {POL_PROCHIH}. Разница "
              f"объяснена полами: {len(objavleno)} кадров объявили пол с "
              f"причиной, суммарный запас {sum_zapas:+d} слова, "
              f"тяжелее предела {PREDEL} — {len(vyshe_predela)}.")
        print("  Это предъявление владельцу, а не дефект: снять медиану можно "
              "только сняв базы у чисел, и прогон этого не просит.")

    print(f"\nзамечаний: {zamechaniy}")
    return 1 if zamechaniy else 0


if __name__ == "__main__":
    sys.exit(main())

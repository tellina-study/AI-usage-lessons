# -*- coding: utf-8 -*-
"""Замер оси главы Лекции 7: где названы четыре адреса платежа, где глава про них молчит.

Запуск из каталога главы:  python3 qa/zamer-osi.py

Повод. Проверка повествования нашла P0 по деке: четыре адреса платежа названы вместе ровно
на одном кадре из 99, а два раздела деки не называют ни одного. За этим стоял тот же вопрос
к главе, и его никто не мерил: глава — source of truth, и если она молчит там же, это дефект
источника, а не деки.

ДВА ИЗМЕРЕНИЯ, и путать их нельзя:
  «широко» — слово-адрес встречается в разделе вообще, в любом смысле;
  «по оси» — адрес назван КАК адрес платежа: в том же АБЗАЦЕ стоит маркер оси
             (плат* / ось / адрес / удешевл* / переехал*) либо это жирная подпись «**Навык.**».
Первое измеряет, занимается ли раздел этим предметом. Второе — говорит ли он, что это платёж.
Расхождение между ними и есть находка: разделы предмет несут, а осью его не называют.

Шаблоны якорятся с двух сторон (`re`, не `grep -P` — по кириллице тот даёт ложный ноль) и
проверяются на положительных И отрицательных примерах перед счётом: проверка, показавшая
число, не значит ничего, пока не доказано, что она умеет находить.

Своя же ловушка, на которой первая версия этого замера соврала: файлы-продолжения
(chapter-part2b, 4a, 4b, 4d, 4da, 4f …) заголовка `## Раздел N` не имеют вовсе, и первая
версия их тихо выбрасывала — § 3.8–3.14 и § 8.8–8.16 в счёт не попадали, а числа выглядели
правдоподобно. Имя раздела поэтому переносится ЧЕРЕЗ границу файла. Тот же класс, что файл,
отдавший ноль в счётчике слов.
"""
import io, re, glob

ORDER = ['chapter.md','chapter-part1b.md','chapter-part1c.md','chapter-part2.md','chapter-part2b.md',
         'chapter-part3.md','chapter-part3b.md','chapter-part3c.md','chapter-part3d.md',
         'chapter-part4.md','chapter-part4a.md','chapter-part4b.md','chapter-part4c.md',
         'chapter-part4d.md','chapter-part4da.md','chapter-part4e.md','chapter-part4f.md',
         'chapter-part5.md','chapter-part5b.md','chapter-part5c.md']

# Четыре адреса. Якорь с двух сторон; `re`, не `grep -P`.
ADDR = {
 'внимание': re.compile(r'(?<![А-Яа-яЁё])вниман(?:ие|ия|ием|ию)(?![А-Яа-яЁё])', re.I),
 'навык':    re.compile(r'(?<![А-Яа-яЁё])навык(?:|а|у|ом|и|ов|ам|ами)(?![А-Яа-яЁё])', re.I),
 'подпись':  re.compile(r'(?<![А-Яа-яЁё])подпис(?:ь|и|ью|ей|ям|ями|ывает|ывают|ан|ана|ано|аны|ать)(?![А-Яа-яЁё])', re.I),
 'арбитраж': re.compile(r'(?<![А-Яа-яЁё])арбитраж(?:|а|у|ем|е|ей|и)(?![А-Яа-яЁё])', re.I),
}
# Маркер «это про ось», а не про обычное употребление слова.
AXIS_MARK = re.compile(
 r'(?<![А-Яа-яЁё])(плат(?:ят|им|ят|ёж|ежа|ежом|ежи|ежей|а|ы|ить)|адрес\w*|ось|оси|осью|'
 r'удешевл\w*|удешевил\w*|переехал\w*|переезжа\w*|уехал\w*|цена удешевления)(?![А-Яа-яЁё])', re.I)
BOLD_LABEL = re.compile(r'^\*\*(Внимание|Навык|Подпись|Арбитраж)\.\*\*')

SENT = re.compile(r'[^.!?…]*[.!?…]')

def all_sections(paths):
    """[(имя раздела, текст)] по всем файлам подряд.

    Имя раздела ПЕРЕНОСИТСЯ ЧЕРЕЗ ГРАНИЦУ ФАЙЛА: файлы-продолжения (chapter-part2b, 4a, 4b,
    4d, 4da, 4f …) начинаются с «## Оглавление» и своего заголовка раздела не имеют вовсе.
    Первая версия этого замера их тихо выбрасывала — § 3.8–3.14 и § 8.8–8.16 в счёт не
    попадали, а числа выглядели правдоподобно. Тот же класс, что файл, отдавший ноль
    в счётчике слов.
    """
    out, cur, name = [], [], 'ДО ПЕРВОГО ЗАГОЛОВКА'
    for path in paths:
        text = io.open(path, encoding='utf-8').read()
        text = re.sub(r'\A---\n.*?\n---\n', '', text, flags=re.S)
        skip_toc = False
        for line in text.split('\n'):
            m = re.match(r'^##\s+(.*)$', line)
            if m:
                t = m.group(1).strip()
                if t.lower().startswith(('оглавление', 'карта главы')):
                    skip_toc = True
                    continue
                skip_toc = False
                out.append((name, '\n'.join(cur), path))
                name, cur = t, []
                continue
            if re.match(r'^###\s', line):
                skip_toc = False
            if skip_toc:
                continue
            cur.append(line)
    out.append((name, '\n'.join(cur), path))
    return out

# ------- замер
per_section = {}
for name, body, f in all_sections(ORDER):
        key = re.sub(r'[:,].*$', '', name)[:58]
        d = per_section.setdefault(key, {'файл': f, 'широко': {a:0 for a in ADDR},
                                          'по оси': {a:0 for a in ADDR}, 'вместе': 0, 'примеры': []})
        for line in body.split('\n'):
            if BOLD_LABEL.match(line.strip()):
                a = BOLD_LABEL.match(line.strip()).group(1).lower()
                a = {'внимание':'внимание','навык':'навык','подпись':'подпись','арбитраж':'арбитраж'}[a]
                d['по оси'][a] += 1
        # Окно — АБЗАЦ, а не фраза. Естественная форма называния в этой главе разводит маркер
        # и адрес по соседним фразам («Чем раздел платит по оси главы. Подписью.»), и замер по
        # одной фразе такие места терял — то есть занижал там, где глава как раз всё сделала.
        for s in [x for x in body.split('\n') if x.strip()]:
            hit = [a for a, rx in ADDR.items() if rx.search(s)]
            for a in hit: d['широко'][a] += 1
            if hit and AXIS_MARK.search(s):
                for a in hit: d['по оси'][a] += 1
                if len(hit) >= 3:
                    d['вместе'] += 1
                    if len(d['примеры']) < 2: d['примеры'].append(re.sub(r'\s+',' ',s.strip())[:150])

# ------- контроль: шаблоны обязаны находить на заведомо положительных примерах
assert ADDR['внимание'].search('Платят вниманием, навыком, подписью и арбитражем.')
assert ADDR['арбитраж'].search('объём арбитража вырос на 53 процента')
# Отрицательные контроли — слова, содержащие тот же корень, но НЕ являющиеся адресом:
assert not ADDR['внимание'].search('читает внимательно и не спешит')
assert not ADDR['подпись'].search('подписка на журнал кончилась')
assert not ADDR['навык'].search('навыкнуть к помощнику')  # не форма слова «навык»
assert ADDR['навык'].search('навыками-и-привычками')     # а это настоящее вхождение слова
assert AXIS_MARK.search('ось называет четыре адреса, по которым платят')
assert not AXIS_MARK.search('это измерено движением глаз')
print('шаблоны проверены на положительных и отрицательных примерах: находят и не ложатся\n')

print(f'{"раздел":<56} | широко: вним навык подп арб | по оси: вним навык подп арб | ≥3')
silent, named_all = [], []
for k, d in per_section.items():
    ax = d['по оси']; tot = sum(ax.values())
    b=d['широко']
    print(f'{k:<56} | {b["внимание"]:>12} {b["навык"]:>5} {b["подпись"]:>4} {b["арбитраж"]:>3}'
          f' | {ax["внимание"]:>11} {ax["навык"]:>5} {ax["подпись"]:>4} {ax["арбитраж"]:>3} | {d["вместе"]:>2}')
    if tot == 0: silent.append(k)
    if all(ax[a] > 0 for a in ADDR): named_all.append(k)
print()
print('РАЗДЕЛОВ ВСЕГО:', len(per_section))
print('МОЛЧАТ ПО ОСИ ПОЛНОСТЬЮ (ни одного адреса):', len(silent))
for s in silent: print('   ·', s, f'[{per_section[s]["файл"]}]')
print('\nНАЗЫВАЮТ ВСЕ ЧЕТЫРЕ:', len(named_all))
for s in named_all: print('   ·', s)
print('\nОГОВОРКА К СТОЛБЦУ «по оси»: он считает, что адрес НАЗВАН, а не что он оплачен.')
print('Разделы 2 и 9 называют все четыре адреса затем, чтобы предъявить ПРОЧЕРК: рядом')
print('с моделью в них никто не работает, и ни одного адреса они не расходуют. Это названо')
print('на их месте намеренно — ось, у которой молчащие разделы не названы, читается шире.')
print('\nФРАЗ, НАЗЫВАЮЩИХ ≥3 АДРЕСА ВМЕСТЕ:', sum(d['вместе'] for d in per_section.values()))
for k,d in per_section.items():
    for ex in d['примеры']: print(f'   [{k[:40]}] {ex}')

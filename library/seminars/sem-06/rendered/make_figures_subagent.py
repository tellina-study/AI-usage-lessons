from fig_toolkit import *

MW = 1600
CODEBG = (0x16, 0x1C, 0x30)


def mtext(d, x, y, t, sz=23, col=INK, b=False, m=False, strike=False):
    fo = f(sz, b, m)
    d.text((x, y), t, font=fo, fill=col)
    w = d.textlength(t, font=fo)
    if strike:
        d.line([x - 4, y + sz * 0.58, x + w + 4, y + sz * 0.58], fill=DEEP, width=3)
    return w


def mcent(d, y, t, sz=23, col=INK, b=False):
    fo = f(sz, b)
    d.text(((MW - d.textlength(t, font=fo)) // 2, y), t, font=fo, fill=col)


def mpanel(d, x, y, w, h, title=None, *, fill=SURF, stroke=LIGHT, tsz=22, tcol=DEEP, r=12, sw=3):
    d.rounded_rectangle([x, y, x + w, y + h], radius=r, fill=fill, outline=stroke, width=sw)
    if title:
        d.text((x + 18, y + 12), title, font=f(tsz, True), fill=tcol)


def code_card(d, x, y, w, h, lines, *, fill=W, stroke=LIGHT, sz=14, lh=20):
    """Светлая карточка кода (правило А4, круг 2 владельца — чёрный фон с
    белыми буквами убрать ВЕЗДЕ): белая подложка, тёмный моно-текст, тонкая
    рамка. Тот же приём, что `code_card` в `make_figures_mcp.py` (n08,
    одностраничник MCP) — тут не импортируется (sem-06/rendered/fig_toolkit.py
    — копия, не общий модуль), переписана заново под то же правило."""
    d.rounded_rectangle([x, y, x + w, y + h], radius=9, fill=fill, outline=stroke, width=2)
    yy = y + 8
    for ln in lines:
        d.text((x + 14, yy), ln, font=f(sz, False, True), fill=DEEP)
        yy += lh


def msave(name):
    print("  ", name)



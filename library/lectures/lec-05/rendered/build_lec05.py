# поэтому порог поставлен по штампу, а не по строке источников.
CONTENT_TOP = 7.00
CONTENT_FLOOR = 7.16


def report_overflows(pres):
    """Печать переполнений ПОСЛЕ сборки полной деки.

    Две разные проверки, потому что они слепы к разному (issue #212):

    1. `b6.WARN` — сторож полос карточек-практик. Он сверяет нужную высоту
       текста с высотой его коробки. Печатал его только build_band6.py, то
       есть сборка ПОЛНОЙ деки о переполнениях молчала, хотя те же функции
       в ней и вызываются. Теперь печатает и она.

    2. Геометрия подвала. Проверка 1 структурно не видит случая, когда текст
       в своей коробке помещается, а сама коробка уехала за низ слайда:
       высоту полосы считает тот же `est_h`, поэтому расхождения между ними
       нет. Так прошло переполнение s17a — полоса «ГДЕ НЕ РАБОТАЕТ» доходила
       до 7,22" и залезала в зону строки источников и в угол номера
       страницы, при пустом WARN. Здесь это ловится по готовому файлу:
       фигура, которая НАЧИНАЕТСЯ в зоне содержания и ЗАКАНЧИВАЕТСЯ ниже
       пола подвала, — переполнение.

    Полосы 1-5 собственного сторожа не имеют вовсе; проверка 2 — пока
    единственное, что покрывает их все.
    """
    warns = list(b6.WARN)
    for i, slide in enumerate(pres.slides, start=1):
        for sh in slide.shapes:
            if sh.top is None or sh.height is None:
                continue
            top = sh.top / 914400.0
            bottom = top + sh.height / 914400.0
            if top < CONTENT_TOP and bottom > CONTENT_FLOOR:
                txt = ""
                if sh.has_text_frame:
                    txt = sh.text_frame.text.strip().split("\n")[0][:60]
                warns.append(
                    f"слайд {i} ({ORDER[i - 1].__name__}): фигура с верхом "
                    f"{top:.2f}\" уходит до {bottom:.2f}\" — в подвал слайда"
                    + (f" | {txt}" if txt else ""))
    if warns:
        print("--- переполнения (надо править высоты) ---")
        for w in warns:
            print("  " + w)
    else:
        print("переполнений нет")



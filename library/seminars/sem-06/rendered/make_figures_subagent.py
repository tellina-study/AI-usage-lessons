def m2(x, y, t, sz=25, col=INK, b=False, m=False):
    fo = f(sz, b, m)
    d.text((x, y), t, font=fo, fill=col)
    return d.textlength(t, font=fo)


def m2fit(x, y, t, limit, sz=25, col=INK, b=False, where="n36"):
    fit(d, t, f(sz, b), limit, where)
    return m2(x, y, t, sz, col, b)


def chip(x, y, t, col, sz=23, padx=14, h=36):
    fo = f(sz, True)
    w_ = d.textlength(t, font=fo) + 2 * padx
    d.rounded_rectangle([x, y, x + w_, y + h], radius=h // 2, fill=col)
    d.text((x + padx, y + (h - sz - 6) / 2), t, font=fo, fill=W)
    return w_



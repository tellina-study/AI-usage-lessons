# -*- coding: utf-8 -*-
"""Сломанные входы на РАСКЛАДКУ ТЕЛА: пол проекции, лестница кеглей,
обтекание боковой иллюстрации.

Отдельным файлом от `probes.py` по двум причинам, и ни одна не про размер.
Во-первых, здесь входы ПАРНЫЕ: каждый собирается дважды — с проверяемым
свойством и без него, — и значение имеет не предупреждение, а РАЗНИЦА между
двумя сборками (`selftest_layout.py`). Во-вторых, кирпич текста у них общий
нарочно: пробы сравниваются друг с другом, и разный текст означал бы, что
сравнивается текст, а не раскладка.
"""

BRICK = ("Абзац тела пробы, достаточно длинный, чтобы занять несколько строк "
         "рамки и дать мере работу: в нём есть и запятые, и длинные слова, и "
         "обычные короткие. ")


def body(blocks, per=3):
    """Тело из `blocks` абзацев по `per` кирпичей в каждом."""
    return "\n\n".join(BRICK * per for _ in range(blocks))


def frame(sid, blocks, *, media="", per=3, title="Проба раскладки тела"):
    return f"""---
id: {sid}
type: case
title: "{title}"
source: "—"
media: "{media}"
---

## Видимый текст слайда

{body(blocks, per)}

## Заметки лектора

проба
"""


# Тело, которое УКЛАДЫВАЕТСЯ — и всё равно набрано ниже порога проекции:
# 11,5 пт при пороге 12. Ни одного блокирующего предупреждения на нём нет, и
# в этом вся соль: прежде такой кадр уходил в деку молча.
PROJ = frame("s93", 6)

# Обтекание ПОКУПАЕТ кегль: то же тело рядом с широким снимком — 9,5 пт
# одной узкой надписью против 10,5 пт двумя.
WRAP_GAIN = frame("s94", 5, media="probe-wide.png")

# Обтекание СТОИЛО БЫ кегля: тело и так укладывается рядом со снимком на
# 13,0 пт, а разрез по границе блока отдаёт остаток узкой части и роняет его
# до 12,5. Такой вход обтекание обязано отвергнуть.
WRAP_LOSS = frame("s95", 3, media="probe-wide.png")

# Резать НЕЧЕМ: тело в один блок, разделителей в прогоне нет. Обтекание
# обязано отказаться И вернуть кегли нетронутыми — иначе следом идущая
# обычная подгонка возьмёт за основу уже ужатые (так `s55` Лекции 7 сел на
# 8,5 пт вместо 15,0, и ни одно предупреждение этого не назвало).
WRAP_NOCUT = frame("s96", 1, media="probe-wide.png", per=4)

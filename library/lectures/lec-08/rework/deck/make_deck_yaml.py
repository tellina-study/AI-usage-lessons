def fm(path):
    """Фронтматтер кадра -> плоский словарь скалярных полей.

    Правило отреза то же, что в Лекции 7 (`make_deck_yaml.py` того производства):
    встрочный комментарий ` #` у НЕЗАКАВЫЧЕННОГО значения отрезается, потому что
    запятая внутри такого комментария рвёт поточную карту YAML в `marks: {...}` ниже —
    там уже однажды падала сборка Лекции 7 с `ParserError`, и это не косметика.
    Закавыченные значения не трогаются — у них комментарий всегда ЗА кавычкой.
    """
    t = open(path, encoding='utf-8').read()
    body = t.split('---')[1]
    d = {}
    for line in body.splitlines():
        m = re.match(r'^([a-z_]+):\s*(.*)$', line)
        if m:
            v = m.group(2).strip()
            if not v.startswith('"'):
                v = re.split(r'\s+#', v, maxsplit=1)[0].strip()
            if v.startswith('"') and v.endswith('"') and len(v) > 1:
                v = v[1:-1]
            d[m.group(1)] = v
    return d


def razbiraetsya(fn):
    """Мера с вывода: разбирается ли ЗАПИСАННЫЙ файл как YAML, в той же строке отчёта,
    что и факт записи -- расходиться между собой им не из чего (см. Лекция 7 docstring)."""
    import yaml
    try:
        yaml.safe_load(open(fn, encoding='utf-8'))
        return '· YAML разбирается'
    except Exception as e:
        return '· YAML НЕ РАЗБИРАЕТСЯ: %s' % str(e).splitlines()[0]


def q(s):
    s = str(s).replace('\\', '\\\\').replace('"', '\\"')
    return '"%s"' % s



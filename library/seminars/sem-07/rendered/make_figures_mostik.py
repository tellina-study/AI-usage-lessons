#!/usr/bin/env python3
"""Схемы открытия и закрытия Семинара 7 — n02, n03, n32 (финальная сквозная
нумерация; имя последнего файла ниже переименовано при технической сборке —
было `os-n34-lestnitsa-tri-zakryty.png` на промежуточном круге сведения,
когда закрывающая ось предполагалась тридцать четвёртым слайдом).

Три схемы, нарисованные пикселями, а не описанные словами:

    mostik-n02-pochta-bez-modeli.png   n02  три коробки и две стрелки:
                                            письмо, правило-триггер, карточка
                                            в трекере; на второй стрелке —
                                            HTTP-запрос
    mostik-n03-lestnitsa.png           n03  девять ступеней снизу вверх, три
                                            нижние в золотой рамке, полоса
                                            справа читает «сегодня»
    os-n32-lestnitsa-tri-zakryty.png   n32  та же лестница, та же геометрия;
                                            три нижние залиты золотом, с
                                            галочкой, полоса читает «закрыто»

Зачем это рисуется, а не печатается таблицей. Вопрос n02 звучит «где в этой
картинке искусственный интеллект» — к абзацу такой вопрос не задаётся, он
задаётся к картинке. А лестница из девяти пунктов, напечатанная таблицей с
колонкой «Статус», в которой девять раз подряд стоит «пусто», показывает залу
колонку шума вместо движения вверх: пустая ступень видна и без слова «пусто».

Зеркальная пара n03/n32 рисуется ОДНОЙ функцией с одним переключателем
(`lestnitsa(..., zakryto=)`), поэтому геометрия открытия и закрытия не может
разойтись: это физически один и тот же объект, прочитанный в конце занятия с
другим результатом. Разница между двумя файлами — заливка трёх нижних
ступеней, галочка на них и слово внутри полосы справа.

Пол кегля. Схема вставляется во всю ширину рабочего поля (12,23″), холст —
2400 px по ширине, отсюда 12,23 × 72 / 2400 = 0,367 pt на пиксель. Порог деки
— 7,5 pt (`tools/seminar-production/README.md` §7), то есть 21 px; самый
мелкий кегль здесь 26 px, и запас оставлен сознательно: когда `deck_kit.
figure` не хватает высоты, она ужимает схему ЦЕЛИКОМ, вместе с кеглем. Прогон
печатает пол кегля каждой схемы и его цену в пунктах — замер, а не обещание.

    python3 make_figures_mostik.py
    python3 make_figures_mostik.py --lang en     # когда заведётся словарь
"""
from fig_toolkit import *          # noqa: F401,F403 — общий тулкит схем этой папки

WHITE = W                          # белый тулкита: имя W ниже занято шириной холста

PT_PER_PX = 12.23 * 72 / 2400      # схема вставляется во всю ширину поля
FLOOR_PT = 7.5


def llabel(d, x, y, txt, sz, col=INK, b=False, limit=None, where="?"):
    """Подпись с ЛЕВЫМ краем в x. Тулкит даёт центрированную (`clabel`) и
    многострочную (`lines_at`); у ступеней лестницы текст прижат влево, и
    выравнивание по центру рассыпало бы лесенку, которую строят левые края."""
    fo = f(sz, b)
    if limit:
        fit(d, txt, fo, limit, where)
    d.text((x, y), T(txt), font=fo, fill=col)


def check_bold(d, cx, cy, s, col, wd=7):
    """Жирная галочка — ступень закрыта. Тулкитная `check_outline` здесь не
    годится дважды. По смыслу она заведена под обратное состояние («вопрос
    задан, не отвечен», Семинар 6), а по виду на таком размере даёт тонкую
    пологую птичку, которая рядом с жирной подписью ступени читается засечкой
    печати."""
    d.line([cx - s, cy, cx - s * 0.25, cy + s * 0.72], fill=col, width=wd)
    d.line([cx - s * 0.25, cy + s * 0.72, cx + s, cy - s * 0.72], fill=col, width=wd)


def vlabel(im, x, y, h, txt, sz, col, b=True):
    """Подпись, повёрнутая на 90°, читается снизу вверх. Нужна полосе статуса:
    горизонтальное слово в полосу шириной 210 px влезает только кеглем, который
    ушёл бы под пол."""
    fo = f(sz, b)
    txt = T(txt, "whole")
    tmp = Image.new("RGBA", (max(int(h), 10), sz + 16), (0, 0, 0, 0))
    td = ImageDraw.Draw(tmp)
    td.text(((max(int(h), 10) - td.textlength(txt, font=fo)) / 2, 2), txt,
            font=fo, fill=col)
    rot = tmp.rotate(90, expand=True)
    im.paste(rot, (int(x), int(y)), rot)


# ── n02 · письмо → правило-триггер → карточка в трекере ─────────────────────
#
# Три коробки, две стрелки. HTTP-запрос — подпись на второй стрелке, а не
# четвёртая коробка: он и есть то, чем правило действует наружу, отдельного
# узла процесса в нём нет. Под цепочкой — реплика инженера, который это
# правило настроил: человек и его слова в кадре с первой картинки занятия.

def fig_n02():
    W, H = 2400, 430
    im = Image.new("RGB", (W, H), WHITE)
    d = ImageDraw.Draw(im)

    cy0, ch = 24, 200
    cw, gap, x0 = 620, 240, 30
    xs = [x0 + i * (cw + gap) for i in range(3)]

    titles = ["письмо", "правило-триггер", "карточка в трекере"]
    subs = [["упало в ящик поддержки"],
            ["если письмо в этом ящике —", "создать карточку"],
            ["тема и текст письма"]]

    for x, t, sub in zip(xs, titles, subs):
        d.rounded_rectangle([x, cy0, x + cw, cy0 + ch], radius=18, fill=SURF,
                            outline=LIGHT, width=3)
        clabel(d, x + cw / 2, cy0 + 42, t, 38, DEEP, b=True, limit=cw - 44,
               where="n02 заголовок коробки")
        for k, ln in enumerate(sub):
            clabel(d, x + cw / 2, cy0 + 110 + k * 38, ln, 26, MUTE, limit=cw - 44,
                   where="n02 подпись коробки")

    for i in range(2):
        arrow(d, xs[i] + cw + 28, cy0 + ch / 2, xs[i + 1] - 28, cy0 + ch / 2,
              col=MID, wd=6, head=20)
    # Подпись только на второй стрелке и ПОД линией: над линией она встаёт
    # вровень с заголовками коробок и читается их четвёртым этажом.
    clabel(d, (xs[1] + cw + xs[2]) / 2, cy0 + ch / 2 + 18, "HTTP-запрос", 28, MID,
           b=True, limit=gap - 20, where="n02 подпись стрелки")

    clabel(d, W / 2, 288, "«Это просто скрипт. Я сам написал его в прошлом месяце.»",
           32, INK, limit=W - 120, where="n02 реплика")
    clabel(d, W / 2, 346, "инженер, который его настроил", 26, MUTE,
           limit=W - 200, where="n02 подпись реплики")

    save(im, "mostik-n02-pochta-bez-modeli.png")


# ── n03 / n32 · лестница из девяти ступеней ─────────────────────────────────
#
# Названия ступеней — дословно `SPLIT-PLAN-7-12.md` §2, без переименования и
# без сокращения приёмов (правило «абстракции не изобретаются»,
# `tools/seminar-production/README.md` §3). Колонок «Закрывает» и «Статус»
# здесь нет: первая уехала в подпись под схемой одной строкой, вторая была
# девятью «пусто» подряд.

STUPENI = [
    "Хватит одного вызова (+RAG) — ничего не строим",
    "Workflow · цепочка (prompt chaining)",
    "Workflow · маршрут (routing), включая decision-модель вместо LLM",
    "Workflow · параллель (parallelization)",
    "Workflow · эталон-переделка (evaluator-optimizer)",
    "Workflow · дирижёр-исполнители (orchestrator-workers)",
    "Один агент (в т.ч. вложенный внутри маршрута workflow)",
    "Мульти-агент (оркестрованный vs «рой»)",
    "Выключить — откат к ручному процессу",
]


def lestnitsa(name, zakryto):
    """Девять ступеней снизу вверх. `zakryto=False` — три нижние в золотой
    рамке и полоса «сегодня» (открытие занятия); `zakryto=True` — те же три
    залиты золотом, с галочкой, полоса читает «закрыто» (закрытие занятия)."""
    W, H = 2400, 720
    im = Image.new("RGB", (W, H), WHITE)
    d = ImageDraw.Draw(im)

    pitch, rh, x_right = 71, 62, 2130

    def x_left(i):
        return 150 + i * 96

    def y_top(i):
        return 628 - i * pitch

    # Ломаная по внешнему углу каждой ступени — то, что делает из девяти строк
    # лестницу. Идёт в 7 px слева от края коробки и в 4 px выше её верхней
    # грани, ровно по зазору между ступенями. Проведённая по самим краям, она
    # уходит под коробку ступенью ниже и оставляет на экране короткие засечки,
    # которые читаются браком печати.
    pts = [(x_left(0) - 7, 690)]
    for i in range(9):
        pts.append((x_left(i) - 7, y_top(i) - 4))
        if i < 8:
            pts.append((x_left(i + 1) - 7, y_top(i) - 4))
    d.line(pts, fill=LIGHT, width=3, joint="curve")

    for i, text in enumerate(STUPENI):
        x, y, segodnya = x_left(i), y_top(i), i <= 2
        w = x_right - x
        if segodnya and zakryto:
            fill, line, wd, tx = GOLD, GOLD, 3, GOLDINK
        elif segodnya:
            fill, line, wd, tx = WHITE, GOLD, 4, DEEP
        else:
            fill, line, wd, tx = WHITE, GREY_FILL, 3, GREY_TX
        d.rounded_rectangle([x, y, x + w, y + rh], radius=14, fill=fill,
                            outline=line, width=wd)
        llabel(d, x + 28, y + 16, text, 30, tx, b=segodnya,
               limit=w - (110 if (segodnya and zakryto) else 56),
               where=f"ступень {i}")
        if segodnya and zakryto:
            check_bold(d, x_right - 48, y + rh / 2 - 6, 17, GOLDINK)

    # Полоса статуса справа — на высоту ровно трёх нижних ступеней.
    by, bh = y_top(2), 690 - y_top(2)
    d.rounded_rectangle([2160, by, 2370, by + bh], radius=16, fill=GOLD)
    vlabel(im, 2186, by + 10, bh - 20, "закрыто" if zakryto else "сегодня", 30, DEEP)

    llabel(d, 40, 64, "выше — сложнее процесс", 26, MUTE, limit=840,
           where="подпись направления")
    save(im, name)


if __name__ == "__main__":
    fig_n02()
    lestnitsa("mostik-n03-lestnitsa.png", zakryto=False)
    lestnitsa("os-n32-lestnitsa-tri-zakryty.png", zakryto=True)
    report()
    print("\nпол кегля в пунктах (порог деки 7,5 pt при вставке во всю ширину):")
    for nm, _size, mn in DREW:
        pt = mn * PT_PER_PX
        print(f"   {nm}  {mn} px = {pt:.2f} pt — "
              f"{'ВЫШЕ' if pt >= FLOOR_PT else 'НИЖЕ'} порога")

#!/usr/bin/env python3
"""Два составных кадра Кейса 4 (переопределённого 2026-10-29, issue #303) из уже
снятых настоящих кусков стенда (`n8n_shots.py --figures-k4n`, живой
`n8n.lessons.tellian.io`). Это НЕ пересъёмка и не стилизация (БРИФ §5
`zamery-k4-novyy/README.md`): пиксели каждой половины — ровно те, что снял
`clip_canvas`/`clip_panel`, без единой правки внутри них. Добавлены только
подписи-заголовки СНАРУЖИ снимков — то же самое, что делает любой слайд деки,
подписывая кадр словами рядом, а не внутри.

1. `k4-holst-0-vs-prc.png` — холст конфигурации «без защиты» (6 узлов, прямая
   линия) и холст конфигурации «все три защиты» (13 узлов, две развилки) друг
   над другом. Владелец просил именно это противопоставление, читаемое с
   одного взгляда (БРИФ §А, `zamery-k4-novyy/README.md`: «холст, на котором
   узла механической проверки физически нет, — честное изображение
   конфигурации «без механики»»).

   **Зум — один на обе половины (правка владельца 2026-10-29, issue #299).**
   Оба холста сняты `zoom-to-fit` (`n8n_shots.py::open_canvas`) — n8n сам
   подбирает зум под число узлов, и у конфигурации с 13 узлами (две развилки,
   виднее целиком) он мельче, чем у конфигурации с 6 узлами в прямую линию.
   Прежняя версия приводила обе картинки к ОДНОЙ ширине холста (2400 px) —
   это НЕ чинит разницу зума, а усугубляет её: узкий холст (6 узлов)
   растягивается меньше, чем широкий (13 узлов) сжимается, и разрыв между
   подписями узлов растёт, а не исчезает. Замерено прямо на прежней версии
   файла (подпись узла «Заявка» — один и тот же узел, дословно та же подпись
   в обеих конфигурациях; метод — тот же, что `_label_height()` ниже, порог
   темноты 120, окно без обрезки глифа с обеих сторон): **19 px у верхней
   половины против 10 px у нижней — разрыв 1,9 раза**, хотя сырые кадры
   стенда расходились только в 1,5 раза (24 px против 16 px, тот же метод).
   Прежнее сведение к общей ширине не выравнивало зум, а растило разрыв.

   Чинится не выравниванием ширины, а выравниванием ЗУМА: конфигурация «0»
   остаётся в своём исходном разрешении (она и была крупнее — её подписи
   читаются лучше), конфигурация «prc» масштабируется ВВЕРХ ровно настолько,
   чтобы подпись «Заявка» совпала по высоте с подписью «Заявка» в
   конфигурации «0». Следствие, предсказанное владельцем заранее: шесть
   узлов конфигурации «0» при общем зуме занимают меньше половины ширины
   композита — и эта пустота справа сама читается доводом «защит нет, и
   делать нечего», без единой подписи.
2. `k4-panel-mehanika.png` — панель узла «Механическая проверка» без нижней
   подсказки интерфейса («Type $ for a list…», мешает содержанию, срезана
   так же, как `crop_k3_panel_tight.py` срезал вкладки Mode/Language там, где
   они были лишними).

Источники — `stend/n8n-screenshots-raw/k4n-holst-0.png`,
`.../k4n-holst-prc.png`, `.../k4n-panel-mehanika-raw.png` (все три — сырые
кадры `n8n_shots.py --figures-k4n`, лежат рядом с остальными сырыми снимками
стенда, НЕ в `figures/`: это вход для склейки ниже, не самостоятельная
фигура деки).

Запуск: `python3 compose_k4n_shots.py` (из `rendered/`).
"""
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

FIGS = Path(__file__).parent / "figures"
RAW = Path(__file__).parents[1] / "stend" / "n8n-screenshots-raw"

F_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
DEEP = (0x21, 0x29, 0x5C)
LIGHT = (0x1C, 0x72, 0x93)
GOLD = (0xF0, 0xAB, 0x00)
SURF = (0xF4, 0xF7, 0xFA)
W = (255, 255, 255)

TARGET_W = 2400

# Окна (в СЫРЫХ, неперемасштабированных пикселях k4n-holst-*.png) вокруг
# подписи узла «Заявка» — первого узла в обеих конфигурациях, дословно той же
# подписи. Подобраны так, чтобы не обрезать глиф ни сверху, ни снизу (см.
# запуск: число печатается, и совпадающая по смыслу обрезанная рамка дала бы
# заниженное число молча — проверено на этом же файле во время правки).
LABEL_BOX_0 = (193, 355, 333, 410)      # «Заявка», холст конфигурации «0»
LABEL_BOX_PRC = (166, 580, 294, 625)    # «Заявка», холст конфигурации «prc»


def _scaled(path, scale):
    im = Image.open(path).convert("RGB")
    w, h = im.size
    return im.resize((round(w * scale), round(h * scale)), Image.LANCZOS)


def _label_height(path, box, thr=120):
    """Высота подписи узла в пикселях — по тёмным пикселям в окне вокруг
    известного ярлыка (мера того же рода, что `pdfmeasure.py`/`pt_report`:
    число, а не взгляд). Падает громко, если окно промахнулось мимо текста —
    молчаливый ноль хуже, чем явная ошибка."""
    arr = np.array(Image.open(path).convert("L"))
    x0, y0, x1, y1 = box
    mask = arr[y0:y1, x0:x1] < thr
    rows = np.where(mask.any(axis=1))[0]
    if len(rows) == 0:
        raise RuntimeError(f"{path.name}: окно {box} не нашло тёмных пикселей — "
                            f"подпись не там, перепроверь координаты")
    return int(rows.max() - rows.min() + 1)


def holst_pair():
    raw0 = RAW / "k4n-holst-0.png"
    raw1 = RAW / "k4n-holst-prc.png"

    # Оба холста сняты zoom-to-fit (`n8n_shots.py::open_canvas`) — зум
    # автоматически подбирается под число узлов в каждом отдельном сценарии,
    # и у конфигурации с 13 узлами (две развилки) он мельче, чем у
    # конфигурации с 6 узлами в прямую линию. Меряем подпись одного и того же
    # узла «Заявка» в обоих сырых кадрах и масштабируем «prc» так, чтобы её
    # высота совпала с высотой той же подписи у «0» — это и значит «один зум
    # на обе половины», а не «одна ширина холста» (прежняя ошибка).
    h0 = _label_height(raw0, LABEL_BOX_0)
    h1 = _label_height(raw1, LABEL_BOX_PRC)
    ratio = h0 / h1
    print(f"  замер подписи «Заявка» (сырые кадры): холст «0» {h0} px, "
          f"холст «prc» {h1} px — зум «0» крупнее в {ratio:.2f} раза")

    scale0 = TARGET_W / Image.open(raw0).size[0]
    scale1 = scale0 * ratio   # тот же зум, что у «0», перенесённый на «prc»

    pad = 40
    label_h = 90
    gap = 30
    im0 = _scaled(raw0, scale0)
    im1 = _scaled(raw1, scale1)
    inner_w = max(im0.width, im1.width)
    total_h = pad + label_h + im0.height + gap + label_h + im1.height + pad

    canvas = Image.new("RGB", (inner_w + pad * 2, total_h), W)
    d = ImageDraw.Draw(canvas)
    fo = ImageFont.truetype(F_BOLD, 54)

    y = pad
    d.rectangle([pad, y, pad + inner_w, y + label_h - 14], fill=SURF,
                outline=LIGHT, width=3)
    d.text((pad + 24, y + 16), "Конфигурация «0» — без единой защиты, 6 узлов",
            font=fo, fill=DEEP)
    y += label_h
    canvas.paste(im0, (pad, y))
    y += im0.height + gap

    d.rectangle([pad, y, pad + inner_w, y + label_h - 14], fill=W,
                outline=GOLD, width=4)
    d.text((pad + 24, y + 16),
            "Конфигурация «prc» — все три защиты вместе, 13 узлов",
            font=fo, fill=DEEP)
    y += label_h
    canvas.paste(im1, (pad, y))

    out = FIGS / "k4-holst-0-vs-prc.png"
    canvas.save(out)
    print(f"  {out.name}  {canvas.size} — один зум на обе половины (подписи узла "
          f"«Заявка» сведены к {h0} px у обеих — по построению: масштаб «prc» "
          f"подобран так, чтобы её подпись совпала с подписью «0»; холст «0» "
          f"занимает {im0.width}/{inner_w} = {im0.width / inner_w:.0%} ширины "
          f"композита)")


#   строки 1–8 массива `PRIEMY` (до закрывающей скобки семейства «прямая
# инъекция») заканчиваются здесь; ниже начинается строка 9 «требование
# игнорировать правило или проверку» — измерено на самом кропнутом кадре
# (1286×1632): окно вокруг открывающей `[` девятой записи тёмное начиная с
# y≈795, пустая (белая) полоса строго над ней идёт с y≈780. Разрез на 788
# не рассекает ни одну строку кода глифом.
MEHANIKA_SPLIT_Y = 788


def mehanika_panel():
    """Панель узла «Механическая проверка» — ДВЕ колонки рядом, не один
    книжный кадр (issue #303, Часть В). Прежняя версия (одна колонка,
    1286×1632) занимала на слайде только 28% ширины и 8% площади — потолок
    приёма упирался в её же книжную пропорцию, а не в соседей (сборка:
    «СХЕМА ЗАЖАТА [n46a]: ПОТОЛОК приёма»). Пиксели те же, что снял стенд —
    список приёмов разрезан пополам по СТРОКАМ кода и положен бок о бок:
    левая половина несёт начало массива `PRIEMY`, правая — его продолжение
    (так же непрерывно, как если бы страница просто перетекала вправо).
    Склейка, не пересъёмка — тот же принцип, что у `holst_pair()` выше."""
    src = RAW / "k4n-panel-mehanika-raw.png"
    im = Image.open(src).convert("RGB")
    w, h = im.size
    # Нижняя подсказка интерфейса («Type $ for a list…») начинается в
    # последних ~150 px кадра — измерено по самому файлу, не на глаз
    # (профиль: оранжевая рамка подсказки видна с y≈1632 до низа).
    cropped = im.crop((0, 0, w, h - 150))
    cw, ch = cropped.size

    left = cropped.crop((0, 0, cw, MEHANIKA_SPLIT_Y))
    right = cropped.crop((0, MEHANIKA_SPLIT_Y, cw, ch))

    pad, gap, label_h = 40, 50, 74
    col_h = max(left.height, right.height)
    total_w = pad * 2 + cw * 2 + gap
    total_h = pad + label_h + col_h + pad

    canvas = Image.new("RGB", (total_w, total_h), W)
    d = ImageDraw.Draw(canvas)
    fo = ImageFont.truetype(F_BOLD, 40)

    lx, rx = pad, pad + cw + gap
    y_label, y_img = pad, pad + label_h
    d.rectangle([lx, y_label, lx + cw, y_label + label_h - 12], fill=SURF,
                outline=LIGHT, width=3)
    d.text((lx + 20, y_label + 14), "Код проверки — начало списка",
           font=fo, fill=DEEP)
    d.rectangle([rx, y_label, rx + cw, y_label + label_h - 12], fill=SURF,
                outline=LIGHT, width=3)
    d.text((rx + 20, y_label + 14), "Код проверки — продолжение",
           font=fo, fill=DEEP)
    canvas.paste(left, (lx, y_img))
    canvas.paste(right, (rx, y_img))

    out = FIGS / "k4-panel-mehanika.png"
    canvas.save(out)
    print(f"  {out.name}  сырой {im.size} -> кроп {cropped.size} -> две "
          f"колонки {canvas.size} (была книжная {cropped.size}, 28% ширины "
          f"слайда, 8% площади — потолок приёма); разрез по y={MEHANIKA_SPLIT_Y} "
          f"между строкой 8 и строкой 9 массива PRIEMY, код не тронут")


if __name__ == "__main__":
    holst_pair()
    mehanika_panel()

# -*- coding: utf-8 -*-
"""НАРОЧНО СЛОМАННЫЕ ВХОДЫ на ПОЛ КОНТРАСТА и на HERO ПО ПОРЯДКУ ДЕКИ.

Отдельным файлом от `probes.py`/`probes_layout.py`/`probes_floor.py` по тому
же правилу, по которому те отделены друг от друга: здесь входы собираются не
из файлов кадров, а ПРЯМО ФИГУРАМИ (контраст) и из пары МИНИАТЮРНЫХ ДЕК
(hero). Ни то, ни другое не кирпич текста, которым живут соседние файлы.

Почему контрастные пары — ПАРАМИ «нарушение и приманка». Проверка, которая
умеет только находить, неотличима от проверки, которая находит ВСЁ: обе
дают непустой список. Поэтому на каждый класс порога здесь по два входа —
чуть ниже порога (обязано сработать) и ровно на пороге либо чуть выше
(обязано молчать).

ОТКУДА ЧИСЛА СЕРЫХ ПАР. Не выдуманы: подобраны перебором всех 65 536 серых
пар по восьми битам на канал — ближайшая к ровно 3,0 даёт 3,000004, то есть
«ровно на пороге» здесь измерено, а не заявлено. Воспроизводится
`selftest_contrast.probe_threshold_edge`.
"""

# ── контраст: пары «цвет текста, заливка под ним» ───────────────────
# (имя · цвет текста · заливка · кегль · полужирный · обязано ли ловиться)
#
# Приманка «ровно на пороге» (`EDGE_PASS`) стоит в списке НЕ как округление:
# 3,000004 — это наибольшее, что дают 8 бит на канал, и проба печатает это
# число, а не слово «ровно».
GREY_BELOW_LARGE = "959595"     # на белом 2,9955 — чуть ниже 3,0
GREY_BELOW_NORMAL = "777777"    # на белом 4,4777 — чуть ниже 4,5
EDGE_FG, EDGE_BG = "242424", "6D6D6D"   # 3,000004 — ровно на пороге

CASES = (
    # 1. КРУПНЫЙ текст чуть ниже своего порога 3,0
    ("крупный ниже 3,0", GREY_BELOW_LARGE, "FFFFFF", 20.0, False, True),
    # 2. ОБЫЧНЫЙ текст чуть ниже своего порога 4,5. Тот же цвет при 20 пт
    #    проходит (4,48 > 3,0) — этим доказывается, что порогов два, а не
    #    один, см. `SIZE_SPLIT` ниже.
    ("обычный ниже 4,5", GREY_BELOW_NORMAL, "FFFFFF", 15.0, False, True),
    # 3. Текст на ЦВЕТНОЙ заливке: глубокий `21295C` на среднем `065A82`
    #    даёт 1,82, а тот же прогон на белом — 13,67. То есть нарушение
    #    существует ТОЛЬКО из-за фактической заливки, и вход доказывает,
    #    что фон читается по z-порядку собранного файла, а не берётся белым.
    ("на цветной заливке", "21295C", "065A82", 16.0, False, True),
    # 4. ПРИМАНКА: ровно на пороге крупного текста — обязана молчать.
    ("ровно на пороге", EDGE_FG, EDGE_BG, 20.0, False, False),
)

# Тот же цвет, два кегля: порог переключается на 18 пт. И он же полужирным
# на 14 пт — порог переключается и там.
SIZE_SPLIT = ((15.0, False, True),      # обычный → порог 4,5 → ловится
              (20.0, False, False),     # крупный → порог 3,0 → молчит
              (14.0, True, False),      # полужирный крупный → молчит
              (14.0, False, True))      # тот же кегль светлым → ловится


# ── hero по порядку деки ────────────────────────────────────────────
# Две миниатюрные деки по три кадра. Файлы кадров тут без тела нарочно:
# мерится ПЛОЩАДЬ СНИМКА на первой и последней странице, и любой текст в
# этом вопросе — лишняя переменная.


def frame(sid, *, img="", hero=False, title="Проба hero по порядку"):
    hd = ""
    if img:
        hd = f'media: "{img}"\n'
        if hero:
            hd += 'media_hero: true\nmedia_caption: "проба, источник"\n'
    return f"""---
id: {sid}
type: case
title: "{title}"
{hd}source: "—"
---

## Видимый текст слайда

Короткий абзац, который заведомо укладывается.

## Заметки лектора

проба
"""


# ДЕКА А. Hero ОБЪЯВЛЕН на последнем кадре — и всё равно занимает 10%:
# снимок узкой лентой 1500×100. Сторож по объявлению автора такой вход
# пропускает: поле `media_hero` на месте, значит «hero есть». Ровно этот
# случай и случился на `s106` Лекции 7 — 10,7% при пороге 40%.
DECK_SMALL_HERO = (
    ("s01-first.md", frame("s01", img="probe-hero-big.png", hero=True)),
    ("s02-mid.md", frame("s02")),
    ("s03-last.md", frame("s03", img="probe-hero-thin.png", hero=True)),
)

# ДЕКА Б. Последний кадр ВОВСЕ без снимка — ни поля `media`, ни файла.
# Сторожу по объявлению тут нечего мерить, и он молчит; сторож по порядку
# деки обязан сказать, что последний кадр показа без hero.
DECK_NO_HERO = (
    ("s01-first.md", frame("s01", img="probe-hero-big.png", hero=True)),
    ("s02-mid.md", frame("s02")),
    ("s03-last.md", frame("s03")),
)

# ДЕКА В (здоровая). Первый и последний кадр несут крупный снимок — сторож
# обязан молчать. Без этой половины проба доказывала бы только, что
# предупреждение с тегом вообще бывает.
DECK_OK = (
    ("s01-first.md", frame("s01", img="probe-hero-big.png", hero=True)),
    ("s02-mid.md", frame("s02")),
    ("s03-last.md", frame("s03", img="probe-hero-big.png", hero=True)),
)

#!/usr/bin/env python3
"""Схема Кейса 1 — `k1-shema-samootchet-i-geyt.png`. Одна схема, две панели.

**Почему одна, а не две.** Первый круг производства нарисовал две отдельные
схемы — самоотчёт и гейт. Карта слайдов даёт Кейсу 1 ОДИН такт слоя 1, то
есть второй схеме кадра просто нет; а правило курса требует, чтобы
сопоставление «решение внутри текста / решение в проверяемом поле» читалось с
одного взгляда — отсутствие такого сопоставления владелец назвал системной
ошибкой, а не недоделкой. Поэтому панели стоят рядом, и это не склейка двух
картинок: у них ОДНИ И ТЕ ЖЕ строки, подписанные один раз слева.

Строки и есть приём. Зал читает не две схемы, а четыре вопроса, заданных
обеим версиям подряд: что делает модель · где записано решение · кто может
его проверить · чего это стоило на одних и тех же пятнадцати трудных
вопросах. Разница тогда видна сама, без слова «сравните».

Грамматика цвета, та же, что на схеме Кейса 4: **золото — то, что нельзя
проверить кодом; тил — то, что код читает сам.** Отсюда рамки панелей, и
отсюда же пунктир вокруг решения в левой панели: пунктирная граница — это
граница, которой на самом деле нет.

**Измеренных чисел на этой схеме нет — ни одного, и это правка второго
круга.** Первая редакция несла четвёртой строкой «Чего это стоило»: 6 из 15,
4 из 15, 2 из 15. Это весь итог тактов `n12`, `n13` и `n16`, выложенный на
кадре `n09` — сразу после разбора, из которого те же числа были сняты
намеренно, и за четыре экрана до того, как их вскрывают. Греп этого не видит:
в схеме числа — пиксели, и сессия честно отчиталась «0 протечек», будучи
правой по тексту. Поймал это человек, открывший картинку (канон §7).

Подзаголовок поправлен тем же решением. Он читался «пятнадцать трудных
вопросов (тема в базе есть, деталь другая)» — дословная развязка такта `n13`.
Теперь он называет только то, что на кадре и есть: заявка одна, база одна,
разница — в том, где записано решение.

Остались три строки, ради которых схема и сводилась: что делает модель · где
записано решение · кто может его проверить. Это устройство, и ему здесь
место. Чем это кончилось — не здесь.

Внутренних имён полей и значений на схеме нет умышленно: слой 1 — устройство
решения, а не экран инструмента. Настоящие имена зал увидит на снимке панели.

Запуск: `python3 make_figures_k1.py` (из `rendered/`).
"""
from make_figures_common import *

# Высоты строк подобраны под САМУЮ ВЫСОКУЮ из двух панелей, а не под среднюю:
# на первом прогоне правая ячейка первой строки была на три строки текста и
# вылезла заголовком ЗА верхнюю грань своей карточки — `node` центрует
# содержимое и при нехватке высоты уводит его вверх молча.
H = 648
LX, LW = 60, 340                      # колонка подписей строк
PX, PW = (440, 1410), 930             # две панели, ширина одна на обе
R1, R1H = 184, 124                    # что делает модель
R2, R2H = 322, 158                    # где записано решение
R3, R3H = 494, 110                    # кто может его проверить
STROKI = (("Что делает модель", "", R1, R1H),
          ("Где записано решение", "", R2, R2H),
          ("Кто может его проверить", "", R3, R3H))


def panel_ramka(d, x, col, zagolovok, podzag):
    card(d, x - 18, 96, PW + 36, 532, fill=W, stroke=col, sw=5)
    ctxt(d, x + PW / 2, 110, zagolovok, 32, DEEP, b=True, limit=PW,
         where=f"панель · {zagolovok[:14]}")
    ctxt(d, x + PW / 2, 150, podzag, 25, col, b=True, limit=PW,
         where=f"панель · подзаголовок {zagolovok[:14]}")


def kletka(d, x, y, h, title, sub, *, col=LIGHT, sw=3, fill=SURF, where="?"):
    node(d, x, y, PW, h, title, sub, fill=fill, stroke=col, sw=sw,
         tsz=29, ssz=25, where=where)


def samootchet_i_geyt():
    im = Image.new("RGB", (CW, H), W)
    d = ImageDraw.Draw(im)
    txt(d, 60, 14, "Где принимается решение «ответить самому или передать человеку»",
        34, MID, b=True, limit=CW - 120, where="заголовок")
    txt(d, 60, 62, "одна и та же заявка и одна и та же база знаний — разница "
        "только в том, где записано решение", 26, LIGHT, limit=CW - 120,
        where="подзаголовок")

    panel_ramka(d, PX[0], GOLD, "Версия 1", "решение внутри текста ответа")
    panel_ramka(d, PX[1], TEAL, "Версия 2", "решение в отдельном поле")

    for name, pod, y, h in STROKI:
        card(d, LX, y, LW, h, fill=SURF, stroke=LIGHT, sw=3)
        n_l = len(wrap(d, name, f(26, True), LW - 40))
        p_l = len(wrap(d, pod, f(24), LW - 40)) if pod else 0
        blok = n_l * 33 + (14 + p_l * 31 if pod else 0)
        y0 = y + (h - blok) / 2 + 2
        wrapped(d, LX + 20, y0, name, 26, DEEP, LW - 40, b=True,
                center=LX + LW / 2, where=f"подпись строки · {name}")
        if pod:
            wrapped(d, LX + 20, y0 + n_l * 33 + 14, pod, 24, LIGHT, LW - 40,
                    center=LX + LW / 2, where=f"условие строки · {name}")

    # ── строка 1: что делает модель ────────────────────────────────────────
    kletka(d, PX[0], R1, R1H, "Отвечает свободно",
           "получает базу знаний целиком и пишет ответ одним текстом",
           where="в1 · что делает модель")
    kletka(d, PX[1], R1, R1H, "Относит вопрос к пункту",
           "называет один из заранее заданных пунктов базы — либо ни одного",
           where="в2 · что делает модель")

    # ── строка 2: где записано решение ─────────────────────────────────────
    card(d, PX[0], R2, PW, R2H, fill=SURF, stroke=GOLD, sw=5)
    ctxt(d, PX[0] + PW / 2, R2 + 14, "Внутри абзаца ответа", 29, DEEP, b=True,
         limit=PW - 40, where="в1 · где решение · название")
    dashbox(d, PX[0] + 30, R2 + 58, PW - 60, 82, GOLD, width=4, bg=SURF)
    wrapped(d, PX[0] + 56, R2 + 76, "«…отвечаю сам или отдаю человеку…» — словами, "
            "вперемешку с самим ответом", 25, DEEP, PW - 112,
            center=PX[0] + PW / 2, where="в1 · где решение · пунктир")

    card(d, PX[1], R2, PW, R2H, fill=SURF, stroke=TEAL, sw=5)
    ctxt(d, PX[1] + PW / 2, R2 + 14, "В отдельном поле", 29, DEEP, b=True,
         limit=PW - 40, where="в2 · где решение · название")
    card(d, PX[1] + 150, R2 + 58, PW - 300, 58, fill=W, stroke=TEAL, sw=3, r=10)
    ctxt(d, PX[1] + PW / 2, R2 + 68, "опора на пункт базы № 7", 29, TEAL, b=True,
         limit=PW - 340, where="в2 · где решение · значение")
    padlock(d, PX[1] + 266, R2 + 130, 15, TEAL)
    txt(d, PX[1] + 296, R2 + 128, "значение, прочитанное кодом", 25, DEEP,
        limit=420, where="в2 · где решение · замок")

    # ── строка 3: кто может его проверить ──────────────────────────────────
    kletka(d, PX[0], R3, R3H, "Никто", "сверить решение не с чем: отдельного "
           "значения не существует", col=GOLD, sw=5, fill=W,
           where="в1 · кто проверяет")
    kletka(d, PX[1], R3, R3H, "Код, условием",
           "одинаково на этом вопросе и на любом следующем", col=TEAL, sw=5,
           fill=W, where="в2 · кто проверяет")

    save(im, "k1-shema-samootchet-i-geyt.png")


if __name__ == "__main__":
    samootchet_i_geyt()
    pt_report("схема Кейса 1")
    audit_sources()

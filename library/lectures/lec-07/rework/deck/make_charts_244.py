#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Диаграммы трёх кадров допуска (#244) — на шаблоне `tools/presentation-build/analitika.py`.

Рисует три картинки и складывает две из них в одну, потому что поле `media:`
у файла кадра одно:

  assets/s0Xb-strany-i-dinamika.png   — столбцы по странам РЯДОМ с линиями динамики
  assets/s0Xc-potok-za-god.png        — столбцы потока за год по странам и системам

ОТКУДА ЧИСЛА — из исследования, не из головы. Страновой ряд и его
знаменатели: `research/11-dinamika-po-stranam-realno-novye.md` §3 и
`research/13-koreya-kitay-proverka.md` §3. Накопленный счёт по годам:
`research/10-II-FDA-PERVICHNYY-SCHET.md` (таблица по годам, разобранная с
самой страницы FDA). Поток за год: `research/14-vnedrenie-agregaty.md` §2–3.

ЧТО СЧИТАНО ЗДЕСЬ, А НЕ ВЗЯТО ГОТОВЫМ — накопленный ряд короткого пути.
В исследовании он лежит по годам, а не накоплением; сложено здесь, и
проверка стоит прогоном: сумма 2014–2025 плюс остаток до 2014 обязана дать
1 377 — счёт короткого пути на конец 2025 года (1 553 всего минус 176 за
неполный 2026-й). Точки 2010 года у короткого пути нет: погодовой разбивки
до 2014-го в первичной таблице нет, и линия начинается там, где начинаются
данные, — пустое место честнее дорисованного.

ЕДИНИЦЫ. У кадра про поток единица у каждого столбца СВОЯ — случаи, решения,
сводки, исследования. Поэтому она стоит подписью под каждым столбцом, а не
одна на диаграмму: ряд из разных единиц без подписи и есть та склейка
выборок, на которой этот круг спотыкался трижды.

    python3 make_charts_244.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / "tools" / "presentation-build"))

import analitika as A  # noqa: E402

ASSETS = HERE / "assets"
VREMENNO = Path("/tmp/charts-244")

# ── кадр об изделиях: страны ──────────────────────────────────────────────
STRANY = [
    ("Корея", 1.70, "88 из 549"),
    ("Россия", 0.39, "57 из 57"),
    ("США", 0.18, "61 из 1 614"),
    ("Япония", 0.11, "≈14 из 51"),
    ("Китай", 0.08, "118 из 154"),
]

# ── кадр об изделиях: динамика, накопленным счётом ────────────────────────
GODY = [2010, 2014, 2018, 2021, 2024, 2025]
NOVYE = [7, 11, 23, 31, 50, 56]
KOROTKIY = [None, 25, 129, 444, 1048, 1377]

# ── кадр о применении: поток за год ───────────────────────────────────────
# Единица у каждой строки СВОЯ, поэтому она едет с числом, а не с именем:
# в полосе высотой три дюйма двухстрочная подпись слева не помещается.
POTOK = [
    ("США · Aidoc", 60, None),
    ("США · оплата", 53, None),
    ("Россия · СберМедИИ", 30, None),
    ("Россия · Москва", 16, None),
    ("20 стран · Qure.ai", 7, None),
    ("Великобритания · NHS", 2.8, None),
]
POTOK_PODPISI = ["60 млн случаев", "53 млн решений", "30 млн сводок",
                 "16 млн исследований", "7 млн обследований",
                 "2,8 млн рентгенограмм"]


def proverka_ryada():
    """Накопленный ряд короткого пути обязан сойтись с первичным счётом."""
    po_godam = [5, 6, 17, 23, 58, 80, 113, 122, 160, 219, 225, 329]  # 2014–2025
    assert sum(po_godam) == 1357, sum(po_godam)
    assert 1553 - 176 == 1377                      # всего минус неполный 2026-й
    do_2014 = 1377 - 1357
    assert do_2014 == 20, do_2014
    nakoplenno = do_2014
    po_letam = {}
    for god, n in zip(range(2014, 2026), po_godam):
        nakoplenno += n
        po_letam[god] = nakoplenno
    for god, zhdem in ((2014, 25), (2018, 129), (2021, 444),
                       (2024, 1048), (2025, 1377)):
        assert po_letam[god] == zhdem, (god, po_letam[god], zhdem)
    print("  проверка ряда: накопленный счёт короткого пути сходится "
          "с первичным (1 377 на конец 2025)")


def main():
    proverka_ryada()
    VREMENNO.mkdir(parents=True, exist_ok=True)

    strany = A.stolbtsy(
        "Допущено без ссылки на предшественник",
        STRANY, "на миллион населения · признак новизны у каждой строки свой",
        zoloto=1, drobnaya=True, kegl_zagolovka=14,
        gorizontal=True)
    dinamika = A.linii(
        "Накопленный счёт изделий с ИИ, США",
        GODY,
        [("без ссылки на предшественник", NOVYE, A.DEEP),
         ("по похожести на предшественник", KOROTKIY, A.TEAL)],
        "штук, накопленным счётом", kegl_zagolovka=14)
    potok = A.stolbtsy(
        "Поток за год через названные системы",
        POTOK, "за год · единица у каждого столбца своя, названа у числа",
        zoloto=0, drobnaya=False, kegl_zagolovka=14,
        gorizontal=True, podpisi_znacheniy=POTOK_PODPISI)

    # ПРОПОРЦИЯ 4,07 — под полосу аналитического кадра, а не под боковую
    # колонку. Полоса идёт во всю ширину тела (12,23") и берёт 3,00" высоты:
    # выше — и комментарий под диаграммой остаётся без строки, ниже — подписи
    # перестают читаться. Прежние пропорции этого круга (2,12 и 1,39) были
    # под кадр-свидетельство справа; тип кадра сменился, и мера вместе с ним.
    a = A.narisovat(strany, VREMENNO / "strany.png",
                    shirina_pt=435, vysota_pt=216)
    b = A.narisovat(dinamika, VREMENNO / "dinamika.png",
                    shirina_pt=435, vysota_pt=216)
    svod = A.ryadom(a, b, ASSETS / "s0Xb-strany-i-dinamika.png", zazor_pt=10)
    pot = A.narisovat(potok, ASSETS / "s0Xc-potok-za-god.png",
                      shirina_pt=880, vysota_pt=216)

    from PIL import Image
    for p in (svod, pot):
        im = Image.open(p)
        print(f"  {p.name}: {im.width}×{im.height} пикс · "
              f"пропорция {im.width / im.height:.2f} · {p.stat().st_size} Б")
    return 0


if __name__ == "__main__":
    sys.exit(main())

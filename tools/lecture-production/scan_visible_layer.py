#!/usr/bin/env python3
"""Скан видимого слоя в планах лекции: что увидит студент на слайде и в заметках.

Зачем отдельный инструмент. Запреты курса (тайминг, методические мета-комментарии,
превосходные формы, научная запись, p-значения и интервалы) действуют ТОЛЬКО на видимом
слое. В планах тайминг и статистика разрешены и обязательны — они живут в служебных полях.
Поэтому скан по файлу целиком даёт лавину ложных срабатываний и бесполезен: нужно отделить
поля «на экране» / «в заметках» / «плашками» от всего остального.

Правило этого файла: проверка, показавшая ноль, не значит ничего, пока не доказано, что она
умеет находить. Поэтому `--selftest` засевает по одному нарушению на класс плюс две приманки
и падает, если поймано не всё. Запускать самотест перед тем, как верить нулю.

    python3 scan_visible_layer.py --selftest
    python3 scan_visible_layer.py library/lectures/lec-07/rework/plans/*.md

Записано по #229. Класс дефекта, из-за которого инструмент появился, — notes/decisions.md,
запись 2026-10-10 про сборщик деки как третий слой текста.
"""
import re, sys

VISIBLE = re.compile(
    r'^\s*[-*]?\s*\*\*(на экране|что на экране|в заметках|что в заметках|плашк\w*)', re.I)

BANS = {
    'тайминг на видимом слое':
        re.compile(r'\b\d+[,.]?\d*\s*мин(ут)?\b', re.I),
    'методический мета-комментарий':
        re.compile(r'методическ|педагогическ|на этом этапе студент|Лектору|Преподавателю|Вы здесь', re.I),
    'превосходная форма':
        re.compile(r'\bглавн\w*|\bсам(ый|ая|ое|ые)\b|\bлучш(ий|ая|ее|ие)\b|крупнейш|важнейш', re.I),
    'научная запись числа':
        re.compile(r'\d\s*[·x×]\s*10[\^⁰-₟]|10[⁰-⁹]'),
    'p-значение или интервал на экране':
        re.compile(r'\bp\s*[=<]\s*0[,.]|95%\s*(ДИ|интервал|CI)', re.I),
}

SEED = [
    ("- **на экране:** раздел идёт 14 минут, три плашки", 'тайминг на видимом слое'),
    ("- **что в заметках:** методически важно произнести это медленно", 'методический мета-комментарий'),
    ("- **на экране:** главный вывод раздела одной строкой", 'превосходная форма'),
    ("- **плашками:** 1,687·10⁵ часов расчёта", 'научная запись числа'),
    ("- **на экране:** разница незначима, p = 0,60, 95% ДИ от −4 до 8", 'p-значение или интервал на экране'),
]
DECOYS = [
    "**минут:** 1,5",                                 # служебное поле плана, не видимый слой
    "- **форма:** нагрузка переехала на другой шаг",  # видимого запрета не несёт
]


def scan(lines):
    vis = [l for l in lines if VISIBLE.match(l)]
    out = {}
    for name, rx in BANS.items():
        out[name] = [l.strip()[:120] for l in vis if rx.search(l)]
    return len(vis), out


def selftest():
    lines = [s for s, _ in SEED] + DECOYS
    nvis, hits = scan(lines)
    ok = True
    if nvis != len(SEED):
        print(f"ПРИМАНКА ПРОСОЧИЛАСЬ: видимых полей {nvis}, ожидалось {len(SEED)}")
        ok = False
    for _, name in SEED:
        if not hits[name]:
            print(f"НЕ ПОЙМАНО: {name}")
            ok = False
    print("самотест пройден: проверка умеет находить" if ok
          else "САМОТЕСТ ПРОВАЛЕН — нулю этой проверки верить нельзя")
    return 0 if ok else 1


def main(paths):
    total = {k: 0 for k in BANS}
    for p in paths:
        try:
            lines = open(p, encoding='utf-8').read().split('\n')
        except OSError as e:
            print(f"{p}: не прочитан ({e})")
            continue
        nvis, hits = scan(lines)
        found = {k: v for k, v in hits.items() if v}
        print(f"\n{p}  (видимых полей: {nvis})")
        if not found:
            print("  чисто")
        for name, ls in found.items():
            total[name] += len(ls)
            print(f"  {name}: {len(ls)}")
            for l in ls[:3]:
                print(f"      {l}")
    print("\nИТОГО:")
    for k, v in total.items():
        print(f"  {k:36s} {v}")
    return 1 if any(total.values()) else 0


if __name__ == '__main__':
    args = sys.argv[1:]
    sys.exit(selftest() if (not args or args[0] == '--selftest') else main(args))

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Диаграмма кадра `s27` — сколько потока снимков читает обученная модель.

ЗАКАЗ ВЛАДЕЛЬЦА (2026-10-19, круг 6, дословно): «графики непонятные в России
млн, в Британии и США %, хотя бы к одинаковым пропорциям сведи. не понятно как
читать. и не понятно какая ценность в дроблении как сейчас. кажется что
достаточно просто показать общее количество и подтверждённая доля с ИИ и всё».

ЧТО БЫЛО И ПОЧЕМУ СНЯТО. Прежняя редакция держала три панели на трёх разных
основаниях счёта: Россия — миллионы исследований по двум контурам и двум
срезам; Британия — доля трастов, развернувших инструмент, от профинансированных;
США — кумулятивная доля одобрений за три десятилетия. Технически каждая панель
была верна и единица у каждой подписана. Нечитаемо это было не из-за ошибки в
числах, а потому что кадр требовал от зала держать три разных вопроса
одновременно и ни на один не отвечал сопоставимо.

ОДНО ОСНОВАНИЕ, ОДНА ОСЬ, ОДИН ВОПРОС: из каждых ста снимков грудной клетки,
которые в стране делают, сколько прочитала обученная модель. Обе доли на оси
посчитаны на знаменателе, названном числом, и знаменатель стоит подписью под
столбцом — не в заметке.

ЗНАМЕНАТЕЛЬ АНГЛИИ ВЗЯТ НЕ У РАЗРАБОТЧИКА. Числитель 2,8 млн — слова самого
разработчика инструмента. Знаменатель 8 194 405 — официальная статистика
службы здравоохранения (NHS England, Diagnostic Imaging Dataset 2023/24,
таблица 6, рентген грудной клетки по всем направлениям за год к марту 2024).
Деление даёт 34 из ста. В том же государственном сообщении о развёртывании
назван ДРУГОЙ знаменатель — «свыше 7 миллионов в год», и с ним тот же
числитель даёт 40 из ста. Оба знаменателя официальные; расхождение больше
миллиона снимков. Поэтому второе число стоит прямо в подписи столбца, а не
выбрано молча: кадр, который учит читать знаменатель, не вправе свой
собственный спрятать.

США НА ОСЬ НЕ ПОСТАВЛЕНЫ, И ЭТО НЕ ПРОБЕЛ ПОИСКА. Доли снимков, прочитанных
моделью, США не публикует. Публикуется другое: 1 430 кумулятивных авторизаций
изделий на конец 2025 года, 76,5 процента из них в радиологии (доля ИЗДЕЛИЙ в
реестре за тридцать лет, не доля потока), и по опросу профессионального
объединения — 34 процента опрошенных ВРАЧЕЙ применяют модель в практике.
Второе число похоже на английское до совпадения первых двух цифр и измеряет
совершенно другое: там доля снимков, здесь доля врачей. Поставить их на одну
ось значило бы совершить на глазах у зала ту самую подмену знаменателя, против
которой написан весь раздел, и совпадение цифр сделало бы подмену незаметной
(`trebovaniya-k-soderzhaniyu-forma.md` §11.8 — два похожих числа). Пробел
назван словами на самом кадре.

ОЦЕНКА «ЧЕТВЕРТЬ ВСЕХ СНИМКОВ РОССИИ» НА ОСЬ ТОЖЕ НЕ ИДЁТ. Мэрия называет
1,4 млн исследований в месяц и оценивает это как четверть страны; знаменателя
к оценке не публикует никто. На оси стоит только то, у чего знаменатель назван
числом. Сама оценка остаётся на кадре строкой — как оценка, а не как доля.

    python3 make_chart_s27.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[4] / "tools" / "presentation-build"))

import analitika as A  # noqa: E402

ASSETS = HERE / "assets"

# ── числители и знаменатели, каждый со своим источником ──────────────────
# Москва: Васильев и соавт., Digital Diagnostics 2025;6(1):5-22,
# DOI 10.17816/DD641703 - проспективное многоцентровое, май-сентябрь 2024.
MSK_MODEL, MSK_VSEGO = 315_491, 575_549
# Англия: числитель - разработчик инструмента; знаменатель - NHS England,
# Diagnostic Imaging Dataset Annual Statistical Release 2023/24, таблица 6.
ANG_MODEL, ANG_VSEGO = 2_800_000, 8_194_405
# Второй знаменатель, названный самим государственным сообщением (10.06.2026).
ANG_VSEGO_GOS = 7_000_000


def dolya(chislitel, znamenatel):
    return round(100.0 * chislitel / znamenatel, 1)


def main():
    msk = dolya(MSK_MODEL, MSK_VSEGO)
    ang = dolya(ANG_MODEL, ANG_VSEGO)
    ang_gos = dolya(ANG_MODEL, ANG_VSEGO_GOS)

    # Обратная проверка: доля, пересчитанная обратно в случаи, обязана вернуть
    # числитель. Назначить долю числом и не проверить - ровно тот способ,
    # которым число на слайде уезжает от числа в главе (§14 storozha).
    assert abs(msk / 100 * MSK_VSEGO - MSK_MODEL) < MSK_VSEGO * 0.0005, msk
    assert abs(ang / 100 * ANG_VSEGO - ANG_MODEL) < ANG_VSEGO * 0.0005, ang
    # Два знаменателя обязаны давать РАЗНЫЕ доли - иначе оговорка на кадре
    # про расхождение знаменателей ничего не значит и её надо снимать.
    assert ang_gos - ang > 3, (ang, ang_gos)

    ryady = [
        ("Москва · профилактический поток", msk,
         "315 491 из 575 549 · измерено"),
        # Подпись короче НЕ для красоты: при длинной колонка имён съедает поле
        # и QuickChart обрезает её СЛЕВА — на первом прогоне этого круга вышло
        # «из 8,19 млн», числитель пропал. Поймано просмотром PNG, прогоном не
        # ловится. Второй знаменатель переехал в тело кадра, где ему и место.
        ("Англия · рентген грудной клетки", ang,
         "2,8 из 8,19 млн"),
    ]
    out = A.narisovat(
        A.stolbtsy("Из ста снимков потока модель прочитала", ryady,
                   "доля снимков, а не доля врачей и не доля больниц",
                   # drobnaya=False, а не True: целочисленный переводчик
                   # печатает «54,8», дробный — «54,80» и засоряет ось
                   # «0,00 10,00 20,00». Проверено прогоном, не памятью.
                   gorizontal=True, kegl=11, kegl_zagolovka=13,
                   drobnaya=False, zoloto=0),
        ASSETS / "s27-dolya-potoka-cherez-model.png",
        shirina_pt=640, vysota_pt=150)

    from PIL import Image
    im = Image.open(out)
    print(f"готово: {out}  {im.width}×{im.height} px, "
          f"соотношение {im.width / im.height:.2f}")
    print(f"Москва {msk} из ста ({MSK_MODEL} из {MSK_VSEGO})")
    print(f"Англия {ang} из ста ({ANG_MODEL} из {ANG_VSEGO}); "
          f"по знаменателю правительства {ang_gos} из ста "
          f"({ANG_MODEL} из {ANG_VSEGO_GOS})")
    return 0


if __name__ == "__main__":
    sys.exit(main())

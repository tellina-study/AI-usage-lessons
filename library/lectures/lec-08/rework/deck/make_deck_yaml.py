in_min = sum(timing(d) for _, d in flat if d.get('in_bucket') == 'true')
TIMING_MISSING = [d['id'] for _, d in flat if not (d.get('timing_min') or '').strip()]

MISSING_CHAP = [d['id'] for _, d in flat if d['id'] not in CHAP]


def media_status(d):
    if (d.get('media') or '').strip():
        return 'wired'
    if (d.get('media_needed') or '').strip():
        return 'needs_media'
    return 'no_decision'


def slide_block(f, d, W):
    sid = d['id']
    W("  - id: %s\n" % sid)
    lid = (d.get('local_id') or '').strip()
    if lid:
        W("    local_id: %s\n" % q(lid))
    W("    file: %s\n" % ('slides/' + os.path.basename(f)))
    W("    type: %s\n" % d['type'])
    W("    title: %s\n" % q(d.get('title', '')))
    W("    chapter_ref: %s\n" % q(CHAP.get(sid, 'НЕ СОПОСТАВЛЕН')))
    W("    timing_min: %s\n" % ((d.get('timing_min') or '').strip() or '0   # поле отсутствует во фронтматтере кадра'))
    W("    marks: { in_bucket: %s, vfy: %s, status: %s, media_status: %s }\n"
      % (d['in_bucket'], d['vfy'], q(d['status']), media_status(d)))



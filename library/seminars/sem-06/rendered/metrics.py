"""Измерение текста: сколько места он реально займёт в рамке заданной ширины.

Зачем отдельный модуль. Прежняя вёрстка считала высоту по ЧИСЛУ элементов
(`0.32 × пунктов + 0.26`, `0.40 × строк + 0.2`) — то есть предполагала, что
каждый пункт и каждая строка таблицы занимают ровно одну строку текста. Любой
пункт длиннее одной строки ломал расчёт, и коробка переполнялась: ревью нашло
три вываливающихся рамки и 14 таблиц из 28, которые в настоящем PowerPoint
вырастут выше отведённого. Здесь высота считается по РЕАЛЬНОМУ переносу.

Честная оговорка про шрифт. Дека задаёт Arial, в окружении его нет — есть
только DejaVu. Для кириллицы DejaVu шире Arial примерно на 5–10%. Поэтому
ширина, измеренная по DejaVu, умножается на ARIAL_K, и все выводы о влезании
остаются консервативными: если по этой мерке текст влезает, в настоящем Arial
он влезает с запасом. Обратное неверно, и это ровно та сторона, в которую
ошибаться безопасно.
"""
import re
from functools import lru_cache
from PIL import ImageFont

# ВАЖНО: поправка на шрифт нужна В ДВЕ РАЗНЫЕ СТОРОНЫ, и перепутать их — значит
# systematically недооценивать высоту рамок.
#
#   * Когда РАЗМЕЧАЕМ рамку, безопасно считать текст ШИРОКИМ: если высота
#     посчитана по DejaVu, в настоящем Arial (он у́же) текст займёт столько же
#     или меньше — и уж точно не вылезет. Поэтому K_LAYOUT = 1.0.
#   * Когда ОБЪЯВЛЯЕМ переполнение дефектом, безопасно считать текст УЗКИМ:
#     иначе предупреждение окажется артефактом чужого шрифта. Поэтому
#     K_REPORT = 0.88 — та же поправка, которой пользовалось ревью дизайна.
#
# Прежняя версия этого файла применяла 0.88 и к разметке тоже: рамки выходили
# у́же нужного, и золотая коробка вопроса на s09 не вмещала последнюю строку.
K_LAYOUT = 1.00
K_REPORT = 0.88
MONO_K = 1.0            # Consolas и DejaVu Sans Mono совпадают по ширине знака

_FR = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
_FB = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
_FM = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"

# Кегль в pt → растр в 4× для устойчивого измерения коротких строк
_RASTER = 4


@lru_cache(maxsize=256)
def _font(size_pt, bold, mono):
    path = _FM if mono else (_FB if bold else _FR)
    return ImageFont.truetype(path, max(4, int(round(size_pt * _RASTER))))


@lru_cache(maxsize=20000)
def text_w(s, size_pt, bold=False, mono=False):
    """Ширина строки в дюймах при кегле `size_pt` — по мерке РАЗМЕТКИ (K_LAYOUT)."""
    if not s:
        return 0.0
    raw = _font(size_pt, bold, mono).getlength(s) / _RASTER / 72.0
    return raw * (MONO_K if mono else K_LAYOUT)


def wrap(s, size_pt, width_in, bold=False, mono=False):
    """Разбиение строки по словам на ширину `width_in` — тот же перенос, что
    сделает PowerPoint. Слово длиннее строки не режется: оно и в PowerPoint
    вылезет, и пусть это будет видно в предупреждении, а не спрятано."""
    if not s:
        return [""]
    out = []
    for para in s.split("\n"):
        line = ""
        for word in para.split():
            probe = (line + " " + word).strip()
            if line and text_w(probe, size_pt, bold, mono) > width_in:
                out.append(line)
                line = word
            else:
                line = probe
        out.append(line)
    return out


def nlines(s, size_pt, width_in, bold=False, mono=False):
    return len(wrap(s, size_pt, width_in, bold, mono))


def line_h(size_pt, spacing=1.18):
    """Высота строки в дюймах. 1.18 — межстрочный, который python-pptx ставит
    по умолчанию для Arial; та же величина используется при задании фигур."""
    return size_pt * spacing / 72.0


def text_h(s, size_pt, width_in, *, spacing=1.18, bold=False, mono=False, pad=0.0):
    """Высота, которую текст займёт в рамке ширины `width_in`, в дюймах."""
    return nlines(s, size_pt, width_in, bold, mono) * line_h(size_pt, spacing) + pad


# ── Разметка внутри строки: её надо не только рисовать, но и МЕРИТЬ ──────────
#
# `**жирный**` и `` `моноширинный` `` стали оформлением (раньше их вырезали), и
# с этого момента строку нельзя мерить одним шрифтом целиком: жирный прогон
# шире обычного, моноширинный — заметно шире обоих. Замер по `plain()` даёт
# МЕНЬШЕ строк, чем отрисовка, рамка выходит ниже нужного, и текст вылезает —
# ровно тот класс дефекта, ради которого этот модуль и писался, только вернувшийся
# через новый вход.
_RUNS = re.compile(r"\*\*(.+?)\*\*|`(.+?)`")
_LINK = re.compile(r"\[(.+?)\]\(.+?\)")


def _mono_words(text):
    """Моноширинный прогон → куски без пробела ВНУТРИ одного прогона.

    Живой случай (n26, Семинар 6): `` `npx -y` `` рисовался как `npx   - y`
    — раздвинутые пробелы вокруг дефиса, хотя в самом файле PPTX, по чтению
    XML, ровно один пробел. Причина — не в разборе markdown (он уже отдавал
    один прогон с одним пробелом), а в LibreOffice: Consolas в окружении не
    установлен, и у шрифта-подстановки пробел, лежащий ВНУТРИ одного
    моноширинного прогона, меряется и рисуется в разы шире буквы. Прогон,
    где пробел — СВОЙ кусок обычным (не моно) шрифтом, этой подмены не
    получает: слово остаётся моноширинным, пробел рисуется как обычный."""
    out, buf = [], ""
    for ch in text:
        if ch.isspace():
            if buf:
                out.append((buf, False, True)); buf = ""
            out.append((ch, False, False))
        else:
            buf += ch
    if buf:
        out.append((buf, False, True))
    return out


def inline_segments(s):
    """Строка → [(текст, жирный, моноширинный)]. Единственный разборщик
    разметки в рендерере: `deck_kit.inline_runs` вызывает его же, чтобы замер
    и отрисовка резали строку одинаково."""
    s = _LINK.sub(r"\1", s)
    out, pos = [], 0
    for m in _RUNS.finditer(s):
        if m.start() > pos:
            out.append((s[pos:m.start()], False, False))
        if m.group(1) is not None:
            # ВЛОЖЕННАЯ разметка: `моноширинный` внутри **жирного**. Без этого
            # шага `**`/skill-doctor`**` отдавался одним жирным куском вместе с
            # кавычками — и кавычки печатались на слайде. Внешний `**` съедал
            # внутренние, потому что искался первым и дальше в кусок никто не
            # заглядывал.
            for seg, _b, mo in inline_segments(m.group(1)):
                out.append((seg, True, mo))
        else:
            out.extend(_mono_words(m.group(2)))
        pos = m.end()
    if pos < len(s):
        out.append((s[pos:], False, False))
    return [r for r in out if r[0]] or [(s, False, False)]


_WS = re.compile(r"(\s+)")
# Одиночная звёздочка, не парная: `**жирный**` разбирается отдельно и сюда не
# доходит. Требуем не меньше двух знаков внутри, чтобы не ловить умножение.
_ITALIC = re.compile(r"(?<![*\w])\*(?!\*)[^*\n]{2,}\*(?![*\w])")


def inline_tokens(s):
    """Строка → [(токен, жирный, моноширинный)], где токен — слово ИЛИ пробел.

    Пробелы берутся из исходника и не досочиняются. Склейка прогонов через
    «добавим пробел, если строка непустая» рвётся на обоих концах разметки:
    `«моментов » + «33»` даёт двойной пробел, а `«один» + «.»` — пробел перед
    точкой. На картинке это видно сразу, в замере — нет."""
    out = []
    for text, b, mo in inline_segments(s):
        for tok in _WS.split(text):
            if tok:
                out.append((tok, b, mo))
    return out


def wrap_tokens(tokens, size_pt, width_in, *, bold=False, measure=None):
    """Жадный перенос потока токенов. `measure(токен, жирный, моно) -> ширина`
    подменяется предпросмотром, который меряет в пикселях, а не в дюймах.
    Возвращает строки как списки токенов — этого хватает и чтобы посчитать их,
    и чтобы нарисовать."""
    mw = measure or (lambda t, b, mo: text_w(t, size_pt, bold or b, mo))
    lines, line, lw = [], [], 0.0
    for tok, b, mo in tokens:
        w = mw(tok, b, mo)
        if tok.isspace():
            if line:                         # пробел в начале строки съедается
                line.append((tok, b, mo)); lw += w
            continue
        if line and lw + w > width_in:
            while line and line[-1][0].isspace():
                line.pop()
            lines.append(line); line, lw = [], 0.0
        line.append((tok, b, mo)); lw += w
    if line:
        lines.append(line)
    return lines or [[]]


def rich_nlines(s, size_pt, width_in, *, bold=False):
    """Число строк, на которые разойдётся строка С РАЗМЕТКОЙ внутри: каждое
    слово меряется тем шрифтом, которым будет нарисовано."""
    segs = inline_segments(s)
    if len(segs) == 1 and not segs[0][1] and not segs[0][2]:
        return nlines(segs[0][0], size_pt, width_in, bold)
    return len(wrap_tokens(inline_tokens(s), size_pt, width_in, bold=bold))


def rich_block_h(lines, size_pt, width_in, *, spacing=1.18, space_after=0.0,
                 bold=False, pad=0.0):
    """`block_h` для абзацев с разметкой внутри. Ей меряются все формы
    грамматики: в любую из них автор вправе поставить `**жирный**`."""
    total = 0.0
    for i, ln in enumerate(lines):
        total += rich_nlines(ln, size_pt, width_in, bold=bold) * line_h(size_pt, spacing)
        if i < len(lines) - 1:
            total += space_after / 72.0
    return total + pad


def block_h(lines, size_pt, width_in, *, spacing=1.18, space_after=0.0,
            bold=False, mono=False, pad=0.0):
    """То же для списка абзацев — каждый переносится сам по себе."""
    total = 0.0
    for i, ln in enumerate(lines):
        total += nlines(ln, size_pt, width_in, bold, mono) * line_h(size_pt, spacing)
        if i < len(lines) - 1:
            total += space_after / 72.0
    return total + pad


def rich_h(s, size_pt, width_in, *, spacing=1.18, bold=False, pad=0.0):
    """Высота текста, в котором есть `моноширинные` и **жирные** куски.

    Consolas заметно шире Arial, поэтому строку с кодом внутри нельзя мерить
    пропорциональным шрифтом: замер даст меньше строк, чем отрисовка, и текст
    вылезет из ячейки — так переполнялись ячейки таблицы вывода хука.

    Прежде эта функция мерила ВСЮ строку моноширинным, стоило в ней появиться
    одному слову в обратных кавычках. Оценка была консервативной в безопасную
    сторону, но грубой: ячейка «46 из `N` РЦ» получала высоту, как если бы
    моноширинным была набрана вся фраза, и таблица росла на строку без всякой
    причины. Теперь каждый кусок меряется своим шрифтом — это и точнее, и
    по-прежнему безопасно, потому что мерка та же, по которой рисуют."""
    return rich_nlines(s, size_pt, width_in, bold=bold) * line_h(size_pt, spacing) + pad


def fit_size(s, width_in, height_in, sizes, *, spacing=1.18, bold=False, mono=False):
    """Наибольший кегль из `sizes` (по убыванию), при котором текст влезает в
    рамку. Если не влезает ни один — возвращается наименьший: вёрстка обязана
    что-то нарисовать, а о переполнении скажет `fits()`."""
    for size in sizes:
        if text_h(s, size, width_in, spacing=spacing, bold=bold, mono=mono) <= height_in:
            return size
    return sizes[-1]


# ── Есть ли знак в начертании ───────────────────────────────────────────────
#
# Проверка односторонняя, и это сказано вслух: дека задаёт Arial и Consolas,
# которых в окружении нет, мерить приходится по DejaVu. У DejaVu покрытие ШИРЕ,
# поэтому «в DejaVu нет» означает «в Arial тем более нет» — это настоящий
# дефект. Обратное неверно: знак, который есть в DejaVu, может отсутствовать в
# Arial, и такого мы не увидим. Та же асимметрия, что у поправки на ширину:
# ошибаться безопасно только в одну сторону.
#
# Отсутствующий знак FreeType подменяет глифом `.notdef`. Опознаём его по
# растру знака из приватной области, которого нет заведомо ни в одном шрифте,
# и сравниваем попиксельно — bbox совпадает и у части настоящих глифов.
_ALWAYS_ABSENT = "\ue000"


@lru_cache(maxsize=8)
def _notdef(bold, mono):
    return _glyph(_ALWAYS_ABSENT, bold, mono)


def _glyph(ch, bold, mono):
    m = _font(12, bold, mono).getmask(ch)
    return (m.size, bytes(bytearray(m)))


@lru_cache(maxsize=20000)
def has_glyph(ch, bold=False, mono=False):
    if ch.isspace() or ch == _ALWAYS_ABSENT:
        return True
    return _glyph(ch, bold, mono) != _notdef(bold, mono)


def missing_glyphs(s, bold=False, mono=False):
    """Знаки строки, которых в начертании нет. Без повторов, в порядке текста."""
    out = []
    for ch in s:
        if ord(ch) > 0x7F and ch not in out and not has_glyph(ch, bold, mono):
            out.append(ch)
    return out


_WARNINGS = []

def floor_reached(size_pt, floor_pt, *, label="", chars=0):
    """Сказать, что блок набран НА ДНЕ своей лестницы кеглей.

    Отдельный класс рядом с `ПОДГОНКА`, и вот зачем. Подгонка сообщает, что
    пришлось УСТУПИТЬ, и молчит, когда уступать не пришлось: таблица, которой
    хватило 9 pt с первого захода, не даёт ни одного предупреждения — она ведь
    влезла. «Влезло» и «читается» — разные вопросы, и на этой деке они
    разошлись: два слайда набраны почти целиком кеглем мельче 10 pt, и ни один
    из четырнадцати `ПОДГОНКА` про них не сказал.

    Порог — НЕ выдуманная типографская норма, а дно лестницы самого приёма:
    9 pt у таблицы, 7,5 у терминальной карточки. Сообщение означает ровно
    одно, проверяемое: вёрстке больше нечего уступить, дальше только
    сокращать содержание. Читается это с задних рядов или нет — решает
    человек, глядя на картинку; вёрстка называет число и не притворяется, что
    знает про аудиторию."""
    if size_pt <= floor_pt:
        _WARNINGS.append(
            f"НА ДНЕ КЕГЛЯ [{label}]: {size_pt} pt — ниже приём не умеет"
            + (f", {chars} знаков" if chars else "")
            + "; уступать больше нечего, дальше только сокращать содержание")


def fits(s, size_pt, width_in, height_in, *, label="", spacing=1.18,
         bold=False, mono=False, tol=0.02, raw=None):
    """Диагностика влезания. Копит предупреждения и печатает их при сборке —
    приём Семинара 4 (`_fits`), но высота меряется, а не оценивается по числу
    знаков в строке. Возвращает True/False, чтобы вёрстка могла не только
    пожаловаться, но и подстроиться.

    `raw` — НЕОБЯЗАТЕЛЬНЫЙ исходный текст ячейки/блока ДО `plain()` (с
    обратными кавычками на месте). Нужен только для проверки курсива ниже:
    без него литеральная `*` внутри одного моноширинного прогона (`*.md`,
    shell-glob) и такая же `*` внутри ДРУГОГО прогона той же ячейки, уже
    склеенные `plain()` в одну строку без разделителей, читаются как один
    курсивный пролёт между ними — так нашёлся ложный «РАЗМЕТКА» на n63
    (`` `…/*.md` ``; `` `…/*.md | …` ``). Когда `raw` не передан, проверка
    идёт по `s`, как раньше — поведение остальных вызывающих не меняется."""
    if not s or width_in <= 0 or height_in <= 0:
        return True
    # предупреждение печатается по мерке ОТЧЁТА: то, что переживает поправку
    # на более узкий Arial, — настоящее переполнение, а не артефакт DejaVu
    # ── По отсутствующему глифу ─────────────────────────────────────────────
    # Знак, которого в начертании нет, печатается пустым прямоугольником —
    # молчаливый дефект той же породы, что курсив со звёздочками: файл
    # собирается, список чист, а на экране квадрат. Кружковые цифры `①②③` в
    # прозе есть, а в МОНОШИРИННОМ их нет — и поймать это можно было только
    # глазами на рендере.
    for ch in missing_glyphs(s, bold, mono):
        _WARNINGS.append(
            f"НЕТ ГЛИФА [{label}]: знак «{ch}» (U+{ord(ch):04X}) отсутствует в "
            f"{'моноширинном' if mono else 'основном'} начертании — напечатается "
            f"пустым прямоугольником")

    # ── По неподдержанной разметке ──────────────────────────────────────────
    # Курсив `*…*` внутри строки вёрстка не умеет (жирный и моноширинный
    # умеет). Молча срезать звёздочки нельзя — так прошлая версия теряла
    # целевые ответы, помеченные жирным; молча печатать их тоже нельзя.
    #
    # Проверка стоит ЗДЕСЬ, а не в разборе блока, потому что `fits()` зовут все
    # формы и каждая ячейка таблицы. В ветке голого абзаца она покрывала один
    # вид блока из шести — и `*«even a JSON permissionDecision…»*` в дорожке
    # Такта Б доехало до слайда со звёздочками, не сказав ни слова. Проверка,
    # поставленная у одного входа, проверяет один вход.
    italic_src = re.sub(r"`[^`]*`", "", raw) if raw is not None else s
    m = _ITALIC.search(italic_src)
    if m:
        _WARNINGS.append(
            f"РАЗМЕТКА [{label}]: курсив «{m.group(0)[:38]}» вёрстка не умеет — "
            f"звёздочки выйдут на слайд как есть; убрать их или пометить жирным")

    # ── По ширине ───────────────────────────────────────────────────────────
    # Перенос по словам спасает от любой длины текста, КРОМЕ одной: слово
    # длиннее рамки не переносится нигде — ни в PowerPoint, ни здесь. Оно
    # выходит за край и накладывается на то, что справа. Высотная проверка
    # этого не видит по построению: строк-то ровно столько, сколько нужно.
    #
    # Мерка та же, что у высоты: узкая (Arial), чтобы не жаловаться на то, чего
    # в настоящем шрифте нет.
    widest = max((text_w(w, size_pt, bold, mono) for w in s.split() if w), default=0.0)
    if widest > width_in / K_REPORT + tol:
        longest = max(s.split(), key=lambda w: text_w(w, size_pt, bold, mono))
        _WARNINGS.append(
            f"ШИРЕ РАМКИ [{label}]: слово «{longest[:30]}» занимает {widest:.2f}″ "
            f"при ширине рамки {width_in:.2f}″ — перенос его не спасёт, "
            f"оно ляжет на то, что справа")

    need = text_h(s, size_pt, width_in / K_REPORT, spacing=spacing, bold=bold, mono=mono)
    if need > height_in + tol:
        _WARNINGS.append(
            f"ПЕРЕПОЛНЕНИЕ [{label}]: «{s[:46]}…» при {size_pt} pt в {width_in:.2f}″ "
            f"требует {need:.2f}″, отведено {height_in:.2f}″ (+{need - height_in:.2f}″)")
        return False
    return True


def report():
    """Список накопленных предупреждений; вызывается в конце сборки."""
    return list(_WARNINGS)


def reset():
    _WARNINGS.clear()
